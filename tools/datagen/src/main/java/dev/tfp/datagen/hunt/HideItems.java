package dev.tfp.datagen.hunt;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import dev.tfp.datagen.material.TfcItemRegistry;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * PAR-FAUNA-17: TFC's hide items as CraftEngine items ({@code configuration/hunt/hides.yml}). TFC registers one plain item per
 * {@code HideItemType} ({@code prepared}, {@code raw}, {@code scraped}, {@code sheepskin}, {@code soaked}) and
 * {@code HideItemType.Size} ({@code small}, {@code medium}, {@code large}): {@code <size>_<type>_hide}, 15 items. Each gets its
 * TFC model and texture ({@code item/hide/<size>/<type>}), its TFC name in every TFC locale
 * ({@code assets/tfp_hunt/lang/<locale>.json}) and a stack of 64: TFC has no {@code item_size} for hides, so they take TFC's
 * default size, the same default as the material items.
 *
 * <p>The meat the hunt drops ({@code food/venison}, {@code food/beef}, ...) is generated with every TFC food by
 * {@code food.FoodItems}; the bone, feather, blubber and horn drops are vanilla or material items. The hunt test checks that
 * every item of {@code HuntDrops} resolves to one of them.
 */
public final class HideItems {
    static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/hunt/hides.yml";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    static final String LANG_NS = "tfp_hunt";
    public static final String LANG_RP = PACK + "resourcepack/assets/" + LANG_NS + "/lang/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String TYPES_SOURCE = "src/main/java/net/dries007/tfc/common/items/HideItemType.java";
    static final String ITEMS_SOURCE = "src/main/java/net/dries007/tfc/common/items/TFCItems.java";
    static final String MODELS = TfcCheckout.ASSETS + "models/item/";
    static final String ITEM_SIZE = "src/generated/resources/data/tfc/tfc/item_size/";
    /** TFC's {@code HideItemType} constants, in declaration order. */
    public static final List<String> TYPES = List.of("prepared", "raw", "scraped", "sheepskin", "soaked");
    /** TFC's {@code HideItemType.Size} constants, in declaration order. */
    public static final List<String> SIZES = List.of("small", "medium", "large");
    static final int STACK = 64;

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    private HideItems() {
    }

    /** Whether the checkout has the hide sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TYPES_SOURCE) && tfc.exists(ITEMS_SOURCE);
    }

    /** The hide item ids ({@code small_raw_hide}, ...), type-major as TFC's {@code HIDES} map iterates. */
    public static List<String> ids() {
        List<String> out = new ArrayList<>();
        for (String type : TYPES) {
            for (String size : SIZES) {
                out.add(size + "_" + type + "_hide");
            }
        }
        return List.copyOf(out);
    }

    /** Writes the CE items, models, textures and names. Returns the ids. */
    public static List<String> run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        Map<String, Object> entries = new TreeMap<>();
        for (String id : ids()) {
            copyModel(tfc, out, id);
            Map<String, Object> entry = new LinkedHashMap<>();
            entry.put("template", "tfp:item/simple");
            entry.put("arguments", Map.of("item_lang_key", langKey(id)));
            entry.put("data", Map.of("max_stack_size", STACK));
            entries.put(Json.TO_NS + ":" + id, entry);
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", entries);
        out.put(CONFIG, Yaml.write(HEADER, root));
        writeLang(tfc, out);
        return ids();
    }

    static String langKey(String id) {
        return "item." + Json.TO_NS + "." + id;
    }

    /** Fails when TFC's hide enums, the {@code HIDES} registration or the hide-free item sizes changed. */
    static void checkSources(TfcCheckout tfc) {
        String types = tfc.readString(TYPES_SOURCE).replaceAll("\\s+", " ");
        String expectTypes = "public enum HideItemType { " + String.join(", ", TYPES.stream().map(String::toUpperCase).toList()) + ";";
        String expectSizes = "public enum Size { " + String.join(", ", SIZES.stream().map(String::toUpperCase).toList()) + " }";
        if (!types.contains(expectTypes) || !types.contains(expectSizes)) {
            throw new DatagenException(TYPES_SOURCE + ": the hide types or sizes changed (update HideItems)");
        }
        TfcItemRegistry.Registration hides = TfcItemRegistry.registrations(tfc).stream().filter(r -> r.field().equals("HIDES"))
            .findFirst().orElseThrow(() -> new DatagenException(ITEMS_SOURCE + " no longer has HIDES"));
        if (!hides.plain() || !new java.util.TreeSet<>(hides.ids()).equals(new java.util.TreeSet<>(ids()))) {
            throw new DatagenException(ITEMS_SOURCE + " HIDES is no longer the 15 plain <size>_<type>_hide items: " + hides);
        }
        for (String f : tfc.list(ITEM_SIZE)) {
            if (f.endsWith(".json") && tfc.readString(f).contains("_hide")) {
                throw new DatagenException(f + " now sizes hides: read its weight for the stack size (update HideItems)");
            }
        }
    }

    private static void copyModel(TfcCheckout tfc, OutputTree out, String id) {
        String src = MODELS + id + ".json";
        JsonObject model = Json.parse(tfc.readString(src), src).getAsJsonObject();
        String parent = model.has("parent") ? model.get("parent").getAsString() : "";
        if (!parent.equals("item/generated") || model.has("overrides") || model.has("loader")) {
            throw new DatagenException(src + ": expected a plain item/generated model, got parent " + parent);
        }
        for (Map.Entry<String, JsonElement> t : model.getAsJsonObject("textures").entrySet()) {
            String ref = t.getValue().getAsString();
            if (!ref.startsWith(Json.FROM_NS + ":")) {
                continue;
            }
            String path = ref.substring(Json.FROM_NS.length() + 1);
            String png = TfcCheckout.ASSETS + "textures/" + path + ".png";
            if (!tfc.exists(png)) {
                throw new DatagenException(src + " uses missing texture " + ref);
            }
            out.put(RP + "textures/" + path + ".png", tfc.read(png));
        }
        out.put(RP + "models/item/" + id + ".json", Json.write(Json.rename(model)));
    }

    /** TFC's hide names in every TFC locale that has them; English must have all. */
    private static void writeLang(TfcCheckout tfc, OutputTree out) {
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            TreeMap<String, String> keys = new TreeMap<>();
            for (String id : ids()) {
                String tfcKey = "item." + Json.FROM_NS + "." + id;
                if (src.has(tfcKey)) {
                    keys.put(langKey(id), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC item tfc:" + id + " has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }

    /** The English names written by {@link #run}, for tests. */
    static JsonObject english(OutputTree out) {
        return Json.parse(new String(out.get(LANG_RP + "en_us.json"), StandardCharsets.UTF_8), LANG_RP).getAsJsonObject();
    }
}
