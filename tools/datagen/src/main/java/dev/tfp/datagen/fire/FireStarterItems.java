package dev.tfp.datagen.fire;

import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import dev.tfp.datagen.material.TfcItemRegistry;
import java.math.BigDecimal;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * PAR-HEAT-05: TFC's firestarter and flint and pyrite as the CraftEngine items {@code tfp:firestarter} and
 * {@code tfp:flint_and_pyrite} ({@code configuration/fire_starters.yml}), on {@code tfp:item/simple} (paper: no vanilla
 * right-click behaviour).
 *
 * <p>The durability is TFC's {@code Properties().durability(n)}, read from {@code TFCItems}. The firestarter carries a
 * vanilla {@code minecraft:consumable} component with TFC's use duration (72 ticks = 3.6 s), the bow animation, no item
 * particles and TFC's firestarter sound ({@code tfp_fire:item.firestarter.use}, TFC's ten oggs), so a vanilla client holds
 * it up and plays the sound while the server waits for the finish (PAR-HEAT-05 {@code FireStarterListener} cancels the
 * eating). The look is TFC's {@code item/handheld} models; the names and the sound subtitle come from TFC's lang files
 * ({@code assets/tfp_fire/lang}).
 */
public final class FireStarterItems {
    static final String PACK = "craftengine/tfp/";
    static final String CONFIG = PACK + "configuration/fire_starters.yml";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    static final String NS = "tfp_fire";
    static final String FIRE_RP = PACK + "resourcepack/assets/" + NS + "/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String ITEMS_SOURCE = "src/main/java/net/dries007/tfc/common/items/TFCItems.java";
    static final String FIRESTARTER_SOURCE = "src/main/java/net/dries007/tfc/common/items/FirestarterItem.java";
    static final String SOUNDS = TfcCheckout.ASSETS + "sounds.json";
    static final String SOUND_EVENT = "item.firestarter.use";
    static final String SUBTITLE_TFC = "subtitles.item.tfc.firestarter.use";
    static final String SUBTITLE = "subtitles.item.tfp.firestarter.use";

    /** One fire starting tool: its TFC id, {@code TFCItems} field and item class. */
    record Tool(String id, String field, String itemClass) {
    }

    static final List<Tool> TOOLS = List.of(
        new Tool("firestarter", "FIRESTARTER", "FirestarterItem"),
        new Tool("flint_and_pyrite", "FLINT_AND_PYRITE", "FlintAndPyriteItem"));

    private static final Pattern DURABILITY = Pattern.compile("\\.durability\\((\\d+)\\)");
    private static final Pattern USE_DURATION = Pattern.compile(
        "getUseDuration\\([^)]*\\)\\s*\\{\\s*return\\s+(\\d+)\\s*;");

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (PAR-HEAT-05, dev.tfp.datagen.fire). Do not edit: fix the "
        + "generator and regenerate.";

    private FireStarterItems() {
    }

    /** Whether the checkout has {@code TFCItems} and the firestarter (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(ITEMS_SOURCE) && tfc.exists(FIRESTARTER_SOURCE)
            && tfc.exists(TfcCheckout.ASSETS + "models/item/firestarter.json");
    }

    /** TFC's durability of {@code tool}, checking the registration's item class. */
    static int durability(TfcCheckout tfc, Tool tool) {
        for (TfcItemRegistry.Registration r : TfcItemRegistry.registrations(tfc)) {
            if (r.field().equals(tool.field())) {
                if (!r.factory().contains("new " + tool.itemClass() + "(")) {
                    throw new DatagenException("TFCItems." + tool.field() + " is no longer a " + tool.itemClass() + ": "
                        + r.factory());
                }
                Matcher m = DURABILITY.matcher(r.factory());
                if (!m.find()) {
                    throw new DatagenException("TFCItems." + tool.field() + " has no durability: " + r.factory());
                }
                return Integer.parseInt(m.group(1));
            }
        }
        throw new DatagenException(ITEMS_SOURCE + " no longer has " + tool.field() + " (update FireStarterItems)");
    }

    /** TFC {@code FirestarterItem.getUseDuration} in ticks. */
    static int useTicks(TfcCheckout tfc) {
        Matcher m = USE_DURATION.matcher(tfc.readString(FIRESTARTER_SOURCE));
        if (!m.find()) {
            throw new DatagenException(FIRESTARTER_SOURCE + ": getUseDuration is no longer a constant");
        }
        if (!tfc.readString(FIRESTARTER_SOURCE).contains("UseAnim.BOW")) {
            throw new DatagenException(FIRESTARTER_SOURCE + ": the use animation is no longer BOW");
        }
        return Integer.parseInt(m.group(1));
    }

    /** The {@code layer0} texture of TFC's handheld model of {@code id} ({@code item/firestarter}). */
    static String texture(TfcCheckout tfc, String id) {
        String path = TfcCheckout.ASSETS + "models/item/" + id + ".json";
        JsonObject model = Json.parse(tfc.readString(path), path).getAsJsonObject();
        if (!model.has("parent") || !model.get("parent").getAsString().endsWith("item/handheld")
                || !model.has("textures")) {
            throw new DatagenException(path + " is no longer an item/handheld model");
        }
        JsonObject tex = model.getAsJsonObject("textures");
        if (tex.size() != 1 || !tex.has("layer0")) {
            throw new DatagenException(path + ": expected exactly layer0, got " + tex.keySet());
        }
        String layer0 = tex.get("layer0").getAsString();
        String prefix = Json.FROM_NS + ":";
        if (!layer0.startsWith(prefix)) {
            throw new DatagenException(path + ": layer0 outside the tfc namespace: " + layer0);
        }
        return layer0.substring(prefix.length());
    }

    /** Writes the items, models, textures, sound and names. */
    public static void run(TfcCheckout tfc, OutputTree out) {
        int useTicks = useTicks(tfc);
        Map<String, Object> items = new LinkedHashMap<>();
        for (Tool tool : TOOLS) {
            String texture = texture(tfc, tool.id());
            String png = TfcCheckout.ASSETS + "textures/" + texture + ".png";
            if (!tfc.exists(png)) {
                throw new DatagenException("missing texture " + png);
            }
            out.put(RP + "textures/" + texture + ".png", tfc.read(png));
            JsonObject model = new JsonObject();
            model.addProperty("parent", "minecraft:item/handheld");
            JsonObject tex = new JsonObject();
            tex.addProperty("layer0", Json.TO_NS + ":" + texture);
            model.add("textures", tex);
            out.put(RP + "models/item/" + tool.id() + ".json", Json.write(model));
            Integer use = tool.id().equals("firestarter") ? useTicks : null;
            items.put(Json.TO_NS + ":" + tool.id(), entry(tool.id(), durability(tfc, tool), use));
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", items);
        out.put(CONFIG, Yaml.write(HEADER, root));
        writeSound(tfc, out);
        writeLang(tfc, out);
    }

    static String langKey(String id) {
        return "item." + Json.TO_NS + "." + id;
    }

    /**
     * One item entry.
     *
     * @param useTicks the firestarter's use duration, or {@code null} for an item without one
     */
    static Map<String, Object> entry(String id, int durability, Integer useTicks) {
        Map<String, Object> args = new LinkedHashMap<>();
        args.put("item_lang_key", langKey(id));
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("max_stack_size", 1);
        data.put("max_damage", durability);
        Map<String, Object> components = new LinkedHashMap<>();
        components.put("minecraft:damage", 0);
        data.put("components", components);
        if (useTicks != null) {
            Map<String, Object> sound = new LinkedHashMap<>();
            sound.put("sound_id", NS + ":" + SOUND_EVENT);
            Map<String, Object> consumable = new LinkedHashMap<>();
            consumable.put("consume_seconds", BigDecimal.valueOf(useTicks).divide(BigDecimal.valueOf(20)));
            consumable.put("animation", "bow");
            consumable.put("sound", sound);
            consumable.put("has_consume_particles", false);
            data.put("consumable", consumable);
        }
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("template", "tfp:item/simple");
        e.put("arguments", args);
        e.put("data", data);
        return e;
    }

    /** TFC's firestarter sound event and its oggs, under {@code tfp_fire}. */
    static void writeSound(TfcCheckout tfc, OutputTree out) {
        JsonObject sounds = Json.parse(tfc.readString(SOUNDS), SOUNDS).getAsJsonObject();
        if (!sounds.has(SOUND_EVENT)) {
            throw new DatagenException(SOUNDS + " has no " + SOUND_EVENT);
        }
        JsonObject src = sounds.getAsJsonObject(SOUND_EVENT);
        JsonArray list = new JsonArray();
        String prefix = Json.FROM_NS + ":";
        for (var el : src.getAsJsonArray("sounds")) {
            String name = el.getAsString();
            if (!name.startsWith(prefix)) {
                throw new DatagenException(SOUNDS + ": " + SOUND_EVENT + " sound outside tfc: " + name);
            }
            String path = name.substring(prefix.length());
            String ogg = TfcCheckout.ASSETS + "sounds/" + path + ".ogg";
            if (!tfc.exists(ogg)) {
                throw new DatagenException("missing sound " + ogg);
            }
            out.put(FIRE_RP + "sounds/" + path + ".ogg", tfc.read(ogg));
            list.add(NS + ":" + path);
        }
        JsonObject event = new JsonObject();
        event.addProperty("subtitle", SUBTITLE);
        event.add("sounds", list);
        JsonObject root = new JsonObject();
        root.add(SOUND_EVENT, event);
        out.put(FIRE_RP + "sounds.json", Json.write(root));
    }

    /** TFC's names of both tools and the sound subtitle, in every locale that has them (English must). */
    private static void writeLang(TfcCheckout tfc, OutputTree out) {
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            JsonObject o = new JsonObject();
            for (Tool tool : TOOLS) {
                String tfcKey = "item." + Json.FROM_NS + "." + tool.id();
                if (src.has(tfcKey)) {
                    o.addProperty(langKey(tool.id()), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC item tfc:" + tool.id() + " has no English name " + tfcKey);
                }
            }
            if (src.has(SUBTITLE_TFC)) {
                o.addProperty(SUBTITLE, src.get(SUBTITLE_TFC).getAsString());
            }
            if (o.size() > 0) {
                out.put(FIRE_RP + "lang/" + locale + ".json", Json.write(o));
            }
        }
    }
}
