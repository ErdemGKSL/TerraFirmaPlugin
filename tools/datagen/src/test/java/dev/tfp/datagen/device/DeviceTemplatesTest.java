package dev.tfp.datagen.device;

import static org.assertj.core.api.Assertions.assertThat;

import dev.tfp.datagen.OutputTree;
import java.nio.charset.StandardCharsets;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.yaml.snakeyaml.LoaderOptions;
import org.yaml.snakeyaml.Yaml;

/** PAR-INFRA-08: the device templates file, golden, and what a templated entry becomes after CraftEngine's merge. */
class DeviceTemplatesTest {
    @Test
    void templatesGolden() {
        OutputTree out = new OutputTree();
        DeviceTemplates.run(out);
        String text = new String(out.get(DeviceTemplates.OUTPUT), StandardCharsets.UTF_8);
        assertThat(DeviceTemplates.OUTPUT).isEqualTo("craftengine/tfp/configuration/templates/device.yml");
        assertThat(text).endsWith("""
            'templates#device':
              tfp:block/device:
                settings:
                  template: tfp:settings/device
                  arguments:
                    device_hardness: '${device_hardness}'
                    device_resistance: '${device_resistance}'
                loot:
                  template: tfp:loot_table/self
                behavior:
                  type: tfp:device
              tfp:block/device_rendered:
                settings:
                  template: tfp:settings/device
                  arguments:
                    device_hardness: '${device_hardness}'
                    device_resistance: '${device_resistance}'
                  can_occlude: false
                  is_suffocating: false
                  is_view_blocking: false
                loot:
                  template: tfp:loot_table/self
                behavior:
                  type: tfp:device
            """);
        assertThat(text).startsWith("# Generated by tools/datagen").doesNotContain("\t");
    }

    /**
     * A model of CraftEngine's map-template merge (template body deep-merged with the caller's extra keys, placeholders
     * substituted): a templated spec ends with the settings call, the self loot, the behaviour and its own states, the
     * same block the literal form writes plus the behaviour.
     */
    @Test
    @SuppressWarnings("unchecked")
    void aTemplatedEntryExpandsToTheLiteralEntry() {
        LoaderOptions opts = new LoaderOptions();
        opts.setAllowDuplicateKeys(false);
        Map<String, Object> templates = (Map<String, Object>) ((Map<String, Object>) new Yaml(opts)
            .load(dev.tfp.datagen.Yaml.write("t", DeviceTemplates.yaml()))).get("templates#device");
        for (DeviceBlockSpec spec : List.of(DeviceYamlGoldenTest.repurposed(), DeviceYamlGoldenTest.autoState(),
                DeviceYamlGoldenTest.rendered())) {
            Map<String, Object> call = block(DeviceYaml.writeTemplated(spec), spec.id(), opts);
            Map<String, Object> literal = block(DeviceYaml.writeLiteral(spec), spec.id(), opts);
            Map<String, Object> args = (Map<String, Object>) call.remove("arguments");
            Object body = substitute(templates.get((String) call.remove("template")), args);
            Map<String, Object> expanded = deepMerge((Map<String, Object>) body, call);
            Map<String, Object> settings = (Map<String, Object>) expanded.get("settings");
            if (spec.rendered()) {
                assertThat(settings).containsEntry("can_occlude", false).containsEntry("is_view_blocking", false);
                settings.remove("can_occlude");
                settings.remove("is_suffocating");
                settings.remove("is_view_blocking");
            }
            assertThat(expanded).as(spec.id()).isEqualTo(literal);
        }
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> block(String text, String id, LoaderOptions opts) {
        Map<String, Object> root = new Yaml(opts).load(text);
        return new LinkedHashMap<>((Map<String, Object>) ((Map<String, Object>) root.get("blocks")).get(id));
    }

    @SuppressWarnings("unchecked")
    private static Object substitute(Object node, Map<String, Object> args) {
        if (node instanceof Map<?, ?> m) {
            Map<String, Object> out = new LinkedHashMap<>();
            m.forEach((k, v) -> out.put((String) k, substitute(v, args)));
            return out;
        }
        if (node instanceof String s && s.startsWith("${") && s.endsWith("}")) {
            String name = s.substring(2, s.length() - 1);
            assertThat(args).as("argument " + name).containsKey(name);
            return args.get(name);
        }
        return node;
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> deepMerge(Map<String, Object> base, Map<String, Object> extra) {
        Map<String, Object> out = new LinkedHashMap<>(base);
        extra.forEach((k, v) -> {
            if (out.get(k) instanceof Map<?, ?> a && v instanceof Map<?, ?> b) {
                out.put(k, deepMerge((Map<String, Object>) a, (Map<String, Object>) b));
            } else {
                out.put(k, v);
            }
        });
        return out;
    }
}
