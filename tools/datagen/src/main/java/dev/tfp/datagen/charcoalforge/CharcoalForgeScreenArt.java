package dev.tfp.datagen.charcoalforge;

import dev.tfp.core.gui.ChestGeometry;
import dev.tfp.core.gui.GuiImage;
import dev.tfp.core.gui.ProgressFrames;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.util.LinkedHashMap;
import java.util.Map;
import javax.imageio.ImageIO;

/**
 * PAR-METAL-09: the charcoal forge screen's art (TFC {@code CharcoalForgeScreen}) for the 4-row chest of the plugin's
 * {@code dev.tfp.paper.charcoalforge.gui.ForgeScreenLayout} ({@code configuration/charcoal_forge_gui.yml}). The numbers here
 * must equal that layout's; {@code CharcoalForgeScreenArtTest} reads the generated YAML and PNGs against them.
 *
 * <ul>
 *   <li>{@code tfp:gui/charcoal_forge}: TFC's {@code charcoal_forge.png} (176 x 186, a 4-row chest is 186 tall) re-laid out.
 *       TFC's slots sit at y 16 + 18 k, a chest's at 18 + 18 k, so everything above the player inventory moves down
 *       {@link #DY} = 2 (two plain panel rows are inserted under the top border); the player inventory (TFC y 104, chest
 *       103) moves up one: three plain rows of the gap between them are cut and the last row repeats.</li>
 *   <li>{@code tfp:gui/charcoal_forge_thermometer}: 52 frames of TFC's temperature indicator (u 176, v 0, 15 x 5) at
 *       (8, 76 - 51), moved by {@link #DY}.</li>
 * </ul>
 */
public final class CharcoalForgeScreenArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/charcoal_forge.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/CharcoalForgeScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/CharcoalForgeContainer.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/charcoal_forge_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    public static final ChestGeometry CHEST = new ChestGeometry(4);
    /** TFC's screen height: 166 + 20. */
    public static final int TFC_HEIGHT = 186;
    /** TFC's player inventory offset ({@code init(playerInv, 20)}). */
    public static final int TFC_INVENTORY_OFFSET = 20;
    /** The upper content's move: TFC's first slot row (y 16) onto chest row 0 (y 18). */
    public static final int DY = 2;
    /** The player inventory's move onto the chest's. */
    public static final int DY_PLAYER = CHEST.playerRowY(0) - (84 + TFC_INVENTORY_OFFSET);
    /** The plain panel row duplicated under the top border. */
    static final int INSERT_ROW = 8;
    /** Output row where the upper band ends and the player band begins. */
    static final int SPLIT = 95;

    public static final int TFC_THERMOMETER_X = 8;
    public static final int TFC_THERMOMETER_BOTTOM = 76;
    public static final int THERMOMETER_U = 176;
    public static final int THERMOMETER_V = 0;

    public static final GuiImage BACKGROUND = GuiImage.of("tfp:gui/charcoal_forge", 0, 0, ChestGeometry.WIDTH, CHEST.height());
    public static final GuiImage THERMOMETER = new GuiImage("tfp:gui/charcoal_forge_thermometer", TFC_THERMOMETER_X,
        TFC_THERMOMETER_BOTTOM - ProgressFrames.THERMOMETER_TRAVEL + DY, ProgressFrames.THERMOMETER_WIDTH,
        ProgressFrames.THERMOMETER_FRAME_HEIGHT, 4, 13);

    private CharcoalForgeScreenArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(SCREEN) && tfc.exists(CONTAINER);
    }

    /** Writes the images and their YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE));
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, BACKGROUND, background(src));
        put(out, images, THERMOMETER, thermometer(src));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The source row of output row {@code y} of the 176 x 186 window. */
    static int sourceRow(int y) {
        if (y <= INSERT_ROW) {
            return y;
        }
        if (y < INSERT_ROW + DY + 1) {
            return INSERT_ROW; // the two inserted plain rows
        }
        if (y < SPLIT) {
            return y - DY;
        }
        return Math.min(y - DY_PLAYER, TFC_HEIGHT - 1);
    }

    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = CHEST.height();
        if (src.getWidth() < w || src.getHeight() < TFC_HEIGHT || h != TFC_HEIGHT || DY_PLAYER != -1) {
            throw new DatagenException(TEXTURE + ": not a 176 x 186 screen under a 4-row chest");
        }
        checkPlain(src, INSERT_ROW);
        for (int y = SPLIT - DY; y <= SPLIT - DY_PLAYER; y++) {
            checkPlain(src, y); // the rows between the two bands, including the three that are cut
        }
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < h; y++) {
            copy(src, out, 0, sourceRow(y), w, 1, 0, y);
        }
        return out;
    }

    /** The thermometer strip: frame 0 empty, frame k the indicator {@code 51 - k} pixels below the frame top. */
    static BufferedImage thermometer(BufferedImage src) {
        GuiImage t = THERMOMETER;
        BufferedImage out = new BufferedImage(t.pngWidth(), t.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 1; k < ProgressFrames.THERMOMETER_FRAMES; k++) {
            int fx = t.frameCol(k) * t.width();
            int fy = t.frameRow(k) * t.height() + ProgressFrames.thermometerOffset(k);
            copy(src, out, THERMOMETER_U, THERMOMETER_V, ProgressFrames.THERMOMETER_WIDTH, ProgressFrames.THERMOMETER_HEIGHT,
                fx, fy);
        }
        keepAdvance(out, t.width(), t.height());
        return out;
    }

    /** Alpha of the width marker: counted by the client's glyph width scan, discarded by the text shader (below 0.1). */
    static final int MARKER = 0x01000000;

    /** A frame with an empty right column gets a nearly transparent pixel in its corner (as the crucible art). */
    static void keepAdvance(BufferedImage png, int w, int h) {
        for (int fy = 0; fy < png.getHeight(); fy += h) {
            for (int fx = 0; fx < png.getWidth(); fx += w) {
                boolean any = false;
                for (int y = fy; y < fy + h && !any; y++) {
                    any = (png.getRGB(fx + w - 1, y) >>> 24) != 0;
                }
                if (!any) {
                    png.setRGB(fx + w - 1, fy + h - 1, MARKER);
                }
            }
        }
    }

    /** TFC's numbers this layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        String screen = tfc.readString(SCREEN).replaceAll("\\s+", " ");
        need(container, CONTAINER, ".init(playerInventory, " + TFC_INVENTORY_OFFSET + ")");
        need(container, CONTAINER, "152, 16 + 18 * (i - CharcoalForgeBlockEntity.SLOT_EXTRA_MIN)");
        need(container, CONTAINER, "new CallbackSlot(blockEntity, index++, 80, 70)");
        need(container, CONTAINER, "new CallbackSlot(blockEntity, index, 44, 16)");
        need(screen, SCREEN, "imageHeight += " + TFC_INVENTORY_OFFSET + ";");
        need(screen, SCREEN, "graphics.blit(texture, leftPos + " + TFC_THERMOMETER_X + ", topPos + " + TFC_THERMOMETER_BOTTOM
            + " - Math.min(" + ProgressFrames.THERMOMETER_TRAVEL + ", temp), " + THERMOMETER_U + ", " + THERMOMETER_V + ", "
            + ProgressFrames.THERMOMETER_WIDTH + ", " + ProgressFrames.THERMOMETER_HEIGHT + ");");
        if (CHEST.slotY(0) != 16 + DY || CHEST.slotX(2) != 44 || CHEST.slotX(8) != 152 || CHEST.slotY(3 * 9 + 4) != 70 + DY) {
            throw new DatagenException("the forge slots do not land on the 4-row chest grid");
        }
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the charcoal forge screen art is stale");
        }
    }

    private static void checkPlain(BufferedImage src, int y) {
        int c = src.getRGB(4, y);
        for (int x = 4; x < ChestGeometry.WIDTH - 4; x++) {
            if (src.getRGB(x, y) != c) {
                throw new DatagenException(TEXTURE + ": row " + y + " is not plain panel; the re-layout would cut art");
            }
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        images.put(image.id(), e);
    }

    static BufferedImage read(byte[] bytes) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(TEXTURE + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
