import javax.imageio.ImageIO;

/**
 * PAR-PROC-18: the powderkeg screen's art (TFC {@code PowderkegScreen}) for a 3-row chest, in the layout of
 * {@link PowderkegScreenLayout} ({@code configuration/powderkeg/powderkeg_gui.yml}).
 *
 * <ul>
 *   <li>{@code tfp:gui/powderkeg}: TFC's {@code powderkeg.png} re-laid out: the panel, the 4 x 3 slot block moved
 *       ({@code DX_SLOTS}, {@code DY_SLOTS}) onto the chest grid, the button frame moved onto chest slot 16, the player
 *       inventory moved onto the chest's rows.</li>
 *   <li>{@code tfp:gui/powderkeg_seal}: the seal button sprites (frame 0 sealed, 1 unsealed).</li>
 *   <li>{@code tfp:gui/powderkeg_disabled}: TFC's {@code drawDisabled} highlight over the twelve slots.</li>
 * </ul>
 */
public final class PowderkegScreenArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/powderkeg.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/PowderkegScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/PowderkegContainer.java";
    public static final String BUTTON = "src/main/java/net/dries007/tfc/client/screen/button/PowderkegSealButton.java";
    public static final String ENTITY = "src/main/java/net/dries007/tfc/common/blockentities/PowderkegBlockEntity.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/powderkeg/powderkeg_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    /** TFC's slot block frame: one pixel up and left of the first item position, 18 per slot. */
    static final int GRID_X = PowderkegScreenLayout.TFC_SLOT_X - 1;
    static final int GRID_Y = PowderkegScreenLayout.TFC_SLOT_Y - 1;
    static final int GRID_W = PowderkegScreenLayout.COLUMNS * ChestGeometry.SLOT;
    static final int GRID_H = PowderkegScreenLayout.ROWS * ChestGeometry.SLOT;
    /** A plain panel row of TFC's art (between the content and the inventory). */
    static final int PLAIN_ROW = 76;
    /** TFC's player inventory part, from the first slot frame row to above the bottom border. */
    static final int INVENTORY_TOP = 82;
    static final int INVENTORY_BOTTOM = PowderkegScreenLayout.TFC_HEIGHT - 4;

    private PowderkegScreenArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(SCREEN) && tfc.exists(CONTAINER) && tfc.exists(BUTTON);
    }

    /** Writes the images and their YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE), TEXTURE);
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, PowderkegScreenLayout.BACKGROUND, background(src));
        GuiImage seal = PowderkegScreenLayout.SEAL;
        BufferedImage sprites = new BufferedImage(seal.pngWidth(), seal.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        int size = PowderkegScreenLayout.BUTTON_SIZE;
        copy(src, sprites, PowderkegScreenLayout.BUTTON_U, PowderkegScreenLayout.BUTTON_V_SEALED, size, size, 0, 0);
        copy(src, sprites, PowderkegScreenLayout.BUTTON_U, PowderkegScreenLayout.BUTTON_V_UNSEALED, size, size, 0, size);
        put(out, images, seal, sprites);
        put(out, images, PowderkegScreenLayout.DISABLED, disabled());
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The 176 x 168 window. */
    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = PowderkegScreenLayout.CHEST.height();
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < h; y++) {
            copy(src, out, 0, PLAIN_ROW, w, 1, 0, y);
        }
        copy(src, out, 0, 0, w, 4, 0, 0); // top border
        copy(src, out, 0, INVENTORY_TOP, w, INVENTORY_BOTTOM - INVENTORY_TOP, 0,
            INVENTORY_TOP + PowderkegScreenLayout.DY_PLAYER); // the player inventory
        copy(src, out, 0, PowderkegScreenLayout.TFC_HEIGHT - 4, w, 4, 0, h - 4); // bottom border
        copy(src, out, GRID_X, GRID_Y, GRID_W, GRID_H, GRID_X + PowderkegScreenLayout.DX_SLOTS,
            GRID_Y + PowderkegScreenLayout.DY_SLOTS); // the slot block
        int bx = PowderkegScreenLayout.TFC_BUTTON_X;
        int by = PowderkegScreenLayout.TFC_BUTTON_Y;
        int size = PowderkegScreenLayout.BUTTON_SIZE;
        copy(src, out, bx, by, size, size, bx + PowderkegScreenLayout.DX_BUTTON, by + PowderkegScreenLayout.DY_BUTTON);
        return out;
    }

    /** TFC {@code renderSlotHighlight}: 0x80FFFFFF over each 16 x 16 slot interior. */
    static BufferedImage disabled() {
        GuiImage d = PowderkegScreenLayout.DISABLED;
        BufferedImage out = new BufferedImage(d.width(), d.height(), BufferedImage.TYPE_INT_ARGB);
        ChestGeometry chest = PowderkegScreenLayout.CHEST;
        for (int tfc = 0; tfc < PowderkegRules.SLOTS; tfc++) {
            int slot = PowderkegScreenLayout.chestSlot(tfc);
            int sx = chest.slotX(slot) - d.x();
            int sy = chest.slotY(slot) - d.y();
            for (int y = 0; y < 16; y++) {
                for (int x = 0; x < 16; x++) {
                    out.setRGB(sx + x, sy + y, 0x80FFFFFF);
                }
            }
        }
        return out;
    }

    /** TFC's numbers the layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        String button = tfc.readString(BUTTON);
        String screen = tfc.readString(SCREEN);
        String entity = tfc.readString(ENTITY);
        need(container, CONTAINER, "for (int y = 0; y < " + PowderkegScreenLayout.ROWS + "; y++)");
        need(container, CONTAINER, "for (int x = 0; x < " + PowderkegScreenLayout.COLUMNS + "; x++)");
        need(container, CONTAINER, "new CallbackSlot(blockEntity, x * " + PowderkegScreenLayout.ROWS + " + y, "
            + PowderkegScreenLayout.TFC_SLOT_X + " + x * 18, " + PowderkegScreenLayout.TFC_SLOT_Y + " + y * 18)");
        need(container, CONTAINER, ".init(playerInv, 0)");
        need(button, BUTTON, "super(guiLeft + " + PowderkegScreenLayout.TFC_BUTTON_X + ", guiTop + "
            + PowderkegScreenLayout.TFC_BUTTON_Y + ", " + PowderkegScreenLayout.BUTTON_SIZE + ", "
            + PowderkegScreenLayout.BUTTON_SIZE + ",");
        need(button, BUTTON, "? " + PowderkegScreenLayout.BUTTON_V_SEALED + " : " + PowderkegScreenLayout.BUTTON_V_UNSEALED + ";");
        need(button, BUTTON, PowderkegScreenLayout.BUTTON_U + ", v, " + PowderkegScreenLayout.BUTTON_SIZE + ", "
            + PowderkegScreenLayout.BUTTON_SIZE + ", 256, 256)");
        need(screen, SCREEN, "drawDisabled(poseStack, 0, PowderkegBlockEntity.SLOTS - 1)");
        need(entity, ENTITY, "public static final int SLOTS = " + PowderkegRules.SLOTS + ";");
        need(entity, ENTITY, "public static final int MAX_STRENGTH = " + PowderkegRules.MAX_STRENGTH + ";");
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the powderkeg port is stale");
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        images.put(image.id(), e);
    }

    static BufferedImage read(byte[] bytes, String what) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(what + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
