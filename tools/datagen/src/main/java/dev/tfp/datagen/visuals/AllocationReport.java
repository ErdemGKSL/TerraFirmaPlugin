package dev.tfp.datagen.visuals;

import dev.tfp.datagen.oreoverlay.OreLook;
import dev.tfp.datagen.visuals.VisualAllocator.Allocation;
import dev.tfp.datagen.visuals.VisualAllocator.Unit;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/** Markdown allocation report for one profile × family (both Nether/End settings). */
final class AllocationReport {
    private AllocationReport() {
    }

    /** @param hostRock the same profile and family (Nether/End off) with {@link OreLook#HOST_ROCK} */
    static String markdown(Allocation off, Allocation on, List<VisualDemand> demand, Allocation hostRock) {
        Profile profile = off.profile();
        VersionFamily family = off.family();
        StringBuilder sb = new StringBuilder();
        boolean isDefault = Profile.defaultFor(family) == profile;
        sb.append("# Visual allocation: ").append(profile.id()).append(", MC ").append(family.id())
            .append(isDefault ? " (default for this family)" : "").append("\n\n");
        sb.append("Generated by tools/datagen (M1-DGN-04). Do not edit. Researched versions: ")
            .append(String.join(", ", family.researchedVersions()))
            .append(" (a state counts only if it is a free opaque full cube in all of them).\n\n");
        Map<String, Integer> blocks = new TreeMap<>();
        demand.forEach(d -> blocks.merge(d.blockId(), 1, Integer::sum));
        sb.append("## Demand\n\n");
        sb.append("- Emitted CE blocks: ").append(blocks.size()).append(" (families emitted by datagen so far; ")
            .append("ARCHITECTURE.md §9.1 \"Our demand\" counts all of TFC and is larger).\n");
        sb.append("- Appearances: ").append(demand.size()).append("; shared by profile rules: ")
            .append(off.sharedByProfile()).append("; distinct visuals after model dedup: ")
            .append(off.units().size()).append(".\n");
        long ores = demand.stream().filter(d -> Profile.hostRock(d) != null).count();
        sb.append("- Ore look shipped: `").append(off.oreLook().id()).append("` (").append(ores).append(" ore appearances). ")
            .append("With `host_rock` (always-on rule, every profile: each ore is its host raw rock's unit, the ore is ")
            .append("drawn by the face overlays of PAR-INFRA-16) the ore demand is 0 and this profile needs **")
            .append(hostRock.units().size()).append(" visuals** (").append(hostRock.explicitUsed())
            .append(" explicit states, ").append(hostRock.solidUsed()).append(" solid-pool states, Nether/End off).")
            .append(off.oreLook() == OreLook.FULL_CUBE ? " `full_cube` keeps each ore's flattened cube until "
                + "PAR-INFRA-16 flips `mode.properties`." : "").append('\n');
        if (!profile.pendingRules().isEmpty()) {
            sb.append("- Profile rules that need content or renderers not built yet:\n");
            profile.pendingRules().forEach(r -> sb.append("  - ").append(r).append('\n'));
        }
        sb.append("\n## Pools\n\n");
        sb.append("Order: identity duplicates → Nether/End (only when on) → absent-in-TFC clean → absent minor → ")
            .append("CE `auto_state: solid`. Reserved as mapping targets: ")
            .append(String.join(", ", new java.util.TreeSet<>(HideTargets.RESERVED)))
            .append(". Kept vanilla (used by TFC terrain): ")
            .append(String.join(", ", new java.util.TreeSet<>(HideTargets.KEEP_VANILLA))).append(".\n\n");
        sb.append("| Pool | capacity (N/E off) | used (N/E off) | free (N/E off) | capacity (N/E on) | used (N/E on) | free (N/E on) |\n");
        sb.append("|---|---|---|---|---|---|---|\n");
        for (String p : VisualAllocator.POOLS) {
            sb.append("| ").append(p);
            for (Allocation a : List.of(off, on)) {
                int cap = a.capacity().get(p);
                int used = a.used().get(p);
                sb.append(" | ").append(cap).append(" | ").append(used).append(" | ").append(cap - used);
            }
            sb.append(" |\n");
        }
        sb.append('\n');
        for (Allocation a : List.of(off, on)) {
            sb.append("- Nether/End ").append(a.netherEnd() ? "on" : "off").append(": ").append(a.explicitUsed())
                .append(" explicit states, ").append(a.solidUsed()).append(" solid-pool states, **")
                .append(a.solidFree()).append(" solid-pool states left for other CE packs** (before CE's own ")
                .append("and other packs' use; checked at runtime). Reserve target ")
                .append(Profile.SOLID_RESERVE_WARNING).append(": ")
                .append(a.solidFree() >= Profile.SOLID_RESERVE_WARNING ? "met" : "NOT met").append(". ")
                .append(a.mappings().size()).append(" block_state_mappings (`").append(a.dir()).append('/')
                .append(VisualOutputs.MAPPINGS_FILE).append("`).\n");
        }
        for (Allocation a : List.of(off, on)) {
            sb.append("\n## Explicit states claimed (Nether/End ").append(a.netherEnd() ? "on" : "off").append(")\n\n");
            sb.append("| Vanilla state | pool | hidden as | used by |\n|---|---|---|---|\n");
            for (Unit u : a.units()) {
                if (u.state() == null) {
                    continue;
                }
                sb.append("| `").append(u.state().state()).append("` | ").append(u.state().pool()).append(" | `")
                    .append(a.mappings().get(u.state().state())).append("` | ").append(u.members().getFirst().key());
                if (u.members().size() > 1) {
                    sb.append(" (+").append(u.members().size() - 1).append(')');
                }
                sb.append(" |\n");
            }
        }
        return sb.toString();
    }
}
