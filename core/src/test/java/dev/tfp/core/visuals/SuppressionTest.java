/** M1-INST-04: the pure suppression rules, one test per rule, plus the shipped lists. */
class SuppressionTest {
    // Shaped like visuals/<family>/<profile>/nether-end-on/suppressed_blocks.json + visual_mappings.yml.
    static final String JSON = """
            {"profile": "level-2", "family": "1.21", "nether_end": true,
             "suppress": [
              {"block": "minecraft:cobblestone", "source": "absent", "states": ["minecraft:cobblestone"], "creation_paths": ["item", "lava_water"]},
              {"block": "minecraft:obsidian", "source": "absent", "states": ["minecraft:obsidian"], "creation_paths": ["item", "lava_water"]},
              {"block": "minecraft:basalt", "source": "nether_end", "states": ["minecraft:basalt[axis=x]", "minecraft:basalt[axis=y]", "minecraft:basalt[axis=z]"],
               "creation_paths": ["item", "lava_soul_soil_blue_ice"]},
              {"block": "minecraft:white_concrete", "source": "absent", "states": ["minecraft:white_concrete"], "creation_paths": ["concrete_powder_water", "item"]},
              {"block": "minecraft:exposed_copper", "source": "absent", "states": ["minecraft:exposed_copper"], "creation_paths": ["copper_weathering_scraping_waxing", "item"]},
              {"block": "minecraft:copper_block", "source": "absent", "states": ["minecraft:copper_block"], "creation_paths": ["copper_weathering_scraping_waxing", "item"]},
              {"block": "minecraft:dead_brain_coral_block", "source": "absent", "states": ["minecraft:dead_brain_coral_block"], "creation_paths": ["coral_death", "item"]},
              {"block": "minecraft:grass_block", "source": "absent", "states": ["minecraft:grass_block[snowy=false]"], "creation_paths": ["block_spread", "item"]},
              {"block": "minecraft:sculk", "source": "absent", "states": ["minecraft:sculk"], "creation_paths": ["item", "sculk_spread"]},
              {"block": "minecraft:moss_block", "source": "absent", "states": ["minecraft:moss_block"], "creation_paths": ["item", "moss_bonemeal"]},
              {"block": "minecraft:clay", "source": "absent", "states": ["minecraft:clay"], "creation_paths": ["item", "mud_drying_under_dripstone"]},
              {"block": "minecraft:sponge", "source": "absent", "states": ["minecraft:sponge"], "creation_paths": ["item", "wet_sponge_drying"]},
              {"block": "minecraft:oak_log", "source": "absent", "states": ["minecraft:oak_log[axis=y]"], "creation_paths": ["item"]}
             ],
             "identity_duplicates": [{"block": "minecraft:andesite_slab", "source": "identity", "states": ["minecraft:andesite_slab[type=double,waterlogged=false]"]}]}
            """;
    static final String MAPPINGS = """
            # Generated by tools/datagen (visual allocator, M1-DGN-04). Do not edit.
            block_state_mappings:
              'minecraft:andesite_slab[type=double,waterlogged=false]': minecraft:stone
              'minecraft:basalt[axis=x]': minecraft:stone
              'minecraft:basalt[axis=y]': minecraft:stone
              minecraft:cobblestone: minecraft:stone
              minecraft:obsidian: minecraft:cobblestone
              minecraft:white_concrete: minecraft:white_concrete_powder
              'minecraft:oak_log[axis=y]': minecraft:oak_planks
            """;
    static final Suppression S = new Suppression(SuppressionSet.parse(JSON, MAPPINGS));

    // ---- parsing ---------------------------------------------------------------------------------

    @Test
    void parsesBlocksPathsAndMappings() {
        SuppressionSet set = S.set();
        assertThat(set.blockIds()).hasSize(13).contains("minecraft:cobblestone").doesNotContain("minecraft:andesite_slab");
        assertThat(set.creationPaths("minecraft:basalt[axis=y]")).containsExactlyInAnyOrder("item", "lava_soul_soil_blue_ice");
        assertThat(set.mappings()).containsEntry("minecraft:basalt[axis=x]", "minecraft:stone")
                .containsEntry("minecraft:cobblestone", "minecraft:stone").hasSize(7);
        assertThat(set.suppressed("cobblestone")).isTrue();
        assertThat(set.suppressed("minecraft:stone")).isFalse();
        assertThatThrownBy(() -> SuppressionSet.parse("{}", null)).isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void normalisesStateStrings() {
        assertThat(SuppressionSet.normalize("basalt[axis=y]")).isEqualTo("minecraft:basalt[axis=y]");
        assertThat(SuppressionSet.normalize("minecraft:bee_nest[honey_level=1,facing=east]"))
                .isEqualTo("minecraft:bee_nest[facing=east,honey_level=1]");
        assertThat(SuppressionSet.blockId("minecraft:chest{Items:[]}")).isEqualTo("minecraft:chest");
        assertThat(S.set().lookAlike("minecraft:basalt[axis=z]")).contains("minecraft:stone"); // via another state of the block
        assertThat(S.set().lookAlike("minecraft:sculk")).isEmpty();
    }

    // ---- one test per rule ---------------------------------------------------------------------------

    @Test
    void notRepurposedIsAllowedOnEveryPath() {
        for (Path p : Path.values()) {
            assertThat(S.decide(p, "minecraft:lava", "minecraft:stone")).as(p.name()).isEqualTo(Verdict.ALLOW);
            assertThat(S.decide(p, null, "minecraft:andesite_slab[type=double,waterlogged=false]")).as("identity duplicate " + p)
                    .isEqualTo(Verdict.ALLOW);
        }
        assertThat(S.decide(Path.FORM, "minecraft:water", null)).isEqualTo(Verdict.ALLOW);
    }

    @Test
    void lavaWaterCobblestoneBecomesItsLookAlike() {
        assertThat(S.decide(Path.FLUID_FORM, "minecraft:lava[level=2]", "minecraft:cobblestone"))
                .isEqualTo(new Verdict.Replace("minecraft:stone"));
    }

    @Test
    void lavaWaterBasaltUsesTheMappingOfTheState() {
        assertThat(S.decide(Path.FLUID_FORM, "minecraft:lava", "minecraft:basalt[axis=y]"))
                .isEqualTo(new Verdict.Replace("minecraft:stone"));
    }

    @Test
    void lavaWaterWithASuppressedLookAlikeFallsBackToStone() {
        // obsidian is mapped to cobblestone, itself repurposed: never create that either.
        assertThat(S.decide(Path.FLUID_FORM, "minecraft:water", "minecraft:obsidian"))
                .isEqualTo(new Verdict.Replace(Suppression.FALLBACK_STONE));
    }

    @Test
    void lavaWaterCancelsWhenEvenStoneIsRepurposed() {
        Suppression s = new Suppression(SuppressionSet.parse("""
                {"suppress": [{"block": "minecraft:stone", "creation_paths": ["lava_water"]},
                              {"block": "minecraft:obsidian", "creation_paths": ["lava_water"]}]}""", null));
        assertThat(s.decide(Path.FLUID_FORM, "minecraft:lava", "minecraft:obsidian")).isEqualTo(Verdict.CANCEL);
    }

    @Test
    void concreteHardeningIsCancelled() {
        assertThat(S.decide(Path.CONCRETE_HARDENING, "minecraft:white_concrete_powder", "minecraft:white_concrete"))
                .isEqualTo(Verdict.CANCEL);
    }

    @Test
    void copperWeatheringIsCancelled() {
        assertThat(S.decide(Path.WEATHERING, "minecraft:copper_block", "minecraft:exposed_copper")).isEqualTo(Verdict.CANCEL);
    }

    @Test
    void scrapingAndWaxingAreCancelled() {
        assertThat(S.decide(Path.ENTITY_CHANGE, "minecraft:exposed_copper", "minecraft:copper_block")).isEqualTo(Verdict.CANCEL);
    }

    @Test
    void otherFormationIsCancelled() {
        assertThat(S.decide(Path.FORM, "minecraft:mud", "minecraft:clay")).isEqualTo(Verdict.CANCEL);
    }

    @Test
    void coralDeathIsCancelled() {
        assertThat(S.decide(Path.FADE, "minecraft:brain_coral_block", "minecraft:dead_brain_coral_block")).isEqualTo(Verdict.CANCEL);
    }

    @Test
    void spreadIsCancelled() {
        assertThat(S.decide(Path.SPREAD, "minecraft:dirt", "minecraft:grass_block[snowy=false]")).isEqualTo(Verdict.CANCEL);
        assertThat(S.decide(Path.SPREAD, "minecraft:stone", "minecraft:sculk")).isEqualTo(Verdict.CANCEL);
    }

    @Test
    void bonemealMossIsCancelled() {
        assertThat(S.decide(Path.FERTILIZE, "minecraft:stone", "minecraft:moss_block")).isEqualTo(Verdict.CANCEL);
    }

    @Test
    void placingDispensingAndWetSpongeDryingAreCancelled() {
        assertThat(S.decide(Path.PLACE, "minecraft:air", "minecraft:oak_log[axis=y]")).isEqualTo(Verdict.CANCEL);
        assertThat(S.decide(Path.PLACE, "minecraft:air", "minecraft:sponge")).isEqualTo(Verdict.CANCEL);
        assertThat(S.decide(Path.DISPENSE, null, "minecraft:oak_log")).isEqualTo(Verdict.CANCEL);
        assertThat(S.suppressedItem("minecraft:oak_log")).isTrue();
        assertThat(S.suppressedItem("minecraft:oak_planks")).isFalse();
    }

    @Test
    void commandsBestEffort() {
        assertThat(S.commandPlaces("/setblock ~ ~ ~ minecraft:cobblestone")).contains("minecraft:cobblestone");
        assertThat(S.commandPlaces("setblock 1 2 3 oak_log[axis=y] replace")).contains("minecraft:oak_log");
        assertThat(S.commandPlaces("fill 0 0 0 4 4 4 minecraft:white_concrete replace minecraft:air")).contains("minecraft:white_concrete");
        assertThat(S.commandPlaces("fill 0 0 0 4 4 4 minecraft:air replace minecraft:cobblestone")).isEmpty();
        assertThat(S.commandPlaces("execute as @p at @s run minecraft:setblock ~ ~1 ~ sculk")).contains("minecraft:sculk");
        assertThat(S.commandPlaces("setblock ~ ~ ~ minecraft:stone")).isEmpty();
        assertThat(S.commandPlaces("setblock ~ ~ ~ #minecraft:logs")).isEmpty();
        assertThat(S.commandPlaces("say setblock ~ ~ ~ cobblestone")).isEmpty();
        assertThat(S.commandPlaces("setblock ~ ~")).isEmpty();
        assertThat(S.commandPlaces(null)).isEmpty();
    }

    @Test
    void recipesAndLootProducingRepurposedBlocks() {
        Map<String, String> recipes = new LinkedHashMap<>();
        recipes.put("minecraft:oak_planks", "minecraft:oak_planks");
        recipes.put("minecraft:oak_wood", "minecraft:oak_log"); // name differs from the result
        recipes.put("minecraft:white_concrete_powder", "minecraft:white_concrete_powder");
        recipes.put("minecraft:copper_block", "minecraft:copper_block");
        recipes.put("minecraft:moss_block_from_x", "minecraft:moss_block");
        recipes.put("tfp:some_recipe", "minecraft:cobblestone"); // not vanilla: not CE's list
        assertThat(S.recipesToDisable(recipes)).containsExactly("minecraft:copper_block", "minecraft:moss_block_from_x",
                "minecraft:oak_wood");
        assertThat(S.suppressedItems(List.of("minecraft:cobblestone", "minecraft:flint", "minecraft:sculk")))
                .containsExactly("minecraft:cobblestone", "minecraft:sculk");
    }

    @Test
    void classifiesBlockFormEvents() {
        assertThat(Suppression.classifyForm("minecraft:lava[level=0]", "minecraft:obsidian")).isEqualTo(Path.FLUID_FORM);
        assertThat(Suppression.classifyForm("minecraft:water[level=3]", "minecraft:stone")).isEqualTo(Path.FLUID_FORM);
        assertThat(Suppression.classifyForm("minecraft:white_concrete_powder", "minecraft:white_concrete")).isEqualTo(Path.CONCRETE_HARDENING);
        assertThat(Suppression.classifyForm("minecraft:weathered_cut_copper", "minecraft:oxidized_cut_copper")).isEqualTo(Path.WEATHERING);
        assertThat(Suppression.classifyForm("minecraft:mud", "minecraft:clay")).isEqualTo(Path.FORM);
        assertThat(Suppression.classifyForm(null, "minecraft:ice")).isEqualTo(Path.FORM);
    }

    // ---- the shipped lists -----------------------------------------------------------------------

    @Test
    void everyShippedCreationPathIsCovered() throws IOException {
        java.nio.file.Path visuals = VisualSelectionTest.contentRoot().resolve("visuals");
        assumeTrue(Files.isDirectory(visuals), "no generated content at " + visuals.toAbsolutePath());
        Set<String> paths = new TreeSet<>();
        int files = 0;
        try (var s = Files.walk(visuals)) {
            for (java.nio.file.Path f : (Iterable<java.nio.file.Path>) s.filter(p -> p.getFileName().toString().equals("suppressed_blocks.json"))::iterator) {
                java.nio.file.Path mappings = f.resolveSibling("visual_mappings.yml");
                Suppression sup = new Suppression(SuppressionSet.parse(Files.readString(f), Files.readString(mappings)));
                files++;
                for (String block : sup.set().blockIds()) {
                    paths.addAll(sup.set().creationPaths(block));
                    // Every repurposed block is hidden by a mapping, and no lava + water result stays repurposed.
                    assertThat(sup.set().lookAlike(block)).as(block + " in " + f).isPresent();
                    if (sup.set().creationPaths(block).stream().anyMatch(p -> Suppression.coverage(p).contains(Path.FLUID_FORM))) {
                        Verdict v = sup.decide(Path.FLUID_FORM, "minecraft:lava", block);
                        assertThat(v).as(block + " in " + f).isInstanceOf(Verdict.Replace.class);
                        assertThat(sup.set().suppressed(((Verdict.Replace) v).state())).isFalse();
                    }
                    for (String p : sup.set().creationPaths(block)) {
                        for (Path path : Suppression.coverage(p)) {
                            assertThat(sup.decide(path, null, block)).as(block + " via " + path).isNotEqualTo(Verdict.ALLOW);
                        }
                    }
                }
            }
        }
        assertThat(files).isEqualTo(20);
        for (String p : paths) {
            assertThat(Suppression.coverage(p)).as("creation path " + p + " has no listener").isNotEmpty();
        }
        assertThat(Suppression.coverage("something_new")).isEqualTo(EnumSet.noneOf(Path.class));
    }
}
