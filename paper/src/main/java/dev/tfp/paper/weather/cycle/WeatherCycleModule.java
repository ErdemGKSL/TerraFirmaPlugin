package dev.tfp.paper.weather.cycle;

import dev.tfp.paper.module.FeatureModule;
import dev.tfp.paper.module.ModuleContext;
import dev.tfp.paper.worldgen.TfcChunkGenerator;
import org.bukkit.Server;
import org.bukkit.World;

/**
 * PAR-CLIM-12: wires the climate-driven weather cycle ({@link ClimateWeatherCycle}, provided as a service for
 * {@code /tfp weather} and {@code /tfp time set rain|clear}) and the vanilla weather gates ({@link VanillaWeatherGates}).
 */
public final class WeatherCycleModule implements FeatureModule {
    public static final String ID = "weather_cycle";

    private ClimateWeatherCycle cycle;

    @Override
    public String id() {
        return ID;
    }

    @Override
    public void enable(ModuleContext context) {
        Server server = context.plugin().getServer();
        cycle = new ClimateWeatherCycle(context.clock(), context.scheduler(), WeatherCycleModule::isTfcOverworld,
                server::getWorlds, server::getOnlinePlayers);
        context.services().provide(ClimateWeatherCycle.class, cycle);
        context.listen(cycle);
        context.listen(new VanillaWeatherGates(cycle, context.clock(), context.scheduler()));
        cycle.start();
    }

    @Override
    public void disable() {
        if (cycle != null) {
            cycle.stop();
        }
    }

    /** A TFC overworld: the overworld environment generated by our generator (TFC: the climate model supports rain). */
    public static boolean isTfcOverworld(World world) {
        return world.getEnvironment() == World.Environment.NORMAL && world.getGenerator() instanceof TfcChunkGenerator;
    }
}
