class PotTest {
    private static final String PIN = TfcCheckout.PINNED_COMMIT;

    /** The TFC class at the pinned commit: it adds no state of its own and extends the firepit. */
    static final String CLASS_SOURCE = """
        public class PotBlock extends FirepitBlock
        {
            private static final VoxelShape POT_SHAPE = Shapes.or(BASE_SHAPE, box(2, 0, 2, 14, 14, 14));

            public PotBlock(ExtendedProperties properties)
            {
                super(properties, POT_SHAPE);
            }
        }
        """;

    /** The six parts of TFC's pot.json at the pinned commit: an axis part and a lit part for each of x and z. */
    static final List<String> PARTS = List.of(
        "{\"when\": {\"axis\": \"x\"}, \"apply\": {\"model\": \"tfc:block/firepit_pot\"}}",
        "{\"when\": {\"axis\": \"z\"}, \"apply\": {\"model\": \"tfc:block/firepit_pot\", \"y\": 90}}",
        "{\"when\": {\"lit\": true, \"axis\": \"x\"}, \"apply\": {\"model\": \"tfc:block/firepit_lit_low\"}}",
        "{\"when\": {\"lit\": true, \"axis\": \"z\"}, \"apply\": {\"model\": \"tfc:block/firepit_lit_low\", \"y\": 90}}",
        "{\"when\": {\"lit\": false, \"axis\": \"x\"}, \"apply\": {\"model\": \"tfc:block/firepit_unlit\"}}",
        "{\"when\": {\"lit\": false, \"axis\": \"z\"}, \"apply\": {\"model\": \"tfc:block/firepit_unlit\", \"y\": 90}}");

    @TempDir
    Path tmp;

    /** Real checkout at the pinned commit (-Ptfc.checkout); skipped when absent. */
    @Test
    void realCheckoutEmitsTheTwentyPotStates() {
        TfcCheckout tfc = FirepitTest.realCheckout();

        assertThat(Pot.props(tfc).stream().map(dev.tfp.datagen.device.DeviceProperty::name).toList()).containsExactly("lit", "smoke_level", "axis");

        OutputTree out = new OutputTree();
        assertThat(Pot.run(tfc, out)).isEqualTo(2 * 5 * 2);
        assertEntry(new String(out.get(Pot.OUTPUT), StandardCharsets.UTF_8), 4);
    }

    /** PAR-HEAT-25: the loaded entry is the literal spec through the device template, written by {@code run}. */
    @Test
    @SuppressWarnings("unchecked")
    void loadedEntryCallsTheDeviceTemplateWithTheSameStatesAndLoot() {
        TfcCheckout tfc = FirepitTest.realCheckout();
        OutputTree out = new OutputTree();
        Pot.run(tfc, out);
        assertThat(Pot.LOADED_OUTPUT).isEqualTo(AssetPipeline.PACK + "configuration/devices/pot.yml");
        assertThat(out.get(Pot.LOADED_OUTPUT)).as("written by run since PAR-HEAT-25").isNotNull();
        String loaded = new String(out.get(Pot.LOADED_OUTPUT), StandardCharsets.UTF_8);
        assertThat(loaded).isEqualTo(Pot.loadedYaml(tfc));
        String literal = new String(out.get(Pot.OUTPUT), StandardCharsets.UTF_8);
        java.util.Map<?, ?> block = (java.util.Map<?, ?>) ((java.util.Map<?, ?>) ((java.util.Map<?, ?>) CeYamlCheck.parse(loaded, Pot.LOADED_OUTPUT))
            .get("blocks")).get(Pot.BLOCK_ID);
        java.util.Map<?, ?> literalBlock = (java.util.Map<?, ?>) ((java.util.Map<?, ?>) ((java.util.Map<?, ?>) CeYamlCheck.parse(literal, Pot.OUTPUT))
            .get("blocks")).get(Pot.BLOCK_ID);
        assertThat(block.get("template")).isEqualTo("tfp:block/device_rendered");
        assertThat(block.get("states")).isEqualTo(literalBlock.get("states"));
        assertThat(block.get("loot")).isEqualTo(literalBlock.get("loot"));
        assertThat(loaded).contains("tfp:ceramic/pot", "tfp:powder/wood_ash");
        assertThat(java.util.regex.Pattern.compile("(?m)^  " + java.util.regex.Pattern.quote(Pot.BLOCK_ID) + ":").matcher(loaded).results().count())
            .as("one entry for tfp:pot in the loaded file").isEqualTo(1);
    }

    /**
     * PAR-HEAT-37: the pot entry: the firepit's properties with TFC's defaults, one variant per state, TFC's lit light,
     * settings and loot, and four (lit, axis) appearances on one empty carrier, each an item display of the merged model of
     * its lit value, axis x a half turn (the display's turn against a block model), axis z 90.
     */
    @SuppressWarnings("unchecked")
    static void assertEntry(String yaml, int smokeMax) {
        assertThat(yaml).startsWith("# Generated by tools/datagen from TerraFirmaCraft @ " + PIN.substring(0, 9));
        java.util.Map<String, Object> root = (java.util.Map<String, Object>) CeYamlCheck.parse(yaml, Pot.OUTPUT);
        java.util.Map<String, Object> block = (java.util.Map<String, Object>) ((java.util.Map<String, Object>) root.get("blocks"))
            .get(Pot.BLOCK_ID);
        java.util.Map<String, Object> states = (java.util.Map<String, Object>) block.get("states");
        java.util.Map<String, Object> props = (java.util.Map<String, Object>) states.get("properties");
        assertThat(props.keySet()).containsExactly("lit", "smoke_level", "axis");
        assertThat(props.get("smoke_level")).isEqualTo(java.util.Map.of("type", "int", "range", "0~" + smokeMax, "default", 0));
        assertThat(yaml).as("no campfire look: lit campfires make client smoke").doesNotContain("lit=true,signal");
        java.util.Map<String, Object> appearances = (java.util.Map<String, Object>) states.get("appearances");
        assertThat(appearances.keySet()).containsExactly("lit_x", "lit_z", "unlit_x", "unlit_z");
        String carrier = dev.tfp.datagen.hitbox.HitboxAllocation.agreed(Pot.BLOCK_ID, "lit_x").state();
        for (String lit : List.of("lit", "unlit")) {
            for (String axis : List.of("x", "z")) {
                java.util.Map<String, Object> a = (java.util.Map<String, Object>) appearances.get(lit + "_" + axis);
                assertThat(a.get("state")).isEqualTo(carrier);
                assertThat(a.get("transparent")).isEqualTo(true);
                assertThat(a).doesNotContainKey("model");
                assertThat(a.get("entity_renderer")).isEqualTo(List.of(java.util.Map.of("item", "tfp:render/pot_" + lit,
                    "rotation", axis.equals("x") ? "0,180,0" : "0,90,0")));
            }
        }
        java.util.Map<String, Object> variants = (java.util.Map<String, Object>) states.get("variants");
        assertThat(variants).hasSize(2 * (smokeMax + 1) * 2);
        assertThat(variants.get("lit=true,smoke_level=0,axis=z"))
            .isEqualTo(java.util.Map.of("appearance", "lit_z", "settings", java.util.Map.of("luminance", 15)));
        assertThat(variants.get("lit=false,smoke_level=" + smokeMax + ",axis=x"))
            .isEqualTo(java.util.Map.of("appearance", "unlit_x", "settings", java.util.Map.of("luminance", 0)));
        java.util.Map<String, Object> items = (java.util.Map<String, Object>) root.get("items");
        assertThat(items.keySet()).containsExactly("tfp:render/pot_lit", "tfp:render/pot_unlit");
        assertThat(items.get("tfp:render/pot_lit")).isEqualTo(java.util.Map.of("template", "tfp:item/render",
            "arguments", java.util.Map.of("render_model", "tfp:block/pot_lit")));
        assertThat(FirepitTest.drops(block.get("loot"))).isEqualTo(FirepitTest.DROPS.get(Pot.BLOCK_ID));
        java.util.Map<String, Object> settings = (java.util.Map<String, Object>) block.get("settings");
        assertThat(settings.get("hardness")).isEqualTo(0.4);
        assertThat(settings.get("tags")).isEqualTo(List.of("minecraft:mineable/pickaxe"));
    }

    /**
     * PAR-HEAT-37: TFC's multipart merged per lit value: firepit_pot's elements then firepit_lit_low's or firepit_unlit's,
     * the textures of both (our names), every TFC texture written.
     */
    @Test
    void mergedModelsAreThePotOverTheFire() {
        TfcCheckout tfc = FirepitTest.realCheckout();
        assertThat(Pot.parts(tfc, true)).containsExactly("block/firepit_pot", "block/firepit_lit_low");
        assertThat(Pot.parts(tfc, false)).containsExactly("block/firepit_pot", "block/firepit_unlit");
        OutputTree out = new OutputTree();
        Pot.run(tfc, out);
        for (boolean lit : new boolean[] {true, false}) {
            String path = AssetPipeline.RP + "models/block/pot_" + (lit ? "lit" : "unlit") + ".json";
            com.google.gson.JsonObject m = com.google.gson.JsonParser.parseString(
                new String(out.get(path), StandardCharsets.UTF_8)).getAsJsonObject();
            int pot = com.google.gson.JsonParser.parseString(tfc.readString(TfcCheckout.ASSETS + "models/block/firepit_pot.json"))
                .getAsJsonObject().getAsJsonArray("elements").size();
            int fire = com.google.gson.JsonParser.parseString(tfc.readString(TfcCheckout.ASSETS + "models/"
                + (lit ? "block/firepit_lit_low" : "block/firepit_unlit") + ".json")).getAsJsonObject()
                .getAsJsonArray("elements").size();
            assertThat(m.getAsJsonArray("elements")).hasSize(pot + fire);
            com.google.gson.JsonObject tex = m.getAsJsonObject("textures");
            assertThat(tex.get("pot_side").getAsString()).isEqualTo("tfp:block/ceramic/large_vessel/side");
            assertThat(m.toString()).doesNotContain("tfc:");
            for (var t : tex.entrySet()) {
                String ref = t.getValue().getAsString();
                if (ref.startsWith("tfp:")) {
                    assertThat(out.get(AssetPipeline.RP + "textures/" + ref.substring(4) + ".png")).as(ref).isNotNull();
                }
            }
        }
    }

    @Test
    void fixtureStatesFollowTheInheritedDefinitionAndTheSmokeRangeOfTheSource() throws IOException {
        Path root = checkout();
        FirepitTest.writeFirepit(root, 2, FirepitTest.DEFINITION, FirepitTest.allVisualVariants());
        writePot(root, CLASS_SOURCE, blockstate(PARTS));
        OutputTree out = new OutputTree();

        assertThat(Pot.run(TfcCheckout.open(root, PIN), out)).isEqualTo(2 * 3 * 2);
        assertEntry(new String(out.get(Pot.OUTPUT), StandardCharsets.UTF_8), 2);
    }

    @Test
    void missingPotSourceIsRefused() throws IOException {
        Path root = checkout();
        FirepitTest.writeFirepit(root, 4, FirepitTest.DEFINITION, FirepitTest.allVisualVariants());
        writeBlockstate(root, PARTS);
        assertThatThrownBy(() -> Pot.run(TfcCheckout.open(root, PIN), new OutputTree()))
            .isInstanceOf(DatagenException.class).hasMessageContaining(Pot.SOURCE);
    }

    @Test
    void potNotExtendingTheFirepitIsRefused() throws IOException {
        Path root = checkout();
        FirepitTest.writeFirepit(root, 4, FirepitTest.DEFINITION, FirepitTest.allVisualVariants());
        writePot(root, CLASS_SOURCE.replace("extends FirepitBlock", "extends Block"), blockstate(PARTS));
        assertThatThrownBy(() -> Pot.run(TfcCheckout.open(root, PIN), new OutputTree()))
            .isInstanceOf(DatagenException.class).hasMessageContaining("does not extend FirepitBlock");
    }

    @Test
    void potDeclaringItsOwnStateIsRefused() throws IOException {
        Path root = checkout();
        FirepitTest.writeFirepit(root, 4, FirepitTest.DEFINITION, FirepitTest.allVisualVariants());
        String own = CLASS_SOURCE.replace("public PotBlock(ExtendedProperties properties)",
            "@Override\n    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder)\n    {\n"
                + "        builder.add(LIT, AXIS);\n    }\n\n    public PotBlock(ExtendedProperties properties)");
        writePot(root, own, blockstate(PARTS));
        assertThatThrownBy(() -> Pot.run(TfcCheckout.open(root, PIN), new OutputTree()))
            .isInstanceOf(DatagenException.class).hasMessageContaining("declares its own block state definition");
    }

    @Test
    void missingBlockstateIsRefused() throws IOException {
        Path root = checkout();
        FirepitTest.writeFirepit(root, 4, FirepitTest.DEFINITION, FirepitTest.allVisualVariants());
        writePot(root, CLASS_SOURCE, blockstate(PARTS));
        Files.delete(root.resolve(Pot.BLOCKSTATE));
        assertThatThrownBy(() -> Pot.run(TfcCheckout.open(root, PIN), new OutputTree()))
            .isInstanceOf(DatagenException.class).hasMessageContaining(Pot.BLOCKSTATE);
    }

    @Test
    void stateWithoutAPartIsRefused() throws IOException {
        Path root = checkout();
        FirepitTest.writeFirepit(root, 4, FirepitTest.DEFINITION, FirepitTest.allVisualVariants());
        writePot(root, CLASS_SOURCE, blockstate(List.of(PARTS.get(0), PARTS.get(2), PARTS.get(3), PARTS.get(4))));
        assertThatThrownBy(() -> Pot.run(TfcCheckout.open(root, PIN), new OutputTree()))
            .isInstanceOf(DatagenException.class).hasMessageContaining("lit=false,smoke_level=0,axis=z");
    }

    @Test
    void partNamingAnotherPropertyIsRefused() throws IOException {
        Path root = checkout();
        FirepitTest.writeFirepit(root, 4, FirepitTest.DEFINITION, FirepitTest.allVisualVariants());
        List<String> parts = new java.util.ArrayList<>(PARTS);
        parts.add("{\"when\": {\"facing\": \"north\"}, \"apply\": {\"model\": \"tfc:block/firepit_pot\"}}");
        writePot(root, CLASS_SOURCE, blockstate(parts));
        assertThatThrownBy(() -> Pot.run(TfcCheckout.open(root, PIN), new OutputTree()))
            .isInstanceOf(DatagenException.class).hasMessageContaining("part names facing");
    }

    /** The default part, added to {@link Fixture#create}: the TFC pot class and its multipart blockstate. */
    static void addDefault(Path root) throws IOException {
        writePot(root, CLASS_SOURCE, blockstate(PARTS));
    }

    static String blockstate(List<String> parts) {
        return "{\"__comment__\": \"x\", \"multipart\": [" + String.join(", ", parts) + "]}";
    }

    static void writePot(Path root, String classSource, String blockstate) throws IOException {
        Fixture.write(root, Pot.SOURCE, classSource);
        Fixture.write(root, Pot.BLOCKSTATE, blockstate);
        FirepitTest.writeDeviceData(root, FirepitTest.registration("POT", "pot", "PotBlock"), "pot", "pickaxe",
            List.of("tfc:powder/wood_ash", "tfc:ceramic/pot"));
    }

    static void writeBlockstate(Path root, List<String> parts) throws IOException {
        Fixture.write(root, Pot.BLOCKSTATE, blockstate(parts));
    }

    /** A checkout at the pinned commit with no firepit or pot sources yet. */
    private Path checkout() throws IOException {
        Path root = tmp.resolve("tfc");
        Fixture.write(root, ".git/HEAD", PIN + "\n");
        return root;
    }
}
