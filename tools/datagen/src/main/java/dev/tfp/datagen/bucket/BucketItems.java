package dev.tfp.datagen.bucket;

import com.google.gson.JsonObject;
import dev.tfp.core.fluid.TfcFluid;
import dev.tfp.core.fluid.TfcFluids;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import dev.tfp.datagen.material.TfcItemRegistry;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * PAR-FLUID-02: TFC's buckets as CraftEngine items ({@code configuration/bucket.yml}).
 *
 * <ul>
 *   <li>The tank buckets {@code tfp:wooden_bucket}, {@code tfp:metal/bucket/red_steel} and
 *       {@code tfp:metal/bucket/blue_steel}. TFC draws them with its {@code tfc:fluid_container} model loader: the base
 *       texture plus the {@code fluid} mask tinted with the contained fluid. Here the item model is a
 *       {@code minecraft:condition} on {@code custom_model_data} flag 0 (set by the runtime while the bucket holds fluid):
 *       true takes a two-layer model whose mask layer is tinted with {@code custom_model_data} colour 0 (the fluid tint),
 *       false the base texture. They stack to 16 (TFC {@code item_size/buckets}: medium weight); a filled one stacks to 1
 *       (the runtime's {@code FluidPdc}).</li>
 *   <li>TFC's per-fluid vanilla buckets {@code tfp:bucket/<fluid>} ({@code FLUID_BUCKETS}, {@code BucketItem}s, stack 1).
 *       TFC draws them with NeoForge's {@code neoforge:fluid_container} loader over the vanilla bucket. NeoForge's mask is
 *       not EUPL, so here the vanilla bucket texture carries TFC's metal bucket mask ({@code item/metal/bucket/overlay})
 *       tinted with a constant of the fluid's tint (ledger divergence).</li>
 * </ul>
 * Names come from TFC's lang files ({@code assets/tfp_bucket/lang}), except the ones the asset pipeline's {@code tfp}
 * lang already has. A missing texture, name, or a bucket fluid that {@link TfcFluids} does not know is an error.
 */
public final class BucketItems {
    static final String PACK = "craftengine/tfp/";
    static final String CONFIG = PACK + "configuration/bucket.yml";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    static final String LANG_NS = "tfp_bucket";
    static final String LANG_RP = PACK + "resourcepack/assets/" + LANG_NS + "/lang/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String ITEMS_SOURCE = "src/main/java/net/dries007/tfc/common/items/TFCItems.java";
    static final String TEXTURES = TfcCheckout.ASSETS + "textures/";
    /** TFC {@code item_size/buckets.json}: {@code weight: medium} = 16. */
    static final int TANK_STACK = 16;
    static final String FLUID_MASK = "item/metal/bucket/overlay";

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (PAR-FLUID-02, dev.tfp.datagen.bucket). Do not edit: fix the "
        + "generator and regenerate.";

    /** One tank bucket: our id and its TFC base and fluid-mask textures. */
    record Tank(String id, String base, String mask) {
    }

    /** TFC's {@code models/item/<id>.json} textures of the three {@code tfc:fluid_container} buckets. */
    static final List<Tank> TANKS = List.of(
        new Tank("wooden_bucket", "item/bucket/wooden_bucket_empty", "item/bucket/wooden_bucket_overlay"),
        new Tank("metal/bucket/red_steel", "item/metal/bucket/red_steel", FLUID_MASK),
        new Tank("metal/bucket/blue_steel", "item/metal/bucket/blue_steel", FLUID_MASK));

    private BucketItems() {
    }

    /** Whether the checkout has {@code TFCItems} and the bucket textures (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(ITEMS_SOURCE) && tfc.exists(TEXTURES + FLUID_MASK + ".png");
    }

    /** The {@code tfp:bucket/<fluid>} paths ({@code bucket/brine}), in TFC registration order. */
    static List<String> fluidBuckets(TfcCheckout tfc) {
        for (TfcItemRegistry.Registration r : TfcItemRegistry.registrations(tfc)) {
            if (r.field().equals("FLUID_BUCKETS")) {
                if (!r.factory().contains("new BucketItem(")) {
                    throw new DatagenException("TFCItems.FLUID_BUCKETS are no longer BucketItems: " + r.factory());
                }
                return r.ids();
            }
        }
        throw new DatagenException(ITEMS_SOURCE + " no longer has FLUID_BUCKETS (update BucketItems)");
    }

    /** The fluid of a {@code bucket/<fluid>} path. */
    static TfcFluid fluidOf(String bucketPath) {
        String id = Json.TO_NS + ":" + bucketPath.substring("bucket/".length());
        return TfcFluids.get(id).orElseThrow(() -> new DatagenException("bucket " + bucketPath + ": unknown fluid " + id));
    }

    /** Writes the items, models, textures and names. Returns the item paths. */
    public static List<String> run(TfcCheckout tfc, OutputTree out) {
        Map<String, Object> items = new LinkedHashMap<>();
        List<String> ids = new ArrayList<>();
        for (Tank t : TANKS) {
            copyTexture(tfc, out, t.base());
            copyTexture(tfc, out, t.mask());
            out.put(RP + "models/item/" + t.id() + ".json", Json.write(generated(t.base(), null)));
            out.put(RP + "models/item/" + t.id() + "_filled.json", Json.write(generated(t.base(), t.mask())));
            items.put(Json.TO_NS + ":" + t.id(), tankEntry(t.id()));
            ids.add(t.id());
        }
        for (String path : fluidBuckets(tfc)) {
            TfcFluid fluid = fluidOf(path);
            out.put(RP + "models/item/" + path + ".json", Json.write(vanillaBucket()));
            items.put(Json.TO_NS + ":" + path, fluidBucketEntry(path, fluid));
            ids.add(path);
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", items);
        out.put(CONFIG, Yaml.write(HEADER, root));
        writeLang(tfc, out, ids);
        return ids;
    }

    static String langKey(String path) {
        return "item." + Json.TO_NS + "." + path.replace('/', '.');
    }

    /** {@code item/generated} with {@code layer0} = base and, if given, {@code layer1} = mask (tint index 1). */
    static JsonObject generated(String base, String mask) {
        JsonObject m = new JsonObject();
        m.addProperty("parent", "minecraft:item/generated");
        JsonObject tex = new JsonObject();
        tex.addProperty("layer0", Json.TO_NS + ":" + base);
        if (mask != null) {
            tex.addProperty("layer1", Json.TO_NS + ":" + mask);
        }
        m.add("textures", tex);
        return m;
    }

    /** The vanilla bucket with TFC's metal bucket mask on top. */
    static JsonObject vanillaBucket() {
        JsonObject m = new JsonObject();
        m.addProperty("parent", "minecraft:item/generated");
        JsonObject tex = new JsonObject();
        tex.addProperty("layer0", "minecraft:item/bucket");
        tex.addProperty("layer1", Json.TO_NS + ":" + FLUID_MASK);
        m.add("textures", tex);
        return m;
    }

    static Map<String, Object> tankEntry(String id) {
        Map<String, Object> filled = new LinkedHashMap<>();
        filled.put("type", "minecraft:model");
        filled.put("path", Json.TO_NS + ":item/" + id + "_filled");
        Map<String, Object> fluidTint = new LinkedHashMap<>();
        fluidTint.put("type", "minecraft:custom_model_data");
        fluidTint.put("index", 0);
        fluidTint.put("default", 0xFFFFFF);
        filled.put("tints", List.of(constant(0xFFFFFF), fluidTint));
        Map<String, Object> empty = new LinkedHashMap<>();
        empty.put("type", "minecraft:model");
        empty.put("path", Json.TO_NS + ":item/" + id);
        Map<String, Object> model = new LinkedHashMap<>();
        model.put("type", "minecraft:condition");
        model.put("property", "minecraft:custom_model_data");
        model.put("index", 0);
        model.put("on_true", filled);
        model.put("on_false", empty);
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("item_name", "<!i><lang:" + langKey(id) + ">");
        data.put("max_stack_size", TANK_STACK);
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("material", "paper");
        e.put("data", data);
        e.put("model", model);
        return e;
    }

    static Map<String, Object> fluidBucketEntry(String path, TfcFluid fluid) {
        Map<String, Object> model = new LinkedHashMap<>();
        model.put("type", "minecraft:model");
        model.put("path", Json.TO_NS + ":item/" + path);
        model.put("tints", List.of(constant(0xFFFFFF), constant(fluid.rgb())));
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("item_name", "<!i><lang:" + langKey(path) + ">");
        data.put("max_stack_size", 1);
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("material", "paper");
        e.put("data", data);
        e.put("model", model);
        return e;
    }

    private static Map<String, Object> constant(int rgb) {
        Map<String, Object> t = new LinkedHashMap<>();
        t.put("type", "minecraft:constant");
        t.put("value", rgb);
        return t;
    }

    private static void copyTexture(TfcCheckout tfc, OutputTree out, String path) {
        String png = TEXTURES + path + ".png";
        if (!tfc.exists(png)) {
            throw new DatagenException("missing bucket texture " + png);
        }
        out.put(RP + "textures/" + path + ".png", tfc.read(png));
    }

    /** TFC's names of the items in every locale that has them (English must have all). */
    private static void writeLang(TfcCheckout tfc, OutputTree out, List<String> ids) {
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            byte[] pipeline = out.get(RP + "lang/" + locale + ".json");
            JsonObject named = pipeline == null ? new JsonObject()
                : Json.parse(new String(pipeline, StandardCharsets.UTF_8), RP + "lang").getAsJsonObject();
            TreeMap<String, String> keys = new TreeMap<>();
            for (String id : ids) {
                String tfcKey = "item." + Json.FROM_NS + "." + id.replace('/', '.');
                if (named.has(langKey(id))) {
                    continue;
                }
                if (src.has(tfcKey)) {
                    keys.put(langKey(id), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC item tfc:" + id + " has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }
}
