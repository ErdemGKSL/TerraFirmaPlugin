package dev.tfp.datagen.salad;

import dev.tfp.core.gui.ChestGeometry;
import dev.tfp.core.gui.GuiImage;
import dev.tfp.core.salad.SaladScreen;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.util.LinkedHashMap;
import java.util.Map;
import javax.imageio.ImageIO;

/**
 * PAR-PROC-36: the salad screen's art (TFC {@code SaladScreen}) for a 3-row chest, in the layout of {@link SaladScreen}
 * ({@code configuration/salad/salad_gui.yml}, image {@code tfp:gui/salad}). TFC's {@code salad.png} is re-laid in
 * bands: the five input frames and the bracket under them move up {@link SaladScreen#DY_INPUTS} onto chest row 0, the
 * bowl frame, the bowl picture and the salad frame move up {@link SaladScreen#DY_BOWLS} onto chest row 2, the player
 * inventory moves down {@link SaladScreen#DY_PLAYER}; every other row is TFC's plain panel row.
 */
public final class SaladArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/salad.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/SaladScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/SaladContainer.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/salad/salad_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    private SaladArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(SCREEN) && tfc.exists(CONTAINER);
    }

    /** Writes the image and its YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE), TEXTURE);
        GuiImage image = SaladScreen.BACKGROUND;
        BufferedImage png = background(src);
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        Map<String, Object> images = new LinkedHashMap<>();
        images.put(image.id(), e);
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The 176 x 168 window. */
    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = SaladScreen.CHEST.height();
        int th = SaladScreen.TFC_HEIGHT;
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < h; y++) {
            copy(src, out, 0, SaladScreen.PLAIN_ROW, w, 1, 0, y);
        }
        copy(src, out, 0, 0, w, 4, 0, 0); // top border
        copy(src, out, 0, SaladScreen.INPUT_BAND_START, w, SaladScreen.BOWL_BAND_START - SaladScreen.INPUT_BAND_START,
            0, SaladScreen.INPUT_BAND_START + SaladScreen.DY_INPUTS); // inputs and bracket
        copy(src, out, 0, SaladScreen.BOWL_BAND_START, w, SaladScreen.BOWL_BAND_END - SaladScreen.BOWL_BAND_START,
            0, SaladScreen.BOWL_BAND_START + SaladScreen.DY_BOWLS); // bowl, bowl picture, salad
        copy(src, out, 0, SaladScreen.PLAYER_BAND_START, w, th - 4 - SaladScreen.PLAYER_BAND_START,
            0, SaladScreen.PLAYER_BAND_START + SaladScreen.DY_PLAYER); // player inventory
        copy(src, out, 0, th - 4, w, 4, 0, h - 4); // bottom border
        return out;
    }

    /** TFC's numbers the layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        String screen = tfc.readString(SCREEN);
        need(container, CONTAINER, "new CallbackSlot(this, inventory, i, " + SaladScreen.TFC_INPUT_X + " + 18 * i, "
            + SaladScreen.TFC_INPUT_Y + ")");
        need(container, CONTAINER, "new CallbackSlot(this, inventory, SLOT_BOWLS, " + SaladScreen.TFC_BOWL_X + ", "
            + SaladScreen.TFC_BOWL_Y + ")");
        need(container, CONTAINER, "new CallbackSlot(this, inventory, SLOT_OUTPUT, " + SaladScreen.TFC_OUTPUT_X + ", "
            + SaladScreen.TFC_BOWL_Y + ")");
        need(container, CONTAINER, "SLOT_INPUT_END = " + SaladScreen.SLOT_INPUT_END + ";");
        need(container, CONTAINER, ".init(inventory)");
        need(screen, SCREEN, "Helpers.identifier(\"textures/gui/salad.png\")");
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the salad screen port is stale");
        }
    }

    static BufferedImage read(byte[] bytes, String what) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(what + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
