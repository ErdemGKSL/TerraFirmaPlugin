package dev.tfp.paper.i18n;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.Properties;
import java.util.concurrent.ConcurrentHashMap;
import org.bukkit.command.CommandSender;
import org.bukkit.entity.Player;

/**
 * Server-side translations of our own messages (command replies, kick texts) (M1-SVC-04). Bundles are
 * UTF-8 {@code .properties} files in the jar under {@code lang/<locale>.properties}, with Minecraft's
 * locale codes ({@code en_us}, {@code tr_tr}); {@code lang/index.txt} lists the shipped locales.
 *
 * <p>Lookup: the exact locale → another shipped locale of the same language ({@code tr} → {@code tr_tr}) →
 * {@value #FALLBACK} → the key itself. Arguments replace {@code {0}}, {@code {1}}, ... literally
 * ({@link java.text.MessageFormat} is not used: its apostrophe quoting breaks Turkish text such as
 * {@code TerraFirmaPlugin'in}).
 *
 * <p>Client-side names (blocks, items) are not here: they go through CraftEngine's {@code lang:} section,
 * generated by datagen from TFC's lang files (M1-DGN).
 *
 * <p>Immutable after loading; bundles load lazily and are cached. Thread-safe.
 */
public final class Messages {
    public static final String FALLBACK = "en_us";
    static final String DIR = "lang/";

    private final ClassLoader loader;
    private final List<String> shipped;
    private final Map<String, Optional<Map<String, String>>> bundles = new ConcurrentHashMap<>();

    public Messages(ClassLoader loader) {
        this.loader = loader;
        this.shipped = List.copyOf(readIndex(loader));
        if (bundle(FALLBACK).isEmpty()) {
            throw new IllegalStateException(DIR + FALLBACK + ".properties is missing from the plugin jar");
        }
    }

    /** Messages from our own jar. */
    public static Messages fromJar() {
        return new Messages(Messages.class.getClassLoader());
    }

    /** The locales shipped in the jar (from {@code lang/index.txt}). */
    public List<String> locales() {
        return shipped;
    }

    /** Minecraft's locale code for {@code locale}: {@code tr_TR} → {@code tr_tr}. */
    public static String code(Locale locale) {
        String lang = locale.getLanguage().toLowerCase(Locale.ROOT);
        String country = locale.getCountry().toLowerCase(Locale.ROOT);
        return country.isEmpty() ? lang : lang + "_" + country;
    }

    /** The sender's locale code: a player's client locale, otherwise {@value #FALLBACK}. */
    public static String code(CommandSender sender) {
        return sender instanceof Player p ? code(p.locale()) : FALLBACK;
    }

    /** The message for {@code key} in {@code locale} (a code like {@code tr_tr}) with {@code args} filled in. */
    public String get(String locale, String key, Object... args) {
        String pattern = resolve(locale.toLowerCase(Locale.ROOT).replace('-', '_'), key);
        return format(pattern, args);
    }

    public String get(Locale locale, String key, Object... args) {
        return get(code(locale), key, args);
    }

    public String get(CommandSender sender, String key, Object... args) {
        return get(code(sender), key, args);
    }

    /** All keys of a shipped bundle (tests: completeness of translations). */
    public Map<String, String> bundleOf(String locale) {
        return bundle(locale).orElse(Map.of());
    }

    private String resolve(String locale, String key) {
        String v = bundle(locale).map(b -> b.get(key)).orElse(null);
        if (v == null) {
            int us = locale.indexOf('_');
            String lang = us < 0 ? locale : locale.substring(0, us);
            for (String other : shipped) {
                if (!other.equals(locale) && other.startsWith(lang + "_")) {
                    v = bundle(other).map(b -> b.get(key)).orElse(null);
                    if (v != null) {
                        break;
                    }
                }
            }
        }
        if (v == null) {
            v = bundle(FALLBACK).map(b -> b.get(key)).orElse(null);
        }
        return v != null ? v : key;
    }

    static String format(String pattern, Object... args) {
        if (args.length == 0 || pattern.indexOf('{') < 0) {
            return pattern;
        }
        StringBuilder sb = new StringBuilder(pattern.length() + 16);
        int i = 0;
        while (i < pattern.length()) {
            char c = pattern.charAt(i);
            if (c == '{') {
                int close = pattern.indexOf('}', i);
                if (close > i + 1) {
                    String idx = pattern.substring(i + 1, close);
                    if (idx.chars().allMatch(Character::isDigit) && idx.length() < 3) {
                        int n = Integer.parseInt(idx);
                        if (n < args.length) {
                            sb.append(args[n]);
                            i = close + 1;
                            continue;
                        }
                    }
                }
            }
            sb.append(c);
            i++;
        }
        return sb.toString();
    }

    private Optional<Map<String, String>> bundle(String locale) {
        return bundles.computeIfAbsent(locale, l -> load(loader, l));
    }

    private static Optional<Map<String, String>> load(ClassLoader loader, String locale) {
        if (!locale.matches("[a-z]{2,3}(_[a-z0-9]{2,8})?")) {
            return Optional.empty();
        }
        try (InputStream in = loader.getResourceAsStream(DIR + locale + ".properties")) {
            if (in == null) {
                return Optional.empty();
            }
            Properties p = new Properties();
            try (Reader r = new InputStreamReader(in, StandardCharsets.UTF_8)) {
                p.load(r);
            }
            Map<String, String> m = new HashMap<>();
            for (String k : p.stringPropertyNames()) {
                m.put(k, p.getProperty(k));
            }
            return Optional.of(Map.copyOf(m));
        } catch (IOException e) {
            throw new UncheckedIOException("cannot read " + DIR + locale + ".properties", e);
        }
    }

    private static List<String> readIndex(ClassLoader loader) {
        List<String> out = new ArrayList<>();
        try (InputStream in = loader.getResourceAsStream(DIR + "index.txt")) {
            if (in == null) {
                return List.of(FALLBACK);
            }
            for (String line : new String(in.readAllBytes(), StandardCharsets.UTF_8).split("\\R")) {
                String l = line.strip();
                if (!l.isEmpty() && !l.startsWith("#")) {
                    out.add(l);
                }
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return out;
    }
}
