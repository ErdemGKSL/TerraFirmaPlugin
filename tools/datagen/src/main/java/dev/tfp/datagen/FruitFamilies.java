package dev.tfp.datagen;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * M6-DECO-04 (data slice): TFC's fruit tree block kinds as CraftEngine-ready data. Every species of {@code FruitBlocks.Tree}
 * gets the five block kinds that TFC registers for it: the leaves, the branch, the growing branch, the sapling and the
 * potted sapling. The fruit itself is a food item, not a block, so no fruit block is generated.
 *
 * <p>The banana is a separate TFC plant ({@code BananaSaplingBlock}, {@code BananaPlantBlock}), not a {@code Tree} species,
 * so it is left out. The growth data of each species (days to grow, lifecycle) and the visuals are not part of this output.
 *
 * <p>The output is {@code craftengine/tfp/families/fruit_tree.yml}, outside the CraftEngine {@code configuration/} folder,
 * so CraftEngine does not load it. The {@code kind} is the registration suffix of TFC's block ({@code leaves},
 * {@code branch}, {@code growing_branch}, {@code sapling}, {@code potted_sapling}), and {@code item} says whether TFC
 * registers a block item for it. Ids are the TFC blockstate paths in our namespace. A missing source, registration or
 * blockstate is an error, so a TFC change shows up here.
 */
final class FruitFamilies {
    static final String TREE_SOURCE = "src/main/java/net/dries007/tfc/common/blocks/plant/fruit/FruitBlocks.java";
    static final String BLOCKS_SOURCE = "src/main/java/net/dries007/tfc/common/blocks/TFCBlocks.java";
    static final String BLOCKSTATES = TfcCheckout.ASSETS + "blockstates/";
    static final String OUTPUT = AssetPipeline.PACK + "families/fruit_tree.yml";

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";
    private static final String PLANT = "plant/";
    private static final Pattern TREE_CONSTANT = Pattern.compile("^ {8}([A-Z_]+)\\(Food\\.", Pattern.MULTILINE);
    /** One {@code FRUIT_TREE_*} registration: {@code register} (with a block item) or {@code registerNoItem}, its path prefix and suffix. */
    private static final Pattern REGISTRATION = Pattern.compile("Map<FruitBlocks\\.Tree, Id<Block>> FRUIT_TREE_[A-Z_]+ = "
        + "Helpers\\.mapOf\\(FruitBlocks\\.Tree\\.class, tree -> (registerNoItem|register)\\(\"(plant/(?:potted/)?)\" \\+ tree\\.name\\(\\) \\+ \"(_[a-z_]+)\"");

    /**
     * One block kind that TFC registers for every species.
     *
     * @param name   the kind, e.g. {@code sapling} or {@code potted_sapling}
     * @param prefix the blockstate path before the species, {@code plant/} or {@code plant/potted/}
     * @param suffix the blockstate path after the species, with its leading underscore
     * @param item   whether TFC registers a block item for it
     */
    record Kind(String name, String prefix, String suffix, boolean item) {
    }

    /** One block of a species: its kind, whether it has an item, and the TFC blockstate path. */
    record Block(String kind, boolean item, String path) {
    }

    /** One species (serialized name) and its blocks in {@link #kinds} order. */
    record Family(String species, List<Block> blocks) {
    }

    private FruitFamilies() {
    }

    /** Writes the family data. Returns the number of blocks. Fails when the checkout lacks a source, a registration or a blockstate. */
    static int run(TfcCheckout tfc, OutputTree out) {
        List<Family> families = families(tfc);
        out.put(OUTPUT, Yaml.write(HEADER, yaml(families)));
        return families.stream().mapToInt(f -> f.blocks().size()).sum();
    }

    /**
     * The species of the checkout, in TFC's declaration order, each with its blocks. Fails when the sources do not match
     * what this generator reads, or a blockstate of a kind is missing for a species.
     */
    static List<Family> families(TfcCheckout tfc) {
        if (!tfc.exists(TREE_SOURCE)) {
            throw new DatagenException("TFC checkout has no " + TREE_SOURCE);
        }
        if (!tfc.exists(BLOCKS_SOURCE)) {
            throw new DatagenException("TFC checkout has no " + BLOCKS_SOURCE);
        }
        List<String> species = species(tfc.readString(TREE_SOURCE));
        List<Kind> kinds = kinds(tfc.readString(BLOCKS_SOURCE));

        List<Family> out = new ArrayList<>();
        for (String s : species) {
            List<Block> blocks = new ArrayList<>();
            for (Kind k : kinds) {
                String path = k.prefix() + s + k.suffix();
                if (!tfc.exists(BLOCKSTATES + path + ".json")) {
                    throw new DatagenException("TFC has no blockstate " + path + " for fruit tree " + s);
                }
                blocks.add(new Block(k.name(), k.item(), path));
            }
            out.add(new Family(s, blocks));
        }
        return out;
    }

    /**
     * The {@code FruitBlocks.Tree} species, lowercase, in declaration order. Fails when the enum is missing or empty.
     */
    static List<String> species(String text) {
        String body = section(text, TREE_SOURCE, "public enum Tree implements");
        List<String> out = new ArrayList<>();
        Matcher m = TREE_CONSTANT.matcher(body);
        while (m.find()) {
            out.add(m.group(1).toLowerCase(Locale.ROOT));
        }
        if (out.isEmpty()) {
            throw new DatagenException(TREE_SOURCE + ": no constants in public enum Tree");
        }
        return out;
    }

    /**
     * The block kinds TFC registers per species, in declaration order. A kind is named after its suffix, with the
     * {@code potted/} folder of the potted kinds folded in, so {@code plant/potted/<s>_sapling} is {@code potted_sapling}.
     * Fails when there is no {@code FRUIT_TREE_*} registration, or two registrations share a name.
     */
    static List<Kind> kinds(String text) {
        List<Kind> out = new ArrayList<>();
        Matcher m = REGISTRATION.matcher(text);
        while (m.find()) {
            String prefix = m.group(2);
            String suffix = m.group(3);
            String name = prefix.substring(PLANT.length()).replace("/", "_") + suffix.substring(1);
            for (Kind k : out) {
                if (k.name().equals(name)) {
                    throw new DatagenException(BLOCKS_SOURCE + ": two fruit tree registrations are named " + name);
                }
            }
            out.add(new Kind(name, prefix, suffix, m.group(1).equals("register")));
        }
        if (out.isEmpty()) {
            throw new DatagenException(BLOCKS_SOURCE + ": no FRUIT_TREE_ registration of FruitBlocks.Tree");
        }
        return out;
    }

    /** The text from {@code enumDecl} to the first semicolon after it: the enum's constant list. */
    static String section(String text, String source, String enumDecl) {
        int start = text.indexOf(enumDecl);
        if (start < 0) {
            throw new DatagenException(source + ": no " + enumDecl);
        }
        int end = text.indexOf(';', start);
        if (end < 0) {
            throw new DatagenException(source + ": " + enumDecl + " has no end");
        }
        return text.substring(start, end);
    }

    /** {@code families: <species>: blocks: [{kind, item, id, tfc}]}, ids in our namespace, TFC's in {@code tfc:}. */
    static Map<String, Object> yaml(List<Family> families) {
        Map<String, Object> bySpecies = new LinkedHashMap<>();
        for (Family f : families) {
            List<Object> blocks = new ArrayList<>();
            for (Block b : f.blocks()) {
                Map<String, Object> m = new LinkedHashMap<>();
                m.put("kind", b.kind());
                m.put("item", b.item());
                m.put("id", Json.TO_NS + ":" + b.path());
                m.put("tfc", Json.FROM_NS + ":" + b.path());
                blocks.add(m);
            }
            Map<String, Object> family = new LinkedHashMap<>();
            family.put("blocks", blocks);
            bySpecies.put(f.species(), family);
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("families", bySpecies);
        return root;
    }
}
