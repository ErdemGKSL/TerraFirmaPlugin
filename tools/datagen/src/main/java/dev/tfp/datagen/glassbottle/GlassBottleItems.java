package dev.tfp.datagen.glassbottle;

import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * PAR-POT-12: the four glass bottles as CraftEngine items ({@code configuration/glassbottle.yml}) and the fluid overlay of the
 * jug.
 *
 * <p>TFC draws the bottles and the jug with its {@code tfc:fluid_container} loader (base texture plus a {@code fluid} mask tinted
 * with the contained fluid). Here the item model is a {@code minecraft:condition} on {@code custom_model_data} flag 0, which
 * the runtime sets while the container holds fluid ({@code BucketVisuals.sync}): true takes a two-layer model whose mask layer
 * is tinted with colour 0 (the fluid tint), false the base texture, the same as the tank buckets of PAR-FLUID-02.
 * The bottles stack to 64 when empty like TFC's {@code FluidContainerItem} (a filled one to 1: the runtime's {@code FluidPdc}).
 * The jug entry is written by {@code PotteryItems} (PAR-POT-02) as a plain item; this pass adds the {@code model} to it.
 */
public final class GlassBottleItems {
    static final String PACK = "craftengine/tfp/";
    static final String CONFIG = PACK + "configuration/glassbottle.yml";
    static final String JUG_CONFIG = PACK + "configuration/pottery/ceramic.yml";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    static final String LANG_NS = "tfp_glassbottle";
    static final String LANG_RP = PACK + "resourcepack/assets/" + LANG_NS + "/lang/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String TEXTURES = TfcCheckout.ASSETS + "textures/";
    static final String OVERLAY = "item/bucket/glass_bottle_overlay";
    static final String JUG = "ceramic/jug";
    static final String JUG_BASE = "item/ceramic/jug_empty";
    static final String JUG_OVERLAY = "item/ceramic/jug_overlay";
    static final int STACK = 64;
    /** TFC's glass types with a bottle ({@code TFCItems.*_GLASS_BOTTLE}). */
    static final List<String> IDS = List.of("silica_glass_bottle", "hematitic_glass_bottle", "volcanic_glass_bottle",
        "olivine_glass_bottle");

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (PAR-POT-12, dev.tfp.datagen.glassbottle). Do not edit: fix the "
        + "generator and regenerate.";

    private GlassBottleItems() {
    }

    /** Whether the checkout has the bottle and jug textures (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURES + OVERLAY + ".png") && tfc.exists(TEXTURES + JUG_OVERLAY + ".png")
            && tfc.exists(TEXTURES + "item/bucket/silica_glass_bottle.png");
    }

    /** Writes the bottle items, models, textures, names and the jug overlay. Run after {@code PotteryItems}. */
    public static List<String> run(TfcCheckout tfc, OutputTree out) {
        Map<String, Object> items = new LinkedHashMap<>();
        copyTexture(tfc, out, OVERLAY);
        for (String id : IDS) {
            String base = "item/bucket/" + id;
            copyTexture(tfc, out, base);
            writeModels(out, id, base, OVERLAY);
            items.put(Json.TO_NS + ":" + id, entry(id));
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", items);
        out.put(CONFIG, Yaml.write(HEADER, root));
        writeLang(tfc, out);
        jugOverlay(tfc, out);
        return IDS;
    }

    static String langKey(String path) {
        return "item." + Json.TO_NS + "." + path.replace('/', '.');
    }

    private static void writeModels(OutputTree out, String id, String base, String mask) {
        out.put(RP + "models/item/" + id + "_filled.json", Json.write(generated(base, mask)));
        out.put(RP + "models/item/" + id + ".json", Json.write(generated(base, null)));
    }

    /** {@code item/generated} with {@code layer0} = base and, if given, {@code layer1} = mask (tint index 1). */
    static JsonObject generated(String base, String mask) {
        JsonObject m = new JsonObject();
        m.addProperty("parent", "minecraft:item/generated");
        JsonObject tex = new JsonObject();
        tex.addProperty("layer0", Json.TO_NS + ":" + base);
        if (mask != null) {
            tex.addProperty("layer1", Json.TO_NS + ":" + mask);
        }
        m.add("textures", tex);
        return m;
    }

    /** The item model: the filled model tinted by custom_model_data colour 0 while flag 0 is set. */
    static Map<String, Object> model(String id) {
        Map<String, Object> filled = new LinkedHashMap<>();
        filled.put("type", "minecraft:model");
        filled.put("path", Json.TO_NS + ":item/" + id + "_filled");
        Map<String, Object> white = new LinkedHashMap<>();
        white.put("type", "minecraft:constant");
        white.put("value", 0xFFFFFF);
        Map<String, Object> fluidTint = new LinkedHashMap<>();
        fluidTint.put("type", "minecraft:custom_model_data");
        fluidTint.put("index", 0);
        fluidTint.put("default", 0xFFFFFF);
        filled.put("tints", List.of(white, fluidTint));
        Map<String, Object> empty = new LinkedHashMap<>();
        empty.put("type", "minecraft:model");
        empty.put("path", Json.TO_NS + ":item/" + id);
        Map<String, Object> model = new LinkedHashMap<>();
        model.put("type", "minecraft:condition");
        model.put("property", "minecraft:custom_model_data");
        model.put("index", 0);
        model.put("on_true", filled);
        model.put("on_false", empty);
        return model;
    }

    static Map<String, Object> entry(String id) {
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("item_name", "<!i><lang:" + langKey(id) + ">");
        data.put("max_stack_size", STACK);
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("material", "paper");
        e.put("data", data);
        e.put("model", model(id));
        return e;
    }

    // ---- the jug ---------------------------------------------------------------------------------------------------------

    /** Adds the fluid overlay model (and its texture) and the {@code model} of the jug entry in {@code ceramic.yml}. */
    private static void jugOverlay(TfcCheckout tfc, OutputTree out) {
        copyTexture(tfc, out, JUG_BASE);
        copyTexture(tfc, out, JUG_OVERLAY);
        out.put(RP + "models/item/" + JUG + "_filled.json", Json.write(generated(JUG_BASE, JUG_OVERLAY)));
        byte[] yml = out.get(JUG_CONFIG);
        if (yml == null) {
            throw new DatagenException(JUG_CONFIG + " is missing: GlassBottleItems must run after PotteryItems");
        }
        Map<String, Object> wrapper = new LinkedHashMap<>();
        wrapper.put("model", model(JUG));
        String block = Yaml.write("x", wrapper).replaceFirst("^# x\n", "");
        StringBuilder indented = new StringBuilder();
        for (String line : block.split("\n")) {
            indented.append("    ").append(line).append('\n');
        }
        String edited = addModel(new String(yml, StandardCharsets.UTF_8), Json.TO_NS + ":" + JUG, indented.toString());
        out.replace(JUG_CONFIG, edited.getBytes(StandardCharsets.UTF_8));
    }

    /** Inserts {@code block} (already indented four spaces) as the last key of the entry {@code id}. */
    static String addModel(String text, String id, String block) {
        String[] in = text.split("\n", -1);
        List<String> res = new ArrayList<>();
        boolean done = false;
        for (int i = 0; i < in.length; i++) {
            res.add(in[i]);
            if (!in[i].equals("  " + id + ":")) {
                continue;
            }
            while (i + 1 < in.length && in[i + 1].startsWith("    ")) {
                res.add(in[++i]);
            }
            res.add(block.stripTrailing());
            done = true;
        }
        if (!done) {
            throw new DatagenException("pottery config has no entry " + id);
        }
        return String.join("\n", res);
    }

    private static void copyTexture(TfcCheckout tfc, OutputTree out, String path) {
        String png = TEXTURES + path + ".png";
        if (!tfc.exists(png)) {
            throw new DatagenException("missing glass bottle texture " + png);
        }
        String dest = RP + "textures/" + path + ".png";
        if (!out.contains(dest)) {
            out.put(dest, tfc.read(png));
        }
    }

    /** TFC's names of the bottles in every locale that has them (English must have all). */
    private static void writeLang(TfcCheckout tfc, OutputTree out) {
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            TreeMap<String, String> keys = new TreeMap<>();
            for (String id : IDS) {
                String tfcKey = "item." + Json.FROM_NS + "." + id;
                if (src.has(tfcKey)) {
                    keys.put(langKey(id), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC item tfc:" + id + " has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }
}
