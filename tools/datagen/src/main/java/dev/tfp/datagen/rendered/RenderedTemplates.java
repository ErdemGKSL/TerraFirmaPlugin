package dev.tfp.datagen.rendered;

import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * The shared CraftEngine templates of renderer-drawn full blocks (PAR-INFRA-17, spike S2), for the families whose look is
 * an {@code item_display} cube over an invisible full-cube hitbox (metal blocks, crates, mechanical blocks):
 *
 * <ul>
 *   <li>{@code tfp:settings/destroy_stages}: CraftEngine's {@code settings.destroy_stages}, ten display items over the
 *       vanilla crack textures {@code minecraft:block/destroy_stage_0..9}. The carrier is a barrier, which has no model,
 *       so the client draws no crack of its own; CraftEngine shows the stage of the server's dig progress to every viewer.
 *       Referenced from the client jar (never copied).</li>
 *   <li>{@code tfp:block/rendered_cube}: the whole block: TFC hardness, resistance, the five sound events of the TFC
 *       {@code SoundType} (CraftEngine replays them; the barrier's own stone sounds are silenced client-side), the
 *       {@code minecraft:mineable/<tool>} tag, the destroy stages, the barrier carrier with one cube display, and the
 *       break particles. A barrier has {@code noTerrainParticles}, so the client spawns no break particles: a
 *       {@code break} event sends {@code minecraft:item} particles of the block's own render item (the material colour,
 *       an explicit action). The caller writes {@code loot} and, for TFC's {@code requiresCorrectToolForDrops},
 *       {@code settings.correct_tools} beside the call (CraftEngine deep-merges them in).</li>
 * </ul>
 *
 * <p>The templates are written out in full and call no other template, so each expands in one step. Arguments carry the
 * {@code rendered_} prefix because the caller's argument always wins in CraftEngine templates.
 *
 * <p>View ranges ({@code view_range} x 64 m x the client's entity distance): the crack stages use {@value #VIEW_RANGE}
 * (48 m, the ore overlay cutoff of {@code ore-overlay.cutoff-blocks}). The cube itself uses {@value #CUBE_VIEW_RANGE}
 * (256 m, beyond any render distance), so it is drawn for as long as its chunk is: spike S2 showed that at the 48 m
 * cutoff a whole block vanishes and leaves a hole (the barrier carrier draws nothing), which is far worse than the
 * specks of an ore overlay popping on a drawn rock. The cube is spawned and removed with its chunk (CraftEngine
 * tracks renderers per chunk), the same moment the terrain appears, so no ring shows. Arguments may override it
 * ({@code rendered_view_range}).
 *
 * <p>Also written: the ten crack quads {@code tfp:item/render/overlay_crack_<n>} that the overlay-ore runtime
 * (PAR-INFRA-16) composes with an ore overlay quad into the cracked overlay variants ({@link CrackedOverlays}).
 */
public final class RenderedTemplates {
    public static final String OUTPUT = "craftengine/tfp/configuration/templates/rendered_block.yml";
    public static final String ITEMS_OUTPUT = "craftengine/tfp/configuration/rendered_block_items.yml";
    public static final String MODELS = "craftengine/tfp/resourcepack/assets/tfp/models/";
    public static final String CUBE = "tfp:block/rendered_cube";
    public static final String DESTROY_STAGES = "tfp:settings/destroy_stages";
    /** The invisible full-cube hitbox carrier (full collision and outline, no model, passes light, no occlusion). */
    public static final String CARRIER = "minecraft:barrier";
    public static final int STAGES = 10;
    public static final String VIEW_RANGE = "0.75";
    public static final String CUBE_VIEW_RANGE = "4.0";
    /** CraftEngine's own internal {@code destroy_stages} template uses 1.01: the crack shell sits outside the cube. */
    public static final String STAGE_SCALE = "1.01";
    /** Vanilla's {@code ParticleEngine.destroy} spawns 4 x 4 x 4 terrain particles per broken block. */
    public static final int BREAK_PARTICLES = 64;
    static final String ARG_HARDNESS = "rendered_hardness";
    static final String ARG_RESISTANCE = "rendered_resistance";
    static final String ARG_TOOL_TAG = "rendered_tool_tag";
    static final String ARG_ITEM = "rendered_item";
    static final String ARG_PARTICLE_ITEM = "rendered_particle_item";
    static final String ARG_VIEW_RANGE = "rendered_view_range";
    static final List<String> SOUND_KEYS = List.of("break", "step", "place", "hit", "fall");

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ " + TfcCheckout.PINNED_COMMIT.substring(0, 9)
        + ". Do not edit: fix the generator and regenerate.\n"
        + "tfp: renderer-drawn full block templates (PAR-INFRA-17). tfp:block/rendered_cube takes rendered_hardness,\n"
        + "rendered_resistance, rendered_sound_<event> (break, step, place, hit, fall), rendered_tool_tag, rendered_item (the\n"
        + "cube display) and rendered_particle_item (break particles); write loot (and correct_tools) beside the call.\n"
        + "tfp:settings/destroy_stages: the crack displays over the vanilla destroy_stage_0..9 textures.";

    private RenderedTemplates() {
    }

    /** Writes the templates, the destroy stage items and the overlay crack quads. */
    public static void run(OutputTree out) {
        out.put(OUTPUT, Yaml.write(HEADER, yaml()));
        out.put(ITEMS_OUTPUT, Yaml.write(HEADER, itemsYaml()));
        for (int n = 0; n < STAGES; n++) {
            out.put(MODELS + "item/render/overlay_crack_" + n + ".json", CrackedOverlays.crackQuadModel(n));
        }
    }

    /** {@code templates#rendered_block: {tfp:settings/destroy_stages, tfp:block/rendered_cube}}. */
    public static Map<String, Object> yaml() {
        Map<String, Object> templates = new LinkedHashMap<>();
        templates.put(DESTROY_STAGES, Map.of("destroy_stages", destroyStages()));
        templates.put(CUBE, cube());
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("templates#rendered_block", templates);
        return root;
    }

    /** The display-only crack items, one per stage. */
    public static Map<String, Object> itemsYaml() {
        Map<String, Object> items = new LinkedHashMap<>();
        for (int n = 0; n < STAGES; n++) {
            Map<String, Object> generation = new LinkedHashMap<>();
            generation.put("parent", "minecraft:block/cube_all");
            generation.put("textures", Map.of("all", crackTexture(n)));
            Map<String, Object> model = new LinkedHashMap<>();
            model.put("path", "tfp:item/render/destroy_stage_" + n);
            model.put("generation", generation);
            Map<String, Object> item = new LinkedHashMap<>();
            item.put("material", "paper");
            item.put("model", model);
            items.put(stageItem(n), item);
        }
        return Map.of("items", items);
    }

    /** {@code tfp:render/destroy_stage/<n>}. */
    public static String stageItem(int n) {
        return "tfp:render/destroy_stage/" + n;
    }

    /** The vanilla crack texture of stage {@code n}: {@code minecraft:block/destroy_stage_<n>}. */
    public static String crackTexture(int n) {
        if (n < 0 || n >= STAGES) {
            throw new IllegalArgumentException("destroy stage " + n);
        }
        return "minecraft:block/destroy_stage_" + n;
    }

    /** The template argument name of a sound event key. */
    static String soundArg(String event) {
        return "rendered_sound_" + event;
    }

    private static Map<String, Object> destroyStages() {
        List<String> items = new ArrayList<>();
        for (int n = 0; n < STAGES; n++) {
            items.add(stageItem(n));
        }
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("items", items);
        m.put("scale", new BigDecimal(STAGE_SCALE));
        m.put("view_range", new BigDecimal(VIEW_RANGE));
        return m;
    }

    private static Map<String, Object> cube() {
        Map<String, Object> sounds = new LinkedHashMap<>();
        SOUND_KEYS.forEach(k -> sounds.put(k, "${" + soundArg(k) + "}"));
        Map<String, Object> settings = new LinkedHashMap<>();
        settings.put("hardness", "${" + ARG_HARDNESS + "}");
        settings.put("resistance", "${" + ARG_RESISTANCE + "}");
        settings.put("sounds", sounds);
        settings.put("tags", List.of("${" + ARG_TOOL_TAG + "}"));
        settings.put("destroy_stages", destroyStages());
        Map<String, Object> display = new LinkedHashMap<>();
        display.put("item", "${" + ARG_ITEM + "}");
        display.put("view_range", "${" + ARG_VIEW_RANGE + ":-" + CUBE_VIEW_RANGE + "}");
        Map<String, Object> state = new LinkedHashMap<>();
        state.put("state", CARRIER);
        state.put("entity_renderer", List.of(display));
        Map<String, Object> particle = new LinkedHashMap<>();
        particle.put("type", "particle");
        particle.put("particle", "minecraft:item");
        particle.put("item", "${" + ARG_PARTICLE_ITEM + "}");
        particle.put("count", BREAK_PARTICLES);
        particle.put("offset_x", new BigDecimal("0.25"));
        particle.put("offset_y", new BigDecimal("0.25"));
        particle.put("offset_z", new BigDecimal("0.25"));
        particle.put("speed", new BigDecimal("0.05"));
        Map<String, Object> onBreak = new LinkedHashMap<>();
        onBreak.put("on", "break");
        onBreak.put("functions", List.of(particle));
        Map<String, Object> body = new LinkedHashMap<>();
        body.put("settings", settings);
        body.put("state", state);
        body.put("events", List.of(onBreak));
        return body;
    }
}
