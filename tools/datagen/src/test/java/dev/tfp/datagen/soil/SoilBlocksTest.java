    @Test
    @SuppressWarnings("unchecked")
    void grassBlocksShareTheTwoGrassBlockStatesWithOneLook() {
        List<String> grass = SoilBlocks.blockIds(tfc).stream().filter(SoilBlocks::isGrass).toList();
        assertThat(grass).hasSize(8 * 2 + 2);
        Object shared = null;
        for (String id : grass) {
            Map<String, Object> states = (Map<String, Object>) blocks.get("tfp:" + id).get("states");
            assertThat(blocks.get("tfp:" + id)).as(id).doesNotContainKey("state");
            // CraftEngine aborts a block whose model on a shared explicit state differs: byte-identical in every block.
            if (shared == null) {
                shared = states;
            }
            assertThat(states).as(id).isEqualTo(shared);
        }
        Map<String, Object> states = (Map<String, Object>) shared;
        Map<String, Object> props = (Map<String, Object>) states.get("properties");
        assertThat(props.keySet()).containsExactly("snowy");
        assertThat((Map<String, Object>) props.get("snowy")).containsEntry("type", "boolean").containsEntry("default", false);
        Map<String, Map<String, Object>> appearances = (Map<String, Map<String, Object>>) states.get("appearances");
        assertThat(appearances.keySet()).containsExactly("snowy_false", "snowy_true");
        assertThat(appearances.get("snowy_false").get("state")).isEqualTo("minecraft:grass_block[snowy=false]");
        assertThat(appearances.get("snowy_true").get("state")).isEqualTo("minecraft:grass_block[snowy=true]");
        // The allocator never hands these two states to another block or maps them away.
        assertThat(HideTargets.KEEP_VANILLA).containsExactlyInAnyOrderElementsOf(SoilBlocks.GRASS_STATES.values());
        assertThat(HideTargets.EXCLUDED).containsAll(SoilBlocks.GRASS_STATES.values());
        for (var e : Map.of("snowy_false", SoilBlocks.SHARED_MODEL, "snowy_true", SoilBlocks.SHARED_SNOWY_MODEL).entrySet()) {
            List<Map<String, Object>> models = (List<Map<String, Object>>) appearances.get(e.getKey()).get("models");
            assertThat(models).hasSize(4).allMatch(m -> m.get("path").equals(e.getValue()));
            // TFC's top: four y rotations, in the blockstate's order
            assertThat(models.stream().map(m -> m.getOrDefault("y", 0)).toList()).containsExactly(90, 0, 180, 270);
        }
        assertThat((Map<String, Object>) states.get("variants")).isEqualTo(Map.of(
            "snowy=false", Map.of("appearance", "snowy_false"), "snowy=true", Map.of("appearance", "snowy_true")));
    }

    @Test
    void theSharedGrassModelsDrawTfcsTexturesWithTheBiomeTint() {
        JsonObject model = json(RP + "models/block/grass/shared.json");
        JsonObject textures = model.getAsJsonObject("textures");
        assertThat(textures.get("cover").getAsString()).isEqualTo("tfp:block/grass_top");
        assertThat(textures.get("bottom").getAsString()).isEqualTo("tfp:block/dirt/" + SoilBlocks.SHARED_SOIL);
        assertThat(textures.get("particle").getAsString()).isEqualTo("tfp:block/dirt/" + SoilBlocks.SHARED_SOIL);
        JsonObject faces = model.getAsJsonArray("elements").get(0).getAsJsonObject().getAsJsonObject("faces");
        assertThat(faces.keySet()).containsExactlyInAnyOrder("down", "up", "north", "south", "west", "east");
        for (String side : faces.keySet()) {
            JsonObject face = faces.getAsJsonObject(side);
            assertThat(face.get("cullface").getAsString()).isEqualTo(side);
            if (side.equals("down")) {
                assertThat(face.get("texture").getAsString()).isEqualTo("#bottom");
                assertThat(face.has("tintindex")).isFalse();
            } else {
                assertThat(face.get("texture").getAsString()).isEqualTo("#cover");
                assertThat(face.get("tintindex").getAsInt()).as("vanilla grass_block tints index 0").isZero();
            }
        }
        JsonObject snowy = json(RP + "models/block/grass/shared_snowy.json");
        assertThat(snowy.getAsJsonObject("textures").get("cover").getAsString()).isEqualTo("minecraft:block/snow");
        assertThat(snowy.toString()).doesNotContain("tintindex");
        assertThat(out.contains(RP + "textures/block/grass_top.png")).isTrue();
        assertThat(out.contains(RP + "textures/block/dirt/" + SoilBlocks.SHARED_SOIL + ".png")).isTrue();
    }

    @Test
    @SuppressWarnings("unchecked")
    void fullCubesAskTheAllocatorForOneVisualOfTfcsModel() {
        assertThat(demand.getFirst()).as("earlier demand kept first").isEqualTo(EARLIER);
        // PAR-WORLD-42's blocks (SoilExtraBlocksTest) have named appearances; this test covers the single-state cubes
        List<VisualDemand> mine = demand.subList(1, demand.size()).stream().filter(d -> d.appearance().isEmpty()).toList();
        List<String> cubes = SoilBlocks.blockIds(tfc).stream().filter(id -> !SoilBlocks.isGrass(id)).toList();
        assertThat(cubes).hasSize(8 * 3 + 4);
        assertThat(mine.stream().map(VisualDemand::key).toList()).containsExactlyInAnyOrderElementsOf(cubes);
        for (VisualDemand d : mine) {
            assertThat(d.models()).as(d.key()).hasSize(1);
            assertThat(d.models().getFirst().path()).isEqualTo("tfp:block/" + d.blockId());
            assertThat(d.models().getFirst().plain()).isTrue();
            assertThat(out.contains(RP + "models/block/" + d.blockId() + ".json")).as(d.key()).isTrue();
            Map<String, Object> state = (Map<String, Object>) blocks.get("tfp:" + d.blockId()).get("state");
            assertThat(state).isEqualTo(Map.of("template", "tfp:visual/" + d.blockId()));
        }
        // fluvisol and podzol have their own top texture (cube_column)
        assertThat(out.contains(RP + "textures/block/coarse_dirt/fluvisol_top.png")).isTrue();
        assertThat(out.contains(RP + "textures/block/peat.png")).isTrue();
    }

    @Test
    @SuppressWarnings("unchecked")
    void lootIsTfcsTable() {
        assertThat(blocks.get("tfp:grass/oxisol").get("loot"))
            .isEqualTo(Map.of("template", "tfp:loot_table/item", "arguments", Map.of("loot_item", "tfp:dirt/oxisol")));
        assertThat(blocks.get("tfp:clay_grass/oxisol").get("loot")).isEqualTo(Map.of("template", "tfp:loot_table/item_count",
            "arguments", Map.of("loot_item", "minecraft:clay_ball", "loot_count_min", 1, "loot_count_max", 3)));
        for (String self : List.of("tfp:coarse_dirt/oxisol", "tfp:mud/oxisol", "tfp:rooted_dirt/oxisol", "tfp:peat")) {
            assertThat(blocks.get(self).get("loot")).as(self).isEqualTo(Map.of("template", "tfp:loot_table/self"));
        }
        assertThat(blocks.get("tfp:peat_grass").get("loot"))
            .isEqualTo(Map.of("template", "tfp:loot_table/item", "arguments", Map.of("loot_item", "tfp:peat")));
        // kaolin: red 1-2, pink 1-3, white 1-4, the grass 1-2 kaolin clay
        Map<String, Integer> max = Map.of("tfp:red_kaolin_clay", 2, "tfp:pink_kaolin_clay", 3, "tfp:white_kaolin_clay", 4,
            "tfp:kaolin_clay_grass", 2);
        max.forEach((id, n) -> assertThat(((Map<String, Object>) blocks.get(id).get("loot")).get("arguments")).as(id)
            .isEqualTo(Map.of("loot_item", "tfp:kaolin_clay", "loot_count_min", 1, "loot_count_max", n)));
    }

    @Test
    @SuppressWarnings("unchecked")
    void itemsPlaceTheirBlockAndGrassItemsCarryTfcsDefaultTint() throws Exception {
        // TFCColors.getClimateColor(10f, 250f): temperature index 255 - 153, rainfall index 255 - 127
        var map = ImageIO.read(new ByteArrayInputStream(tfc.read(TfcCheckout.ASSETS + "textures/colormap/grass.png")));
        int colour = map.getRGB(102, 128) & 0xFFFFFF;
        assertThat(SoilBlocks.defaultGrassColour(tfc)).isEqualTo(colour);
        for (String id : SoilBlocks.blockIds(tfc)) {
            Map<String, Object> item = items.get("tfp:" + id);
            assertThat(out.contains(RP + "models/item/" + id + ".json")).as(id).isTrue();
            if (SoilBlocks.isGrass(id)) {
                assertThat(item.get("material")).isEqualTo("paper");
                assertThat(item.get("behavior")).isEqualTo(Map.of("type", "block_item", "block", "tfp:" + id));
                assertThat(((Map<String, Object>) item.get("data")).get("item_name"))
                    .isEqualTo("<!i><lang:block.tfp." + id.replace('/', '.') + ">");
                Map<String, Object> model = (Map<String, Object>) item.get("model");
                assertThat(model).containsEntry("path", "tfp:item/" + id);
                assertThat(model.get("tints")).isEqualTo(List.of(Map.of("type", "minecraft:constant", "value", colour)));
            } else {
                assertThat(item).isEqualTo(Map.of("template", "tfp:item/block_item",
                    "arguments", Map.of("item_lang_key", "block.tfp." + id.replace('/', '.'))));
            }
        }
        assertThat(out.contains(RP + "models/item/grass_inv.json")).isTrue();
        assertThat(json(RP + "models/item/grass_inv.json").toString()).contains("\"tintindex\":0").doesNotContain("\"tintindex\":1");
    }

    @Test
    void namesAndPeatSoundsComeFromTfc() {
        JsonObject en = json(SOIL_RP + "lang/en_us.json");
        List<String> named = new ArrayList<>();
        List<String> all = new ArrayList<>(SoilBlocks.blockIds(tfc));
        all.addAll(SoilExtraBlocks.ids(tfc)); // PAR-WORLD-42
        for (String id : all) {
            if (!SoilBlocks.pipelineNames(id)) {
                named.add("block.tfp." + id.replace('/', '.'));
            }
        }
        assertThat(en.keySet()).containsExactlyInAnyOrderElementsOf(named);
        assertThat(en.get("block.tfp.peat_grass").getAsString()).isEqualTo("Peat Grass");
        assertThat(en.get("block.tfp.coarse_dirt.alfisol").getAsString()).isEqualTo("Coarse Alfisol");
        // the grass names are the asset pipeline's (its grass family): TFC has them
        JsonObject tfcEn = Json.parse(tfc.readString(TfcCheckout.ASSETS + "lang/en_us.json"), "en_us").getAsJsonObject();
        assertThat(tfcEn.has("block.tfc.grass.alfisol")).isTrue();
        JsonObject sounds = json(SOIL_RP + "sounds.json");
        assertThat(sounds.keySet()).containsExactlyInAnyOrder("block.peat.break", "block.peat.step", "block.peat.place",
            "block.peat.hit", "block.peat.fall");
        JsonObject tfcSounds = Json.parse(tfc.readString(TfcCheckout.ASSETS + "sounds.json"), "sounds").getAsJsonObject();
        for (String event : sounds.keySet()) {
            assertThat(sounds.get(event).toString()).as(event)
                .isEqualTo(tfcSounds.get(event).toString().replace("tfc:", "tfp_soil:"));
        }
        assertThat(out.files().keySet().stream().filter(k -> k.startsWith(SOIL_RP + "sounds/block/peat/") && k.endsWith(".ogg")))
            .hasSize(11);
    }

