    public static final String TAB_BUTTON = "src/main/java/net/dries007/tfc/client/screen/button/PlayerInventoryTabButton.java";
    public static final String NUTRITION_SCREEN = "src/main/java/net/dries007/tfc/client/screen/NutritionScreen.java";
    public static final String CALENDAR_SCREEN = "src/main/java/net/dries007/tfc/client/screen/CalendarScreen.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/player_tabs.yml";
