package dev.tfp.datagen.vesselgui;

import dev.tfp.core.gui.ChestGeometry;
import dev.tfp.core.gui.GuiImage;
import dev.tfp.core.gui.VesselScreenLayout;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.util.LinkedHashMap;
import java.util.Map;
import javax.imageio.ImageIO;

/**
 * PAR-POT-10: the small vessel screen's art (TFC {@code SmallVesselInventoryScreen}, which draws {@code small_inventory.png}) for a
 * 3-row chest, in the layout of {@link VesselScreenLayout} ({@code configuration/pottery/vessel_gui.yml}).
 *
 * <ul>
 *   <li>{@code tfp:gui/small_vessel}: TFC's {@code small_inventory.png} re-laid out: the panel, the 2 x 2 slot block moved
 *       ({@code DX_SLOTS}, {@code DY_SLOTS}) onto chest columns 3 and 4, and the player inventory moved onto the chest's
 *       rows. The art is TFC's own; nothing is generated by hand.</li>
 * </ul>
 */
public final class VesselScreenArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/small_inventory.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/SmallVesselInventoryScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/SmallVesselInventoryContainer.java";
    public static final String BASE = "src/main/java/net/dries007/tfc/client/screen/TFCContainerScreen.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/pottery/vessel_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    /** TFC's slot block frame: one pixel up and left of the first item position, 18 per slot. */
    static final int GRID_X = VesselScreenLayout.TFC_SLOT_X - 1;
    static final int GRID_Y = VesselScreenLayout.TFC_SLOT_Y - 1;
    static final int GRID_W = VesselScreenLayout.COLUMNS * ChestGeometry.SLOT;
    static final int GRID_H = VesselScreenLayout.ROWS * ChestGeometry.SLOT;
    /** A plain panel row of TFC's art (between the content and the inventory). */
    static final int PLAIN_ROW = 76;
    /** TFC's player inventory part, from the first slot frame row to above the bottom border. */
    static final int INVENTORY_TOP = 82;
    static final int INVENTORY_BOTTOM = VesselScreenLayout.TFC_HEIGHT - 4;

    private VesselScreenArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(SCREEN) && tfc.exists(CONTAINER) && tfc.exists(BASE);
    }

    /** Writes the image and its YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE), TEXTURE);
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, VesselScreenLayout.BACKGROUND, background(src));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The 176 x 168 window. */
    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = VesselScreenLayout.CHEST.height();
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < h; y++) {
            copy(src, out, 0, PLAIN_ROW, w, 1, 0, y);
        }
        copy(src, out, 0, 0, w, 4, 0, 0); // top border
        copy(src, out, 0, INVENTORY_TOP, w, INVENTORY_BOTTOM - INVENTORY_TOP, 0,
            INVENTORY_TOP + VesselScreenLayout.DY_PLAYER); // the player inventory
        copy(src, out, 0, VesselScreenLayout.TFC_HEIGHT - 4, w, 4, 0, h - 4); // bottom border
        copy(src, out, GRID_X, GRID_Y, GRID_W, GRID_H, GRID_X + VesselScreenLayout.DX_SLOTS,
            GRID_Y + VesselScreenLayout.DY_SLOTS); // the slot block
        return out;
    }

    /** TFC's numbers the layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        String screen = tfc.readString(SCREEN).replaceAll("\\s+", " ");
        String base = tfc.readString(BASE);
        int x = VesselScreenLayout.TFC_SLOT_X;
        int y = VesselScreenLayout.TFC_SLOT_Y;
        need(container, CONTAINER, "addSlot(new SlotItemHandler(vessel, 0, " + x + ", " + y + "));");
        need(container, CONTAINER, "addSlot(new SlotItemHandler(vessel, 1, " + (x + 18) + ", " + y + "));");
        need(container, CONTAINER, "addSlot(new SlotItemHandler(vessel, 2, " + x + ", " + (y + 18) + "));");
        need(container, CONTAINER, "addSlot(new SlotItemHandler(vessel, 3, " + (x + 18) + ", " + (y + 18) + "));");
        need(screen, SCREEN, "super(container, playerInventory, name, INVENTORY_2x2);");
        need(base, BASE, "INVENTORY_2x2 = Helpers.identifier(\"textures/gui/small_inventory.png\");");
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the small vessel screen art is stale");
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        images.put(image.id(), e);
    }

    static BufferedImage read(byte[] bytes, String what) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(what + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
