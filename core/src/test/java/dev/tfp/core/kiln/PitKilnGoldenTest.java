    @Test
    void temperatureMatchesTfc() {
        List<String[]> rows = rows(TEMPERATURE);
        assertThat(rows).hasSize(90);
        for (String[] r : rows) {
            PitKilnRules.Config cfg = new PitKilnRules.Config(Long.parseLong(r[0]), cfgMax(r[0]));
            long lit = Long.parseLong(r[1]);
            long now = lit + Long.parseLong(r[2]);
            assertThat(PitKilnRules.temperatureAt(now, lit, cfg))
                .as("dur %s lit %s elapsed %s", r[0], r[1], r[2])
                .isEqualTo(Float.parseFloat(r[3]));
        }
    }

    @Test
    void conversionTickMatchesTfc() {
        List<String[]> rows = rows(CONVERT);
        assertThat(rows).hasSize(72);
        for (String[] r : rows) {
            PitKilnRules.Config cfg = new PitKilnRules.Config(Long.parseLong(r[0]), cfgMax(r[0]));
            long lit = Long.parseLong(r[1]);
            long tick = PitKilnRules.convertTick(Float.parseFloat(r[2]), lit, cfg);
            long expected = Long.parseLong(r[3]);
            assertThat(tick == PitKilnRules.NEVER ? -1 : tick - lit)
                .as("dur %s lit %s recipe %s", r[0], r[1], r[2])
                .isEqualTo(expected);
        }
    }

    @Test
    void outcomeAndConvertedMatchTfc() {
        List<String[]> rows = rows(OUTCOME);
        assertThat(rows).hasSize(540);
        for (String[] r : rows) {
            long dur = Long.parseLong(r[0]);
            PitKilnRules.Config cfg = new PitKilnRules.Config(dur, cfgMax(r[0]));
            long lit = Long.parseLong(r[1]);
            long now = lit + Long.parseLong(r[2]);
            long failed = "-".equals(r[3]) ? PitKilnRules.NEVER : lit + Long.parseLong(r[3]);
            PitKilnRules.Outcome out = PitKilnRules.evaluate(true, lit, now, cfg, failed);
            String where = String.join("|", r);
            assertThat(out.phase().name()).as(where).isEqualTo(r[4]);
            assertThat(out.cookedThrough() - lit).as(where).isEqualTo(Long.parseLong(r[5]));
            StringBuilder conv = new StringBuilder();
            for (float recipe : RECIPES) {
                conv.append(PitKilnRules.converted(true, recipe, lit, out, cfg) ? 'Y' : 'N');
            }
            assertThat(conv.toString()).as(where).isEqualTo(r[6]);
        }
    }

    @Test
    void theDefaultsAreTfcDefaults() {
        assertThat(PitKilnRules.Config.DEFAULT.durationTicks()).isEqualTo(7200L);
        assertThat(PitKilnRules.Config.DEFAULT.maxTemperature()).isEqualTo(1400f);
    }

    private static float cfgMax(String duration) {
        // the max temperature of each config row group: 1400 for 7200 and 1200, 900 for 100
        return "100".equals(duration) ? 900f : 1400f;
    }

    private static List<String[]> rows(String golden) {
        List<String[]> out = new ArrayList<>();
        for (String line : golden.strip().split("\n")) {
            if (!line.isBlank() && !line.startsWith("#")) {
                out.add(line.strip().split("\\|", -1));
            }
        }
        return out;
    }
