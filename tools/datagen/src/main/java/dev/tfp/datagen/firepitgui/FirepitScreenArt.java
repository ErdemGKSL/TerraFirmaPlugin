/**
 * PAR-HEAT-20: the firepit screen's art (TFC {@code FirepitScreen}) for the 4-row chest of the plugin's
 * {@code dev.tfp.paper.firepit.gui.FirepitScreenLayout} ({@code configuration/firepit_gui.yml}). The numbers here must
 * equal that layout's; {@code FirepitScreenLayoutContentTest} (paper) reads the generated YAML and PNGs against it.
 *
 * <ul>
 *   <li>{@code tfp:gui/firepit}: TFC's {@code fire_pit.png} (176 x 186, exactly a 4-row chest) re-laid out. The content
 *       part (fuel column and thermometer) moves down {@link #DY} = 2 so the fuel frames sit under chest column 0; the
 *       input frame moves from (79, 28) to chest slot 4's frame (79, 17), the two output frames from (70, 56) and
 *       (88, 56) to chest slots 21 and 23 (61, 53) and (97, 53); TFC's two arrows (stem and head, its own pixels) are
 *       re-laid as two L-shaped pipes from under the input to above each output. The player inventory moves up
 *       {@link #DY_PLAYER} = -1: TFC's sits 20 lower than a vanilla screen's (y 104), the 4-row chest's at y 103. Every
 *       other pixel is TFC's plain
 *       panel, so the 25 chest slots TFC does not have show no frame.</li>
 *   <li>{@code tfp:gui/firepit_thermometer}: 52 frames (4 x 13) of TFC's thermometer indicator (u 176, v 0, 15 x 5):
 *       frame 0 empty but for the width marker (TFC draws nothing when cold), frame k the indicator {@code 51 - k} pixels below the frame top,
 *       the frame top at TFC's {@code 76 - 51} plus {@link #DY}.</li>
 * </ul>
 */
public final class FirepitScreenArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/fire_pit.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/FirepitScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/FirepitContainer.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/firepit_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    /** The chest: TFC's screen is 166 + 20 = 186 tall, a 4-row chest. */
    public static final ChestGeometry CHEST = new ChestGeometry(4);
    public static final int TFC_HEIGHT = 186;
    /** TFC's player inventory offset ({@code init(playerInv, 20)}): its inventory at y 104. */
    public static final int TFC_INVENTORY_OFFSET = 20;
    /** The player inventory's move onto the 4-row chest's (y 103). */
    public static final int DY_PLAYER = CHEST.playerRowY(0) - (84 + TFC_INVENTORY_OFFSET);
    /** The content's move: fuel slot 3 (y 16) onto chest row 0 (y 18). */
    public static final int DY = 2;

    /** TFC's slot item positions, in block entity order (fuel 0..3, input 4, outputs 5 and 6). */
    public static final List<int[]> TFC_SLOTS = List.of(new int[] {8, 70}, new int[] {8, 52}, new int[] {8, 34},
        new int[] {8, 16}, new int[] {80, 29}, new int[] {71, 57}, new int[] {89, 57});
    /** The chest slot of each TFC slot ({@code FirepitScreenLayout.CHEST_SLOTS}). */
    public static final List<Integer> CHEST_SLOTS = List.of(27, 18, 9, 0, 4, 21, 23);
    public static final int SLOT_INPUT = 4;
    public static final int SLOT_OUTPUT_1 = 5;
    public static final int SLOT_OUTPUT_2 = 6;

    /** TFC's thermometer blit: x 30, bottom 76, the indicator sprite at (176, 0). */
    public static final int TFC_THERMOMETER_X = 30;
    public static final int TFC_THERMOMETER_BOTTOM = 76;
    public static final int THERMOMETER_U = 176;
    public static final int THERMOMETER_V = 0;

    public static final GuiImage BACKGROUND = GuiImage.of("tfp:gui/firepit", 0, 0, ChestGeometry.WIDTH, CHEST.height());
    public static final GuiImage THERMOMETER = new GuiImage("tfp:gui/firepit_thermometer", TFC_THERMOMETER_X,
        TFC_THERMOMETER_BOTTOM - ProgressFrames.THERMOMETER_TRAVEL + DY, ProgressFrames.THERMOMETER_WIDTH,
        ProgressFrames.THERMOMETER_FRAME_HEIGHT, 4, 13);

    /** A plain panel row of TFC's art (above the fuel column). */
    static final int PLAIN_ROW = 10;
    /** The top and bottom border rows, kept in place. */
    static final int BORDER = 4;
    /** TFC's content band [BORDER, CONTENT_END) moves by DY; the player band [CONTENT_END, height - BORDER) by DY_PLAYER. */
    static final int CONTENT_END = 94;
    /** TFC's arrows: stem columns 82 and 93, rows 47 to 54 (the head on the last three rows), 5 wide. */
    static final int ARROW_X1 = 82;
    static final int ARROW_X2 = 93;
    static final int ARROW_TOP = 47;
    static final int ARROW_HEIGHT = 8;
    static final int ARROW_HALF = 2;
    /** The area of TFC's input, arrows and outputs, cleared before they are laid out again. */
    static final int MIDDLE_X0 = 70;
    static final int MIDDLE_X1 = 106;
    static final int MIDDLE_Y0 = 28;
    static final int MIDDLE_Y1 = 74;

    private FirepitScreenArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(SCREEN) && tfc.exists(CONTAINER);
    }

    /** Writes the images and their YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE), TEXTURE);
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, BACKGROUND, background(src));
        put(out, images, THERMOMETER, thermometer(src));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The item position (x, y) of chest slot {@code slot}. */
    static int[] chestPoint(int slot) {
        return new int[] {CHEST.slotX(slot), CHEST.slotY(slot)};
    }

    /** The 176 x 186 window. */
    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = CHEST.height();
        if (src.getWidth() < w || src.getHeight() < TFC_HEIGHT || h != TFC_HEIGHT) {
            throw new DatagenException(TEXTURE + ": not a 176 x 186 screen over a 4-row chest");
        }
        checkPlain(src, PLAIN_ROW);
        if (CHEST.hotbarY() - (142 + TFC_INVENTORY_OFFSET) != DY_PLAYER) {
            throw new DatagenException(TEXTURE + ": the chest's hotbar does not move with its inventory");
        }
        for (int y = CONTENT_END - DY + DY_PLAYER; y < CONTENT_END + DY - DY_PLAYER; y++) {
            checkPlain(src, y); // the rows the content band and the player band both cover
        }
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < h; y++) {
            copy(src, out, 0, PLAIN_ROW, w, 1, 0, y);
        }
        copy(src, out, 0, BORDER, w, CONTENT_END - BORDER, 0, BORDER + DY); // the content, moved down
        copy(src, out, 0, CONTENT_END, w, TFC_HEIGHT - BORDER - CONTENT_END, 0,
            CONTENT_END + DY_PLAYER); // the player inventory
        copy(src, out, 0, 0, w, BORDER, 0, 0); // top border
        copy(src, out, 0, TFC_HEIGHT - BORDER, w, BORDER, 0, h - BORDER); // bottom border

        // the input, arrows and outputs, laid out again on the chest grid
        for (int y = MIDDLE_Y0 + DY; y < MIDDLE_Y1 + DY; y++) {
            copy(src, out, MIDDLE_X0, PLAIN_ROW, MIDDLE_X1 - MIDDLE_X0, 1, MIDDLE_X0, y);
        }
        for (int tfc : new int[] {SLOT_INPUT, SLOT_OUTPUT_1, SLOT_OUTPUT_2}) {
            int[] from = TFC_SLOTS.get(tfc);
            int[] to = chestPoint(CHEST_SLOTS.get(tfc));
            copy(src, out, from[0] - 1, from[1] - 1, ChestGeometry.SLOT, ChestGeometry.SLOT, to[0] - 1, to[1] - 1);
        }
        arrows(src, out);
        return out;
    }

    /**
     * TFC's arrows, re-laid: from each of TFC's stem columns under the input, a stem down, a bar across to the column of
     * its output's centre, then TFC's arrow (stem and head) down to one pixel above the output frame.
     */
    static void arrows(BufferedImage src, BufferedImage out) {
        int ink = src.getRGB(ARROW_X1, ARROW_TOP);
        int[] input = chestPoint(CHEST_SLOTS.get(SLOT_INPUT));
        int stemTop = input[1] - 1 + ChestGeometry.SLOT + 1; // one plain row under the input frame
        int[][] pairs = {{ARROW_X1, SLOT_OUTPUT_1}, {ARROW_X2, SLOT_OUTPUT_2}};
        for (int[] pair : pairs) {
            int[] output = chestPoint(CHEST_SLOTS.get(pair[1]));
            int tip = output[1] - 1 - 2; // one plain row above the output frame
            int arrowTop = tip - ARROW_HEIGHT + 1;
            int bar = arrowTop - 1;
            if (bar <= stemTop) {
                throw new DatagenException(TEXTURE + ": no room for the arrows between the input and the outputs");
            }
            int column = pair[0];
            int target = output[0] + (pair[1] == SLOT_OUTPUT_1 ? 7 : 8); // the centre pixel (mirrored about the input)
            for (int y = stemTop; y <= bar; y++) {
                out.setRGB(column, y, ink);
            }
            for (int x = Math.min(column, target); x <= Math.max(column, target); x++) {
                out.setRGB(x, bar, ink);
            }
            int srcX = pair[1] == SLOT_OUTPUT_1 ? ARROW_X1 : ARROW_X2;
            copy(src, out, srcX - ARROW_HALF, ARROW_TOP, 2 * ARROW_HALF + 1, ARROW_HEIGHT, target - ARROW_HALF, arrowTop);
        }
    }

    /** The thermometer strip: frame 0 empty, frame k the indicator {@code 51 - k} pixels below the frame top. */
    static BufferedImage thermometer(BufferedImage src) {
        GuiImage t = THERMOMETER;
        BufferedImage out = new BufferedImage(t.pngWidth(), t.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 1; k < ProgressFrames.THERMOMETER_FRAMES; k++) {
            int fx = t.frameCol(k) * t.width();
            int fy = t.frameRow(k) * t.height() + ProgressFrames.thermometerOffset(k);
            copy(src, out, THERMOMETER_U, THERMOMETER_V, ProgressFrames.THERMOMETER_WIDTH, ProgressFrames.THERMOMETER_HEIGHT,
                fx, fy);
        }
        keepAdvance(out, t.width(), t.height());
        return out;
    }

    /** Alpha of the width marker: counted by the client's glyph width scan, discarded by the text shader (below 0.1). */
    static final int MARKER = 0x01000000;

    /**
     * The client measures a bitmap glyph's advance from its rightmost non-transparent column, not from the cell: the empty
     * frame 0 (a cold firepit) would move the title pen 1 pixel instead of 16 and shift the label after it (seen in game:
     * "Firepit" drawn 15 pixels left of the window). A frame with an empty right column gets a nearly transparent pixel
     * (alpha 1) in its bottom-right corner, as {@code PlayerTabArt.keepAdvance}.
     */
    static void keepAdvance(BufferedImage png, int w, int h) {
        for (int fy = 0; fy < png.getHeight(); fy += h) {
            for (int fx = 0; fx < png.getWidth(); fx += w) {
                boolean any = false;
                for (int y = fy; y < fy + h && !any; y++) {
                    any = (png.getRGB(fx + w - 1, y) >>> 24) != 0;
                }
                if (!any) {
                    png.setRGB(fx + w - 1, fy + h - 1, MARKER);
                }
            }
        }
    }

    /** TFC's numbers this layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        String screen = tfc.readString(SCREEN).replaceAll("\\s+", " ");
        need(container, CONTAINER, "for (int i = 0; i < 4; i++) { addSlot(new CallbackSlot(blockEntity, i, "
            + TFC_SLOTS.get(0)[0] + ", " + TFC_SLOTS.get(0)[1] + " - 18 * i)); }");
        need(container, CONTAINER, "new CallbackSlot(blockEntity, FirepitBlockEntity.SLOT_ITEM_INPUT, "
            + TFC_SLOTS.get(SLOT_INPUT)[0] + ", " + TFC_SLOTS.get(SLOT_INPUT)[1] + ")");
        need(container, CONTAINER, "new CallbackSlot(blockEntity, FirepitBlockEntity.SLOT_OUTPUT_1, "
            + TFC_SLOTS.get(SLOT_OUTPUT_1)[0] + ", " + TFC_SLOTS.get(SLOT_OUTPUT_1)[1] + ")");
        need(container, CONTAINER, "new CallbackSlot(blockEntity, FirepitBlockEntity.SLOT_OUTPUT_2, "
            + TFC_SLOTS.get(SLOT_OUTPUT_2)[0] + ", " + TFC_SLOTS.get(SLOT_OUTPUT_2)[1] + ")");
        need(container, CONTAINER, ".init(playerInv, " + TFC_INVENTORY_OFFSET + ")");
        need(screen, SCREEN, "imageHeight += " + TFC_INVENTORY_OFFSET + ";");
        need(screen, SCREEN, "graphics.blit(texture, leftPos + " + TFC_THERMOMETER_X + ", topPos + " + TFC_THERMOMETER_BOTTOM
            + " - Math.min(" + ProgressFrames.THERMOMETER_TRAVEL + ", temp), " + THERMOMETER_U + ", " + THERMOMETER_V + ", "
            + ProgressFrames.THERMOMETER_WIDTH + ", " + ProgressFrames.THERMOMETER_HEIGHT + ");");
        need(screen, SCREEN, "leftPos + " + TFC_THERMOMETER_X + ", topPos + " + TFC_THERMOMETER_BOTTOM + " - "
            + ProgressFrames.THERMOMETER_TRAVEL + ", " + ProgressFrames.THERMOMETER_WIDTH + ", "
            + ProgressFrames.THERMOMETER_TRAVEL + ")");
        for (int fuel = 0; fuel < 4; fuel++) {
            int[] p = TFC_SLOTS.get(fuel);
            int slot = CHEST_SLOTS.get(fuel);
            if (CHEST.slotX(slot) != p[0] || CHEST.slotY(slot) != p[1] + DY) {
                throw new DatagenException("fuel slot " + fuel + " does not land on chest slot " + slot + " moved by " + DY);
            }
        }
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the firepit screen art is stale");
        }
    }

    private static void checkPlain(BufferedImage src, int y) {
        int c = src.getRGB(BORDER, y);
        for (int x = BORDER; x < ChestGeometry.WIDTH - BORDER; x++) {
            if (src.getRGB(x, y) != c) {
                throw new DatagenException(TEXTURE + ": row " + y + " is not plain panel; the re-layout would cut art");
            }
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        images.put(image.id(), e);
    }

    static BufferedImage read(byte[] bytes, String what) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(what + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
