/**
 * PAR-METAL-05: the anvil forging screen's art (TFC {@code AnvilScreen}) for the 5-row chest of
 * {@link AnvilScreenLayout} ({@code configuration/anvil_gui.yml}).
 *
 * <ul>
 *   <li>{@code tfp:gui/anvil}: TFC's {@code anvil.png} (176 x 207) re-laid out into the 176 x 204 window: the elements move as
 *       blocks onto the chest's slot grid (see {@link AnvilScreenLayout}) and the eight step icons are drawn on their buttons.
 *       The progress bar stays; the player inventory moves up by 4.</li>
 *   <li>{@code tfp:gui/anvil_progress}, {@code _target}, {@code _target_left}, {@code _target_right}, {@code _target_centre}:
 *       strips of 151 frames, frame {@code f} has TFC's marker sprite {@code f} pixels from the left of the strip.</li>
 *   <li>{@code tfp:gui/anvil_rule_<i>}: the rule slot {@code i}: frame 0 empty, then for each rule its icon under TFC's order
 *       overlay tinted red (the history does not match) or green (it does).</li>
 *   <li>{@code tfp:gui/anvil_step_<i>}: the icon of the {@code i}-th last step, frame 0 empty.</li>
 *   <li>{@code tfp:gui/anvil_weld}, {@code tfp:gui/anvil_plan_button}: TFC's two button frames with their glyphs.</li>
 * </ul>
 */
public final class AnvilForgeArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/anvil.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/AnvilScreen.java";
    public static final String STEP_BUTTON = "src/main/java/net/dries007/tfc/client/screen/button/AnvilStepButton.java";
    public static final String PLAN_BUTTON = "src/main/java/net/dries007/tfc/client/screen/button/AnvilPlanButton.java";
    public static final String WELD_BUTTON = "src/main/java/net/dries007/tfc/client/screen/button/AnvilWeldButton.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/AnvilContainer.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/anvil_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    /** A plain panel row of TFC's art (above the bar) and the split row of the player band (a plain row below the bar). */
    static final int PLAIN_ROW = 10;
    static final int SPLIT_ROW = 115;
    static final int BORDER = 4;
    /** TFC's content band that holds the moved elements: rows 4 to 99; the bar (100 to 106) stays. */
    static final int CONTENT_END = 100;

    /** An element of TFC's screen: a rectangle (x, y, w, h) that moves by (dx, dy). */
    record Block(String name, int x, int y, int w, int h, int dx, int dy) {
    }

    static final List<Block> BLOCKS = List.of(
        new Block("second and flux, arrows", 14, 19, 32, 53, AnvilScreenLayout.LEFT_DX, AnvilScreenLayout.LEFT_DY),
        new Block("main input, arrow heads", 14, 75, 32, 18, AnvilScreenLayout.LEFT_DX, AnvilScreenLayout.MAIN_DY),
        new Block("display and step buttons", 50, 14, 76, 79, AnvilScreenLayout.CENTRE_DX, AnvilScreenLayout.CENTRE_DY),
        new Block("hammer", 137, 75, 18, 18, AnvilScreenLayout.HAMMER_DX, AnvilScreenLayout.HAMMER_DY));

    private AnvilForgeArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(SCREEN) && tfc.exists(STEP_BUTTON) && tfc.exists(PLAN_BUTTON)
            && tfc.exists(WELD_BUTTON) && tfc.exists(CONTAINER);
    }

    /** Writes the images and their YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = AnvilPlanArt.read(tfc.read(TEXTURE), TEXTURE);
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, AnvilScreenLayout.BACKGROUND, background(src));
        put(out, images, AnvilScreenLayout.PROGRESS, strip(src, AnvilScreenLayout.PROGRESS, 176, 0, 5, 5));
        put(out, images, AnvilScreenLayout.POINTER, strip(src, AnvilScreenLayout.POINTER, 181, 0, 5, 5));
        put(out, images, AnvilScreenLayout.LEFT, strip(src, AnvilScreenLayout.LEFT, 176, 7, 5, 7));
        put(out, images, AnvilScreenLayout.RIGHT, strip(src, AnvilScreenLayout.RIGHT, 186, 7, 5, 7));
        put(out, images, AnvilScreenLayout.CENTRE, strip(src, AnvilScreenLayout.CENTRE, 181, 5, 5, 5));
        for (int i = 0; i < AnvilScreenLayout.RULE_SLOTS; i++) {
            put(out, images, AnvilScreenLayout.ruleImage(i), rules(src, AnvilScreenLayout.ruleImage(i)));
            put(out, images, AnvilScreenLayout.stepImage(i), steps(src, AnvilScreenLayout.stepImage(i)));
        }
        put(out, images, AnvilScreenLayout.WELD_BUTTON, weld(src));
        put(out, images, AnvilScreenLayout.PLAN_BUTTON, plan(src));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The 176 x 204 window. */
    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = AnvilScreenLayout.CHEST.height();
        if (src.getWidth() < w || src.getHeight() < AnvilScreenLayout.TFC_HEIGHT) {
            throw new DatagenException(TEXTURE + ": smaller than the 176 x 207 screen");
        }
        int dyPlayer = AnvilScreenLayout.PLAYER_DY;
        if (AnvilScreenLayout.CHEST.hotbarY() - (142 + AnvilScreenLayout.TFC_INVENTORY_OFFSET) != dyPlayer) {
            throw new DatagenException(TEXTURE + ": the chest's hotbar does not move with its inventory");
        }
        checkCovered(src);
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < h; y++) {
            copy(src, out, 0, PLAIN_ROW, w, 1, 0, y);
        }
        copy(src, out, 0, BORDER, w, SPLIT_ROW - BORDER, 0, BORDER); // the content band and the bar
        copy(src, out, 0, SPLIT_ROW, w, AnvilScreenLayout.TFC_HEIGHT - BORDER - SPLIT_ROW, 0, SPLIT_ROW + dyPlayer); // the player part
        copy(src, out, 0, 0, w, BORDER, 0, 0);
        copy(src, out, 0, AnvilScreenLayout.TFC_HEIGHT - BORDER, w, BORDER, 0, h - BORDER);
        int plain = src.getRGB(30, 60);
        for (Block b : BLOCKS) { // erase every element, then draw them where they go
            fill(out, b.x, b.y, b.w, b.h, plain);
        }
        for (Block b : BLOCKS) {
            copy(src, out, b.x, b.y, b.w, b.h, b.x + b.dx, b.y + b.dy);
        }
        // the eight step icons on their buttons
        for (ForgeStep step : ForgeStep.VALUES) {
            int slot = AnvilScreenLayout.stepSlot(step);
            over(src, out, step.iconX(), step.iconY(), 16, 16, AnvilScreenLayout.CHEST.slotX(slot), AnvilScreenLayout.CHEST.slotY(slot));
        }
        return out;
    }

    /** Frame {@code f} (0 to 150): the sprite {@code f} pixels from the left of the strip's cell. */
    static BufferedImage strip(BufferedImage src, GuiImage g, int u, int v, int w, int h) {
        BufferedImage out = new BufferedImage(g.pngWidth(), g.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int f = 0; f < AnvilScreenLayout.BAR_FRAMES; f++) {
            copy(src, out, u, v, w, h, g.frameCol(f) * g.width() + f, g.frameRow(f) * g.height());
        }
        keepAdvance(out, g.width(), g.height());
        return out;
    }

    /** Frame {@code 1 + 2 r + m}: rule {@code r}'s icon under its order overlay, tinted green when matched, red when not. */
    static BufferedImage rules(BufferedImage src, GuiImage g) {
        BufferedImage out = new BufferedImage(g.pngWidth(), g.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (ForgeRule rule : ForgeRule.VALUES) {
            for (int m = 0; m < 2; m++) {
                int f = AnvilScreenLayout.ruleFrame(rule, m == 1);
                int fx = g.frameCol(f) * g.width();
                int fy = g.frameRow(f) * g.height();
                over(src, out, rule.iconX(), rule.iconY() - 16, 16, 16, fx + 2, fy);
                // setShaderColor(0, 0.6, 0.2) green, (1, 0.4, 0) red, multiplied into the sprite's colour
                tinted(src, out, 198, rule.overlayY(), 20, 22, fx, fy, m == 1 ? 0f : 1f, m == 1 ? 0.6f : 0.4f, m == 1 ? 0.2f : 0f);
            }
        }
        keepAdvance(out, g.width(), g.height());
        return out;
    }

    /** Frame {@code 1 + s}: the small icon of step {@code s}. */
    static BufferedImage steps(BufferedImage src, GuiImage g) {
        BufferedImage out = new BufferedImage(g.pngWidth(), g.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (ForgeStep step : ForgeStep.VALUES) {
            int f = AnvilScreenLayout.stepFrame(step);
            over(src, out, step.iconX(), step.iconY() - 16, 16, 16, g.frameCol(f) * g.width(), g.frameRow(f) * g.height());
        }
        keepAdvance(out, g.width(), g.height());
        return out;
    }

    /** Frame 0 the unlit frame, frame 1 the lit one, both with the weld glyph. */
    static BufferedImage weld(BufferedImage src) {
        GuiImage g = AnvilScreenLayout.WELD_BUTTON;
        BufferedImage out = new BufferedImage(g.pngWidth(), g.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int f = 0; f < 2; f++) {
            copy(src, out, 218, f == 1 ? 0 : 18, 18, 18, f * 18, 0);
            over(src, out, 236, 16, 16, 16, f * 18 + 1, 1);
        }
        return out;
    }

    /** Frame 0 workable and 1 not workable (the question mark glyph), frame 2 the plan's (the result item is the slot's). */
    static BufferedImage plan(BufferedImage src) {
        GuiImage g = AnvilScreenLayout.PLAN_BUTTON;
        BufferedImage out = new BufferedImage(g.pngWidth(), g.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int f = 0; f < 3; f++) {
            copy(src, out, 218, f == 1 ? 18 : 0, 18, 18, f * 18, 0);
            if (f < 2) {
                over(src, out, 236, 0, 16, 16, f * 18 + 1, 1);
            }
        }
        return out;
    }

    /** Alpha of the width marker: counted by the client's glyph width scan, discarded by the text shader (below 0.1). */
    static final int MARKER = 0x01000000;

    /** A frame with an empty right column gets a nearly transparent pixel in its corner (the glyph keeps its advance). */
    static void keepAdvance(BufferedImage png, int w, int h) {
        for (int fy = 0; fy < png.getHeight(); fy += h) {
            for (int fx = 0; fx < png.getWidth(); fx += w) {
                boolean any = false;
                for (int y = fy; y < fy + h && !any; y++) {
                    any = (png.getRGB(fx + w - 1, y) >>> 24) != 0;
                }
                if (!any) {
                    png.setRGB(fx + w - 1, fy + h - 1, MARKER);
                }
            }
        }
    }

    /** TFC's numbers this layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String screen = tfc.readString(SCREEN).replaceAll("\\s+", " ");
        String step = tfc.readString(STEP_BUTTON).replaceAll("\\s+", " ");
        String plan = tfc.readString(PLAN_BUTTON).replaceAll("\\s+", " ");
        String weld = tfc.readString(WELD_BUTTON).replaceAll("\\s+", " ");
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        need(screen, SCREEN, "inventoryLabelY += 41; imageHeight += 41;");
        need(screen, SCREEN, "graphics.blit(texture, guiLeft + 11 + forging.work(), guiTop + 104, 176, 0, 5, 5);");
        need(screen, SCREEN, "graphics.blit(texture, guiLeft + 11 + target, guiTop + 98, 181, 0, 5, 5);");
        need(screen, SCREEN, "graphics.blit(texture, guiLeft + 11 + leftLimit, guiTop + 96, 176, 7, 5, 7);");
        need(screen, SCREEN, "graphics.blit(texture, guiLeft + 11 + rightLimit, guiTop + 96, 186, 7, 5, 7);");
        need(screen, SCREEN, "graphics.blit(texture, guiLeft + 13 + (rightLimit + leftLimit) / 2, guiTop + 94, 181, 5, 5, 5);");
        need(screen, SCREEN, "graphics.blit(texture, guiLeft + 61 + xOffset, guiTop + 13, 16, 16, rule.iconX(), rule.iconY() - 16, 16, 16, 256, 256);");
        need(screen, SCREEN, "graphics.blit(texture, guiLeft + 59 + xOffset, guiTop + 13, 198, rule.overlayY(), 20, 22);");
        need(screen, SCREEN, "RenderSystem.setShaderColor(0f, 0.6f, 0.2f, 1f);");
        need(screen, SCREEN, "RenderSystem.setShaderColor(1f, 0.4f, 0, 1f);");
        need(screen, SCREEN, "graphics.blit(texture, guiLeft + 99 - (index * 19), guiTop + 34, 16, 16, step.iconX(), step.iconY() - 16, 16, 16, 256, 256);");
        need(step, STEP_BUTTON, "graphics.blit(AnvilScreen.BACKGROUND, getX(), getY(), 16, 16, step.iconX(), step.iconY(), 16, 16, 256, 256);");
        need(plan, PLAN_BUTTON, "super(guiLeft + 137, guiTop + 56, 18, 18");
        need(plan, PLAN_BUTTON, "graphics.blit(AnvilScreen.BACKGROUND, x, y, 218, 0, width, height, 256, 256);");
        need(plan, PLAN_BUTTON, "graphics.blit(AnvilScreen.BACKGROUND, x, y, 218, workable ? 0 : 18, width, height, 256, 256);");
        need(plan, PLAN_BUTTON, "graphics.blit(AnvilScreen.BACKGROUND, x + 1, y + 1, 236, 0, 16, 16, 256, 256);");
        need(weld, WELD_BUTTON, "super(guiLeft + 21, guiTop + 56, 18, 18");
        need(weld, WELD_BUTTON, "graphics.blit(AnvilScreen.BACKGROUND, x, y, 218, canWeld ? 0 : 18, width, height, 256, 256);");
        need(weld, WELD_BUTTON, "graphics.blit(AnvilScreen.BACKGROUND, x + 1, y + 1, 236, 16, 16, 16, 256, 256);");
        need(container, CONTAINER, "addSlot(new CallbackSlot(blockEntity, AnvilBlockEntity.SLOT_INPUT_MAIN, 22, 76));");
        need(container, CONTAINER, "addSlot(new CallbackSlot(blockEntity, AnvilBlockEntity.SLOT_INPUT_SECOND, 22, 20));");
        need(container, CONTAINER, "addSlot(new CallbackSlot(blockEntity, AnvilBlockEntity.SLOT_HAMMER, 138, 76));");
        need(container, CONTAINER, "addSlot(new CallbackSlot(blockEntity, AnvilBlockEntity.SLOT_CATALYST, 22, 38));");
        need(container, CONTAINER, ".init(playerInv, 41)");
        // the layout's numbers equal TFC's (a TFC step button must still land on its chest slot)
        for (ForgeStep s : ForgeStep.VALUES) {
            int slot = AnvilScreenLayout.stepSlot(s);
            int dx = AnvilScreenLayout.CHEST.slotX(slot) - s.buttonX();
            int dy = AnvilScreenLayout.CHEST.slotY(slot) - s.buttonY();
            if (dx != AnvilScreenLayout.CENTRE_DX || dy != AnvilScreenLayout.CENTRE_DY) {
                throw new DatagenException("step button " + s + " is not on its chest slot");
            }
        }
        for (int i = 0; i < AnvilScreenLayout.TFC_SLOTS.length; i++) {
            int[] at = AnvilScreenLayout.TFC_SLOTS[i];
            int slot = AnvilScreenLayout.CHEST_SLOTS[i];
            int dx = AnvilScreenLayout.CHEST.slotX(slot) - at[0];
            int dy = AnvilScreenLayout.CHEST.slotY(slot) - at[1];
            int[] want = switch (i) {
                case 0 -> new int[] {AnvilScreenLayout.LEFT_DX, AnvilScreenLayout.MAIN_DY};
                case 1, 3 -> new int[] {AnvilScreenLayout.LEFT_DX, AnvilScreenLayout.LEFT_DY};
                default -> new int[] {AnvilScreenLayout.HAMMER_DX, AnvilScreenLayout.HAMMER_DY};
            };
            if (dx != want[0] || dy != want[1]) {
                throw new DatagenException("slot " + i + " is not where the layout moves it");
            }
        }
    }

    /** Every non-plain pixel of TFC's content band is inside a moved block or is the bar: a TFC art change fails here. */
    static void checkCovered(BufferedImage src) {
        int plain = src.getRGB(30, 60);
        for (int y = BORDER; y < CONTENT_END; y++) {
            for (int x = BORDER; x < ChestGeometry.WIDTH - BORDER; x++) {
                if (src.getRGB(x, y) == plain) {
                    continue;
                }
                final int px = x;
                final int py = y;
                boolean in = BLOCKS.stream().anyMatch(b -> px >= b.x && px < b.x + b.w && py >= b.y && py < b.y + b.h);
                if (!in) {
                    throw new DatagenException(TEXTURE + ": pixel (" + x + ", " + y + ") is art no block moves");
                }
            }
        }
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the anvil screen art is stale");
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), AnvilPlanArt.png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        images.put(image.id(), e);
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    private static void fill(BufferedImage dst, int x0, int y0, int w, int h, int argb) {
        for (int y = y0; y < y0 + h; y++) {
            for (int x = x0; x < x0 + w; x++) {
                dst.setRGB(x, y, argb);
            }
        }
    }

    /** Alpha-composites the sprite over {@code dst} (vanilla's blit of a sprite with transparent pixels). */
    private static void over(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        tinted(src, dst, sx, sy, w, h, dx, dy, 1f, 1f, 1f);
    }

    private static void tinted(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy, float r, float g,
            float b) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x < 0 || y < 0 || x >= dst.getWidth() || y >= dst.getHeight()) {
                    continue;
                }
                int s = src.getRGB(sx + i, sy + j);
                int sa = s >>> 24;
                if (sa == 0) {
                    continue;
                }
                int sr = Math.round(((s >> 16) & 0xFF) * r);
                int sg = Math.round(((s >> 8) & 0xFF) * g);
                int sb = Math.round((s & 0xFF) * b);
                int d = dst.getRGB(x, y);
                int da = d >>> 24;
                if (sa == 255 || da == 0) {
                    dst.setRGB(x, y, (sa << 24) | (sr << 16) | (sg << 8) | sb);
                    continue;
                }
                float a = sa / 255f;
                int or = Math.round(sr * a + ((d >> 16) & 0xFF) * (1 - a));
                int og = Math.round(sg * a + ((d >> 8) & 0xFF) * (1 - a));
                int ob = Math.round(sb * a + (d & 0xFF) * (1 - a));
                dst.setRGB(x, y, (Math.max(da, sa) << 24) | (or << 16) | (og << 8) | ob);
            }
        }
    }
}
