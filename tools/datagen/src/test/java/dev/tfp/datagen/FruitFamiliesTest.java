package dev.tfp.datagen;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class FruitFamiliesTest {
    private static final String PIN = TfcCheckout.PINNED_COMMIT;
    /** TFC's {@code FruitBlocks.Tree} species, lowercase. Banana is a separate plant and is not among them. */
    private static final Set<String> SPECIES = Set.of("cherry", "green_apple", "lemon", "olive", "orange", "peach", "plum", "red_apple");
    /** The five kinds, in TFC's registration order. */
    private static final List<String> KINDS = List.of("leaves", "branch", "growing_branch", "sapling", "potted_sapling");
    /** The kinds TFC registers with a block item: the leaves and the sapling. */
    private static final Set<String> WITH_ITEM = Set.of("leaves", "sapling");

    @TempDir
    Path tmp;

    /** Real checkout at the pinned commit (-Dtfc.checkout, from -Ptfc.checkout or $TFC_CHECKOUT); skipped when absent. */
    @Test
    void realCheckoutHasEightFruitTreesWithFiveKinds() {
        TfcCheckout tfc = realCheckout();

        List<String> species = FruitFamilies.species(tfc.readString(FruitFamilies.TREE_SOURCE));
        assertThat(species).hasSize(8);
        assertThat(new TreeSet<>(species)).isEqualTo(new TreeSet<>(SPECIES));

        List<FruitFamilies.Kind> kinds = FruitFamilies.kinds(tfc.readString(FruitFamilies.BLOCKS_SOURCE));
        assertThat(kinds.stream().map(FruitFamilies.Kind::name).toList()).isEqualTo(KINDS);
        for (FruitFamilies.Kind k : kinds) {
            assertThat(k.item()).as(k.name()).isEqualTo(WITH_ITEM.contains(k.name()));
        }

        List<FruitFamilies.Family> families = FruitFamilies.families(tfc);
        assertThat(families).hasSize(8);
        for (FruitFamilies.Family f : families) {
            assertThat(f.blocks().stream().map(FruitFamilies.Block::kind).toList()).as(f.species()).isEqualTo(KINDS);
            for (FruitFamilies.Block b : f.blocks()) {
                String prefix = b.kind().equals("potted_sapling") ? "plant/potted/" : "plant/";
                String suffix = b.kind().equals("potted_sapling") ? "_sapling" : "_" + b.kind();
                assertThat(b.path()).as(f.species() + " " + b.kind()).isEqualTo(prefix + f.species() + suffix);
                assertThat(tfc.exists(FruitFamilies.BLOCKSTATES + b.path() + ".json")).as(b.path()).isTrue();
            }
        }
        assertThat(families.stream().mapToInt(f -> f.blocks().size()).sum()).isEqualTo(40);
        assertThat(families.stream().flatMap(f -> f.blocks().stream()).map(FruitFamilies.Block::path))
            .noneMatch(p -> p.contains("banana"));

        OutputTree out = new OutputTree();
        assertThat(FruitFamilies.run(tfc, out)).isEqualTo(40);
        String yaml = new String(out.get(FruitFamilies.OUTPUT), StandardCharsets.UTF_8);
        Map<?, ?> bySpecies = (Map<?, ?>) ((Map<?, ?>) CeYamlCheck.parse(yaml, FruitFamilies.OUTPUT)).get("families");
        assertThat(bySpecies.keySet().stream().map(String::valueOf).toList()).hasSize(8);
        assertThat(yaml).contains("      - kind: sapling\n        item: true\n        id: tfp:plant/cherry_sapling\n"
            + "        tfc: tfc:plant/cherry_sapling\n");
        assertThat(yaml).contains("      - kind: potted_sapling\n        item: false\n        id: tfp:plant/potted/red_apple_sapling\n");
        assertThat(yaml).doesNotContain("banana");
    }

    @Test
    void fixtureFamiliesHaveTheFiveKindsAndYaml() throws IOException {
        Path root = checkout();
        FruitFixture.writeAll(root, List.of("CHERRY", "OLIVE"), FruitFixture.TFC_REGISTRATIONS);
        TfcCheckout tfc = TfcCheckout.open(root, PIN);
        OutputTree out = new OutputTree();

        assertThat(FruitFamilies.run(tfc, out)).isEqualTo(2 * 5);

        String yaml = new String(out.get(FruitFamilies.OUTPUT), StandardCharsets.UTF_8);
        Map<?, ?> bySpecies = (Map<?, ?>) ((Map<?, ?>) CeYamlCheck.parse(yaml, FruitFamilies.OUTPUT)).get("families");
        assertThat(bySpecies.keySet().stream().map(String::valueOf).toList()).containsExactly("cherry", "olive");
        List<?> cherry = (List<?>) ((Map<?, ?>) bySpecies.get("cherry")).get("blocks");
        assertThat(cherry).hasSize(5);
        assertThat(kindsOf(cherry)).isEqualTo(KINDS);

        assertThat(yaml).startsWith("# Generated by tools/datagen");
        assertThat(yaml).contains("families:\n  cherry:\n    blocks:\n      - kind: leaves\n        item: true\n"
            + "        id: tfp:plant/cherry_leaves\n        tfc: tfc:plant/cherry_leaves\n");
        assertThat(yaml).contains("      - kind: growing_branch\n        item: false\n        id: tfp:plant/olive_growing_branch\n");
        assertThat(yaml).contains("      - kind: potted_sapling\n        item: false\n        id: tfp:plant/potted/olive_sapling\n");
        assertThat(yaml).doesNotContain("green_apple");
    }

    @Test
    void missingTreeSourceIsRefused() throws IOException {
        Path root = checkout();
        assertThatThrownBy(() -> FruitFamilies.families(TfcCheckout.open(root, PIN)))
            .isInstanceOf(DatagenException.class).hasMessageContaining(FruitFamilies.TREE_SOURCE);
    }

    @Test
    void missingBlocksSourceIsRefused() throws IOException {
        Path root = checkout();
        FruitFixture.writeAll(root, List.of("CHERRY"), FruitFixture.TFC_REGISTRATIONS);
        Files.delete(root.resolve(FruitFamilies.BLOCKS_SOURCE));
        assertThatThrownBy(() -> FruitFamilies.families(TfcCheckout.open(root, PIN)))
            .isInstanceOf(DatagenException.class).hasMessageContaining(FruitFamilies.BLOCKS_SOURCE);
    }

    @Test
    void missingRegistrationIsRefused() throws IOException {
        Path root = checkout();
        FruitFixture.writeAll(root, List.of("CHERRY"), "");
        assertThatThrownBy(() -> FruitFamilies.families(TfcCheckout.open(root, PIN)))
            .isInstanceOf(DatagenException.class).hasMessageContaining("no FRUIT_TREE_ registration");
    }

    @Test
    void emptyTreeEnumIsRefused() throws IOException {
        Path root = checkout();
        FruitFixture.writeAll(root, List.of(), FruitFixture.TFC_REGISTRATIONS);
        assertThatThrownBy(() -> FruitFamilies.families(TfcCheckout.open(root, PIN)))
            .isInstanceOf(DatagenException.class).hasMessageContaining("no constants in public enum Tree");
    }

    @Test
    void missingFruitTreeBlockstateIsRefused() throws IOException {
        Path root = checkout();
        FruitFixture.writeAll(root, List.of("CHERRY", "OLIVE"), FruitFixture.TFC_REGISTRATIONS);
        Files.delete(root.resolve(TfcCheckout.ASSETS + "blockstates/plant/potted/olive_sapling.json"));
        assertThatThrownBy(() -> FruitFamilies.families(TfcCheckout.open(root, PIN)))
            .isInstanceOf(DatagenException.class).hasMessageContaining("plant/potted/olive_sapling")
            .hasMessageContaining("olive");
    }

    /** The kind of each block of a parsed YAML family, in order. */
    private static List<String> kindsOf(List<?> blocks) {
        return blocks.stream().map(b -> (String) ((Map<?, ?>) b).get("kind")).toList();
    }

    private static TfcCheckout realCheckout() {
        Path checkout = Path.of(System.getProperty("tfc.checkout", "/opt/tfc"));
        Assumptions.assumeTrue(Files.isDirectory(checkout.resolve(".git")), "no TFC checkout at " + checkout);
        Assumptions.assumeTrue(PIN.equals(TfcCheckout.resolveHead(checkout)), "TFC checkout is not at the pinned commit");
        return TfcCheckout.open(checkout, PIN);
    }

    /** A checkout at the pinned commit with no fruit tree sources yet. */
    private Path checkout() throws IOException {
        Path root = tmp.resolve("tfc");
        Fixture.write(root, ".git/HEAD", PIN + "\n");
        return root;
    }
}
