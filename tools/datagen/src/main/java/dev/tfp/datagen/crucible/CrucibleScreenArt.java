import java.util.Map;
import javax.imageio.ImageIO;

/**
 * PAR-METAL-12: the crucible screen's art (TFC {@code CrucibleScreen}) for the 6-row chest of the plugin's
 * {@code dev.tfp.paper.crucible.gui.CrucibleScreenLayout} ({@code configuration/crucible_gui.yml}). The numbers here must
 * equal that layout's; {@code CrucibleScreenArtTest} reads the generated YAML and PNGs against them.
 *
 * <ul>
 *   <li>{@code tfp:gui/crucible}: TFC's {@code crucible.png} (176 x 221, a 6-row chest is 222 tall) re-laid out. The nine
 *       inputs (x 25 + 18 column, y 81 + 18 line) and the output (151, 99) are slots 10 higher than a chest row grid
 *       allows, so everything under the text panel moves up {@link #DY} = -10 and the same ten rows are cut from the
 *       middle of the text panel (rows 30 to 39, plain panel pixels), which the scroll marker no longer needs. The
 *       space between the moved band and the player inventory is filled with TFC's plain panel row. The player inventory
 *       is already on the chest's rows (the chest is one row taller: the last row repeats).</li>
 *   <li>{@code tfp:gui/crucible_thermometer}: 52 frames of TFC's temperature indicator (u 176, v 0, 15 x 5) at (7, 131 - 51),
 *       moved by {@link #DY}.</li>
 *   <li>{@code tfp:gui/crucible_fluid}: 32 frames, frame {@code k} the molten fill {@code k} pixels high at the bottom of
 *       TFC's 36 x 31 fluid area (97, 93), moved by {@link #DY}: TFC's {@code molten_still} sprite (first frame) tinted
 *       molten orange.</li>
 * </ul>
 */
public final class CrucibleScreenArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/crucible.png";
    public static final String FLUID_TEXTURE = "src/main/resources/assets/tfc/textures/block/molten_still.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/CrucibleScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/CrucibleContainer.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/crucible_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    public static final ChestGeometry CHEST = new ChestGeometry(6);
    /** TFC's screen height: 166 + 55. */
    public static final int TFC_HEIGHT = 221;
    /** TFC's player inventory offset ({@code init(playerInv, 55)}). */
    public static final int TFC_INVENTORY_OFFSET = 55;
    /** The lower content's move: the inputs' first row (y 82) onto chest row 3 (y 72). */
    public static final int DY = -10;
    /** The player inventory's move onto the chest's: none. */
    public static final int DY_PLAYER = CHEST.playerRowY(0) - (84 + TFC_INVENTORY_OFFSET);

    /** Plain panel rows of the text panel that are cut: {@code [CUT_FROM, CUT_FROM - DY)}. */
    static final int CUT_FROM = 30;
    /** A plain row of TFC's art between the lower band and the player inventory. */
    static final int FILL_ROW = 136;

    /** TFC's thermometer blit: x 7, bottom 131, the indicator sprite at (176, 0). */
    public static final int TFC_THERMOMETER_X = 7;
    public static final int TFC_THERMOMETER_BOTTOM = 131;
    public static final int THERMOMETER_U = 176;
    public static final int THERMOMETER_V = 0;
    /** TFC's fluid area: 36 wide, bottom 124, 31 high, at x 97. */
    public static final int TFC_FLUID_X = 97;
    public static final int TFC_FLUID_BOTTOM = 124;
    public static final int FLUID_WIDTH = 36;
    public static final int FLUID_HEIGHT = 31;
    public static final int FLUID_FRAMES = FLUID_HEIGHT + 1;
    /** The tint of the fill (TFC tints the sprite with the metal's colour; ours is one molten orange). */
    static final int TINT_R = 0xFF;
    static final int TINT_G = 0x8C;
    static final int TINT_B = 0x2A;

    public static final GuiImage BACKGROUND = GuiImage.of("tfp:gui/crucible", 0, 0, ChestGeometry.WIDTH, CHEST.height());
    public static final GuiImage THERMOMETER = new GuiImage("tfp:gui/crucible_thermometer", TFC_THERMOMETER_X,
        TFC_THERMOMETER_BOTTOM - ProgressFrames.THERMOMETER_TRAVEL + DY, ProgressFrames.THERMOMETER_WIDTH,
        ProgressFrames.THERMOMETER_FRAME_HEIGHT, 4, 13);
    public static final GuiImage FLUID = new GuiImage("tfp:gui/crucible_fluid", TFC_FLUID_X,
        TFC_FLUID_BOTTOM - FLUID_HEIGHT + DY, FLUID_WIDTH, FLUID_HEIGHT, 4, 8);

    private CrucibleScreenArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(SCREEN) && tfc.exists(CONTAINER) && tfc.exists(FLUID_TEXTURE);
    }

    /** Writes the images and their YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE), TEXTURE);
        BufferedImage molten = read(tfc.read(FLUID_TEXTURE), FLUID_TEXTURE);
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, BACKGROUND, background(src));
        put(out, images, THERMOMETER, thermometer(src));
        put(out, images, FLUID, fluid(molten));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The 176 x 222 window. */
    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = CHEST.height();
        if (src.getWidth() < w || src.getHeight() < TFC_HEIGHT || h != TFC_HEIGHT + 1) {
            throw new DatagenException(TEXTURE + ": not a 176 x 221 screen under a 6-row chest");
        }
        for (int y = CUT_FROM; y < CUT_FROM - DY; y++) {
            checkSameRow(src, y, 11); // the rows that are cut equal the plain panel row above them
        }
        checkPlain(src, FILL_ROW);
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        int lowerEnd = 138; // TFC row 138: the first row of the player inventory frame
        for (int y = 0; y < h; y++) {
            int from;
            if (y < CUT_FROM) {
                from = y;
            } else if (y < lowerEnd + DY) {
                from = y - DY;
            } else if (y < lowerEnd + DY_PLAYER) {
                from = FILL_ROW;
            } else {
                from = Math.min(y - DY_PLAYER, TFC_HEIGHT - 1); // the chest is one row taller: the last row repeats
            }
            copy(src, out, 0, from, w, 1, 0, y);
        }
        return out;
    }

    /** The thermometer strip: frame 0 empty, frame k the indicator {@code 51 - k} pixels below the frame top. */
    static BufferedImage thermometer(BufferedImage src) {
        GuiImage t = THERMOMETER;
        BufferedImage out = new BufferedImage(t.pngWidth(), t.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 1; k < ProgressFrames.THERMOMETER_FRAMES; k++) {
            int fx = t.frameCol(k) * t.width();
            int fy = t.frameRow(k) * t.height() + ProgressFrames.thermometerOffset(k);
            copy(src, out, THERMOMETER_U, THERMOMETER_V, ProgressFrames.THERMOMETER_WIDTH, ProgressFrames.THERMOMETER_HEIGHT,
                fx, fy);
        }
        keepAdvance(out, t.width(), t.height());
        return out;
    }

    /** The fill strip: frame k is {@code k} rows of the tinted sprite at the bottom, TFC's tiling of a 16 x 16 sprite. */
    static BufferedImage fluid(BufferedImage molten) {
        GuiImage f = FLUID;
        BufferedImage out = new BufferedImage(f.pngWidth(), f.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 1; k < FLUID_FRAMES; k++) {
            int fx = f.frameCol(k) * f.width();
            int fy = f.frameRow(k) * f.height();
            for (int j = 0; j < k; j++) {
                int y = FLUID_HEIGHT - 1 - j; // the bottom row of the frame is the first row of the sprite
                for (int i = 0; i < FLUID_WIDTH; i++) {
                    int px = molten.getRGB(i % 16, j % 16);
                    out.setRGB(fx + i, fy + y, tint(px));
                }
            }
        }
        keepAdvance(out, f.width(), f.height());
        return out;
    }

    private static int tint(int argb) {
        int a = argb >>> 24;
        int r = ((argb >> 16) & 0xFF) * TINT_R / 255;
        int g = ((argb >> 8) & 0xFF) * TINT_G / 255;
        int b = (argb & 0xFF) * TINT_B / 255;
        return a << 24 | r << 16 | g << 8 | b;
    }

    /** Alpha of the width marker: counted by the client's glyph width scan, discarded by the text shader (below 0.1). */
    static final int MARKER = 0x01000000;

    /** A frame with an empty right column gets a nearly transparent pixel in its corner, as {@code FirepitScreenArt}. */
    static void keepAdvance(BufferedImage png, int w, int h) {
        for (int fy = 0; fy < png.getHeight(); fy += h) {
            for (int fx = 0; fx < png.getWidth(); fx += w) {
                boolean any = false;
                for (int y = fy; y < fy + h && !any; y++) {
                    any = (png.getRGB(fx + w - 1, y) >>> 24) != 0;
                }
                if (!any) {
                    png.setRGB(fx + w - 1, fy + h - 1, MARKER);
                }
            }
        }
    }

    /** TFC's numbers this layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        String screen = tfc.readString(SCREEN).replaceAll("\\s+", " ");
        need(container, CONTAINER, "new CallbackSlot(blockEntity, slot, 26 + column * 18, 82 + line * 18)");
        need(container, CONTAINER, "new CallbackSlot(blockEntity, CrucibleBlockEntity.SLOT_OUTPUT, 152, 100)");
        need(container, CONTAINER, ".init(playerInv, " + TFC_INVENTORY_OFFSET + ")");
        need(screen, SCREEN, "imageHeight += " + TFC_INVENTORY_OFFSET + ";");
        need(screen, SCREEN, "graphics.blit(texture, leftPos + " + TFC_THERMOMETER_X + ", topPos + " + TFC_THERMOMETER_BOTTOM
            + " - Math.min(temperature, " + ProgressFrames.THERMOMETER_TRAVEL + "), " + THERMOMETER_U + ", " + THERMOMETER_V
            + ", " + ProgressFrames.THERMOMETER_WIDTH + ", " + ProgressFrames.THERMOMETER_HEIGHT + ");");
        need(screen, SCREEN, "final int fillHeight = (int) Math.ceil((float) " + FLUID_HEIGHT + " * alloy.getAmount()");
        need(screen, SCREEN, "leftPos + " + TFC_FLUID_X + ", topPos + " + TFC_FLUID_BOTTOM + " - fillHeight, " + FLUID_WIDTH
            + ", fillHeight, 16, 16");
        int slotY = CHEST.slotY(3 * 9);
        if (slotY != 82 + DY) {
            throw new DatagenException("chest row 3 is at y " + slotY + ", not the inputs' 82 + " + DY);
        }
        if (CHEST.slotX(1) != 26 || CHEST.slotX(8) != 152 || CHEST.slotY(4 * 9 + 8) != 100 + DY) {
            throw new DatagenException("the output does not land on chest slot 44, the inputs on columns 1 to 3");
        }
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the crucible screen art is stale");
        }
    }

    private static void checkPlain(BufferedImage src, int y) {
        int c = src.getRGB(4, y);
        for (int x = 4; x < ChestGeometry.WIDTH - 4; x++) {
            if (src.getRGB(x, y) != c) {
                throw new DatagenException(TEXTURE + ": row " + y + " is not plain panel; the re-layout would cut art");
            }
        }
    }

    private static void checkSameRow(BufferedImage src, int y, int like) {
        for (int x = 0; x < ChestGeometry.WIDTH; x++) {
            if (src.getRGB(x, y) != src.getRGB(x, like)) {
                throw new DatagenException(TEXTURE + ": row " + y + " differs from row " + like + "; cutting it would lose art");
            }
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        images.put(image.id(), e);
    }

    static BufferedImage read(byte[] bytes, String what) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(what + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
