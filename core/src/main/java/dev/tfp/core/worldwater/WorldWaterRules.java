package dev.tfp.core.worldwater;

import dev.tfp.core.worldgen.chunk.ChunkData;
import dev.tfp.core.worldgen.groundcover.SaltWater;
import dev.tfp.core.worldgen.river.Flow;
import dev.tfp.core.worldgen.river.RiverBiomes;
import java.util.Locale;

/**
 * Which TFC water a vanilla water block is (PAR-FLUID-03). Pure; any thread.
 *
 * <p>TFC's order: a hot spring pool holds spring water. The water of a {@code salty()} biome is salt water, a different fluid
 * than {@code minecraft:water}, so the river rule never replaces it. Fresh water of a column whose local biome has rivers and
 * whose flow is not {@link Flow#NONE} is river water at or above {@code min(seaLevel - 4, surfaceHeight)}
 * ({@code ChunkNoiseFiller.fillColumn}). Everything else is fresh water.
 */
public final class WorldWaterRules {
    /** {@code TFCChunkGenerator.SEA_LEVEL_Y}. */
    public static final int SEA_LEVEL_Y = ChunkData.SEA_LEVEL_Y;

    private WorldWaterRules() {
    }

    /**
     * The water kind of a water block in a TFC world.
     *
     * @param localBiome    the TFC biome id of the column ({@code localBiomes}: the river biome where the river makes it)
     * @param flow          the river flow of the column ({@code calculateFlowAt}); ignored when the biome has no rivers
     * @param surfaceHeight the column's surface height
     * @param y             the y of the water block
     * @param springPool    whether the block is inside a hot spring pool
     */
    public static WaterKind classify(int localBiome, Flow flow, int surfaceHeight, int y, boolean springPool) {
        if (springPool) {
            return WaterKind.SPRING;
        }
        if (SaltWater.isSalty(localBiome)) {
            return WaterKind.SALT;
        }
        return isRiverWater(localBiome, flow, surfaceHeight, y) ? WaterKind.RIVER : WaterKind.FRESH;
    }

    /** {@code fillColumn}: river water where the biome has rivers, the column flows, and {@code y} is high enough. */
    public static boolean isRiverWater(int localBiome, Flow flow, int surfaceHeight, int y) {
        return RiverBiomes.hasRivers(localBiome) && flow != Flow.NONE && y >= Math.min(SEA_LEVEL_Y - 4, surfaceHeight);
    }

    /** {@code calculateFlowAt} is only asked where the local biome has rivers; elsewhere the flow is {@link Flow#NONE}. */
    public static Flow columnFlow(int localBiome, Flow sampled) {
        return RiverBiomes.hasRivers(localBiome) ? sampled : Flow.NONE;
    }

    /**
     * The water kind in a world that is not generated by our TFC generator: decided by the vanilla biome key alone. Every
     * ocean, beach and salt marsh like biome is salt; nothing flows (there is no TFC river data).
     *
     * @param biomeKey the biome key, with or without namespace ({@code minecraft:deep_ocean}, {@code beach})
     */
    public static WaterKind classifyVanillaBiome(String biomeKey) {
        if (biomeKey == null) {
            return WaterKind.FRESH;
        }
        String key = biomeKey.toLowerCase(Locale.ROOT);
        int colon = key.indexOf(':');
        if (colon >= 0) {
            key = key.substring(colon + 1);
        }
        if (key.contains("ocean") || key.equals("beach") || key.equals("snowy_beach") || key.equals("stony_shore")
                || key.contains("salt")) {
            return WaterKind.SALT;
        }
        return WaterKind.FRESH;
    }
}
