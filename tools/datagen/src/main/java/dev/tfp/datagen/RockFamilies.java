package dev.tfp.datagen;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * M6-DECO-02 (data slice): TFC's rock families as CraftEngine-ready data. Every rock of {@code Rock} gets the
 * {@code Rock.BlockType} kinds (raw, hardened, smooth, cobble, bricks, gravel, spike, cracked bricks, mossy bricks,
 * mossy cobble, chiseled, loose, mossy loose, pressure plate, button, aqueduct, rope anchor). The kinds that TFC gives
 * slab, stair and wall variants (flag {@code variants} in {@code Rock.BlockType}) get those three shapes too. Igneous
 * rocks (display category {@code *_IGNEOUS_*}) also get the rock anvil and the magma block, which TFC registers in
 * {@code TFCBlocks} outside {@code BlockType}.
 *
 * <p>The output is {@code craftengine/tfp/families/rock.yml}, outside the CraftEngine {@code configuration/} folder,
 * so CraftEngine does not load it. Ids are the TFC blockstate paths in our namespace. Unlike the wood families, a
 * missing source or blockstate is an error: a TFC change must show up here, not as a silently smaller family.
 */
final class RockFamilies {
    static final String SOURCE = "src/main/java/net/dries007/tfc/common/blocks/rock/Rock.java";
    static final String BLOCKSTATES = TfcCheckout.ASSETS + "blockstates/rock/";
    static final String OUTPUT = AssetPipeline.PACK + "families/rock.yml";

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";
    private static final Pattern ROCK_CONSTANT = Pattern.compile("^ {4}([A-Z_]+)\\(RockDisplayCategory\\.([A-Z_]+),", Pattern.MULTILINE);
    private static final Pattern BLOCK_TYPE_CONSTANT = Pattern.compile("^ {8}([A-Z_]+)\\(.*, (true|false)\\)[,;]?\\s*$", Pattern.MULTILINE);
    /** Blockstate folders of the two kinds that TFC registers outside {@code Rock.BlockType}. */
    static final String ANVIL = "anvil";
    static final String MAGMA = "magma";

    /** The slab, stair and wall shapes of a variant kind, after the full block. */
    static final List<String> VARIANT_SHAPES = List.of("slab", "stairs", "wall");

    /**
     * One block kind. {@code variants} means the kind has slab, stair and wall shapes. {@code igneousOnly} means only
     * igneous rocks have it (anvil and magma).
     */
    record Kind(String kind, boolean variants, boolean igneousOnly) {
    }

    /** One block of a family: its kind, its shape ({@code full} or a variant shape) and the TFC blockstate path. */
    record Block(String kind, String shape, String path) {
    }

    /** One rock (serialized name), whether it is igneous, and its blocks in kind order. */
    record Family(String rock, boolean igneous, List<Block> blocks) {
    }

    /** One {@code Rock} constant: its name and its display category constant. */
    record RockConstant(String name, String displayCategory) {
    }

    private RockFamilies() {
    }

    /** Writes the family data. Returns the number of blocks. Fails when the checkout lacks the source or a blockstate. */
    static int run(TfcCheckout tfc, OutputTree out) {
        List<Family> families = families(tfc);
        out.put(OUTPUT, Yaml.write(HEADER, yaml(families)));
        return families.stream().mapToInt(f -> f.blocks().size()).sum();
    }

    /**
     * The families of the checkout, in TFC's declaration order. Fails when the source or a constant is missing, a

     */
    static List<Family> families(TfcCheckout tfc) {
        if (!tfc.exists(SOURCE)) {
            throw new DatagenException("TFC checkout has no " + SOURCE);
        }
        String text = tfc.readString(SOURCE);
        List<RockConstant> rocks = rockConstants(text);
        List<Kind> kinds = kinds(text);

        List<String> folders = tfc.childDirs(BLOCKSTATES);
        List<String> expectedFolders = kinds.stream().map(Kind::kind).sorted().toList();
        if (!folders.equals(expectedFolders)) {
            throw new DatagenException("TFC blockstate folders in " + BLOCKSTATES + " are " + folders
                + ", expected the Rock.BlockType kinds plus anvil and magma " + expectedFolders);
        }
        List<Family> out = new ArrayList<>();
        for (RockConstant r : rocks) {
            String rock = r.name().toLowerCase(Locale.ROOT);
            List<Block> blocks = new ArrayList<>();
            for (Kind k : kinds) {
                if (k.igneousOnly() && !igneous(r)) {
                    continue;
                }
                List<String> shapes = new ArrayList<>(List.of("full"));
                if (k.variants()) {
                    shapes.addAll(VARIANT_SHAPES);
                }
                for (String shape : shapes) {
                    String path = path(k.kind(), rock, shape);
                    if (!tfc.exists(TfcCheckout.ASSETS + "blockstates/" + path + ".json")) {
                        throw new DatagenException("TFC has no blockstate " + path + " for rock " + rock);
                    }
                    blocks.add(new Block(k.kind(), shape, path));
                }
            }
            out.add(new Family(rock, igneous(r), blocks));
        }
        return out;
    }

    /** The blockstate path of a block below {@code blockstates/}: {@code rock/<kind>/<rock><_shape>}. */
    static String path(String kind, String rock, String shape) {
        String suffix = shape.equals("full") ? "" : "_" + shape;
        return "rock/" + kind + "/" + rock + suffix;
    }

    static boolean igneous(RockConstant r) {
        return r.displayCategory().contains("IGNEOUS");
    }

    /** The {@code Rock} constants with their display category, in declaration order. */
    static List<RockConstant> rockConstants(String text) {
        String body = section(text, "public enum Rock implements");
        List<RockConstant> out = new ArrayList<>();
        Matcher m = ROCK_CONSTANT.matcher(body);
        while (m.find()) {
            out.add(new RockConstant(m.group(1), m.group(2)));
        }
        if (out.isEmpty()) {
            throw new DatagenException(SOURCE + ": no constants in public enum Rock");
        }
        return out;
    }

    /**
     * The kinds: every {@code Rock.BlockType} constant (serialized name, variants flag), then anvil and magma. Fails
     * when the blockstate folders under {@code blockstates/rock/} are not exactly these kinds.
     */
    static List<Kind> kinds(String text) {
        String body = section(text, "public enum BlockType");
        List<Kind> out = new ArrayList<>();
        Matcher m = BLOCK_TYPE_CONSTANT.matcher(body);
        while (m.find()) {
            out.add(new Kind(m.group(1).toLowerCase(Locale.ROOT), Boolean.parseBoolean(m.group(2)), false));
        }
        if (out.isEmpty()) {
            throw new DatagenException(SOURCE + ": no constants in public enum BlockType");
        }
        out.add(new Kind(ANVIL, false, true));
        out.add(new Kind(MAGMA, false, true));
        return out;
    }

    /** The text from {@code enumDecl} to the first semicolon after it: the enum's constant list. */
    static String section(String text, String enumDecl) {
        int start = text.indexOf(enumDecl);
        if (start < 0) {
            throw new DatagenException(SOURCE + ": no " + enumDecl);
        }
        int end = text.indexOf(';', start);
        if (end < 0) {
            throw new DatagenException(SOURCE + ": " + enumDecl + " has no end");
        }
        return text.substring(start, end);
    }

    /** {@code families: <rock>: blocks: [{kind, shape, id, tfc}]}, ids in our namespace, TFC's in {@code tfc:}. */
    static Map<String, Object> yaml(List<Family> families) {
        Map<String, Object> byRock = new LinkedHashMap<>();
        for (Family f : families) {
            List<Object> blocks = new ArrayList<>();
            for (Block b : f.blocks()) {
                Map<String, Object> m = new LinkedHashMap<>();
                m.put("kind", b.kind());
                m.put("shape", b.shape());
                m.put("id", Json.TO_NS + ":" + b.path());
                m.put("tfc", Json.FROM_NS + ":" + b.path());
                blocks.add(m);
            }
            Map<String, Object> family = new LinkedHashMap<>();
            family.put("blocks", blocks);
            byRock.put(f.rock(), family);
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("families", byRock);
        return root;
    }
}
