    private void writeLang() {
        String dir = TfcCheckout.ASSETS + "lang/";
        for (String f : tfc.list(dir)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(dir.length(), f.length() - 5);
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            TreeMap<String, String> keys = new TreeMap<>();
            for (Map.Entry<String, JsonElement> e : src.entrySet()) {
                if (LANG_KEY.matcher(e.getKey()).matches()) {
                    String k = e.getKey();
                    int dot = k.indexOf('.');
                    keys.put(k.substring(0, dot) + "." + Json.TO_NS + k.substring(dot + 1 + Json.FROM_NS.length()),
                        e.getValue().getAsString());
                }
            }
            JsonObject o = new JsonObject();
            keys.forEach(o::addProperty);
            out.put(RP + "lang/" + locale + ".json", Json.write(o));
            report.lang(locale, keys.size());
        }
    }

    private static Map<String, Object> packYml() {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("author", "TerraFirmaPlugin");
        m.put("version", Manifest.FORMAT + ".0");
        m.put("description", "TerraFirmaCraft content ported from TerraFirmaCraft (EUPL-1.2)");
        m.put("namespace", Json.TO_NS);
        m.put("enable", true);
        return m;
    }

    /** One generated configuration file: a blocks section and an items section. */
    private final class ConfigFile {
        final Map<String, Object> blocks = new LinkedHashMap<>();
        final Map<String, Object> items = new LinkedHashMap<>();

        void write(String name) {
            if (blocks.isEmpty() && items.isEmpty()) {
                return;
            }
            Map<String, Object> root = new LinkedHashMap<>();
            if (!blocks.isEmpty()) {
                root.put("blocks", blocks);
            }
            if (!items.isEmpty()) {
                root.put("items", items);
            }
            out.put(CONFIG + name + ".yml", Yaml.write(HEADER, root));
            report.count("ce_config_files");
        }
    }
