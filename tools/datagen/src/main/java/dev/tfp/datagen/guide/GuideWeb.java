package dev.tfp.datagen.guide;

import dev.tfp.core.guide.FieldGuide;
import dev.tfp.core.guide.GuideLink;
import dev.tfp.core.guide.GuideRun;
import dev.tfp.core.guide.GuideStyle;
import dev.tfp.core.guide.PatchouliMarkup;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * The field guide's web export (PAR-DATA-04): one self-contained HTML page with the contents and every entry, rendered
 * from the same converted pages as the in-game books. Entry links are in-page anchors; key names show their default
 * English binding. Deterministic.
 */
public final class GuideWeb {
    private static final Map<String, String> KEYS = Map.of(
        "key.use", "Right Click", "key.attack", "Left Click", "key.sneak", "Shift", "key.drop", "Q",
        "key.inventory", "E", "key.jump", "Space", "key.sprint", "Ctrl", "key.swapOffhand", "F",
        "key.pickItem", "Middle Click");

    private GuideWeb() {
    }

    public static String html(FieldGuide guide) {
        StringBuilder sb = new StringBuilder();
        sb.append("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
            .append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
            .append("<title>").append(esc(guide.name())).append("</title>\n")
            .append("<!-- Generated by tools/datagen from TerraFirmaCraft's field guide (EUPL-1.2). Do not edit. -->\n")
            .append("<style>\n")
            .append(":root{--bg:#f4ecd8;--fg:#1a1a1a;--muted:#555;--link:#0000ee;--card:#fbf6ea}\n")
            .append("@media (prefers-color-scheme: dark){:root{--bg:#1d1b17;--fg:#e8e2d4;--muted:#aaa;--link:#8ab4ff;--card:#27241f}}\n")
            .append("body{background:var(--bg);color:var(--fg);font:16px/1.5 Georgia,serif;margin:0 auto;max-width:46rem;padding:1rem}\n")
            .append("a{color:var(--link)}section.entry{background:var(--card);border-radius:6px;padding:.5rem 1rem;margin:1rem 0}\n")
            .append("h3{margin:.8rem 0 .2rem}p.desc{color:var(--muted)}kbd{border:1px solid var(--muted);border-radius:3px;padding:0 .2rem}\n")
            .append(".page{margin:.6rem 0;white-space:normal}\n</style>\n</head>\n<body>\n");
        sb.append("<h1>").append(esc(guide.name())).append("</h1>\n<p>").append(render(guide.landingText())).append("</p>\n");
        sb.append("<nav><h2>Contents</h2>\n");
        for (FieldGuide.Category c : guide.categories()) {
            sb.append("<h3><a href=\"#").append(anchor(c.id())).append("\">").append(esc(c.name())).append("</a></h3>\n<ul>\n");
            for (FieldGuide.Entry e : c.entries()) {
                sb.append("<li><a href=\"#").append(anchor(e.id())).append("\">").append(esc(e.title())).append("</a></li>\n");
            }
            sb.append("</ul>\n");
        }
        sb.append("</nav>\n");
        for (FieldGuide.Category c : guide.categories()) {
            sb.append("<h2 id=\"").append(anchor(c.id())).append("\">").append(esc(c.name())).append("</h2>\n")
                .append("<p class=\"desc\">").append(render(c.description())).append("</p>\n");
            for (FieldGuide.Entry e : c.entries()) {
                sb.append("<section class=\"entry\" id=\"").append(anchor(e.id())).append("\">\n<h3>")
                    .append(esc(e.title())).append("</h3>\n");
                for (FieldGuide.Page p : e.pages()) {
                    sb.append("<div class=\"page\">");
                    if (p.title() != null && !p.title().isBlank()) {
                        sb.append("<strong>").append(esc(p.title())).append("</strong><br>");
                    }
                    sb.append(render(p.text())).append("</div>\n");
                }
                sb.append("</section>\n");
            }
        }
        sb.append("</body>\n</html>\n");
        return sb.toString();
    }

    /** Patchouli markup as HTML. */
    static String render(String markup) {
        List<GuideRun> runs = PatchouliMarkup.parse(markup, GuideStyle.PLAIN, "tfp");
        StringBuilder sb = new StringBuilder();
        for (GuideRun r : runs) {
            switch (r) {
                case GuideRun.Text t -> sb.append(styled(esc(t.text()), t.style()));
                case GuideRun.Keybind k -> sb.append(styled("<kbd>" + esc(KEYS.getOrDefault(k.key(), k.key())) + "</kbd>",
                    k.style()));
                case GuideRun.Break b -> sb.append("<br>");
                case GuideRun.PageBreak p -> sb.append("<br>");
            }
        }
        return sb.toString();
    }

    private static String styled(String html, GuideStyle s) {
        String out = html;
        if (s.bold()) {
            out = "<b>" + out + "</b>";
        }
        if (s.italic()) {
            out = "<i>" + out + "</i>";
        }
        if (s.underlined()) {
            out = "<u>" + out + "</u>";
        }
        if (s.strikethrough()) {
            out = "<s>" + out + "</s>";
        }
        if (s.color() != GuideStyle.NO_COLOR && s.link() == null) {
            out = "<span style=\"color:#" + String.format(Locale.ROOT, "%06x", s.color()) + "\">" + out + "</span>";
        }
        if (s.tooltip() != null) {
            out = "<span title=\"" + esc(s.tooltip()) + "\">" + out + "</span>";
        }
        if (s.link() != null) {
            String id = GuideLink.entryId(s.link());
            if (id != null) {
                out = "<a href=\"#" + anchor(id) + "\">" + out + "</a>";
            } else if (s.link().startsWith(GuideLink.URL)) {
                out = "<a href=\"" + esc(s.link().substring(GuideLink.URL.length())) + "\" rel=\"noopener\">" + out + "</a>";
            }
        }
        return out;
    }

    static String anchor(String id) {
        return id.replace(':', '-').replace('/', '-');
    }

    static String esc(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }
}
