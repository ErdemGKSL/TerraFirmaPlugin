package dev.tfp.datagen.glass;

import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * PAR-PROC-52: the glassworking items as CraftEngine items ({@code configuration/glass/glass.yml}): the two blowpipes and
 * their with-glass forms, the jacks and paddle, and the four glass batches, the lamp glass and the lens ({@code wool_cloth} and {@code gem_saw} are
 * defined by {@code MaterialItems}).
 *
 * <p>All are flat {@code item/generated} items with TFC's textures. TFC draws the blowpipes with a 3D held model and a glass
 * layer whose texture follows the heat ({@code blowpipe/0..5}); here the flat inventory icon is used in every context (the
 * with-glass items show the cold icon; ledger divergence). The tools, blowpipes and with-glass blowpipes are in TFC's
 * {@code very_heavy} size (stack 1: the {@code tfc:all_blowpipes} and {@code c:tools/glassworking} entries of
 * {@code item_size/tools.json}, checked below); the batches have no size definition and stack to 64.
 */
public final class GlassItems {
    static final String PACK = "craftengine/tfp/";
    static final String CONFIG = PACK + "configuration/glass/glass.yml";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    static final String LANG_NS = "tfp_glass";
    static final String LANG_RP = PACK + "resourcepack/assets/" + LANG_NS + "/lang/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String TEXTURES = TfcCheckout.ASSETS + "textures/";
    static final String TOOL_SIZES = TfcCheckout.GENERATED + "data/tfc/tfc/item_size/tools.json";
    static final int BATCH_STACK = 64;
    static final int TOOL_STACK = 1;

    /** Item path to its flat texture (under {@code textures/item/}); the tools stack to 1. */
    static final Map<String, String> TOOLS = tools();
    static final List<String> BATCHES = List.of("silica_glass_batch", "hematitic_glass_batch", "olivine_glass_batch",
        "volcanic_glass_batch");
    /** The finished plain glass items (TFC {@code LAMP_GLASS}, {@code LENS}); they stack to 64 like the batches. */
    static final List<String> GLASS = List.of("lamp_glass", "lens");

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (PAR-PROC-52, dev.tfp.datagen.glass). Do not edit: fix the generator "
        + "and regenerate.";

    private GlassItems() {
    }

    private static Map<String, String> tools() {
        Map<String, String> m = new LinkedHashMap<>();
        m.put("blowpipe", "blowpipe");
        m.put("ceramic_blowpipe", "ceramic_blowpipe");
        m.put("blowpipe_with_glass", "blowpipe_with_glass");
        m.put("ceramic_blowpipe_with_glass", "ceramic_blowpipe_with_glass");
        m.put("jacks", "jacks");
        m.put("paddle", "paddle");
        return java.util.Collections.unmodifiableMap(m);
    }

    /** Every texture this pass copies exists (the small test fixtures have none). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TOOL_SIZES) && textures().stream().allMatch(t -> tfc.exists(TEXTURES + "item/" + t + ".png"));
    }

    private static List<String> textures() {
        List<String> all = new java.util.ArrayList<>(TOOLS.values());
        all.addAll(BATCHES);
        all.addAll(GLASS);
        return all;
    }

    /** Writes the items, models, textures and names. Returns the item paths. */
    public static List<String> run(TfcCheckout tfc, OutputTree out) {
        checkSizes(tfc);
        Map<String, Object> items = new LinkedHashMap<>();
        List<String> ids = new java.util.ArrayList<>(TOOLS.keySet());
        ids.addAll(BATCHES);
        ids.addAll(GLASS);
        for (String id : ids) {
            String texture = TOOLS.getOrDefault(id, id);
            copyTexture(tfc, out, texture);
            out.put(RP + "models/item/" + id + ".json", Json.write(model(texture)));
            items.put(Json.TO_NS + ":" + id, entry(id, TOOLS.containsKey(id) ? TOOL_STACK : BATCH_STACK));
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", items);
        out.put(CONFIG, Yaml.write(HEADER, root));
        writeLang(tfc, out, ids);
        return ids;
    }

    static String langKey(String path) {
        return "item." + Json.TO_NS + "." + path;
    }

    static JsonObject model(String texture) {
        JsonObject m = new JsonObject();
        m.addProperty("parent", "minecraft:item/generated");
        JsonObject tex = new JsonObject();
        tex.addProperty("layer0", Json.TO_NS + ":item/" + texture);
        m.add("textures", tex);
        return m;
    }

    static Map<String, Object> entry(String id, int stack) {
        Map<String, Object> args = new LinkedHashMap<>();
        args.put("item_lang_key", langKey(id));
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("max_stack_size", stack);
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("template", "tfp:item/simple");
        e.put("arguments", args);
        e.put("data", data);
        return e;
    }

    /** The blowpipes and glassworking tools must still be in the very_heavy tools size (stack 1). */
    private static void checkSizes(TfcCheckout tfc) {
        JsonObject sizes = Json.parse(tfc.readString(TOOL_SIZES), TOOL_SIZES).getAsJsonObject();
        String text = sizes.toString();
        if (!text.contains("tfc:all_blowpipes") || !text.contains("c:tools/glassworking")
            || !"very_heavy".equals(sizes.get("weight").getAsString())) {
            throw new DatagenException(TOOL_SIZES + " no longer lists the blowpipes and glassworking tools as very_heavy");
        }
    }

    private static void copyTexture(TfcCheckout tfc, OutputTree out, String texture) {
        String png = TEXTURES + "item/" + texture + ".png";
        if (!tfc.exists(png)) {
            throw new DatagenException("missing glassworking texture " + png);
        }
        out.put(RP + "textures/item/" + texture + ".png", tfc.read(png));
    }

    /** TFC's names in every locale that has them (English must have all). */
    private static void writeLang(TfcCheckout tfc, OutputTree out, List<String> ids) {
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            TreeMap<String, String> keys = new TreeMap<>();
            for (String id : ids) {
                String tfcKey = "item." + Json.FROM_NS + "." + id;
                if (src.has(tfcKey)) {
                    keys.put(langKey(id), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC item tfc:" + id + " has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }
}
