/**
 * PAR-HEAT-25: the pot screen's art (TFC {@code PotScreen}) for the 4-row chest of the plugin's
 * {@code dev.tfp.paper.pot.gui.PotScreenLayout}: {@code tfp:gui/pot}, the thermometer strip {@code tfp:gui/pot_thermometer},
 * the bubble strip {@code tfp:gui/pot_boiling} and the flame overlay {@code tfp:gui/pot_flames}, in
 * {@code configuration/pot_gui.yml}. The numbers here must equal that layout's.
 *
 * <p>TFC's {@code fire_pit_cooking_pot.png} is 176 x 186, exactly a 4-row chest. As the firepit and grill art the content band
 * moves down {@link #DY} = 2 (the fuel column onto chest column 0) and the player inventory up {@link #DY_PLAYER} = -1 onto the
 * chest's. TFC's five ingredient frames (two over three, touching) are not on the chest's 18-pixel grid once moved, so they are
 * cut out of the art and drawn again on chest slots 3 and 4 (row 0) and 12, 13 and 14 (row 1), pixel for pixel from TFC's frames.
 * The pot drawing, its static bubbles and the steam lines stay where TFC has them; no frame is drawn under the fluid and status
 * buttons (chest slots 16 and 25), which are hover areas over the drawing as TFC's fluid tooltip and label are. The
 * thermometer, the flames and the bubbles are overlay strips, as TFC blits them over the background.
 */
public final class PotScreenArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/fire_pit_cooking_pot.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/PotScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/PotContainer.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/pot_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    /** The chest: TFC's screen is 166 + 20 = 186 tall, a 4-row chest. */
    public static final ChestGeometry CHEST = new ChestGeometry(4);
    public static final int TFC_HEIGHT = 186;
    /** TFC's player inventory offset ({@code init(playerInv, 20)}): its inventory at y 104. */
    public static final int TFC_INVENTORY_OFFSET = 20;
    /** The player inventory's move onto the 4-row chest's (y 103). */
    public static final int DY_PLAYER = CHEST.playerRowY(0) - (84 + TFC_INVENTORY_OFFSET);
    /** The content's move: fuel slot 3 (y 16) onto chest row 0 (y 18). */
    public static final int DY = 2;

    /** TFC's slot item positions, in block entity order (fuel 0..3, inputs 4..8). */
    public static final List<int[]> TFC_SLOTS = List.of(new int[] {8, 70}, new int[] {8, 52}, new int[] {8, 34},
        new int[] {8, 16}, new int[] {65, 23}, new int[] {83, 23}, new int[] {56, 41}, new int[] {74, 41}, new int[] {92, 41});
    /** The chest slot of each TFC slot ({@code PotScreenLayout.CHEST_SLOTS}). */
    public static final List<Integer> CHEST_SLOTS = List.of(27, 18, 9, 0, 3, 4, 12, 13, 14);
    public static final int FIRST_INPUT = 4;

    /** TFC's thermometer blit: x 30, bottom 76, the indicator sprite at (176, 0). */
    public static final int TFC_THERMOMETER_X = 30;
    public static final int TFC_THERMOMETER_BOTTOM = 76;
    public static final int THERMOMETER_U = 176;
    public static final int THERMOMETER_V = 0;
    /** TFC's flames: three 13 x 13 sprites at (192, 0), drawn at x 121, 136 and 151, y 58. */
    public static final int FLAME_U = 192;
    public static final int FLAME_V = 0;
    public static final int FLAME_SIZE = 13;
    public static final int FLAME_X = 121;
    public static final int FLAME_Y = 58;
    public static final int FLAME_STEP = 15;
    public static final int FLAME_COUNT = 3;
    /** TFC's bubbles: 11 wide at (193, 16 .. 36), two columns at x 131 and 144, the 20 rows above y 30. */
    public static final int BUBBLE_U = 193;
    public static final int BUBBLE_V = 16;
    public static final int BUBBLE_SPRITE_ROWS = 21;
    public static final int BUBBLE_WIDTH = 11;
    public static final int BUBBLE_X = 131;
    public static final int BUBBLE_X2 = 144;
    public static final int BUBBLE_Y = 10;
    public static final int BUBBLE_HEIGHT = 20;

    public static final GuiImage BACKGROUND = GuiImage.of("tfp:gui/pot", 0, 0, ChestGeometry.WIDTH, CHEST.height());
    public static final GuiImage THERMOMETER = new GuiImage("tfp:gui/pot_thermometer", TFC_THERMOMETER_X,
        TFC_THERMOMETER_BOTTOM - ProgressFrames.THERMOMETER_TRAVEL + DY, ProgressFrames.THERMOMETER_WIDTH,
        ProgressFrames.THERMOMETER_FRAME_HEIGHT, 4, 13);
    /** The bubble strip: frame {@code h} shows the bottom {@code h} rows of both columns. */
    public static final GuiImage BOILING = new GuiImage("tfp:gui/pot_boiling", BUBBLE_X, BUBBLE_Y + DY,
        BUBBLE_X2 + BUBBLE_WIDTH - BUBBLE_X, BUBBLE_HEIGHT, 3, 7);
    /** The flame overlay: frame 0 nothing, frame 1 the three flames. */
    public static final GuiImage FLAMES = new GuiImage("tfp:gui/pot_flames", FLAME_X, FLAME_Y + DY,
        FLAME_STEP * (FLAME_COUNT - 1) + FLAME_SIZE, FLAME_SIZE, 1, 2);

    /** A plain panel row of TFC's art (above the fuel column; row 10 holds the static bubbles). */
    static final int PLAIN_ROW = 6;
    /** The top and bottom border rows, kept in place. */
    static final int BORDER = 4;
    /** TFC's content band [BORDER, CONTENT_END) moves by DY; the player band [CONTENT_END, height - BORDER) by DY_PLAYER. */
    static final int CONTENT_END = 94;
    /** The frame of an item slot starts one pixel up and left of the item. */
    static final int FRAME = ChestGeometry.SLOT;
    /** Where the cleared band of TFC's input frames ends on the right: the pot drawing starts after it. */
    static final int CLEAR_X0 = 55;
    static final int CLEAR_X1 = 116;
    /** TFC's frame band rows (item y - 1 of the first row, to the bottom of the second). */
    static final int CLEAR_Y0 = 15;
    static final int CLEAR_Y1 = 59;
    /** The marker that keeps a frame's advance (see {@link #keepAdvance}). */
    static final int MARKER = 0x01000000;

    private PotScreenArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(SCREEN) && tfc.exists(CONTAINER);
    }

    /** Writes the images and their YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE), TEXTURE);
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, BACKGROUND, background(src));
        put(out, images, THERMOMETER, thermometer(src));
        put(out, images, BOILING, boiling(src));
        put(out, images, FLAMES, flames(src));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The item position of chest slot {@code slot}. */
    static int[] chestPoint(int slot) {
        return new int[] {CHEST.slotX(slot), CHEST.slotY(slot)};
    }

    /** The 176 x 186 window. */
    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = CHEST.height();
        if (src.getWidth() < w || src.getHeight() < TFC_HEIGHT || h != TFC_HEIGHT) {
            throw new DatagenException(TEXTURE + ": not a 176 x 186 screen over a 4-row chest");
        }
        checkPlain(src, PLAIN_ROW);
        if (CHEST.hotbarY() - (142 + TFC_INVENTORY_OFFSET) != DY_PLAYER) {
            throw new DatagenException(TEXTURE + ": the chest's hotbar does not move with its inventory");
        }
        for (int y = CONTENT_END - DY + DY_PLAYER; y < CONTENT_END + DY - DY_PLAYER; y++) {
            checkPlain(src, y); // the rows the content band and the player band both cover
        }
        checkClearedBand(src);
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < h; y++) {
            copy(src, out, 0, PLAIN_ROW, w, 1, 0, y);
        }
        copy(src, out, 0, BORDER, w, CONTENT_END - BORDER, 0, BORDER + DY); // the content, moved down
        copy(src, out, 0, CONTENT_END, w, TFC_HEIGHT - BORDER - CONTENT_END, 0, CONTENT_END + DY_PLAYER); // the inventory
        copy(src, out, 0, 0, w, BORDER, 0, 0); // top border
        copy(src, out, 0, TFC_HEIGHT - BORDER, w, BORDER, 0, h - BORDER); // bottom border

        // the five input frames: plain panel over their old and new places, then TFC's frames on the chest slots
        for (int y = CLEAR_Y0 + DY; y < CLEAR_Y1 + DY; y++) {
            for (int x = CLEAR_X0; x < CLEAR_X1; x++) {
                out.setRGB(x, y, src.getRGB(PLAIN_ROW, PLAIN_ROW));
            }
        }
        for (int i = FIRST_INPUT; i < TFC_SLOTS.size(); i++) {
            int[] from = TFC_SLOTS.get(i);
            int[] to = chestPoint(CHEST_SLOTS.get(i));
            copy(src, out, from[0] - 1, from[1] - 1, FRAME, FRAME, to[0] - 1, to[1] - 1);
        }
        return out;
    }

    /** The cleared band must hold nothing but TFC's five frames and plain panel, or the re-layout would cut art. */
    static void checkClearedBand(BufferedImage src) {
        int plain = src.getRGB(PLAIN_ROW, PLAIN_ROW);
        for (int y = CLEAR_Y0; y < CLEAR_Y1; y++) {
            for (int x = CLEAR_X0; x < CLEAR_X1; x++) {
                if (!inOldFrame(x, y) && src.getRGB(x, y) != plain) {
                    throw new DatagenException(TEXTURE + ": pixel (" + x + ", " + y + ") beside the input frames is not plain panel");
                }
            }
        }
    }

    private static boolean inOldFrame(int x, int y) {
        for (int i = FIRST_INPUT; i < TFC_SLOTS.size(); i++) {
            int[] p = TFC_SLOTS.get(i);
            if (x >= p[0] - 1 && x < p[0] - 1 + FRAME && y >= p[1] - 1 && y < p[1] - 1 + FRAME) {
                return true;
            }
        }
        return false;
    }

    /** The thermometer strip: frame k has TFC's indicator k pixels above the bottom of its travel; frame 0 is empty. */
    static BufferedImage thermometer(BufferedImage src) {
        GuiImage t = THERMOMETER;
        BufferedImage out = new BufferedImage(t.pngWidth(), t.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 1; k < ProgressFrames.THERMOMETER_FRAMES; k++) {
            int fx = t.frameCol(k) * t.width();
            int fy = t.frameRow(k) * t.height() + ProgressFrames.thermometerOffset(k);
            copy(src, out, THERMOMETER_U, THERMOMETER_V, ProgressFrames.THERMOMETER_WIDTH, ProgressFrames.THERMOMETER_HEIGHT, fx, fy);
        }
        keepAdvance(out, t.width(), t.height());
        return out;
    }

    /** The bubble strip: frame h (0 to 20) draws the bottom h rows of TFC's bubble sprite in both columns. */
    static BufferedImage boiling(BufferedImage src) {
        GuiImage b = BOILING;
        BufferedImage out = new BufferedImage(b.pngWidth(), b.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int rows = 1; rows <= BUBBLE_HEIGHT; rows++) {
            int fx = b.frameCol(rows) * b.width();
            int fy = b.frameRow(rows) * b.height() + BUBBLE_HEIGHT - rows;
            int v = BUBBLE_V + BUBBLE_SPRITE_ROWS - rows;
            copy(src, out, BUBBLE_U, v, BUBBLE_WIDTH, rows, fx, fy);
            copy(src, out, BUBBLE_U, v, BUBBLE_WIDTH, rows, fx + BUBBLE_X2 - BUBBLE_X, fy);
        }
        keepAdvance(out, b.width(), b.height());
        return out;
    }

    /** The flame overlay: frame 1 draws TFC's flame sprite three times, frame 0 nothing. */
    static BufferedImage flames(BufferedImage src) {
        GuiImage f = FLAMES;
        BufferedImage out = new BufferedImage(f.pngWidth(), f.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 0; k < FLAME_COUNT; k++) {
            copy(src, out, FLAME_U, FLAME_V, FLAME_SIZE, FLAME_SIZE, f.frameCol(1) * f.width() + k * FLAME_STEP, 0);
        }
        keepAdvance(out, f.width(), f.height());
        return out;
    }

    /**
     * The client measures a bitmap glyph's advance from its rightmost non-transparent column, not from the cell: an empty
     * frame would move the title pen 1 pixel instead of its width. A frame with an empty right column gets a nearly
     * transparent pixel (alpha 1) in its bottom-right corner, as the firepit's strips.
     */
    static void keepAdvance(BufferedImage png, int w, int h) {
        for (int fy = 0; fy < png.getHeight(); fy += h) {
            for (int fx = 0; fx < png.getWidth(); fx += w) {
                boolean any = false;
                for (int y = fy; y < fy + h && !any; y++) {
                    any = (png.getRGB(fx + w - 1, y) >>> 24) != 0;
                }
                if (!any) {
                    png.setRGB(fx + w - 1, fy + h - 1, MARKER);
                }
            }
        }
    }

    /** TFC's numbers this layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        String screen = tfc.readString(SCREEN).replaceAll("\\s+", " ");
        need(container, CONTAINER, "for (int i = 0; i < 4; i++) // Fuel { addSlot(new CallbackSlot(blockEntity, i, "
            + TFC_SLOTS.get(0)[0] + ", " + TFC_SLOTS.get(0)[1] + " - 18 * i)); }");
        String[] names = {"SLOT_EXTRA_INPUT_START", "SLOT_EXTRA_INPUT_START + 1", "SLOT_EXTRA_INPUT_START + 2",
            "SLOT_EXTRA_INPUT_START + 3", "SLOT_EXTRA_INPUT_END"};
        for (int i = 0; i < names.length; i++) {
            int[] p = TFC_SLOTS.get(FIRST_INPUT + i);
            need(container, CONTAINER, "addSlot(new CallbackSlot(blockEntity, " + names[i] + ", " + p[0] + ", " + p[1] + "));");
        }
        need(container, CONTAINER, ".init(playerInv, " + TFC_INVENTORY_OFFSET + ")");
        need(screen, SCREEN, "textures/gui/fire_pit_cooking_pot.png");
        need(screen, SCREEN, "imageHeight += " + TFC_INVENTORY_OFFSET + ";");
        need(screen, SCREEN, "graphics.blit(texture, leftPos + " + TFC_THERMOMETER_X + ", topPos + " + TFC_THERMOMETER_BOTTOM
            + " - Math.min(" + ProgressFrames.THERMOMETER_TRAVEL + ", temp), " + THERMOMETER_U + ", " + THERMOMETER_V + ", "
            + ProgressFrames.THERMOMETER_WIDTH + ", " + ProgressFrames.THERMOMETER_HEIGHT + ");");
        for (int k = 0; k < FLAME_COUNT; k++) {
            need(screen, SCREEN, "graphics.blit(BACKGROUND, leftPos + " + (FLAME_X + k * FLAME_STEP) + ", topPos + " + FLAME_Y
                + ", " + FLAME_U + ", " + FLAME_V + ", " + FLAME_SIZE + ", " + FLAME_SIZE + ");");
        }
        need(screen, SCREEN, "final int vHeight = Mth.ceil(ticks / 35f * 20f);");
        need(screen, SCREEN, "graphics.blit(BACKGROUND, leftPos + " + BUBBLE_X + ", topPos + " + BUBBLE_Y + " + 20 - vHeight, "
            + BUBBLE_U + ", " + BUBBLE_V + " + 21 - vHeight, " + BUBBLE_WIDTH + ", vHeight);");
        need(screen, SCREEN, "graphics.blit(BACKGROUND, leftPos + " + BUBBLE_X2 + ", topPos + " + BUBBLE_Y + " + 20 - vHeight, "
            + BUBBLE_U + ", " + BUBBLE_V + " + 21 - vHeight, " + BUBBLE_WIDTH + ", vHeight);");
        for (int fuel = 0; fuel < 4; fuel++) {
            int[] p = TFC_SLOTS.get(fuel);
            int slot = CHEST_SLOTS.get(fuel);
            if (CHEST.slotX(slot) != p[0] || CHEST.slotY(slot) != p[1] + DY) {
                throw new DatagenException("fuel slot " + fuel + " does not land on chest slot " + slot + " moved by " + DY);
            }
        }
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the pot screen art is stale");
        }
    }

    private static void checkPlain(BufferedImage src, int y) {
        int c = src.getRGB(PLAIN_ROW, PLAIN_ROW);
        for (int x = BORDER; x < ChestGeometry.WIDTH - BORDER; x++) {
            if (src.getRGB(x, y) != c) {
                throw new DatagenException(TEXTURE + ": row " + y + " is not plain panel; the re-layout would cut art");
            }
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        images.put(image.id(), e);
    }

    static BufferedImage read(byte[] bytes, String what) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(what + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
