/**
 * PAR-DECO-23 (first part): {@code tfp:golden_bamboo_block}, a block with three axes ({@code BambooBlock}, a rotated pillar):
 * hitbox-only on the barrier carrier with the model of its axis ({@code golden_bamboo_x|y|z}) as an item display, vanilla
 * {@code BAMBOO_BLOCK} strength (2.0 / 2.0), the bamboo-wood sounds, an axe, the plain self drop. The placement axis comes
 * from CraftEngine's hardcoded {@code axis} behaviour. Stripping with an axe, the palm mosaic stairs and slabs, tree roots and
 * the light block need hitbox rows and the integration adapters (PAR-DECO-30).
 */
public final class MiscShapedBlocks {
    public static final String OUTPUT = "craftengine/tfp/configuration/misc/shaped.yml";
    public static final String PATH = "golden_bamboo_block";
    public static final List<String> AXES = List.of("x", "y", "z");
    static final String LANG_RP = "craftengine/tfp/resourcepack/assets/tfp_misc_shaped/lang/";
    private static final String CARRIER = "minecraft:barrier";
    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ " + TfcCheckout.PINNED_COMMIT.substring(0, 9)
        + ". Do not edit: fix the generator and regenerate.\nPAR-DECO-23: golden bamboo block.";

    private MiscShapedBlocks() {
    }

    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(MiscCubes.BLOCKSTATES + PATH + ".json") && tfc.exists(MiscCubes.MODELS + "block/golden_bamboo_x.json")
            && tfc.exists(MiscCubes.MODELS + "item/" + PATH + ".json");
    }

    /** {@code tfp:render/golden_bamboo_block/y}. */
    static String renderId(String axis) {
        return Json.TO_NS + ":render/" + PATH + "/" + axis;
    }

    static DeviceBlockSpec spec(TfcCheckout tfc) {
        String id = Json.TO_NS + ":" + PATH;
        DeviceBlockSpec.Builder b = DeviceBlockSpec.builder(id).property(DeviceProperty.names("axis", AXES, "y"));
        DeviceAppearance.Carrier carrier = DeviceAppearance.Carrier.state(CARRIER);
        for (String axis : AXES) {
            b.renderItem(renderId(axis), Json.TO_NS + ":block/golden_bamboo_" + axis);
            b.appearance(DeviceAppearance.rendered(axis, carrier, List.of(DeviceAppearance.Renderer.item(renderId(axis)))));
        }
        return b.everyState(s -> s.get("axis"), null)
            // Blocks.BAMBOO_BLOCK: strength(2.0F), SoundType.BAMBOO_WOOD, minecraft:mineable/axe (vanilla tag; TFC tags do not list it)
            .settings(DeviceBlockSpec.Settings.of("2.0", "2.0", RenderedSound.BAMBOO_WOOD, "axe"))
            .loot(DeviceLoot.fromTfc(tfc, PATH))
            .blockItem(MiscCubes.langKey(PATH))
            .build();
    }

    /** Writes the block, its models, textures and names; returns the number of blocks (1). */
    @SuppressWarnings("unchecked")
    public static int run(TfcCheckout tfc, OutputTree out) {
        Map<String, Object> entry = DeviceYaml.literal(spec(tfc));
        for (String axis : AXES) {
            MiscCubes.copyModel(tfc, out, "block/golden_bamboo_" + axis);
        }
        MiscCubes.copyModel(tfc, out, "item/" + PATH);
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("blocks", entry.get("blocks"));
        root.put("items", entry.get("items"));
        out.put(OUTPUT, Yaml.write(HEADER, root));
        writeLang(tfc, out);
        return ((Map<String, Object>) entry.get("blocks")).size();
    }

    static void writeLang(TfcCheckout tfc, OutputTree out) {
        String tfcKey = "block." + Json.FROM_NS + "." + PATH;
        for (String f : tfc.list(MiscCubes.LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(MiscCubes.LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            if (src.has(tfcKey)) {
                JsonObject o = new JsonObject();
                o.addProperty(MiscCubes.langKey(PATH), src.get(tfcKey).getAsString());
                out.put(LANG_RP + locale + ".json", Json.write(o));
            } else if (locale.equals("en_us")) {
                throw new DatagenException("TFC has no English name " + tfcKey);
            }
        }
    }
}
