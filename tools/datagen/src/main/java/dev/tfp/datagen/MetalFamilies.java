package dev.tfp.datagen;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * M6-DECO-03 (data slice): TFC's metal block families as CraftEngine-ready data. Every metal of {@code Metal} that has
 * block kinds gets the {@code Metal.BlockType} kinds that its {@code PartType} allows, using TFC's own rules
 * ({@code BlockType.has}): the plain block with its slab and stair (full, slab, stairs), the weathering block of each age
 * (exposed, weathered, oxidized, with slab and stair) for the metals that weather, the grate (and its three weathered
 * ages for the metals whose parts all weather), bars, chain, lamp and trapdoor.
 *
 * <p>The anvil is parsed and checked (its folder must exist) but left out: it is a forging device (M4-ANV-02), not a
 * decoration. Metals with the {@code INGOT} part type have no metal block in TFC and are not in the output. A metal
 * that gets no block but is not {@code INGOT} is an error, so a TFC change shows up here.
 *
 * <p>The output is {@code craftengine/tfp/families/metal.yml}, outside the CraftEngine {@code configuration/} folder,
 * so CraftEngine does not load it. The {@code kind} is the blockstate folder under {@code blockstates/metal/}, and the
 * {@code shape} is {@code full}, {@code slab} or {@code stairs}. Ids are the TFC blockstate paths in our namespace.
 * Unlike the wood families, a missing source or blockstate is an error.
 */
final class MetalFamilies {
    static final String SOURCE = "src/main/java/net/dries007/tfc/util/Metal.java";
    static final String BLOCKSTATES = TfcCheckout.ASSETS + "blockstates/metal/";
    static final String OUTPUT = AssetPipeline.PACK + "families/metal.yml";

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";
    /** The {@code Metal.PartType} constants in TFC's declaration order. The ordinal rules of {@link #allows} use it. */
    static final List<String> PART_TYPES = List.of("INGOT", "DEFAULT", "DEFAULT_WEATHERING", "ALL", "ALL_WEATHERING",
        "WEATHERED", "ALL_WEATHERED");
    /** Block types TFC registers but this family set leaves out. The anvil is a device of M4-ANV-02. */
    static final Set<String> EXCLUDED = Set.of("ANVIL");

    private static final Pattern METAL_CONSTANT = Pattern.compile("^ {4}([A-Z_]+)\\((.*)\\)[,;]?\\s*$", Pattern.MULTILINE);
    private static final Pattern BLOCK_TYPE_CONSTANT = Pattern.compile("^ {8}([A-Z_]+)\\((PartType\\.[A-Z_]+)\\b", Pattern.MULTILINE);

    /** One {@code Metal} constant: its name, its {@code PartType} name, and its weathering resistance ({@code -1} = none). */
    record MetalConstant(String name, String partType, float weathering) {
    }

    /** One {@code Metal.BlockType} constant: its blockstate folder, its shape and the {@code PartType} it is registered with. */
    record BlockKind(String name, String folder, String shape, String partType) {
    }

    /** One block of a family: its kind (blockstate folder), its shape and the TFC blockstate path. */
    record Block(String kind, String shape, String path) {
    }

    /** One metal (serialized name) and its blocks in {@code BlockType} order. */
    record Family(String metal, List<Block> blocks) {
    }

    private MetalFamilies() {
    }

    /** Writes the family data. Returns the number of blocks. Fails when the checkout lacks the source or a blockstate. */
    static int run(TfcCheckout tfc, OutputTree out) {
        List<Family> families = families(tfc);
        out.put(OUTPUT, Yaml.write(HEADER, yaml(families)));
        return families.stream().mapToInt(f -> f.blocks().size()).sum();
    }

    /**
     * The families of the checkout, in TFC's declaration order. Fails when the source, a constant or the blockstate
     * folders do not match what this generator reads, or a blockstate of a block kind is missing.
     */
    static List<Family> families(TfcCheckout tfc) {
        if (!tfc.exists(SOURCE)) {
            throw new DatagenException("TFC checkout has no " + SOURCE);
        }
        String text = tfc.readString(SOURCE);
        List<MetalConstant> metals = metals(text);
        List<BlockKind> kinds = blockKinds(text);
        checkFolders(tfc, kinds);

        List<Family> out = new ArrayList<>();
        for (MetalConstant m : metals) {
            List<Block> blocks = new ArrayList<>();
            for (BlockKind k : kinds) {
                if (EXCLUDED.contains(k.name()) || !allows(k.partType(), m.partType())) {
                    continue;
                }
                String path = path(k, m.name().toLowerCase(Locale.ROOT));
                if (!tfc.exists(TfcCheckout.ASSETS + "blockstates/" + path + ".json")) {
                    throw new DatagenException("TFC has no blockstate " + path + " for metal " + m.name());
                }
                blocks.add(new Block(k.folder(), k.shape(), path));
            }
            if (blocks.isEmpty()) {
                if (!m.partType().equals("INGOT")) {
                    throw new DatagenException("TFC metal " + m.name() + " has part type " + m.partType()
                        + " but no metal block kind allows it");
                }
                continue;
            }
            out.add(new Family(m.name().toLowerCase(Locale.ROOT), blocks));
        }
        return out;
    }

    /** The blockstate path of a block below {@code blockstates/}: {@code metal/<folder><_shape>/<metal>}, as TFC names it. */
    static String path(BlockKind k, String metal) {
        return "metal/" + k.folder() + "/" + metal + (k.shape().equals("full") ? "" : "_" + k.shape());
    }

    /**
     * The {@code Metal} constants with their part type and weathering resistance, in declaration order. Fails when there
     * are none, a constant has an unknown argument shape, or a part type is not one of {@link #PART_TYPES}.
     */
    static List<MetalConstant> metals(String text) {
        String body = section(text, "public enum Metal implements");
        List<MetalConstant> out = new ArrayList<>();
        Matcher m = METAL_CONSTANT.matcher(body);
        while (m.find()) {
            String[] args = m.group(2).split(",\\s*");
            float weathering;
            try {
                weathering = Float.parseFloat(args[3].replaceAll("f$", ""));
            } catch (ArrayIndexOutOfBoundsException | NumberFormatException e) {
                throw new DatagenException(SOURCE + ": constant " + m.group(1) + " has no weathering argument");
            }
            String partType;
            if (args.length == 5 && args[4].startsWith("PartType.")) {
                partType = args[4].substring("PartType.".length());
            } else if (args.length == 6 && args[4].startsWith("TFCTiers.") && args[5].startsWith("TFCArmorMaterials.")) {
                // TFC: a tiered metal is ALL when it does not weather, ALL_WEATHERING when it does.
                partType = weathering == -1 ? "ALL" : "ALL_WEATHERING";
            } else {
                throw new DatagenException(SOURCE + ": constant " + m.group(1) + " has an unknown shape: " + m.group(2));
            }
            if (!PART_TYPES.contains(partType)) {
                throw new DatagenException(SOURCE + ": constant " + m.group(1) + " has unknown part type " + partType);
            }
            out.add(new MetalConstant(m.group(1), partType, weathering));
        }
        if (out.isEmpty()) {
            throw new DatagenException(SOURCE + ": no constants in public enum Metal");
        }
        return out;
    }

    /**
     * The {@code Metal.BlockType} constants, in declaration order, with the folder and shape TFC gives them (a
     * {@code _slab} or {@code _stairs} suffix is the shape, and the rest is the folder, as {@code BlockType.createName}).
     * Fails when the enum is missing, a constant has no part type, or {@code PART_TYPES} does not match TFC's enum.
     */
    static List<BlockKind> blockKinds(String text) {
        List<String> partTypes = partTypes(text);
        if (!partTypes.equals(PART_TYPES)) {
            throw new DatagenException(SOURCE + ": Metal.PartType is " + partTypes + ", expected " + PART_TYPES);
        }
        String body = section(text, "public enum BlockType");
        List<BlockKind> out = new ArrayList<>();
        Matcher m = BLOCK_TYPE_CONSTANT.matcher(body);
        while (m.find()) {
            String name = m.group(1).toLowerCase(Locale.ROOT);
            String part = m.group(2).substring("PartType.".length());
            String shape = "full";
            String folder = name;
            if (name.contains("_slab")) {
                shape = "slab";
                folder = name.split("_slab")[0];
            } else if (name.contains("_stairs")) {
                shape = "stairs";
                folder = name.split("_stairs")[0];
            }
            out.add(new BlockKind(m.group(1), folder, shape, part));
        }
        if (out.isEmpty()) {
            throw new DatagenException(SOURCE + ": no constants in public enum BlockType");
        }
        return out;
    }

    /** TFC's {@code BlockType.has} rule: whether a block registered with {@code blockPart} exists for {@code metalPart}. */
    static boolean allows(String blockPart, String metalPart) {
        int ordinal = PART_TYPES.indexOf(metalPart);
        return switch (blockPart) {
            case "DEFAULT" -> ordinal >= PART_TYPES.indexOf("DEFAULT");
            case "ALL" -> ordinal >= PART_TYPES.indexOf("ALL");
            case "WEATHERED" -> metalPart.equals("DEFAULT_WEATHERING") || metalPart.equals("ALL_WEATHERING");
            case "ALL_WEATHERED" -> metalPart.equals("ALL_WEATHERING");
            default -> throw new DatagenException(SOURCE + ": unknown block part type " + blockPart);
        };
    }

    /**
     * The blockstate folders under {@code blockstates/metal/} must be exactly the folders of the block kinds, the anvil
     * included, so a new or removed TFC kind fails here.
     */
    static void checkFolders(TfcCheckout tfc, List<BlockKind> kinds) {
        List<String> folders = tfc.childDirs(BLOCKSTATES);
        Set<String> expected = new TreeSet<>();
        kinds.forEach(k -> expected.add(k.folder()));
        if (!folders.equals(List.copyOf(expected))) {
            throw new DatagenException("TFC blockstate folders in " + BLOCKSTATES + " are " + folders
                + ", expected the Metal.BlockType folders " + expected);
        }
    }

    /** The {@code Metal.PartType} constants, in declaration order. */
    static List<String> partTypes(String text) {
        int start = text.indexOf("enum PartType");
        if (start < 0) {
            throw new DatagenException(SOURCE + ": no enum PartType");
        }
        int open = text.indexOf('{', start);
        int end = open < 0 ? -1 : text.indexOf(';', open);
        if (end < 0) {
            throw new DatagenException(SOURCE + ": enum PartType has no body");
        }
        List<String> out = new ArrayList<>();
        for (String s : text.substring(open + 1, end).split(",")) {
            if (!s.isBlank()) {
                out.add(s.trim());
            }
        }
        return out;
    }

    /** The text from {@code enumDecl} to the first semicolon after it: the enum's constant list. */
    static String section(String text, String enumDecl) {
        int start = text.indexOf(enumDecl);
        if (start < 0) {
            throw new DatagenException(SOURCE + ": no " + enumDecl);
        }
        int end = text.indexOf(';', start);
        if (end < 0) {
            throw new DatagenException(SOURCE + ": " + enumDecl + " has no end");
        }
        return text.substring(start, end);
    }

    /** {@code families: <metal>: blocks: [{kind, shape, id, tfc}]}, ids in our namespace, TFC's in {@code tfc:}. */
    static Map<String, Object> yaml(List<Family> families) {
        Map<String, Object> byMetal = new LinkedHashMap<>();
        for (Family f : families) {
            List<Object> blocks = new ArrayList<>();
            for (Block b : f.blocks()) {
                Map<String, Object> m = new LinkedHashMap<>();
                m.put("kind", b.kind());
                m.put("shape", b.shape());
                m.put("id", Json.TO_NS + ":" + b.path());
                m.put("tfc", Json.FROM_NS + ":" + b.path());
                blocks.add(m);
            }
            Map<String, Object> family = new LinkedHashMap<>();
            family.put("blocks", blocks);
            byMetal.put(f.metal(), family);
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("families", byMetal);
        return root;
    }
}
