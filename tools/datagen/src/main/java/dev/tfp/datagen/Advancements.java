package dev.tfp.datagen;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

/**
 * M6-ADV-01 (data slice): TFC's advancement tree as plugin data, {@code advancements/advancement_tree.json}.
 *
 * <p>Every TFC advancement is kept as a node: its id ({@code tfc:} renamed to {@code tfp:}), its tab (the first folder),
 * its parent (absent for a tab's root), its display title and description translation keys, the frame and the three
 * flags that decide the toast and chat messages, its requirements (criterion groups) and each criterion's name and
 * trigger. The triggers, rewards and icons are not part of the tree; the award glue and the trigger mapping come later.
 *
 * <p>TFC keeps these files in {@code src/main/resources}, not in the generated tree. The output is not under
 * {@code data/}: the server would register the stripped definitions as vanilla advancements and {@link
 * dev.tfp.core.registry.DataLoader} rejects unknown folders. The file is {@link OutputTree#OWNED} with its own root.
 *
 * <p>Missing or unexpected data is an error: an empty folder, a non-JSON file, a display without a
 * {@code translate} key, a requirement naming a missing criterion, a parent that does not exist, a cycle, or a tab
 * without exactly one root named {@code root}.
 */
final class Advancements {
    static final String SOURCE = TfcCheckout.MAIN + "data/" + Json.FROM_NS + "/advancement/";
    static final String OUTPUT = "advancements/advancement_tree.json";
    static final String ROOT = "root";

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (" + SOURCE + "). Do not edit: fix the generator and regenerate. "
        + "A node without parent is the root of its tab. Triggers, rewards and icons are not part of this tree.";

    /** One criterion of an advancement: its name in {@code criteria}, and the trigger it listens for. */
    record Criterion(String name, String trigger) {
    }

    /**
     * One advancement.
     *
     * @param id            our id, e.g. {@code tfp:story/saw}
     * @param tfc           TFC's id, e.g. {@code tfc:story/saw}
     * @param tab           the first folder of the path, e.g. {@code story}
     * @param parent        our id of the parent, or null for the root of the tab
     * @param title         the translation key of the title
     * @param description   the translation key of the description
     * @param frame         {@code task}, {@code goal} or {@code challenge}
     * @param hidden        whether TFC hides it until it is earned
     * @param showToast     whether TFC shows the toast when it is earned
     * @param announceToChat whether TFC announces it in chat
     * @param requirements  groups of criterion names; each inner list is one OR group, the groups are ANDed
     * @param criteria      every criterion, in file order
     */
    record Advancement(String id, String tfc, String tab, String parent, String title, String description, String frame,
                       boolean hidden, boolean showToast, boolean announceToChat, List<List<String>> requirements,
                       List<Criterion> criteria) {
    }

    private Advancements() {
    }

    /** Writes the tree. Returns the number of advancements. Fails when TFC's advancement data is missing or unexpected. */
    static int run(TfcCheckout tfc, OutputTree out) {
        List<Advancement> all = read(tfc);
        out.put(OUTPUT, Json.write(toJson(all)));
        return all.size();
    }

    /** Every advancement of the checkout, sorted by our id. Fails on any missing or unexpected data (see the class comment). */
    static List<Advancement> read(TfcCheckout tfc) {
        List<String> files = tfc.list(SOURCE);
        if (files.isEmpty()) {
            throw new DatagenException("TFC has no advancements at " + SOURCE + " (the pinned checkout is incomplete)");
        }
        Map<String, Advancement> byTfcId = new TreeMap<>();
        for (String file : files) {
            if (!file.endsWith(".json")) {
                throw new DatagenException("unexpected non-JSON advancement file " + file);
            }
            String rest = file.substring(SOURCE.length(), file.length() - ".json".length());
            int slash = rest.indexOf('/');
            if (slash <= 0 || rest.indexOf('/', slash + 1) >= 0) {
                throw new DatagenException("advancement file is not <tab>/<name>.json: " + file);
            }
            Advancement a = parse(tfc.readString(file), file, Json.FROM_NS + ":" + rest, rest.substring(0, slash));
            if (byTfcId.put(a.tfc(), a) != null) {
                throw new DatagenException("two advancements share the id " + a.tfc());
            }
        }
        // Parents are checked after every file is read, since a parent may come later in the sorted order.
        List<Advancement> out = new ArrayList<>();
        Map<String, Integer> rootsPerTab = new TreeMap<>();
        for (Advancement a : byTfcId.values()) {
            if (a.parent() != null && !byTfcId.containsKey(tfcOf(a.parent()))) {
                throw new DatagenException(a.tfc() + ": parent " + tfcOf(a.parent()) + " is not an advancement of TFC");
            }
            rootsPerTab.merge(a.tab(), 0, Integer::sum);
            if (a.parent() == null) {
                if (!a.tfc().equals(Json.FROM_NS + ":" + a.tab() + "/" + ROOT)) {
                    throw new DatagenException(a.tfc() + " has no parent but is not the root of its tab (" + a.tab() + "/" + ROOT + ")");
                }
                rootsPerTab.merge(a.tab(), 1, Integer::sum);
            }
            out.add(a);
        }
        for (Map.Entry<String, Integer> tab : rootsPerTab.entrySet()) {
            if (tab.getValue() != 1) {
                throw new DatagenException("tab " + tab.getKey() + " has " + tab.getValue() + " roots, expected 1");
            }
        }
        for (Advancement a : out) {
            checkNoCycle(a, byTfcId);
        }
        out.sort((x, y) -> x.id().compareTo(y.id()));
        return out;
    }

    /** One advancement file, with its id and tab already known from its path. Fails on a missing or unexpected field. */
    static Advancement parse(String text, String source, String tfcId, String tab) {
        JsonElement root = Json.parse(text, source);
        if (!root.isJsonObject()) {
            throw new DatagenException(source + ": advancement is not a JSON object");
        }
        JsonObject o = root.getAsJsonObject();
        JsonObject display = object(o, "display", source);
        String parent = null;
        if (o.has("parent")) {
            parent = Json.renameId(string(o, "parent", source));
        }

        JsonObject criteriaObj = object(o, "criteria", source);
        List<Criterion> criteria = new ArrayList<>();
        for (Map.Entry<String, JsonElement> e : criteriaObj.entrySet()) {
            JsonObject c = e.getValue().getAsJsonObject();
            criteria.add(new Criterion(e.getKey(), string(c, "trigger", source)));
        }
        if (criteria.isEmpty()) {
            throw new DatagenException(source + ": advancement has no criteria");
        }
        Set<String> names = new HashSet<>();
        criteria.forEach(c -> names.add(c.name()));

        List<List<String>> requirements = new ArrayList<>();
        JsonArray groups = array(o, "requirements", source);
        for (JsonElement g : groups) {
            List<String> group = new ArrayList<>();
            for (JsonElement n : g.getAsJsonArray()) {
                String name = n.getAsString();
                if (!names.contains(name)) {
                    throw new DatagenException(source + ": requirement names criterion '" + name + "' that is not in criteria");
                }
                group.add(name);
            }
            if (group.isEmpty()) {
                throw new DatagenException(source + ": empty requirement group");
            }
            requirements.add(group);
        }
        if (requirements.isEmpty()) {
            throw new DatagenException(source + ": advancement has no requirements");
        }

        return new Advancement(Json.TO_NS + tfcId.substring(Json.FROM_NS.length()), tfcId, tab, parent,
            translate(display, "title", source), translate(display, "description", source),
            string(display, "frame", source), bool(display, "hidden", source), bool(display, "show_toast", source),
            bool(display, "announce_to_chat", source), requirements, criteria);
    }

    /** Fails when following the parents from {@code a} does not reach a root within the number of advancements. */
    private static void checkNoCycle(Advancement a, Map<String, Advancement> byTfcId) {
        Advancement cur = a;
        for (int steps = 0; cur.parent() != null; steps++) {
            if (steps > byTfcId.size()) {
                throw new DatagenException(a.tfc() + ": parent chain is a cycle");
            }
            cur = byTfcId.get(tfcOf(cur.parent()));
        }
    }

    /** TFC's id of one of our ids ({@code tfp:x} → {@code tfc:x}). */
    private static String tfcOf(String ourId) {
        return Json.FROM_NS + ourId.substring(Json.TO_NS.length());
    }

    /** The output document: {@code {"comment", "advancements": [...]}}, one object per advancement in id order. */
    static JsonObject toJson(List<Advancement> all) {
        JsonObject root = new JsonObject();
        root.addProperty("comment", HEADER);
        JsonArray list = new JsonArray();
        for (Advancement a : all) {
            JsonObject o = new JsonObject();
            o.addProperty("id", a.id());
            o.addProperty("tfc", a.tfc());
            o.addProperty("tab", a.tab());
            if (a.parent() != null) {
                o.addProperty("parent", a.parent());
            }
            o.addProperty("title", a.title());
            o.addProperty("description", a.description());
            o.addProperty("frame", a.frame());
            o.addProperty("hidden", a.hidden());
            o.addProperty("show_toast", a.showToast());
            o.addProperty("announce_to_chat", a.announceToChat());
            JsonArray req = new JsonArray();
            for (List<String> group : a.requirements()) {
                JsonArray g = new JsonArray();
                group.forEach(g::add);
                req.add(g);
            }
            o.add("requirements", req);
            JsonArray crit = new JsonArray();
            for (Criterion c : a.criteria()) {
                JsonObject co = new JsonObject();
                co.addProperty("name", c.name());
                co.addProperty("trigger", Json.renameId(c.trigger()));
                crit.add(co);
            }
            o.add("criteria", crit);
            list.add(o);
        }
        root.add("advancements", list);
        return root;
    }

    private static JsonObject object(JsonObject o, String key, String source) {
        JsonElement e = o.get(key);
        if (e == null || !e.isJsonObject()) {
            throw new DatagenException(source + ": missing object '" + key + "'");
        }
        return e.getAsJsonObject();
    }

    private static JsonArray array(JsonObject o, String key, String source) {
        JsonElement e = o.get(key);
        if (e == null || !e.isJsonArray()) {
            throw new DatagenException(source + ": missing array '" + key + "'");
        }
        return e.getAsJsonArray();
    }

    private static String string(JsonObject o, String key, String source) {
        JsonElement e = o.get(key);
        if (e == null || !e.isJsonPrimitive() || !e.getAsJsonPrimitive().isString()) {
            throw new DatagenException(source + ": missing string '" + key + "'");
        }
        return e.getAsString();
    }

    private static boolean bool(JsonObject o, String key, String source) {
        JsonElement e = o.get(key);
        if (e == null || !e.isJsonPrimitive() || !e.getAsJsonPrimitive().isBoolean()) {
            throw new DatagenException(source + ": missing boolean '" + key + "'");
        }
        return e.getAsBoolean();
    }

    /** A display text, which TFC always writes as {@code {"translate": key}}; a literal text is refused. */
    private static String translate(JsonObject display, String key, String source) {
        JsonObject text = object(display, key, source);
        if (text.size() != 1) {
            throw new DatagenException(source + ": display " + key + " has keys other than translate: " + text.keySet());
        }
        return string(text, "translate", source);
    }
}
