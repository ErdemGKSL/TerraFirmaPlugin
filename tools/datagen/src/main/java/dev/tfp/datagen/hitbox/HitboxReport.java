package dev.tfp.datagen.hitbox;

import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.hitbox.HitboxAllocation.Assignment;
import dev.tfp.datagen.hitbox.HitboxAllocation.Result;
import dev.tfp.datagen.hitbox.HitboxCarrier.Choice;
import dev.tfp.datagen.hitbox.HitboxCarrier.Rejected;
import dev.tfp.datagen.hitbox.HitboxCarrier.Scored;
import dev.tfp.datagen.hitbox.HitboxCarrier.TfcState;
import dev.tfp.datagen.hitbox.TfcShapes.Row;
import dev.tfp.datagen.visuals.Profile;
import dev.tfp.datagen.visuals.VersionFamily;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Writes {@code reports/hitbox-carriers-<family>.md}: the allocation of every demand (carrier, both IoUs, mode, hide
 * mapping, override), the states used per vanilla block, the hide mappings, and a reference table with the unbudgeted
 * choice for every row of the TFC shape table plus the best rejected candidates with their reason and shape metrics.
 * Every profile is allocated and checked; carriers do not depend on the profile today, so the report shows one.
 */
public final class HitboxReport {
    public static final String PREFIX = "reports/hitbox-carriers-";

    private HitboxReport() {
    }

    /** Allocates every profile x family (failing on overflow) and writes one report per family. */
    public static void run(OutputTree out) {
        Map<String, Result> all = HitboxAllocation.standard();
        for (VersionFamily f : VersionFamily.values()) {
            Result r = all.get(f.id() + "/" + Profile.defaultFor(f).id());
            for (Profile p : Profile.values()) {
                Result other = all.get(f.id() + "/" + p.id());
                if (!other.lookByState().equals(r.lookByState()) || !other.hideMappings().equals(r.hideMappings())) {
                    throw new dev.tfp.datagen.DatagenException("hitbox allocation differs between profiles on " + f.id());
                }
            }
            out.put(PREFIX + f.id() + ".md", markdown(r));
        }
    }

    static String markdown(Result r) {
        StringBuilder b = new StringBuilder();
        b.append("# Hitbox carriers, MC ").append(r.family().id()).append(".x\n\n");
        b.append("Generated by tools/datagen (PAR-INFRA-13, `dev.tfp.datagen.hitbox`). Every profile (")
            .append(String.join(", ", java.util.Arrays.stream(Profile.values()).map(Profile::id).toList()))
            .append(") gives this allocation. Score = (0.6 IoU sel + 0.4 IoU col) x quality x penalties, worst of ")
            .append(String.join(" and ", r.family().researchedVersions())).append(".\n\n");
        b.append("## Allocation\n\n");
        b.append("| demand | TFC row | carrier | mode | IoU sel | IoU col | quality | score | hide | note |\n");
        b.append("|---|---|---|---|---|---|---|---|---|---|\n");
        for (Assignment a : r.assignments()) {
            Scored s = a.carrier();
            String note = a.choice().override() != null
                ? "override #" + a.choice().overrideIndex() + (a.choice().overrideIndex() > 0 ? " (fallback: ledger row)" : "")
                : String.join("; ", s.notes().stream()
                    .filter(n -> a.mode() != HitboxAllocation.Mode.VANILLA || !n.startsWith("hide ")).toList());
            b.append("| ").append(a.demand().id()).append(" | ").append(a.demand().tfcKey()).append(" | `").append(s.carrier())
                .append("` | ").append(a.mode().name().toLowerCase(Locale.ROOT)).append(" | ").append(f(s.selIoU()))
                .append(" | ").append(f(s.colIoU())).append(" | ").append(f(s.quality())).append(" | ").append(f(s.score()))
                .append(" | ").append(a.hideTarget() == null ? "-" : "`" + a.hideTarget() + "`").append(" | ").append(note)
                .append(" |\n");
        }
        b.append("\n## States used per vanilla block\n\n");
        for (Map.Entry<String, Set<String>> e : r.statesByBlock().entrySet()) {
            b.append("- `").append(e.getKey()).append("`: ").append(e.getValue().size()).append(" (")
                .append(String.join(", ", e.getValue().stream().map(s -> "`" + s + "` " + r.lookByState().get(s)).toList()))
                .append(")\n");
        }
        b.append("\n## Hide mappings (block_state_mappings, one hop)\n\n");
        if (r.hideMappings().isEmpty()) {
            b.append("none\n");
        }
        r.hideMappings().forEach((k, v) -> b.append("- `").append(k).append("` -> `").append(v).append("`\n"));
        b.append("\nHidden vanilla states: ").append(r.hideMappings().size()).append("\n");
        b.append("\n## Reference: every TFC shape row, unbudgeted\n\n");
        b.append("Below ").append(HitboxCarrier.MIN_SCORE).append(" a rare block takes hitbox-only mode. Rejected: the best ")
            .append("candidate of the three best vanilla blocks a hard filter removed (raw score without filters, outline parts / ")
            .append("fill / centroid offset).\n\n");
        b.append("| TFC row | class | TFC sel / col | carrier | IoU sel | IoU col | score | runner-up | best rejected |\n");
        b.append("|---|---|---|---|---|---|---|---|---|\n");
        for (Row row : TfcShapes.load().values()) {
            Choice c = HitboxCarrier.select(new TfcState(row, 0, false), r.profile(), r.family());
            Scored s = c.chosen();
            String runner = c.ranked().stream().filter(x -> s == null || !x.carrier().equals(s.carrier())).findFirst()
                .map(x -> "`" + x.carrier() + "` " + f(x.score())).orElse("-");
            java.util.Set<String> seenBlocks = new java.util.HashSet<>();
            List<Rejected> rej = c.rejected().stream().filter(x -> !Double.isNaN(x.rawScore()))
                .sorted(Comparator.comparingDouble(Rejected::rawScore).reversed().thenComparing(Rejected::carrier))
                .filter(x -> seenBlocks.add(x.carrier().contains("[") ? x.carrier().substring(0, x.carrier().indexOf('[')) : x.carrier()))
                .limit(3).toList();
            StringBuilder rs = new StringBuilder();
            for (Rejected x : rej) {
                if (!rs.isEmpty()) {
                    rs.append("<br>");
                }
                rs.append("`").append(x.carrier()).append("` ").append(f(x.rawScore())).append(": ").append(x.reason())
                    .append(" (").append(metrics(row.selection(), x.carrier(), r.family())).append(")");
            }
            b.append("| ").append(row.key()).append(" | ").append(row.shapeClass()).append(" | ")
                .append(row.selection().describe()).append(" / ").append(row.collision().describe()).append(" | ")
                .append(s == null ? "-" : "`" + s.carrier() + "`" + (c.override() != null ? " (override)" : ""))
                .append(" | ").append(s == null ? "-" : f(s.selIoU())).append(" | ").append(s == null ? "-" : f(s.colIoU()))
                .append(" | ").append(s == null ? "-" : f(s.score()) + (s.score() < HitboxCarrier.MIN_SCORE ? " (hitbox-only)" : ""))
                .append(" | ").append(runner).append(" | ").append(rs.isEmpty() ? "-" : rs).append(" |\n");
        }
        return b.toString();
    }

    private static String metrics(Shape tfc, String state, VersionFamily family) {
        VanillaCandidates v = VanillaCandidates.load();
        VanillaCandidates.VState s = v.get(family.researchedVersions().getLast(), state);
        if (s == null || s.selection().isEmpty() || tfc.isEmpty()) {
            return "-";
        }
        double[] a = tfc.centroid();
        double[] c = s.selection().centroid();
        double d = Math.sqrt(Math.pow(a[0] - c[0], 2) + Math.pow(a[1] - c[1], 2) + Math.pow(a[2] - c[2], 2));
        return s.selection().components().size() + " parts / fill " + f(s.selection().fill()) + " / centroid "
            + String.format(Locale.ROOT, "%.1f", d) + " px";
    }

    static String f(double d) {
        return String.format(Locale.ROOT, "%.3f", d);
    }
}
