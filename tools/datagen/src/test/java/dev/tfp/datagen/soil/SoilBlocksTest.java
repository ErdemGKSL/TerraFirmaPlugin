    @BeforeAll
    @SuppressWarnings("unchecked")
    static void generate() {
        Path path = Path.of(System.getProperty("tfc.checkout", "/opt/tfc"));
        Assumptions.assumeTrue(Files.isDirectory(path.resolve(".git")), "no TFC checkout at " + path);
        try {
            tfc = TfcCheckout.open(path, TfcCheckout.PINNED_COMMIT);
        } catch (RuntimeException e) {
            Assumptions.abort("TFC checkout is not at the pinned commit: " + e.getMessage());
            return;
        }
        assertThat(SoilBlocks.available(tfc)).isTrue();
        out = new OutputTree();
        demand = SoilBlocks.run(tfc, out, List.of(EARLIER));
        blocks = new LinkedHashMap<>();
        items = new LinkedHashMap<>();
        for (Map.Entry<String, byte[]> f : out.files().entrySet()) {
            if (f.getKey().startsWith(SoilBlocks.OUTPUT_DIR)) {
                String text = new String(f.getValue(), StandardCharsets.UTF_8);
                assertThat(text).as(f.getKey()).doesNotContain("\t").startsWith("# Generated by tools/datagen");
                Map<String, Object> root = new Yaml().load(text);
                assertThat(root.keySet()).as(f.getKey()).containsExactly("blocks", "items");
                blocks.putAll((Map<String, Map<String, Object>>) root.get("blocks"));
                items.putAll((Map<String, Map<String, Object>>) root.get("items"));
            }
        }
    }

    @Test
    void countsPerSoilMatchTfcsRegistry() {
        // SoilBlockType.Variant: 8 soils, in TFC's order
        List<String> soils = SoilBlocks.variants(tfc);
        assertThat(soils).containsExactly("entisol", "aridisol", "oxisol", "fluvisol", "andisol", "podzol", "alfisol", "mollisol");
        // One file per soil plus peat and kaolin; per soil the five types, each a TFC blockstate of that soil.
        Set<String> files = new TreeSet<>();
        out.files().keySet().stream().filter(k -> k.startsWith(SoilBlocks.OUTPUT_DIR))
            .forEach(k -> files.add(k.substring(SoilBlocks.OUTPUT_DIR.length())));
        Set<String> expectedFiles = new TreeSet<>(List.of("peat.yml", "kaolin.yml"));
        if (out.files().containsKey(SoilBlocks.OUTPUT_DIR + "grass_path_carriers.yml")) {
            expectedFiles.add("grass_path_carriers.yml"); // PAR-WORLD-42: the grass path carriers' hide mappings
        }
        soils.forEach(s -> expectedFiles.add(s + "_set.yml"));
        assertThat(files).isEqualTo(expectedFiles);
        for (String type : List.of("grass", "clay_grass", "coarse_dirt", "mud", "rooted_dirt")) {
            List<String> tfcBlocks = tfc.list(TfcCheckout.ASSETS + "blockstates/" + type + "/").stream()
                .map(f -> "tfp:" + type + "/" + f.substring(f.lastIndexOf('/') + 1, f.length() - ".json".length())).toList();
            assertThat(tfcBlocks).as(type).hasSize(8);
            assertThat(blocks.keySet()).as(type).containsAll(tfcBlocks);
            assertThat(blocks.keySet().stream().filter(k -> k.startsWith("tfp:" + type + "/"))).as(type).hasSize(8);
        }
        assertThat(blocks.keySet()).contains("tfp:peat", "tfp:peat_grass", "tfp:red_kaolin_clay", "tfp:pink_kaolin_clay",
            "tfp:white_kaolin_clay", "tfp:kaolin_clay_grass");
        assertThat(blocks).hasSize(8 * 5 + 6 + 8 * 4); // + duff, clay duff, grass path, muddy roots (PAR-WORLD-42)
        assertThat(items.keySet()).containsAll(blocks.keySet());
        List<String> all = new ArrayList<>(SoilBlocks.blockIds(tfc));
        all.addAll(SoilExtraBlocks.ids(tfc));
        assertThat(all.stream().map(id -> "tfp:" + id).toList()).containsExactlyInAnyOrderElementsOf(blocks.keySet());
    }

    @Test
    void settingsAreTfcsProperties() {
        // SoilBlockType: GRASS strength(1.8f) SoundType.GRASS MapColor.GRASS randomTicks
        assertThat(SoilBlocks.props(tfc, "grass/alfisol"))
            .isEqualTo(new SoilBlocks.Props(new BigDecimal("1.8"), 1, "SoundType.GRASS", "harp", false, true));
        assertThat(SoilBlocks.props(tfc, "clay_grass/alfisol"))
            .isEqualTo(new SoilBlocks.Props(new BigDecimal("1.8"), 1, "SoundType.GRASS", "harp", false, true));
        // COARSE_DIRT strength(1.6f) GRAVEL BASEDRUM requiresCorrectToolForDrops; MUD strength(2f) MUD BASEDRUM
        assertThat(SoilBlocks.props(tfc, "coarse_dirt/podzol"))
            .isEqualTo(new SoilBlocks.Props(new BigDecimal("1.6"), 10, "SoundType.GRAVEL", "basedrum", true, false));
        assertThat(SoilBlocks.props(tfc, "mud/podzol"))
            .isEqualTo(new SoilBlocks.Props(new BigDecimal("2"), 10, "SoundType.MUD", "basedrum", false, false));
        assertThat(SoilBlocks.props(tfc, "rooted_dirt/podzol"))
            .isEqualTo(new SoilBlocks.Props(new BigDecimal("2.0"), 10, "SoundType.ROOTED_DIRT", "harp", false, false));
        // TFCBlocks: PEAT 3.0 TERRACOTTA_BLACK TFCSounds.PEAT; kaolin 4.0 / 4.5 / 5.0; the grasses MapColor.GRASS
        assertThat(SoilBlocks.props(tfc, "peat"))
            .isEqualTo(new SoilBlocks.Props(new BigDecimal("3.0"), 51, "TFCSounds.PEAT", "harp", false, false));
        assertThat(SoilBlocks.props(tfc, "peat_grass"))
            .isEqualTo(new SoilBlocks.Props(new BigDecimal("3.0"), 1, "TFCSounds.PEAT", "harp", false, true));
        assertThat(SoilBlocks.props(tfc, "red_kaolin_clay").strength()).isEqualByComparingTo("4.0");
        assertThat(SoilBlocks.props(tfc, "red_kaolin_clay").mapColor()).isEqualTo(28);
        assertThat(SoilBlocks.props(tfc, "pink_kaolin_clay").strength()).isEqualByComparingTo("4.5");
        assertThat(SoilBlocks.props(tfc, "pink_kaolin_clay").mapColor()).isEqualTo(20);
        assertThat(SoilBlocks.props(tfc, "white_kaolin_clay").strength()).isEqualByComparingTo("5.0");
        assertThat(SoilBlocks.props(tfc, "white_kaolin_clay").mapColor()).isEqualTo(36);
        assertThat(SoilBlocks.props(tfc, "kaolin_clay_grass"))
            .isEqualTo(new SoilBlocks.Props(new BigDecimal("5.0"), 1, "SoundType.GRAVEL", "harp", false, true));

        Map<String, Object> mud = settings("tfp:mud/alfisol");
        assertThat(mud.get("template")).isEqualTo("tfp:settings/granular");
        assertThat(arguments(mud)).containsEntry("sound_block_type", "mud").containsEntry("granular_hardness", 2.0)
            .containsEntry("granular_resistance", 2.0).containsEntry("granular_instrument", "basedrum")
            .containsEntry("granular_map_color", 10);
        assertThat(mud).doesNotContainKeys("sounds", "correct_tools");
        Map<String, Object> coarse = settings("tfp:coarse_dirt/alfisol");
        assertThat(coarse.get("correct_tools")).isEqualTo(List.of("#minecraft:shovels", "#tfp:tools/shovel"));
        Map<String, Object> peat = settings("tfp:peat_grass");
        assertThat(peat.get("sounds")).isEqualTo(Map.of("break", "tfp_soil:block.peat.break", "step", "tfp_soil:block.peat.step",
            "place", "tfp_soil:block.peat.place", "hit", "tfp_soil:block.peat.hit", "fall", "tfp_soil:block.peat.fall"));
    }

