package dev.tfp.datagen;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.regex.Pattern;

/**
 * M6-GUIDE-01 (data slice): TFC's Patchouli field guide as plugin data, {@code guide/field_guide.json}.
 *
 * <p>The book is read from its English (en_us) files: {@code book.json} (the template), {@code categories/*.json} and
 * {@code entries/<category>/*.json}. The output keeps the book's structure only: the book's two translation keys, every
 * category and every entry, each entry with its page count and its icon, in reading order. Page bodies, recipe mappings,
 * the subtitle and the other locales are not carried.
 *
 * <p>An icon is either an item (with its optional component string, e.g. {@code tfc:ceramic/ingot_mold[...]}) or a
 * texture ({@code .png} under {@code textures/}). Reading order: categories by {@code sortnum}; entries of a category by
 * {@code sortnum} (an entry without one counts as 0), then by id. Category and entry names have no translation key in
 * TFC, so each gets a {@code tfp.field_guide.*} key with the English text as its source; the book keys are TFC's own.
 *
 * <p>{@code templates/} holds Patchouli's page templates (the multiblock and recipe views that pages reuse). They are not
 * guide structure and are not read.
 *
 * <p>Missing or unexpected data is an error: a missing book, category or entry folder, a category without entries, an
 * entry whose category does not resolve or is not its folder, a non-JSON file, an empty page list, a missing field, a
 * duplicate category {@code sortnum}, or an icon that is neither an item nor a texture.
 */
final class FieldGuide {
    static final String SOURCE = TfcCheckout.ASSETS + "patchouli_books/field_guide/en_us/";
    static final String BOOK = "src/main/templates/data/tfc/patchouli_books/field_guide/book.json";
    static final String OUTPUT = "guide/field_guide.json";

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (" + SOURCE + "). Do not edit: fix the generator and regenerate. "
        + "Categories and entries are in reading order. Page bodies, recipe mappings and other locales are not included.";
    private static final Pattern ITEM = Pattern.compile("[a-z0-9_.-]+:[a-z0-9_./-]+(\\[.*\\])?");

    /** The book: its id and the two TFC translation keys of its name and landing text. */
    record Book(String id, String nameKey, String landingTextKey) {
    }

    /**
     * An icon link.
     *
     * @param type       {@code item} or {@code texture}
     * @param id         our id (an item id, or a texture path under {@code tfp:}); {@code minecraft:} ids are kept
     * @param components the bracketed item components as given (renamed), or null
     */
    record Icon(String type, String id, String components) {
    }

    /** One category; {@code id} is {@code tfp:<name>}. */
    record Category(String id, String tfc, String name, String description, Icon icon, int sortnum) {
    }

    /** One entry; {@code id} is {@code tfp:<category>/<name>}, {@code category} is our category id. */
    record Entry(String id, String tfc, String category, String title, String titleKey, int sortnum, int pages,
                 Icon icon, boolean readByDefault) {
    }

    /** The whole book in reading order. */
    record Guide(Book book, List<Category> categories, List<Entry> entries) {
    }

    private FieldGuide() {
    }

    /** Writes the guide. Returns the number of entries. Fails when TFC's field guide data is missing or unexpected. */
    static int run(TfcCheckout tfc, OutputTree out) {
        Guide g = read(tfc);
        out.put(OUTPUT, Json.write(toJson(g)));
        return g.entries().size();
    }

    static Guide read(TfcCheckout tfc) {
        if (!tfc.exists(BOOK)) {
            throw new DatagenException("TFC has no field guide book.json at " + BOOK + " (the pinned checkout is incomplete)");
        }
        JsonObject bookObj = object(parseFile(tfc, BOOK), BOOK);
        Book book = new Book(Json.TO_NS + ":field_guide", string(bookObj, "name", BOOK), string(bookObj, "landing_text", BOOK));

        List<String> files = tfc.list(SOURCE);
        if (files.isEmpty()) {
            throw new DatagenException("TFC has no field guide at " + SOURCE + " (the pinned checkout is incomplete)");
        }
        // Categories: one file each, named by its folder in entries/.
        Map<String, Category> byName = new TreeMap<>();
        Map<String, JsonObject> categoryJson = new TreeMap<>();
        for (String file : files) {
            String rest = file.substring(SOURCE.length());
            if (rest.startsWith("categories/")) {
                String name = jsonName(rest.substring("categories/".length()), file);
                JsonObject o = object(parseFile(tfc, file), file);
                categoryJson.put(name, o);
            }
        }
        if (categoryJson.isEmpty()) {
            throw new DatagenException("TFC field guide has no categories at " + SOURCE + "categories/");
        }
        Set<Integer> sortnums = new HashSet<>();
        for (Map.Entry<String, JsonObject> e : categoryJson.entrySet()) {
            JsonObject o = e.getValue();
            String name = e.getKey();
            Category c = new Category(Json.TO_NS + ":" + name, Json.FROM_NS + ":" + name, string(o, "name", name),
                string(o, "description", name), icon(string(o, "icon", name), name), integer(o, "sortnum", name));
            if (!sortnums.add(c.sortnum())) {
                throw new DatagenException("two field guide categories share the sortnum " + c.sortnum());
            }
            byName.put(name, c);
        }
        List<Category> categories = new ArrayList<>(byName.values());
        categories.sort(Comparator.comparingInt(Category::sortnum));

        // Entries: one folder per category, one JSON file per entry, nothing deeper.
        Map<String, List<Entry>> entriesByCategory = new TreeMap<>();
        for (String file : files) {
            String rest = file.substring(SOURCE.length());
            if (rest.startsWith("categories/")) {
                continue;
            }
            if (rest.startsWith("templates/")) {
                continue; // Patchouli templates that pages reuse (multiblock and recipe views), not guide entries
            }
            if (!rest.startsWith("entries/")) {
                throw new DatagenException("unexpected field guide file " + file);
            }
            String path = rest.substring("entries/".length());
            int slash = path.indexOf('/');
            if (slash <= 0 || path.indexOf('/', slash + 1) >= 0) {
                throw new DatagenException("field guide entry is not entries/<category>/<name>.json: " + file);
            }
            String folder = path.substring(0, slash);
            String name = jsonName(path.substring(slash + 1), file);
            Entry entry = parseEntry(tfc.readString(file), file, folder, name);
            entriesByCategory.computeIfAbsent(folder, k -> new ArrayList<>()).add(entry);
        }
        for (String folder : entriesByCategory.keySet()) {
            if (!byName.containsKey(folder)) {
                throw new DatagenException("field guide folder entries/" + folder + " has no category file");
            }
        }
        for (String name : byName.keySet()) {
            if (!entriesByCategory.containsKey(name)) {
                throw new DatagenException("field guide category " + name + " has no entries");
            }
        }

        List<Entry> entries = new ArrayList<>();
        for (Category c : categories) {
            String folder = c.id().substring(Json.TO_NS.length() + 1);
            List<Entry> list = new ArrayList<>(entriesByCategory.get(folder));
            list.sort(Comparator.comparingInt(Entry::sortnum).thenComparing(Entry::id));
            entries.addAll(list);
        }
        return new Guide(book, categories, entries);
    }

    /** One entry file. Its {@code category} must resolve to a category file and be the folder it sits in. */
    static Entry parseEntry(String text, String source, String folder, String name) {
        JsonObject o = object(Json.parse(text, source), source);
        String category = string(o, "category", source);
        if (!category.equals(Json.FROM_NS + ":" + folder)) {
            throw new DatagenException(source + ": category " + category + " is not the folder category " + Json.FROM_NS + ":" + folder);
        }
        JsonArray pages = array(o, "pages", source);
        if (pages.isEmpty()) {
            throw new DatagenException(source + ": entry has no pages");
        }
        for (JsonElement p : pages) {
            if (!p.isJsonObject() || !p.getAsJsonObject().has("type") || !p.getAsJsonObject().get("type").isJsonPrimitive()) {
                throw new DatagenException(source + ": page without a string type");
            }
        }
        String id = Json.TO_NS + ":" + folder + "/" + name;
        String key = "tfp.field_guide.entry." + folder + "." + name + ".title";
        return new Entry(id, Json.FROM_NS + ":" + folder + "/" + name, Json.TO_NS + ":" + folder,
            string(o, "name", source), key, o.has("sortnum") ? integer(o, "sortnum", source) : 0, pages.size(),
            icon(string(o, "icon", source), source), bool(o, "read_by_default", source));
    }

    /** An icon id: an item (optionally with components) or a {@code .png} texture under {@code textures/}. Renamed to tfp. */
    static Icon icon(String raw, String source) {
        String ns = Json.renameId(raw);
        String path = ns.indexOf(':') >= 0 ? ns.substring(ns.indexOf(':') + 1) : ns;
        if (path.startsWith("textures/")) {
            if (!path.endsWith(".png") || ns.indexOf(':') < 0) {
                throw new DatagenException(source + ": texture icon " + raw + " is not a .png under textures/");
            }
            return new Icon("texture", ns, null);
        }
        if (!ITEM.matcher(ns).matches()) {
            throw new DatagenException(source + ": icon " + raw + " is neither an item id nor a texture");
        }
        int bracket = ns.indexOf('[');
        if (bracket < 0) {
            return new Icon("item", ns, null);
        }
        return new Icon("item", ns.substring(0, bracket), ns.substring(bracket));
    }

    private static String jsonName(String fileName, String file) {
        if (!fileName.endsWith(".json") || fileName.substring(0, fileName.length() - 5).contains("/")) {
            throw new DatagenException("unexpected non-JSON or nested field guide file " + file);
        }
        return fileName.substring(0, fileName.length() - ".json".length());
    }

    private static JsonElement parseFile(TfcCheckout tfc, String file) {
        return Json.parse(tfc.readString(file), file);
    }

    /** The output document: {@code {"comment", "book", "categories", "entries"}}, both lists in reading order. */
    static JsonObject toJson(Guide g) {
        JsonObject root = new JsonObject();
        root.addProperty("comment", HEADER);
        JsonObject book = new JsonObject();
        book.addProperty("id", g.book().id());
        book.addProperty("name_key", g.book().nameKey());
        book.addProperty("landing_text_key", g.book().landingTextKey());
        root.add("book", book);
        JsonArray cats = new JsonArray();
        for (Category c : g.categories()) {
            JsonObject o = new JsonObject();
            o.addProperty("id", c.id());
            o.addProperty("tfc", c.tfc());
            o.addProperty("sortnum", c.sortnum());
            o.addProperty("name_key", "tfp.field_guide.category." + c.id().substring(Json.TO_NS.length() + 1) + ".name");
            o.addProperty("name", c.name());
            o.addProperty("description", c.description());
            o.add("icon", icon(c.icon()));
            cats.add(o);
        }
        root.add("categories", cats);
        JsonArray entries = new JsonArray();
        for (Entry e : g.entries()) {
            JsonObject o = new JsonObject();
            o.addProperty("id", e.id());
            o.addProperty("tfc", e.tfc());
            o.addProperty("category", e.category());
            o.addProperty("sortnum", e.sortnum());
            o.addProperty("title_key", e.titleKey());
            o.addProperty("title", e.title());
            o.addProperty("pages", e.pages());
            o.add("icon", icon(e.icon()));
            o.addProperty("read_by_default", e.readByDefault());
            entries.add(o);
        }
        root.add("entries", entries);
        return root;
    }

    private static JsonObject icon(Icon i) {
        JsonObject o = new JsonObject();
        o.addProperty("type", i.type());
        o.addProperty("id", i.id());
        if (i.components() != null) {
            o.addProperty("components", i.components());
        }
        return o;
    }

    private static JsonObject object(JsonElement e, String source) {
        if (!e.isJsonObject()) {
            throw new DatagenException(source + ": not a JSON object");
        }
        return e.getAsJsonObject();
    }

    private static JsonArray array(JsonObject o, String key, String source) {
        JsonElement e = o.get(key);
        if (e == null || !e.isJsonArray()) {
            throw new DatagenException(source + ": missing array '" + key + "'");
        }
        return e.getAsJsonArray();
    }

    private static String string(JsonObject o, String key, String source) {
        JsonElement e = o.get(key);
        if (e == null || !e.isJsonPrimitive() || !e.getAsJsonPrimitive().isString()) {
            throw new DatagenException(source + ": missing string '" + key + "'");
        }
        return e.getAsString();
    }

    private static int integer(JsonObject o, String key, String source) {
        JsonElement e = o.get(key);
        if (e == null || !e.isJsonPrimitive() || !e.getAsJsonPrimitive().isNumber()) {
            throw new DatagenException(source + ": missing number '" + key + "'");
        }
        return e.getAsInt();
    }

    private static boolean bool(JsonObject o, String key, String source) {
        JsonElement e = o.get(key);
        if (e == null || !e.isJsonPrimitive() || !e.getAsJsonPrimitive().isBoolean()) {
            throw new DatagenException(source + ": missing boolean '" + key + "'");
        }
        return e.getAsBoolean();
    }
}
