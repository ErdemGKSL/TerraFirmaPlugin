import java.util.TreeSet;
import java.util.function.Function;

/**
 * Writes every allocation (M1-DGN-04) and the vanilla-block suppression data (M1-DGN-05) into the content tree.
 *
 * <ul>
 *   <li>{@code visuals/<family>/<profile>/nether-end-<off|on>/}: {@code visual_templates.yml} (the
 *       {@code tfp:visual/<id>} templates the block entries call), {@code visual_mappings.yml}
 *       ({@code block_state_mappings} hiding real instances of the claimed states) and
 *       {@code suppressed_blocks.json} (repurposed vanilla blocks whose creation the runtime blocks, M1-INST-04).
 *       The installer (M1-INST-03) copies the two YAML files of the selected allocation into our CE pack.</li>
 *   <li>{@code visuals/index.json}: every allocation's pool use, the defaults and the reserve threshold.</li>
 *   <li>{@code datapack/tfp_visuals/}: block tag edits for the client-relevant tags of every vanilla block used
 *       as a visual in any allocation (tags are global, so one datapack serves every profile).</li>
 *   <li>{@code reports/visual-allocation-<profile>-<family>.md}: human-readable allocation report.</li>
 * </ul>
 */
public final class VisualOutputs {
    public static final String INDEX = "visuals/index.json";
    public static final String DATAPACK = "datapack/tfp_visuals/";
    public static final String TAGS = DATAPACK + "data/minecraft/tags/block/";
    static final String TEMPLATES_FILE = "visual_templates.yml";
    static final String MAPPINGS_FILE = "visual_mappings.yml";
    static final String SUPPRESSED_FILE = "suppressed_blocks.json";
    private static final String HEADER = "Generated by tools/datagen (visual allocator, M1-DGN-04). Do not edit: "
        + "fix the generator and regenerate.";

    /** Vanilla contents (1.21.5+ and 26.x jars) of the tags we edit; 1.21.4 lacks the ambient tags. */
    static final Map<String, List<String>> VANILLA_TAGS = vanillaTags();

    private VisualOutputs() {
    }

    private static Map<String, List<String>> vanillaTags() {
        Map<String, List<String>> m = new LinkedHashMap<>();
        m.put("triggers_ambient_desert_sand_block_sounds", List.of("minecraft:sand", "minecraft:red_sand"));
        m.put("triggers_ambient_desert_dry_vegetation_block_sounds",
            List.of("#minecraft:terracotta", "minecraft:sand", "minecraft:red_sand"));
        m.put("triggers_ambient_dried_ghast_block_sounds", List.of("minecraft:soul_sand", "minecraft:soul_soil"));
        m.put("crystal_sound_blocks", List.of("minecraft:amethyst_block", "minecraft:budding_amethyst"));
        return m;
    }

    /** Allocates every profile × family × Nether/End setting and writes all outputs. Throws on any overflow. */
    public static List<Allocation> run(OutputTree out, List<VisualDemand> demand, Function<String, String> modelContent) {
        VanillaSupply supply = VanillaSupply.load();
        List<Allocation> all = new ArrayList<>();
        for (VersionFamily family : VersionFamily.values()) {
            for (Profile profile : Profile.values()) {
                List<Allocation> pair = new ArrayList<>();
                for (boolean ne : new boolean[] {false, true}) {
                    Allocation a = VisualAllocator.allocate(demand, modelContent, profile, family, ne, supply);
                    writeAllocation(out, a);
                    pair.add(a);
                }
                out.put("reports/visual-allocation-" + profile.id() + "-" + family.id() + ".md",
                    AllocationReport.markdown(pair.get(0), pair.get(1), demand));
                all.addAll(pair);
            }
        }
        out.put(INDEX, Json.write(index(all)));
        writeDatapack(out, all);
        return all;
    }

    static void writeAllocation(OutputTree out, Allocation a) {
        String dir = a.dir() + "/";
        out.put(dir + TEMPLATES_FILE, Yaml.write(HEADER + "\nAllocation " + label(a) + ".",
            Map.of("templates#visuals", templates(a))));
        Map<String, Object> mappings = new LinkedHashMap<>(a.mappings());
        out.put(dir + MAPPINGS_FILE, Yaml.write(HEADER + "\nAllocation " + label(a) + ": real vanilla instances of "
            + "every claimed state are sent as a look-alike that no custom block uses.",
            Map.of("block_state_mappings", mappings)));
        out.put(dir + SUPPRESSED_FILE, Json.write(suppression(a)));
    }

    static String label(Allocation a) {
        return a.profile().id() + ", MC " + a.family().id() + ", Nether/End " + (a.netherEnd() ? "on" : "off");
    }

    /** {@code tfp:visual/<block id>} → appearance (single state) or appearance name → appearance. */
    static Map<String, Object> templates(Allocation a) {
        Map<String, Map<String, Object>> byBlock = new TreeMap<>();
        for (VisualDemand d : a.demand()) {
            Unit u = a.unitByDemand().get(d.key());
            byBlock.computeIfAbsent(d.blockId(), k -> new LinkedHashMap<>())
                .put(d.appearance(), CeBlockStates.appearance(u.visual(), u.models()));
        }
        Map<String, Object> t = new LinkedHashMap<>();
        byBlock.forEach((id, apps) -> t.put(CeBlockStates.visualTemplate(id),
            apps.size() == 1 && apps.containsKey("") ? apps.get("") : apps));
        return t;
    }

    /** M1-DGN-05: repurposed vanilla blocks of one allocation and the creation paths the runtime must block. */
    static JsonObject suppression(Allocation a) {
        SortedMap<String, List<VanillaSupply.State>> byBlock = new TreeMap<>();
        for (Unit u : a.units()) {
            if (u.state() != null) {
                byBlock.computeIfAbsent(u.state().block(), k -> new ArrayList<>()).add(u.state());
            }
        }
        JsonObject o = new JsonObject();
        o.addProperty("profile", a.profile().id());
        o.addProperty("family", a.family().id());
        o.addProperty("nether_end", a.netherEnd());
        JsonArray suppress = new JsonArray();
        JsonArray identity = new JsonArray();
        byBlock.forEach((block, states) -> {
            JsonObject b = new JsonObject();
            b.addProperty("block", block);
            JsonArray st = new JsonArray();
            states.stream().map(VanillaSupply.State::state).sorted().forEach(st::add);
            boolean allIdentity = states.stream().allMatch(s -> s.source().identity());
            b.addProperty("source", allIdentity ? "identity" : states.stream().filter(s -> !s.source().identity())
                .findFirst().orElseThrow().source().csv);
            b.add("states", st);
            if (allIdentity) {
                identity.add(b); // real instances look identical through the mapping; nothing to suppress
            } else {
                JsonArray paths = new JsonArray();
                creationPaths(block).forEach(paths::add);
                b.add("creation_paths", paths);
                suppress.add(b);
            }
        });
        o.add("suppress", suppress);
        o.add("identity_duplicates", identity);
        return o;
    }

    /**
     * Ways a vanilla block can appear in a TFC world. {@code item} (recipes, loot, creative, dispensers, commands)
     * applies to every block; the rest are world mechanics the runtime intercepts (M1-INST-04).
     */
    static List<String> creationPaths(String block) {
        String b = block.substring(block.indexOf(':') + 1);
        List<String> p = new ArrayList<>();
        p.add("item");
        switch (b) {
            case "stone", "cobblestone", "obsidian" -> p.add("lava_water");
            case "basalt" -> p.add("lava_soul_soil_blue_ice");
            case "grass_block", "mycelium" -> p.add("block_spread");
            case "clay" -> p.add("mud_drying_under_dripstone");
            case "moss_block" -> p.add("moss_bonemeal");
            case "sculk" -> p.add("sculk_spread");
            case "sponge" -> p.add("wet_sponge_drying");
            default -> {
            }
        }
        if (b.endsWith("_concrete")) {
            p.add("concrete_powder_water");
        }
        if (b.contains("copper") && !b.contains("ore") && !b.startsWith("raw_")) {
            p.add("copper_weathering_scraping_waxing");
        }
        if (b.startsWith("dead_") && b.endsWith("_coral_block")) {
            p.add("coral_death");
        }
        return p;
    }

    static JsonObject index(List<Allocation> all) {
        JsonObject o = new JsonObject();
        o.addProperty("format", 1);
        o.addProperty("solid_reserve_warning", Profile.SOLID_RESERVE_WARNING);
        JsonObject fams = new JsonObject();
        for (VersionFamily f : VersionFamily.values()) {
            JsonObject j = new JsonObject();
            j.addProperty("default_profile", Profile.defaultFor(f).id());
            j.addProperty("solid_pool", f.solidPool());
            JsonArray v = new JsonArray();
            f.researchedVersions().forEach(v::add);
            j.add("researched_versions", v);
            fams.add(f.id(), j);
        }
        o.add("families", fams);
        JsonArray arr = new JsonArray();
        for (Allocation a : all) {
            JsonObject j = new JsonObject();
            j.addProperty("family", a.family().id());
            j.addProperty("profile", a.profile().id());
            j.addProperty("nether_end", a.netherEnd());
            j.addProperty("dir", a.dir());
            j.addProperty("appearances", a.demand().size());
            j.addProperty("visuals", a.units().size());
            j.addProperty("explicit_states", a.explicitUsed());
            j.addProperty("solid_used", a.solidUsed());
            j.addProperty("solid_free", a.solidFree());
            j.addProperty("mappings", a.mappings().size());
            JsonObject pools = new JsonObject();
            for (String p : VisualAllocator.POOLS) {
                JsonObject pj = new JsonObject();
                pj.addProperty("capacity", a.capacity().get(p));
                pj.addProperty("used", a.used().get(p));
                pools.add(p, pj);
            }
            j.add("pools", pools);
            arr.add(j);
        }
        o.add("allocations", arr);
        return o;
    }

    /** One datapack for all profiles: edits the client-relevant block tags of every vanilla block used as a visual. */
    static void writeDatapack(OutputTree out, List<Allocation> all) {
        Set<String> used = new TreeSet<>();
        Set<String> waterloggedBlocks = new TreeSet<>();
        for (Allocation a : all) {
            for (Unit u : a.units()) {
                if (u.state() != null) {
                    used.add(u.state().block());
                    if (u.state().state().contains("waterlogged=true")) {
                        waterloggedBlocks.add(u.state().block());
                    }
                }
            }
        }
        JsonObject pack = new JsonObject();
        JsonObject p = new JsonObject();
        p.addProperty("description", "TerraFirmaPlugin visual-state tag edits (generated)");
        p.addProperty("pack_format", 61);
        JsonObject sf = new JsonObject();
        sf.addProperty("min_inclusive", 61);
        sf.addProperty("max_inclusive", 1000);
        p.add("supported_formats", sf);
        p.addProperty("min_format", 61);
        p.addProperty("max_format", 1000);
        pack.add("pack", p);
        out.put(DATAPACK + "pack.mcmeta", Json.write(pack));
        for (Map.Entry<String, List<String>> tag : VANILLA_TAGS.entrySet()) {
            List<String> values = editedTag(tag.getValue(), used);
            if (!values.equals(tag.getValue())) {
                out.put(TAGS + tag.getKey() + ".json", Json.write(tagJson(true, values)));
            }
        }
        if (!waterloggedBlocks.isEmpty()) {
            out.put(TAGS + "impermeable.json", Json.write(tagJson(false, List.copyOf(waterloggedBlocks))));
        }
    }

    /** Vanilla tag values minus the used blocks; {@code #minecraft:terracotta} is expanded only if needed. */
    static List<String> editedTag(List<String> vanilla, Set<String> used) {
        List<String> out = new ArrayList<>();
        for (String v : vanilla) {
            if (v.equals("#minecraft:terracotta")) {
                List<String> members = new ArrayList<>();
                members.add("minecraft:terracotta");
                HideTargets.COLORS.forEach(c -> members.add("minecraft:" + c + "_terracotta"));
                if (members.stream().anyMatch(used::contains)) {
                    members.stream().filter(m -> !used.contains(m)).forEach(out::add);
                } else {
                    out.add(v);
                }
            } else if (!used.contains(v)) {
                out.add(v);
            }
        }
        return out;
    }

    private static JsonObject tagJson(boolean replace, List<String> values) {
        JsonObject o = new JsonObject();
        o.addProperty("replace", replace);
        JsonArray a = new JsonArray();
        values.forEach(a::add);
        o.add("values", a);
        return o;
    }
}
