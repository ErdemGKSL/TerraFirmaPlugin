/**
 * PAR-HEAT-11: candles, candle cakes and jack-o'-lanterns. Registers the {@link CandleDevice} kinds, provides
 * {@link CandleService} (lazy burnout, lighting, dousing, the candle on a cake, pumpkin carving), registers its
 * {@code FireLightable} with the fire starting service, catches the lit blocks of a loaded chunk up and listens for the
 * held torch, the candle on a cake and the carving knife. Needs the tags, device, catch-up and fire modules before it in
 * the service file.
 *
 * <p>The CraftEngine blocks and items are generated by {@code tools/datagen} {@code light/candle/CandleBlocks} and loaded
 * with PAR-HEAT-26; until then no candle block exists and nothing here runs. The candle cake's bite needs the cake of
 * PAR-DECO-12 ({@link CandleDevice.CakeEating} in the services) and the carving the pumpkin of PAR-FARM-05
 * ({@link CandleService.Rotting} in the services; without it a pumpkin is never rotten).
 */
public final class CandleModule implements FeatureModule {
    public static final String ID = "candle";
    /** TFC {@code TFCTags.Items.TOOLS_KNIFE}. */
    public static final String KNIVES = "c:tools/knife";
    /** NeoForge {@code Tags.Items.TOOLS_SHEAR}. */
    public static final String SHEARS = "c:tools/shear";
    /** Vanilla's block interaction range, for the candle cake's hit height. */
    static final double REACH = 6.0;

    @Override
    public String id() {
        return ID;
    }

    @Override
    public void enable(ModuleContext context) {
        DeviceService devices = context.services().require(DeviceService.class);
        Tags tags = context.services().require(Tags.class);
        CustomBlocks blocks = context.integrations().customBlocks();
        AtomicReference<CandleService> ref = new AtomicReference<>();
        PaperCandleEffects effects = new PaperCandleEffects(context.scheduler(), blocks,
            () -> context.integrations().blockVisuals(), ref::get);
        CandleDevice device = new CandleDevice(new CandleDevice.Services(
            () -> CandleRules.CANDLE_TICKS, () -> CandleRules.JACK_O_LANTERN_TICKS,
            stack -> context.integrations().customItems().idOf(stack).filter(FireStarterListener.FIRESTARTER::equals)
                .isPresent(),
            CandleModule::hitHeight,
            () -> context.services().get(CandleDevice.CakeEating.class),
            id -> context.integrations().customItems().create(id, 1).orElse(ItemStack.empty()),
            effects));
        device.kinds().forEach(devices::register);
        CandleService service = new CandleService(blocks, devices, device, () -> context.clock().get().playerTicks(),
            context::regions, context.scheduler().cpuExecutor(),
            new CommitBudget(CandleService.BUDGET_NANOS, System::nanoTime));
        ref.set(service);
        context.services().provide(CandleService.class, service);
        Optional<FireStarting> fire = context.services().get(FireStarting.class);
        fire.ifPresent(f -> f.register(service.lightable()));
        blocks.onChunkLoad(chunk -> {
            for (CandleService.Waiting w : service.chunkLoaded(chunk, lazyBlocks(context, chunk))) {
                effects.burnoutIn(w.block(), w.ticks());
            }
        });
        context.listen(new CandleListener(stack -> context.integrations().customItems().idOf(stack),
            stack -> stack.getType() == Material.SHEARS || tags.is(stack, KNIVES) || tags.is(stack, SHEARS),
            blocks, service, effects,
            (block, face, player, stack) -> {
                if (fire.isPresent()) {
                    fire.get().start(block, face, player, stack,
                        FireStarting.Starter.fixed(FireStart.Strength.WEAK, FireStart.NO_FIREPIT), r -> { });
                } else {
                    service.light(block);
                }
            },
            () -> CandleRules.PUMPKIN_CARVING,
            () -> context.services().get(CandleService.Rotting.class).orElse(b -> false)));
    }

    /** Where the player's look ray hits {@code block}, 0 (bottom) to 1 (top); 0 when it misses. Player's thread. */
    static double hitHeight(Player player, Block block) {
        RayTraceResult hit = player.rayTraceBlocks(REACH);
        if (hit == null || hit.getHitBlock() == null || !hit.getHitBlock().equals(block)) {
            return 0;
        }
        return Math.max(0, Math.min(1, hit.getHitPosition().getY() - block.getY()));
    }

    /** The devices of the chunk's lazy block index (PAR-INFRA-25 lists every device there). Region thread. */
    static Collection<BlockPos> lazyBlocks(ModuleContext context, org.bukkit.Chunk chunk) {
        return context.services().get(CatchUpService.class).flatMap(c -> c.index(chunk))
            .map(index -> index.entries().entrySet().stream()
                .filter(e -> CatchUpModule.DEVICE_KIND.equals(e.getValue()))
                .map(Map.Entry::getKey).toList())
            .orElse(List.of());
    }
}
