package dev.tfp.datagen.tool;

import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * PAR-TOOL-01: TFC's rock tool heads and tools ({@code stone/<type>/<category>}, 4 rock categories x 12 types = 48 items) as
 * CraftEngine items ({@code configuration/tool/stone.yml}). The six heads of each category are plain items; the six tools carry
 * the tier's durability and, for the mining kinds, a vanilla {@code tool} component: speed and mineable tag of the kind, break
 * power = the tier's level (0: the rock tiers cannot mine stone-level blocks). The attack damage and attack speed are TFC's
 * {@code ToolItem.productAttributes(tier, factor, speed)} (the modifier amount is {@code factor x tier damage}, which in
 * game adds to the base 1 as in TFC).
 *
 * <p>The values are read from TFC's source ({@code RockCategory.ItemType}, {@code TFCTiers}); a changed format fails the run.
 * The javelin is a plain damageable weapon here; its throwing is PAR-TOOL-05. TFC's javelin model is a NeoForge
 * {@code separate_transforms} model, so the generated one is the flat {@code _gui} sprite held as a handheld item.
 */
public final class RockTools {
    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/tool/";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    /** The pack namespace of the names (any namespace's lang file is merged by the client). */
    static final String LANG_NS = "tfp_tool";
    static final String LANG_RP = PACK + "resourcepack/assets/" + LANG_NS + "/lang/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String CATEGORY_SOURCE = "src/main/java/net/dries007/tfc/common/blocks/rock/RockCategory.java";
    public static final String TIERS_SOURCE = "src/main/java/net/dries007/tfc/common/TFCTiers.java";
    public static final String ITEMS_SOURCE = "src/main/java/net/dries007/tfc/common/items/TFCItems.java";

    static final List<String> CATEGORIES = List.of("igneous_extrusive", "igneous_intrusive", "metamorphic", "sedimentary");
    static final List<String> KINDS = List.of("axe", "hammer", "hoe", "javelin", "knife", "shovel");

    /** The block tag each mining kind mines faster; the javelin mines nothing. Knife and hammer use our own tags. */
    static final Map<String, String> MINEABLE = Map.of(
        "axe", "minecraft:mineable/axe", "hammer", "tfp:mineable/hammer", "hoe", "minecraft:mineable/hoe",
        "knife", "tfp:mineable/knife", "shovel", "minecraft:mineable/shovel",
        "chisel", "tfp:mineable/chisel", "propick", "tfp:mineable/propick");
    /** The vanilla tool each kind is rendered as (hand pose, enchantability). */
    static final Map<String, String> VANILLA_BASE = Map.of(
        "axe", "axe", "hammer", "pickaxe", "hoe", "hoe", "knife", "hoe", "shovel", "shovel", "javelin", "sword",
        "chisel", "pickaxe", "propick", "pickaxe");

    private static final Pattern TIER = Pattern.compile(
        "(\\w+) = create\\(\"(\\w+)\", BlockTags\\.INCORRECT_FOR_(\\w+)_TOOL, (\\d+), (\\d+), ([\\d.]+)f, ([\\d.]+)f, \\d+\\)");
    private static final Pattern KIND = Pattern.compile(
        "(AXE|HAMMER|HOE|JAVELIN|KNIFE|SHOVEL)\\(rock -> new \\w+\\([^;]*?tool\\(rock, (-?[\\d.]+)f, (-?[\\d.]+)f\\)\\)");

    public static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (PAR-TOOL-01, dev.tfp.datagen.tool). Do not edit: fix the generator "
        + "and regenerate.";

    /** One TFC tool tier: level, uses, mining speed, attack damage bonus. */
    public record Tier(int level, int uses, BigDecimal speed, BigDecimal damage) {
        /**
         * The vanilla tool material the item is rendered as (hand pose, enchantability), by TFC's {@code INCORRECT_FOR_*}
         * tag: level 0 wooden, 1 stone, 2 and 3 iron, above that diamond (netherite as diamond: no fire resistance).
         */
        public String vanillaTool() {
            return level == 0 ? "wooden" : level == 1 ? "stone" : level <= 3 ? "iron" : "diamond";
        }
    }

    /** One tool kind's attack: the damage factor and the attack speed modifier. */
    public record Attack(BigDecimal factor, BigDecimal speed) {
    }

    /** One generated item. {@code tool} is false for a head. */
    public record Item(String id, String kind, String category, boolean tool) {
        /** The name of the model file of the item: a javelin tool uses its flat {@code _gui} sprite. */
        String modelSource() {
            return id + (kind.equals("javelin") && tool ? "_gui" : "");
        }

        String langKey() {
            return "item." + Json.TO_NS + "." + id.replace('/', '.');
        }

        String tfcLangKey() {
            return "item." + Json.FROM_NS + "." + id.replace('/', '.');
        }
    }

    private RockTools() {
    }

    /** Whether the checkout has the rock tools (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(CATEGORY_SOURCE) && tfc.exists(TIERS_SOURCE)
            && tfc.exists(TfcCheckout.ASSETS + "models/item/stone/axe/igneous_intrusive.json");
    }

    /** Every item in registration order: per category, the head then the tool of each kind. */
    public static List<Item> items() {
        List<Item> out = new ArrayList<>();
        for (String category : CATEGORIES) {
            for (String kind : KINDS) {
                out.add(new Item("stone/" + kind + "_head/" + category, kind, category, false));
                out.add(new Item("stone/" + kind + "/" + category, kind, category, true));
            }
        }
        return out;
    }

    /** TFC's rock tiers by category name. */
    public static Map<String, Tier> tiers(TfcCheckout tfc) {
        Map<String, Tier> out = new TreeMap<>();
        Matcher m = TIER.matcher(tfc.readString(TIERS_SOURCE));
        while (m.find()) {
            {
                out.put(m.group(2), new Tier(Integer.parseInt(m.group(4)), Integer.parseInt(m.group(5)),
                    new BigDecimal(m.group(6)), new BigDecimal(m.group(7))));
            }
        }
        if (!out.keySet().containsAll(CATEGORIES) || !out.containsKey(ObsidianTools.TIER)) {
            throw new DatagenException(TIERS_SOURCE + ": rock tiers " + CATEGORIES + " not all found, got " + out.keySet());
        }
        return out;
    }

    /** TFC's attack factor and attack speed per kind ({@code RockCategory.ItemType}). */
    public static Map<String, Attack> attacks(TfcCheckout tfc) {
        Map<String, Attack> out = new TreeMap<>();
        Matcher m = KIND.matcher(tfc.readString(CATEGORY_SOURCE));
        while (m.find()) {
            out.put(m.group(1).toLowerCase(Locale.ROOT), new Attack(new BigDecimal(m.group(2)), new BigDecimal(m.group(3))));
        }
        if (!out.keySet().containsAll(KINDS)) {
            throw new DatagenException(CATEGORY_SOURCE + ": item types " + KINDS + " not all found, got " + out.keySet());
        }
        return out;
    }

    /** Writes the CE items, models, textures and names. */
    public static void run(TfcCheckout tfc, OutputTree out) {
        write(tfc, out, items(), tiers(tfc), attacks(tfc), "stone.yml", "");
    }

    /** Writes {@code items} to {@code configuration/tool/<file>} with their models and names. */
    public static void write(TfcCheckout tfc, OutputTree out, List<Item> items, Map<String, Tier> tiers, Map<String, Attack> attacks,
            String file, String langSuffix) {
        Map<String, Object> entries = new LinkedHashMap<>();
        for (Item item : items) {
            copyModel(tfc, out, item);
            entries.put(Json.TO_NS + ":" + item.id(), entry(item, tiers.get(item.category()), attacks.get(item.kind())));
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", entries);
        out.put(CONFIG + file, Yaml.write(HEADER, root));
        writeLang(tfc, out, items, langSuffix);
    }

    /** The CE entry of one item. */
    static Map<String, Object> entry(Item item, Tier tier, Attack attack) {
        Map<String, Object> e = new LinkedHashMap<>();
        Map<String, Object> args = new LinkedHashMap<>();
        args.put("item_lang_key", item.langKey());
        if (!item.tool()) {
            e.put("template", "tfp:item/simple");
            e.put("arguments", args);
            return e;
        }
        if (item.kind().equals("tuyere")) { // TFC TieredItem: no durability, no tool rules
            e.put("template", "tfp:item/simple");
            e.put("arguments", args);
            return e;
        }
        if (item.kind().equals("shears")) { // vanilla ShearsItem with the tier's uses
            args.put("durability", tier.uses());
            e.put("template", "tfp:item/shears");
            e.put("arguments", args);
            return e;
        }
        if (item.kind().equals("javelin")) { // PAR-TOOL-05: a trident carrier the player throws
            args.put("damage", attack.factor().multiply(tier.damage()).stripTrailingZeros());
            args.put("attack_speed", attack.speed());
            args.put("durability", tier.uses());
            args.put("break_power", tier.level());
            e.put("template", "tfp:item/javelin");
            e.put("arguments", args);
            return e;
        }
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("attribute_modifiers", List.of(modifier("attack_damage", attack.factor().multiply(tier.damage())),
            modifier("attack_speed", attack.speed())));
        String mineable = MINEABLE.get(item.kind());
        args.put("material", tier.vanillaTool() + "_" + VANILLA_BASE.get(item.kind()));
        args.put("durability", tier.uses());
        args.put("speed", tier.speed());
        args.put("break_power", tier.level());
        args.put("mineable_tag", mineable);
        args.put("tool_tag", Json.TO_NS + ":tools/" + item.kind());
        e.put("template", "tfp:item/tool");
        e.put("arguments", args);
        e.put("data", data);
        return e;
    }

    private static Map<String, Object> modifier(String type, BigDecimal amount) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("type", type);
        m.put("amount", amount.stripTrailingZeros());
        m.put("operation", "add_value");
        m.put("slot", "mainhand");
        return m;
    }

    /**
     * Copies the item model and its texture. A head or a plain tool is TFC's {@code item/handheld} model; the javelin's own
     * model is a NeoForge loader model, so its flat {@code _gui} sprite is used.
     */
    public static void copyModel(TfcCheckout tfc, OutputTree out, Item item) {
        String src = TfcCheckout.ASSETS + "models/item/" + item.modelSource() + ".json";
        JsonObject model = Json.parse(tfc.readString(src), src).getAsJsonObject();
        String parent = model.has("parent") ? model.get("parent").getAsString() : "";
        boolean flipped = parent.equals(Json.FROM_NS + ":item/handheld_flipped"); // the knives; the asset pipeline writes its parent
        if (!(parent.equals("item/handheld") || parent.equals("item/generated") || flipped) || model.has("loader")
                || model.has("overrides") || !model.has("textures")) {
            throw new DatagenException(src + ": expected a plain handheld or generated model, got parent " + parent);
        }
        String ref = model.getAsJsonObject("textures").get("layer0").getAsString();
        if (!ref.startsWith(Json.FROM_NS + ":")) {
            throw new DatagenException(src + ": layer0 outside the tfc namespace: " + ref);
        }
        String path = ref.substring(Json.FROM_NS.length() + 1);
        String png = TfcCheckout.ASSETS + "textures/" + path + ".png";
        if (!tfc.exists(png)) {
            throw new DatagenException(src + " uses missing texture " + ref);
        }
        out.put(RP + "textures/" + path + ".png", tfc.read(png));
        if (tfc.exists(png + ".mcmeta")) {
            out.put(RP + "textures/" + path + ".png.mcmeta", tfc.read(png + ".mcmeta"));
        }
        JsonObject m = new JsonObject();
        m.addProperty("parent", flipped ? Json.TO_NS + ":item/handheld_flipped" : "minecraft:item/handheld");
        JsonObject t = new JsonObject();
        t.addProperty("layer0", Json.TO_NS + ":" + path);
        m.add("textures", t);
        out.put(RP + "models/item/" + item.id() + ".json", Json.write(m));
    }

    /** TFC's names in every locale that has them (English must have all). */
    private static void writeLang(TfcCheckout tfc, OutputTree out, List<Item> items) {
        writeLang(tfc, out, items, "");
    }

    /** As above, into the lang file named {@code <locale><suffix>} under a namespace of its own when {@code suffix} is set. */
    public static void writeLang(TfcCheckout tfc, OutputTree out, List<Item> items, String suffix) {
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            TreeMap<String, String> keys = new TreeMap<>();
            for (Item item : items) {
                if (src.has(item.tfcLangKey())) {
                    keys.put(item.langKey(), src.get(item.tfcLangKey()).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC item tfc:" + item.id() + " has no English name " + item.tfcLangKey());
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put((suffix.isEmpty() ? LANG_RP : LANG_RP.replace(LANG_NS, LANG_NS + "_" + suffix)) + locale + ".json", Json.write(o));
            }
        }
    }
}
