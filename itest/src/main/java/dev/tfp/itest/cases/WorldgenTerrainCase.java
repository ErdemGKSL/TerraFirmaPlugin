package dev.tfp.itest.cases;

import dev.tfp.core.climate.ChunkClimate;
import dev.tfp.itest.SelfTestCase;
import dev.tfp.itest.SelfTestContext;
import dev.tfp.paper.TfpPlugin;
import dev.tfp.paper.climate.ChunkClimateSource;
import dev.tfp.paper.integration.BlockStateRef;
import dev.tfp.paper.integration.CustomBlocks;
import dev.tfp.paper.scheduler.Scheduler;
import java.time.Duration;
import java.util.List;
import java.util.Optional;
import java.util.concurrent.CompletableFuture;
import org.bukkit.Bukkit;
import org.bukkit.Location;
import org.bukkit.Material;
import org.bukkit.World;
import org.bukkit.block.Block;

/**
 * {@code worldgen.terrain_generates} (M2-GEN-07): a chunk away from spawn is generated by our
 * {@code TfcChunkGenerator} and its surface column has TFC terrain. On the owning region thread, the top
 * block that is neither air nor water at a fixed column is one of the expected terrain classes (stone, dirt,
 * grass block, sand, gravel, or a CraftEngine rock visual {@value #ROCK_PREFIX}*), and the chunk's climate
 * reading differs from the neutral placeholder.
 *
 * <p>Chunk: {@value #CHUNK_OFFSET} chunks east of spawn (outside the always-loaded spawn chunks), force-loaded
 * while it is generated and checked, then released. Column: the chunk's centre block column (x and z at +8).
 * The world seed is the harness world's, so the expected classes are deterministic for a given world.
 */
public final class WorldgenTerrainCase implements SelfTestCase {
    static final int CHUNK_OFFSET = 24;
    /** Rock visuals are CraftEngine blocks in the {@code tfp} namespace: {@code tfp:rock/...}. */
    static final String ROCK_PREFIX = "tfp:rock/";
    /** Vanilla materials a TFC surface can show, besides a rock visual. */
    static final List<Material> EXPECTED = List.of(Material.STONE, Material.DIRT, Material.GRASS_BLOCK,
            Material.SAND, Material.GRAVEL);
    private static final Duration STEP = Duration.ofSeconds(20);
    private static final Duration GENERATE = Duration.ofSeconds(60);

    @Override
    public String name() {
        return "worldgen.terrain_generates: a generated chunk has TFC terrain at the surface (M2-GEN-07)";
    }

    @Override
    public Duration timeout() {
        return Duration.ofSeconds(CraftEngineBlockRoundTripCase.REBUILD.toSeconds() + GENERATE.toSeconds()
                + 3 * STEP.toSeconds() + 30);
    }

    @Override
    public CompletableFuture<String> run(SelfTestContext ctx) {
        TfpPlugin tfp = ctx.tfp();
        Scheduler s = tfp.scheduler();
        CustomBlocks blocks = tfp.integrations().customBlocks();
        return OnThread.script("worldgen-terrain", () -> {
            // The rock visuals need CraftEngine's pack; a rebuild in progress would make them look missing.
            OnThread.awaitPackRebuild(tfp, CraftEngineBlockRoundTripCase.REBUILD);
            World world = Bukkit.getWorlds().getFirst();
            Location spawn = world.getSpawnLocation();
            int cx = (spawn.getBlockX() >> 4) + CHUNK_OFFSET;
            int cz = spawn.getBlockZ() >> 4;
            int x = (cx << 4) + 8;
            int z = (cz << 4) + 8;
            // Force-load before generating, so the chunk stays loaded for the read below.
            OnThread.global(s, STEP, () -> {
                world.setChunkForceLoaded(cx, cz, true);
                return null;
            });
            try {
                OnThread.await(world.getChunkAtAsync(cx, cz), GENERATE, "generating chunk " + cx + "," + cz);
                return OnThread.region(s, world, cx, cz, STEP, () -> check(world, blocks, x, z, cx, cz));
            } finally {
                OnThread.global(s, STEP, () -> {
                    world.setChunkForceLoaded(cx, cz, false);
                    return null;
                });
            }
        });
    }

    /** Runs on the owning region thread of chunk {@code cx, cz}. */
    static String check(World world, CustomBlocks blocks, int x, int z, int cx, int cz) {
        Block top = null;
        for (int y = world.getMaxHeight() - 1; y >= world.getMinHeight(); y--) {
            Block b = world.getBlockAt(x, y, z);
            if (!b.isEmpty() && !b.isLiquid()) {
                top = b;
                break;
            }
        }
        if (top == null) {
            throw new AssertionError("chunk " + cx + "," + cz + " has no solid block in column " + x + "," + z
                    + ": the generator wrote nothing (refused or not run)");
        }
        Material material = top.getType();
        Optional<BlockStateRef> custom = blocks.stateAt(top);
        String rock = custom.map(BlockStateRef::id).filter(id -> id.startsWith(ROCK_PREFIX)).orElse(null);
        if (rock == null && !EXPECTED.contains(material)) {
            throw new AssertionError("top block at " + x + "," + top.getY() + "," + z + " is " + material
                    + (custom.isPresent() ? " (" + custom.get().id() + ")" : "") + ", expected one of " + EXPECTED
                    + " or " + ROCK_PREFIX + "*");
        }
        ChunkClimate climate = ChunkClimateSource.climateAt(world.getSeed(), x, z);
        if (climate.equals(ChunkClimate.NEUTRAL)) {
            throw new AssertionError("climate at " + x + "," + z + " is the neutral placeholder " + climate);
        }
        return "chunk " + cx + "," + cz + " top " + (rock != null ? rock : material.name()) + " at y=" + top.getY()
                + " in column " + x + "," + z + "; climate " + climate;
    }
}
