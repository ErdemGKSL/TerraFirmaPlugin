/**
 * PAR-INFRA-03 {@code fw-background-art}: the GUI images of {@link GuiImages} as PNGs in our CraftEngine resource pack
 * ({@code assets/tfp/textures/font/gui/}) and their {@code images:} entries ({@code configuration/gui.yml}, font
 * {@code tfp:gui}), plus the empty item model ({@code tfp:gui/blank}) button slots show.
 *
 * <p>Every image is made from TFC's own GUI textures: backgrounds re-laid out for a chest ({@link ChestRelayout}),
 * sprites cut out into frame grids. The TFC numbers the core layout uses (slot positions, sprite rectangles) are read
 * from TFC's sources here and must equal the core constants, so a TFC change fails datagen instead of misaligning.
 */
public final class GuiArt {
    public static final String GUI_DIR = "src/main/resources/assets/tfc/textures/gui/";
    public static final String LARGE_VESSEL_TEXTURE = GUI_DIR + "large_vessel.png";
    public static final String FIRE_PIT_TEXTURE = GUI_DIR + "fire_pit.png";
    public static final String LARGE_VESSEL_CONTAINER = "src/main/java/net/dries007/tfc/common/container/LargeVesselContainer.java";
    public static final String SEAL_BUTTON = "src/main/java/net/dries007/tfc/client/screen/button/VesselSealButton.java";
    public static final String LARGE_VESSEL_SCREEN = "src/main/java/net/dries007/tfc/client/screen/LargeVesselScreen.java";
    public static final String FIREPIT_SCREEN = "src/main/java/net/dries007/tfc/client/screen/FirepitScreen.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";
    /** 1.21.4 item model definition of {@link GuiImages#BLANK_MODEL}: draws nothing. */
    public static final String BLANK_ITEM = RP + "items/gui/blank.json";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    private static final Pattern ADD_SLOT = Pattern.compile("addSlot\\(new \\w+\\(blockEntity, (\\d+), (\\d+), (\\d+)\\)\\);");
    private static final Pattern BUTTON_RECT = Pattern.compile("super\\(guiLeft \\+ (\\d+), guiTop \\+ (\\d+), (\\d+), (\\d+),");
    private static final Pattern BUTTON_V = Pattern.compile("SEALED\\) \\? (\\d+) : (\\d+);");
    private static final Pattern BUTTON_BLIT = Pattern.compile("blit\\(LargeVesselScreen\\.BACKGROUND, getX\\(\\), getY\\(\\), (\\d+), v, (\\d+), (\\d+), 256, 256\\)");
    private static final Pattern BUTTON_AT = Pattern.compile("new VesselSealButton\\(blockEntity, getGuiLeft\\(\\) \\+ (\\d+), getGuiTop\\(\\)");
    private static final Pattern THERMO_BLIT = Pattern.compile(
        "blit\\(texture, leftPos \\+ (\\d+), topPos \\+ (\\d+) - Math\\.min\\((\\d+), temp\\), (\\d+), (\\d+), (\\d+), (\\d+)\\)");

    private GuiArt() {
    }

    /** True when the checkout has the textures and sources this step reads (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(LARGE_VESSEL_TEXTURE) && tfc.exists(FIRE_PIT_TEXTURE) && tfc.exists(LARGE_VESSEL_CONTAINER);
    }

    /** Writes the images, their YAML and the blank model. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkLargeVessel(tfc);
        int[] thermo = checkThermometer(tfc);
        BufferedImage vessel = read(tfc, LARGE_VESSEL_TEXTURE);
        BufferedImage firePit = read(tfc, FIRE_PIT_TEXTURE);

        Map<String, BufferedImage> pngs = new LinkedHashMap<>();
        pngs.put(SampleScreen.BACKGROUND.id(), ChestRelayout.compose(vessel, SampleScreen.TFC_HEIGHT, SampleScreen.CHEST,
            SampleScreen.DY, LARGE_VESSEL_TEXTURE));
        pngs.put(SampleScreen.SEAL.id(), frames(SampleScreen.SEAL, List.of(
            crop(vessel, SampleScreen.BUTTON_U, SampleScreen.BUTTON_V_SEALED, SampleScreen.BUTTON_SIZE, SampleScreen.BUTTON_SIZE),
            crop(vessel, SampleScreen.BUTTON_U, SampleScreen.BUTTON_V_UNSEALED, SampleScreen.BUTTON_SIZE, SampleScreen.BUTTON_SIZE))));
        pngs.put(GuiImages.THERMOMETER.id(), thermometer(GuiImages.THERMOMETER, crop(firePit, thermo[0], thermo[1],
            ProgressFrames.THERMOMETER_WIDTH, ProgressFrames.THERMOMETER_HEIGHT)));

        Map<String, Object> images = new LinkedHashMap<>();
        for (GuiImage image : GuiImages.all()) {
            BufferedImage png = pngs.get(image.id());
            if (png == null) {
                throw new DatagenException("no art recipe for GUI image " + image.id());
            }
            if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
                throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight() + ", expected "
                    + image.pngWidth() + "x" + image.pngHeight());
            }
            out.put(RP + image.packPath(), png(png));
            images.put(image.id(), entry(image));
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        out.put(BLANK_ITEM, "{\n  \"model\": {\n    \"type\": \"minecraft:empty\"\n  }\n}\n");
        return images.size();
    }

    /** The CraftEngine {@code images:} entry of one image. */
    static Map<String, Object> entry(GuiImage image) {
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        return e;
    }

    /** Frames laid out along rows of the image's grid. */
    static BufferedImage frames(GuiImage image, List<BufferedImage> frames) {
        if (frames.size() > image.frames()) {
            throw new DatagenException(image.id() + ": " + frames.size() + " frames for a grid of " + image.frames());
        }
        BufferedImage out = new BufferedImage(image.pngWidth(), image.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int f = 0; f < frames.size(); f++) {
            BufferedImage fr = frames.get(f);
            if (fr.getWidth() != image.width() || fr.getHeight() != image.height()) {
                throw new DatagenException(image.id() + ": frame " + f + " is " + fr.getWidth() + "x" + fr.getHeight());
            }
            blit(fr, out, image.frameCol(f) * image.width(), image.frameRow(f) * image.height());
        }
        return out;
    }

    /** The thermometer strip: frame 0 empty, frame k the indicator {@code 51 - k} pixels below the frame top. */
    static BufferedImage thermometer(GuiImage image, BufferedImage indicator) {
        List<BufferedImage> frames = new ArrayList<>();
        frames.add(new BufferedImage(image.width(), image.height(), BufferedImage.TYPE_INT_ARGB));
        for (int k = 1; k < ProgressFrames.THERMOMETER_FRAMES; k++) {
            BufferedImage f = new BufferedImage(image.width(), image.height(), BufferedImage.TYPE_INT_ARGB);
            blit(indicator, f, 0, ProgressFrames.thermometerOffset(k));
            frames.add(f);
        }
        return frames(image, frames);
    }

    /** TFC's slot positions and button numbers must be the ones {@link SampleScreen} holds. */
    static void checkLargeVessel(TfcCheckout tfc) {
        String container = tfc.readString(LARGE_VESSEL_CONTAINER);
        List<SlotLayout.Point> slots = new ArrayList<>();
        Matcher m = ADD_SLOT.matcher(container);
        while (m.find()) {
            if (Integer.parseInt(m.group(1)) != slots.size()) {
                throw new DatagenException(LARGE_VESSEL_CONTAINER + ": slots are not added in index order");
            }
            slots.add(new SlotLayout.Point(Integer.parseInt(m.group(2)), Integer.parseInt(m.group(3))));
        }
        if (!slots.equals(SampleScreen.TFC_SLOTS)) {
            throw new DatagenException(LARGE_VESSEL_CONTAINER + ": slots " + slots + " differ from SampleScreen " + SampleScreen.TFC_SLOTS);
        }
        String button = tfc.readString(SEAL_BUTTON);
        String screen = tfc.readString(LARGE_VESSEL_SCREEN);
        int[] rect = ints(BUTTON_RECT, button, SEAL_BUTTON, 4);
        int[] v = ints(BUTTON_V, button, SEAL_BUTTON, 2);
        int[] blit = ints(BUTTON_BLIT, button, SEAL_BUTTON, 3);
        int[] at = ints(BUTTON_AT, screen, LARGE_VESSEL_SCREEN, 1);
        expect(at[0] + rect[0], SampleScreen.TFC_BUTTON_X, "button x");
        expect(rect[1], SampleScreen.TFC_BUTTON_Y, "button y");
        expect(rect[2], SampleScreen.BUTTON_SIZE, "button width");
        expect(rect[3], SampleScreen.BUTTON_SIZE, "button height");
        expect(blit[0], SampleScreen.BUTTON_U, "button sprite u");
        expect(blit[1], SampleScreen.BUTTON_SIZE, "button sprite width");
        expect(blit[2], SampleScreen.BUTTON_SIZE, "button sprite height");
        expect(v[0], SampleScreen.BUTTON_V_SEALED, "sealed sprite v");
        expect(v[1], SampleScreen.BUTTON_V_UNSEALED, "unsealed sprite v");
    }

    /** The thermometer sprite's (u, v), after checking TFC's blit against {@link GuiImages#THERMOMETER}. */
    static int[] checkThermometer(TfcCheckout tfc) {
        int[] b = ints(THERMO_BLIT, tfc.readString(FIREPIT_SCREEN), FIREPIT_SCREEN, 7);
        expect(b[0], GuiImages.THERMOMETER.x(), "thermometer x");
        expect(b[1] - b[2], GuiImages.THERMOMETER.y(), "thermometer travel top");
        expect(b[2], ProgressFrames.THERMOMETER_TRAVEL, "thermometer travel");
        expect(b[5], ProgressFrames.THERMOMETER_WIDTH, "thermometer width");
        expect(b[6], ProgressFrames.THERMOMETER_HEIGHT, "thermometer height");
        return new int[] {b[3], b[4]};
    }

    private static int[] ints(Pattern p, String text, String file, int n) {
        Matcher m = p.matcher(text);
        if (!m.find()) {
            throw new DatagenException(file + ": no match for " + p.pattern());
        }
        int[] out = new int[n];
        for (int i = 0; i < n; i++) {
            out[i] = Integer.parseInt(m.group(i + 1));
        }
        return out;
    }

    private static void expect(int tfc, int ours, String what) {
        if (tfc != ours) {
            throw new DatagenException("TFC's " + what + " is " + tfc + ", the core GUI layout says " + ours);
        }
    }

    static BufferedImage read(TfcCheckout tfc, String path) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(tfc.read(path)));
            if (img == null) {
                throw new DatagenException(path + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            blit(img, argb, 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    static BufferedImage crop(BufferedImage src, int x, int y, int w, int h) {
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                out.setRGB(i, j, src.getRGB(x + i, y + j));
            }
        }
        return out;
    }

    private static void blit(BufferedImage src, BufferedImage dst, int x, int y) {
        for (int j = 0; j < src.getHeight(); j++) {
            for (int i = 0; i < src.getWidth(); i++) {
                dst.setRGB(x + i, y + j, src.getRGB(i, j));
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** For tests: the YAML text. */
    static String yaml(OutputTree out) {
        return new String(out.get(CONFIG), StandardCharsets.UTF_8);
    }
}
