package dev.tfp.datagen;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * M6-DECO-01 (data slice): TFC's wood families as CraftEngine-ready data. Every wood of {@code Wood} gets the block
 * kinds of {@code Wood.BlockType} that the wood block families use (stairs, slabs, fences, gates, doors, trapdoors,
 * buttons, plates, signs, hanging signs, chests, trapped chests, bookshelves, lecterns, tool racks, shelves, scribing
 * and sewing tables, looms, sluices). Hanging signs exist per metal, so they carry a {@code metal} key.
 *
 * <p>The output is {@code craftengine/tfp/families/wood.yml}, outside the CraftEngine {@code configuration/} folder,
 * so CraftEngine does not load it. It is the input of the block-entry generator, which is not written yet. Ids are
 * the TFC blockstate paths in our namespace, so the blockstate of a block is {@code tfc:<path>} in the TFC checkout.
 * The barrel rack is one block, not a wood block, and is left out.
 */
final class WoodFamilies {
    static final String SOURCE = "src/main/java/net/dries007/tfc/common/blocks/wood/Wood.java";
    static final String BLOCKSTATES = TfcCheckout.ASSETS + "blockstates/";
    static final String OUTPUT = AssetPipeline.PACK + "families/wood.yml";

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";
    private static final Pattern WOOD_CONSTANT = Pattern.compile("^ {4}([A-Z_]+)\\(", Pattern.MULTILINE);
    private static final Pattern BLOCK_TYPE_CONSTANT = Pattern.compile("^ {8}([A-Z_]+)\\(", Pattern.MULTILINE);
    private static final String METAL = "{metal}";
    private static final String WOOD = "{wood}";

    /**
     * One block kind. {@code blockType} is the {@code Wood.BlockType} constant that TFC registers the kind under
     * (null when TFC registers it per metal, as the hanging signs). {@code pattern} is the blockstate path below
     * {@code blockstates/} with {@code {wood}} and {@code {metal}} filled in.
     */
    record Kind(String kind, String blockType, String pattern) {
        boolean perMetal() {
            return pattern.contains(METAL);
        }

        String path(String wood, String metal) {
            return pattern.replace(WOOD, wood).replace(METAL, metal == null ? "" : metal);
        }
    }

    static final List<Kind> KINDS = List.of(
        new Kind("stairs", "STAIRS", "wood/planks/" + WOOD + "_stairs"),
        new Kind("slab", "SLAB", "wood/planks/" + WOOD + "_slab"),
        new Kind("fence", "FENCE", "wood/fence/" + WOOD),
        new Kind("log_fence", "LOG_FENCE", "wood/log_fence/" + WOOD),
        new Kind("fence_gate", "FENCE_GATE", "wood/fence_gate/" + WOOD),
        new Kind("door", "DOOR", "wood/door/" + WOOD),
        new Kind("trapdoor", "TRAPDOOR", "wood/trapdoor/" + WOOD),
        new Kind("button", "BUTTON", "wood/button/" + WOOD),
        new Kind("pressure_plate", "PRESSURE_PLATE", "wood/pressure_plate/" + WOOD),
        new Kind("sign", "SIGN", "wood/sign/" + WOOD),
        new Kind("wall_sign", "WALL_SIGN", "wood/wall_sign/" + WOOD),
        new Kind("hanging_sign", null, "wood/hanging_sign/" + METAL + "/" + WOOD),
        new Kind("wall_hanging_sign", null, "wood/wall_hanging_sign/" + METAL + "/" + WOOD),
        new Kind("chest", "CHEST", "wood/chest/" + WOOD),
        new Kind("trapped_chest", "TRAPPED_CHEST", "wood/trapped_chest/" + WOOD),
        new Kind("bookshelf", "BOOKSHELF", "wood/bookshelf/" + WOOD),
        new Kind("lectern", "LECTERN", "wood/lectern/" + WOOD),
        new Kind("tool_rack", "TOOL_RACK", "wood/tool_rack/" + WOOD),
        new Kind("shelf", "SHELF", "wood/shelf/" + WOOD),
        new Kind("scribing_table", "SCRIBING_TABLE", "wood/scribing_table/" + WOOD),
        new Kind("sewing_table", "SEWING_TABLE", "wood/sewing_table/" + WOOD),
        new Kind("loom", "LOOM", "wood/loom/" + WOOD),
        new Kind("sluice", "SLUICE", "wood/sluice/" + WOOD));

    /** One block of a family: its kind, its metal (per-metal kinds only), and the TFC blockstate path. */
    record Block(String kind, String metal, String path) {
    }

    /** One wood (serialized name) and its blocks in {@link #KINDS} order. */
    record Family(String wood, List<Block> blocks) {
    }

    private WoodFamilies() {
    }

    /** Writes the family data. Returns the number of blocks, or 0 when the checkout has no wood blockstates. */
    static int run(TfcCheckout tfc, OutputTree out) {
        if (!tfc.isDirectory(BLOCKSTATES + "wood/")) {
            return 0; // absent in this checkout; the full-checkout test pins the wood and block counts
        }
        List<Family> families = families(tfc);
        out.put(OUTPUT, Yaml.write(HEADER, yaml(families)));
        return families.stream().mapToInt(f -> f.blocks().size()).sum();
    }

    /**
     * The families of the checkout, in TFC's declaration order. Fails when a kind's {@code BlockType} constant is
     * missing, or a wood lacks a blockstate of any kind, so a TFC change is noticed instead of dropped silently.
     */
    static List<Family> families(TfcCheckout tfc) {
        String text = tfc.readString(SOURCE);
        List<String> woods = constants(text, "public enum Wood implements", WOOD_CONSTANT).stream()
            .map(w -> w.toLowerCase(Locale.ROOT)).toList();
        Set<String> blockTypes = Set.copyOf(constants(text, "public enum BlockType", BLOCK_TYPE_CONSTANT));
        for (Kind k : KINDS) {
            if (k.blockType() != null && !blockTypes.contains(k.blockType())) {
                throw new DatagenException(SOURCE + ": no Wood.BlockType." + k.blockType() + " for kind " + k.kind());
            }
        }
        List<String> metals = tfc.childDirs(BLOCKSTATES + "wood/hanging_sign/");
        if (!metals.equals(tfc.childDirs(BLOCKSTATES + "wood/wall_hanging_sign/"))) {
            throw new DatagenException("hanging and wall hanging sign metals differ in " + BLOCKSTATES);
        }
        List<Family> out = new ArrayList<>();
        for (String wood : woods) {
            List<Block> blocks = new ArrayList<>();
            for (Kind k : KINDS) {
                for (String metal : k.perMetal() ? metals : List.of("")) {
                    String path = k.path(wood, metal.isEmpty() ? null : metal);
                    if (!tfc.exists(BLOCKSTATES + path + ".json")) {
                        throw new DatagenException("TFC has no blockstate " + path + " for wood " + wood);
                    }
                    blocks.add(new Block(k.kind(), metal.isEmpty() ? null : metal, path));
                }
            }
            out.add(new Family(wood, blocks));
        }
        return out;
    }

    /** Names of the constants of {@code enumDecl}: from its declaration to the first semicolon, matched by {@code p}. */
    static List<String> constants(String text, String enumDecl, Pattern p) {
        int start = text.indexOf(enumDecl);
        if (start < 0) {
            throw new DatagenException(SOURCE + ": no " + enumDecl);
        }
        int end = text.indexOf(';', start);
        if (end < 0) {
            throw new DatagenException(SOURCE + ": " + enumDecl + " has no end");
        }
        List<String> out = new ArrayList<>();
        Matcher m = p.matcher(text.substring(start, end));
        while (m.find()) {
            out.add(m.group(1));
        }
        if (out.isEmpty()) {
            throw new DatagenException(SOURCE + ": no constants in " + enumDecl);
        }
        return out;
    }

    /** {@code families: <wood>: blocks: [{kind, metal?, id, tfc}]}, ids in our namespace, TFC's in {@code tfc:}. */
    static Map<String, Object> yaml(List<Family> families) {
        Map<String, Object> byWood = new LinkedHashMap<>();
        for (Family f : families) {
            List<Object> blocks = new ArrayList<>();
            for (Block b : f.blocks()) {
                Map<String, Object> m = new LinkedHashMap<>();
                m.put("kind", b.kind());
                if (b.metal() != null) {
                    m.put("metal", b.metal());
                }
                m.put("id", Json.TO_NS + ":" + b.path());
                m.put("tfc", Json.FROM_NS + ":" + b.path());
                blocks.add(m);
            }
            Map<String, Object> family = new LinkedHashMap<>();
            family.put("blocks", blocks);
            byWood.put(f.wood(), family);
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("families", byWood);
        return root;
    }

    /** The distinct kinds of a family (metal kinds once), for checks. */
    static Set<String> kinds(Family f) {
        Set<String> out = new TreeSet<>();
        f.blocks().forEach(b -> out.add(b.kind()));
        return out;
    }
}
