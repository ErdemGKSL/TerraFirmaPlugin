package dev.tfp.datagen.pan;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * PAR-PROC-12: panning content: {@code tfp:pan/empty} and {@code tfp:pan/filled} ({@code configuration/pan.yml}), TFC's pan
 * models and the deposit loot tables.
 *
 * <p>The filled pan carries a vanilla {@code consumable} (120 ticks, brush animation, no particles) so the client holds it up
 * while the server waits for the finish. Its model is a {@code select} on {@code custom_model_data} string 0, which the
 * runtime sets to the deposit's model key, over TFC's {@code <mineral>/<rock>_full} models (half and result stages are not
 * shown: ledger divergence). The deposit loot tables ({@code data/tfp/loot_table/deposit/<mineral>_<rock>.json}) are TFC's,
 * renamed; TFC's type {@code minecraft:empty} becomes {@code minecraft:entity} because {@code LootTableExport} accepts only
 * block and entity types (TFC rolls them with the player as {@code this_entity}).
 */
public final class PanItems {
    static final String PACK = "craftengine/tfp/";
    static final String CONFIG = PACK + "configuration/pan.yml";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    static final String LANG_RP = PACK + "resourcepack/assets/tfp_pan/lang/";
    static final String MODELS = TfcCheckout.ASSETS + "models/item/pan/";
    static final String TEXTURES = TfcCheckout.ASSETS + "textures/item/pan/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String LOOT_SOURCE = TfcCheckout.MAIN + "data/" + Json.FROM_NS + "/loot_table/deposit/";
    static final String LOOT_TARGET = "data/" + Json.TO_NS + "/loot_table/deposit/";
    static final String ITEMS_SOURCE = "src/main/java/net/dries007/tfc/common/items/TFCItems.java";
    static final String EMPTY = "pan/empty";
    static final String FILLED = "pan/filled";
    static final int USE_TICKS = 120;

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (PAR-PROC-12, dev.tfp.datagen.pan). Do not edit: fix the "
        + "generator and regenerate.";

    private PanItems() {
    }

    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(ITEMS_SOURCE) && tfc.exists(MODELS + "empty.json") && tfc.exists(MODELS + "full.json");
    }

    /** The model keys ({@code native_copper/granite}) of TFC's {@code <mineral>/<rock>_full} models, sorted. */
    static List<String> modelKeys(TfcCheckout tfc) {
        List<String> keys = new ArrayList<>();
        for (String mineral : tfc.childDirs(MODELS)) {
            for (String f : tfc.list(MODELS + mineral)) {
                if (f.endsWith("_full.json")) {
                    keys.add(mineral + "/" + f.substring((MODELS + mineral + "/").length(), f.length() - "_full.json".length()));
                }
            }
        }
        if (keys.isEmpty()) {
            throw new DatagenException("no pan <mineral>/<rock>_full models under " + MODELS);
        }
        return keys;
    }

    public static void run(TfcCheckout tfc, OutputTree out) {
        String src = tfc.readString(ITEMS_SOURCE);
        if (!src.contains("register(\"pan/empty\", () -> new EmptyPanItem(")
                || !src.contains("register(\"pan/filled\", () -> new PanItem(")) {
            throw new DatagenException(ITEMS_SOURCE + " no longer registers pan/empty and pan/filled as EmptyPanItem and PanItem");
        }
        for (String tex : List.of("interior", "grid")) {
            String png = TEXTURES + tex + ".png";
            if (!tfc.exists(png)) {
                throw new DatagenException("missing pan texture " + png);
            }
            out.put(RP + "textures/item/pan/" + tex + ".png", tfc.read(png));
        }
        copyModel(tfc, out, "empty");
        copyModel(tfc, out, "full");
        List<String> keys = modelKeys(tfc);
        for (String key : keys) {
            copyModel(tfc, out, key + "_full");
        }
        int tables = 0;
        for (String f : tfc.list(LOOT_SOURCE)) {
            if (f.endsWith(".json")) {
                out.put(LOOT_TARGET + f.substring(LOOT_SOURCE.length()), Json.write(lootTable(tfc, f)));
                tables++;
            }
        }
        if (tables != keys.size()) {
            throw new DatagenException("pan models (" + keys.size() + ") and deposit loot tables (" + tables + ") differ");
        }
        Map<String, Object> items = new LinkedHashMap<>();
        items.put(Json.TO_NS + ":" + EMPTY, emptyEntry());
        items.put(Json.TO_NS + ":" + FILLED, filledEntry(keys));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", items);
        out.put(CONFIG, Yaml.write(HEADER, root));
        writeLang(tfc, out);
    }

    static JsonElement lootTable(TfcCheckout tfc, String path) {
        JsonObject table = Json.rename(Json.parse(tfc.readString(path), path)).getAsJsonObject();
        table.remove("__comment__");
        if (!table.has("type") || !table.get("type").getAsString().equals("minecraft:empty")) {
            throw new DatagenException(path + ": TFC's deposit tables are no longer minecraft:empty");
        }
        table.addProperty("type", "minecraft:entity");
        return table;
    }

    private static void copyModel(TfcCheckout tfc, OutputTree out, String name) {
        String src = MODELS + name + ".json";
        if (!tfc.exists(src)) {
            throw new DatagenException("missing pan model " + src);
        }
        out.put(RP + "models/item/pan/" + name + ".json", Json.write(Json.rename(Json.parse(tfc.readString(src), src))));
    }

    static String langKey(String path) {
        return "item." + Json.TO_NS + "." + path.replace('/', '.');
    }

    static Map<String, Object> model(String path) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("type", "minecraft:model");
        m.put("path", Json.TO_NS + ":item/" + path);
        return m;
    }

    static Map<String, Object> emptyEntry() {
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("item_name", "<!i><lang:" + langKey(EMPTY) + ">");
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("material", "paper");
        e.put("data", data);
        e.put("model", model(EMPTY));
        return e;
    }

    static Map<String, Object> filledEntry(List<String> keys) {
        List<Object> cases = new ArrayList<>();
        for (String key : keys) {
            Map<String, Object> c = new LinkedHashMap<>();
            c.put("when", key);
            c.put("model", model("pan/" + key + "_full"));
            cases.add(c);
        }
        Map<String, Object> select = new LinkedHashMap<>();
        select.put("type", "minecraft:select");
        select.put("property", "minecraft:custom_model_data");
        select.put("index", 0);
        select.put("cases", cases);
        select.put("fallback", model(EMPTY));
        Map<String, Object> consumable = new LinkedHashMap<>();
        consumable.put("consume_seconds", BigDecimal.valueOf(USE_TICKS).divide(BigDecimal.valueOf(20)));
        consumable.put("animation", "brush");
        consumable.put("has_consume_particles", false);
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("item_name", "<!i><lang:" + langKey(FILLED) + ">");
        data.put("max_stack_size", 1);
        data.put("consumable", consumable);
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("material", "paper");
        e.put("data", data);
        e.put("model", select);
        return e;
    }

    private static void writeLang(TfcCheckout tfc, OutputTree out) {
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            TreeMap<String, String> keys = new TreeMap<>();
            for (String id : List.of(EMPTY, FILLED)) {
                String tfcKey = "item." + Json.FROM_NS + "." + id.replace('/', '.');
                if (src.has(tfcKey)) {
                    keys.put(langKey(id), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC item tfc:" + id + " has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }
}
