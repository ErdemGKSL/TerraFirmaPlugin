package dev.tfp.datagen.anvil;

import dev.tfp.core.gui.ChestGeometry;
import dev.tfp.core.gui.GuiImage;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import dev.tfp.datagen.gui.ChestRelayout;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.util.LinkedHashMap;
import java.util.Map;
import javax.imageio.ImageIO;

/**
 * PAR-METAL-04: the anvil plan screen's art (TFC {@code AnvilPlanScreen}) for the 3-row chest of the plugin's
 * {@code dev.tfp.paper.anvil.plan.PlanLayout} ({@code configuration/anvil_plan_gui.yml}). The numbers here must equal that
 * layout's; {@code AnvilPlanArtTest} reads the generated YAML and PNGs against them.
 *
 * <ul>
 *   <li>{@code tfp:gui/anvil_plan}: TFC's {@code anvil_plan.png} (176 x 166) re-laid out into the 176 x 168 window of a 3-row
 *       chest ({@link ChestRelayout}): the plain panel above the player inventory, the inventory itself one pixel lower. TFC
 *       draws the plan buttons as widgets, so the panel is plain where they go.</li>
 *   <li>{@code tfp:gui/anvil_plan_buttons}: 19 frames of the button area (162 x 36 at (7, 17)); frame {@code k} has TFC's
 *       18 x 18 button frame (the sprite at (176, 0)) under the first {@code k} cells, row by row, as TFC shows only the
 *       buttons of the recipes of the page.</li>
 *   <li>{@code tfp:gui/anvil_plan_arrows}: 4 frames of the arrow row (162 x 13 at (7, 56)): none, the left arrow (sprite at
 *       (201, 3), 9 x 13), the right arrow (sprite at (212, 3), placed at x 160), both.</li>
 * </ul>
 */
public final class AnvilPlanArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/anvil_plan.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/AnvilPlanScreen.java";
    public static final String BUTTON = "src/main/java/net/dries007/tfc/client/screen/button/AnvilPlanSelectButton.java";
    public static final String ARROWS = "src/main/java/net/dries007/tfc/client/screen/button/NextPageButton.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/anvil_plan_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    public static final ChestGeometry CHEST = new ChestGeometry(3);
    /** TFC's screen height. */
    public static final int TFC_HEIGHT = 166;

    /** TFC's button grid: 9 columns, 2 rows of 18 x 18 buttons from (7, 17). */
    public static final int BUTTON_X = 7;
    public static final int BUTTON_Y = 17;
    public static final int BUTTON_SIZE = 18;
    public static final int COLUMNS = 9;
    public static final int ROWS = 2;
    public static final int PER_PAGE = COLUMNS * ROWS;
    /** The button frame sprite in TFC's texture. */
    public static final int BUTTON_U = 176;
    public static final int BUTTON_V = 0;
    /** The arrows: 9 x 13 at y 56, the left at x 7 (sprite u 201), the right at x 160 (sprite u 212), both at v 3. */
    public static final int ARROW_Y = 56;
    public static final int ARROW_W = 9;
    public static final int ARROW_H = 13;
    public static final int LEFT_X = 7;
    public static final int LEFT_U = 201;
    public static final int RIGHT_X = 160;
    public static final int RIGHT_U = 212;
    public static final int ARROW_V = 3;

    public static final GuiImage BACKGROUND = GuiImage.of("tfp:gui/anvil_plan", 0, 0, ChestGeometry.WIDTH, CHEST.height());
    public static final GuiImage BUTTONS = new GuiImage("tfp:gui/anvil_plan_buttons", BUTTON_X, BUTTON_Y, COLUMNS * BUTTON_SIZE,
        ROWS * BUTTON_SIZE, 4, 5);
    public static final GuiImage ARROW_IMAGE = new GuiImage("tfp:gui/anvil_plan_arrows", LEFT_X, ARROW_Y,
        RIGHT_X + ARROW_W - LEFT_X, ARROW_H, 2, 2);

    private AnvilPlanArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(SCREEN) && tfc.exists(BUTTON) && tfc.exists(ARROWS);
    }

    /** Writes the images and their YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE), TEXTURE);
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, BACKGROUND, background(src));
        put(out, images, BUTTONS, buttons(src));
        put(out, images, ARROW_IMAGE, arrows(src));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The 176 x 168 window: TFC's screen with its player inventory moved onto the chest's rows. */
    static BufferedImage background(BufferedImage src) {
        return ChestRelayout.compose(src, TFC_HEIGHT, CHEST, 0, TEXTURE);
    }

    /** Frame {@code k} (0 to 18): the button frame under the first {@code k} cells. */
    static BufferedImage buttons(BufferedImage src) {
        GuiImage g = BUTTONS;
        BufferedImage out = new BufferedImage(g.pngWidth(), g.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 1; k <= PER_PAGE; k++) {
            int fx = g.frameCol(k) * g.width();
            int fy = g.frameRow(k) * g.height();
            for (int cell = 0; cell < k; cell++) {
                copy(src, out, BUTTON_U, BUTTON_V, BUTTON_SIZE, BUTTON_SIZE, fx + (cell % COLUMNS) * BUTTON_SIZE,
                    fy + (cell / COLUMNS) * BUTTON_SIZE);
            }
        }
        keepAdvance(out, g.width(), g.height());
        return out;
    }

    /** Frame 0 none, 1 the left arrow, 2 the right arrow, 3 both. */
    static BufferedImage arrows(BufferedImage src) {
        GuiImage g = ARROW_IMAGE;
        BufferedImage out = new BufferedImage(g.pngWidth(), g.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 1; k < 4; k++) {
            int fx = g.frameCol(k) * g.width();
            int fy = g.frameRow(k) * g.height();
            if ((k & 1) != 0) {
                copy(src, out, LEFT_U, ARROW_V, ARROW_W, ARROW_H, fx, fy);
            }
            if ((k & 2) != 0) {
                copy(src, out, RIGHT_U, ARROW_V, ARROW_W, ARROW_H, fx + RIGHT_X - LEFT_X, fy);
            }
        }
        keepAdvance(out, g.width(), g.height());
        return out;
    }

    /** Alpha of the width marker: counted by the client's glyph width scan, discarded by the text shader (below 0.1). */
    static final int MARKER = 0x01000000;

    /** A frame with an empty right column gets a nearly transparent pixel in its corner (the glyph keeps its advance). */
    static void keepAdvance(BufferedImage png, int w, int h) {
        for (int fy = 0; fy < png.getHeight(); fy += h) {
            for (int fx = 0; fx < png.getWidth(); fx += w) {
                boolean any = false;
                for (int y = fy; y < fy + h && !any; y++) {
                    any = (png.getRGB(fx + w - 1, y) >>> 24) != 0;
                }
                if (!any) {
                    png.setRGB(fx + w - 1, fy + h - 1, MARKER);
                }
            }
        }
    }

    /** TFC's numbers this layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String screen = tfc.readString(SCREEN).replaceAll("\\s+", " ");
        String button = tfc.readString(BUTTON).replaceAll("\\s+", " ");
        String arrows = tfc.readString(ARROWS).replaceAll("\\s+", " ");
        need(screen, SCREEN, "final int recipesPerPage = " + PER_PAGE + ";");
        need(screen, SCREEN, "final int posX = " + BUTTON_X + " + (index % " + COLUMNS + ") * " + BUTTON_SIZE + ";");
        need(screen, SCREEN, "final int posY = " + BUTTON_Y + " + ((index % " + PER_PAGE + ") / " + COLUMNS + ") * " + BUTTON_SIZE + ";");
        need(screen, SCREEN, "NextPageButton.left(guiLeft + " + LEFT_X + ", guiTop + " + ARROW_Y);
        need(screen, SCREEN, "NextPageButton.right(guiLeft + " + RIGHT_X + ", guiTop + " + ARROW_Y);
        need(button, BUTTON, "graphics.blit(AnvilPlanScreen.BACKGROUND, x, y, " + BUTTON_U + ", " + BUTTON_V + ", width, height, 256, 256);");
        need(button, BUTTON, "super(x, y, " + BUTTON_SIZE + ", " + BUTTON_SIZE + ", tooltip");
        need(arrows, ARROWS, "left ? " + LEFT_U + " : " + RIGHT_U + ", " + ARROW_V + ", " + ARROW_W + ", " + ARROW_H + ", 256, 256");
        need(arrows, ARROWS, "super(x, y, " + ARROW_W + ", " + ARROW_H + ", Component.empty()");
        // the button grid is the chest's: cell (c, r) frame at (7 + 18c, 17 + 18r), the slot item at +1
        for (int cell = 0; cell < PER_PAGE; cell++) {
            if (CHEST.slotX(cell) - 1 != BUTTON_X + (cell % COLUMNS) * BUTTON_SIZE
                || CHEST.slotY(cell) - 1 != BUTTON_Y + (cell / COLUMNS) * BUTTON_SIZE) {
                throw new DatagenException("button cell " + cell + " is not on chest slot " + cell);
            }
        }
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the anvil plan screen art is stale");
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        images.put(image.id(), e);
    }

    static BufferedImage read(byte[] bytes, String what) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(what + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
