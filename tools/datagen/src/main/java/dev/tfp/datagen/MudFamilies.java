package dev.tfp.datagen;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * M6-DECO-02 (data slice): TFC's mud brick families as CraftEngine-ready data. Every soil of {@code SoilBlockType.Variant}
 * gets the mud bricks block and its slab, stair and wall, which TFC registers per variant ({@code MUD_BRICK_DECORATIONS}).
 * The raw mud and the smooth mud bricks are not here: the raw mud is a soil block, and the smooth mud bricks are one
 * block for all soils.
 *
 * <p>The output is {@code craftengine/tfp/families/mud.yml}, outside the CraftEngine {@code configuration/} folder,
 * so CraftEngine does not load it. Ids are the TFC blockstate paths in our namespace. A missing source or blockstate
 * is an error, as for the rock families.
 */
final class MudFamilies {
    static final String SOURCE = "src/main/java/net/dries007/tfc/common/blocks/soil/SoilBlockType.java";
    static final String BLOCKSTATES = TfcCheckout.ASSETS + "blockstates/mud_bricks/";
    static final String OUTPUT = AssetPipeline.PACK + "families/mud.yml";
    static final String KIND = "mud_bricks";

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";
    private static final Pattern VARIANT_CONSTANT = Pattern.compile("^ {8}([A-Z_]+)\\b", Pattern.MULTILINE);
    private static final Pattern MUD_BRICKS_CONSTANT = Pattern.compile("^ {4}MUD_BRICKS\\(", Pattern.MULTILINE);
    /** The shapes of the mud bricks block: the full block, then the slab, stair and wall that TFC registers with it. */
    static final List<String> SHAPES = List.of("full", "slab", "stairs", "wall");

    /** One block of a family: its shape and the TFC blockstate path. */
    record Block(String shape, String path) {
    }

    /** One soil (serialized name) and its mud brick blocks in {@link #SHAPES} order. */
    record Family(String soil, List<Block> blocks) {
    }

    private MudFamilies() {
    }

    /** Writes the family data. Returns the number of blocks. Fails when the checkout lacks the source or a blockstate. */
    static int run(TfcCheckout tfc, OutputTree out) {
        List<Family> families = families(tfc);
        out.put(OUTPUT, Yaml.write(HEADER, yaml(families)));
        return families.stream().mapToInt(f -> f.blocks().size()).sum();
    }

    /**
     * The families of the checkout, in TFC's declaration order. Fails when the source, the {@code MUD_BRICKS} kind or a
     * soil constant is missing, or a blockstate is missing. Extra files in the folder are not read.
     */
    static List<Family> families(TfcCheckout tfc) {
        if (!tfc.exists(SOURCE)) {
            throw new DatagenException("TFC checkout has no " + SOURCE);
        }
        String text = tfc.readString(SOURCE);
        if (!MUD_BRICKS_CONSTANT.matcher(text).find()) {
            throw new DatagenException(SOURCE + ": no SoilBlockType.MUD_BRICKS");
        }
        List<String> soils = variants(text);
        List<Family> out = new ArrayList<>();
        for (String soil : soils) {
            List<Block> blocks = new ArrayList<>();
            for (String shape : SHAPES) {
                String path = path(soil, shape);
                if (!tfc.exists(TfcCheckout.ASSETS + "blockstates/" + path + ".json")) {
                    throw new DatagenException("TFC has no blockstate " + path + " for soil " + soil);
                }
                blocks.add(new Block(shape, path));
            }
            out.add(new Family(soil, blocks));
        }
        return out;
    }

    /** The blockstate path of a block below {@code blockstates/}: {@code mud_bricks/<soil><_shape>}. */
    static String path(String soil, String shape) {
        String suffix = shape.equals("full") ? "" : "_" + shape;
        return KIND + "/" + soil + suffix;
    }

    /** The {@code SoilBlockType.Variant} constants, serialized, in declaration order. */
    static List<String> variants(String text) {
        int start = text.indexOf("public enum Variant");
        if (start < 0) {
            throw new DatagenException(SOURCE + ": no public enum Variant");
        }
        int end = text.indexOf(';', start);
        if (end < 0) {
            throw new DatagenException(SOURCE + ": public enum Variant has no end");
        }
        List<String> out = new ArrayList<>();
        Matcher m = VARIANT_CONSTANT.matcher(text.substring(start, end));
        while (m.find()) {
            out.add(m.group(1).toLowerCase(Locale.ROOT));
        }
        if (out.isEmpty()) {
            throw new DatagenException(SOURCE + ": no constants in public enum Variant");
        }
        return out;
    }

    /** {@code families: <soil>: blocks: [{kind, shape, id, tfc}]}, ids in our namespace, TFC's in {@code tfc:}. */
    static Map<String, Object> yaml(List<Family> families) {
        Map<String, Object> bySoil = new LinkedHashMap<>();
        for (Family f : families) {
            List<Object> blocks = new ArrayList<>();
            for (Block b : f.blocks()) {
                Map<String, Object> m = new LinkedHashMap<>();
                m.put("kind", KIND);
                m.put("shape", b.shape());
                m.put("id", Json.TO_NS + ":" + b.path());
                m.put("tfc", Json.FROM_NS + ":" + b.path());
                blocks.add(m);
            }
            Map<String, Object> family = new LinkedHashMap<>();
            family.put("blocks", blocks);
            bySoil.put(f.soil(), family);
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("families", bySoil);
        return root;
    }
}
