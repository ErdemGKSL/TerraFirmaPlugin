    /** TFC block loot table → one of our loot templates. Unknown shapes fail, so nothing is dropped silently. */
    private Map<String, Object> loot(String id) {
        String src = TfcCheckout.MAIN + "data/" + Json.FROM_NS + "/loot_table/blocks/" + id + ".json";
        if (!tfc.exists(src)) {
            throw new DatagenException("no TFC loot table for " + id + " (" + src + ")");
        }
        JsonElement table = Json.rename(Json.parse(tfc.readString(src), src));
        String self = Json.TO_NS + ":" + id;
        if (table.equals(LootShapes.single(self))) {
            return CeBlockStates.call("tfp:loot_table/self", Map.of());
        }
        String item = LootShapes.singleItem(table);
        if (item != null && table.equals(LootShapes.single(item))) {
            drop(item);
            return CeBlockStates.call("tfp:loot_table/item", Map.of("loot_item", item));
        }
        String[] counted = LootShapes.singleCount(table);
        if (counted != null) {
            drop(counted[0]);
            Map<String, Object> args = new LinkedHashMap<>();
            args.put("loot_item", counted[0]);
            args.put("loot_count_min", Integer.valueOf(counted[1]));
            args.put("loot_count_max", Integer.valueOf(counted[2]));
            return CeBlockStates.call("tfp:loot_table/item_count", args);
        }
        String[] rock = LootShapes.rockToLoose(table);
        if (rock != null) {
            drop(rock[1]);
            report.divergence("tfc:is_isolated", id);
            return CeBlockStates.call("tfp:loot_table/rock_to_loose", Map.of("loot_loose_rock", rock[1]));
        }
        if (table.equals(LootShapes.gravel(self))) {
            return CeBlockStates.call("tfp:loot_table/gravel", Map.of());
        }
        throw new DatagenException("loot table " + src + " has a shape with no tfp:loot_table template: "
            + Json.write(table));
    }

    private void drop(String itemId) {
        if (!itemId.startsWith(Json.TO_NS + ":")) {
            return; // vanilla items need no CE entry
        }
        String path = itemId.substring(Json.TO_NS.length() + 1);
        boolean isBlockItem = tfc.exists(blockstate(path));
        dropItems.put(path, langKey(isBlockItem ? "block" : "item", path));
    }

    private void reportSkipped() {
        Set<String> emitted = report.emittedIds();
        for (String fam : FAMILIES) {
            String dir = TfcCheckout.ASSETS + "blockstates/" + fam + "/";
            for (String f : tfc.list(dir)) {
                String id = f.substring((TfcCheckout.ASSETS + "blockstates/").length(), f.length() - 5);
                if (!emitted.contains(id) && !dropItems.containsKey(id)) {
                    report.skipped(id, skipReason(id, tfc.readString(f)));
                }
            }
        }
    }

    static String skipReason(String id, String blockstate) {
        String last = id.substring(id.lastIndexOf('/') + 1);
        if (blockstate.contains("\"multipart\"")) {
            return "multipart blockstate (connected sides / walls): needs flattening or entity_renderer";
        }
        if (last.endsWith("_slab") || last.endsWith("_stairs") || last.endsWith("_wall")) {
            return "slab/stairs/wall: needs tfp:block_state/slab|stairs|wall on freed vanilla states (visual allocator)";
        }
        if (id.startsWith("ore/small_")) {
            return "small ore: non-cube groundcover shape (button hitbox), separate behaviour";
        }
        return "non-cube shape or block entity (" + id.substring(0, id.lastIndexOf('/')) + "): later task";
    }

