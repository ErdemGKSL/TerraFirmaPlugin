import java.util.Map;
import javax.imageio.ImageIO;

/**
 * PAR-METAL-27: the blast furnace screen's art (TFC {@code BlastFurnaceScreen}) for the 4-row chest of
 * {@link dev.tfp.core.blastfurnace.BlastFurnaceScreenLayout} ({@code configuration/blast_furnace_gui.yml}); the numbers come
 * from that class, {@code BlastFurnaceScreenArtTest} reads the generated PNGs against TFC's texture.
 *
 * <ul>
 *   <li>{@code tfp:gui/blast_furnace}: TFC's {@code blast_furnace.png} (176 x 186) re-laid out: TFC's tuyere slot (y 17) is a
 *       pixel above a chest's, so one plain panel row is inserted under the top border ({@link #DY}) and the player
 *       inventory (TFC y 104, chest 103) moves up one: two plain rows between the bands are cut.</li>
 *   <li>{@code blast_furnace_thermometer}: 52 frames of the indicator (u 176, v 0, 15 x 5), moved by {@link #DY}.</li>
 *   <li>{@code blast_furnace_ore_bar} / {@code _fuel_bar}: 66 frames of {@code renderCapacityLimitedFillMeter}'s empty part:
 *       frame 0 the dotted region (no capacity, u 246), frame {@code 1 + e} the top {@code 1 + e} rows of the empty bar
 *       (u 236) at {@code 64 - e}.</li>
 *   <li>{@code blast_furnace_ore_fill} (128 frames: 64 unlit u 226, then 64 lit u 216) and {@code _fuel_fill} (64 frames,
 *       u 206): frame {@code h - 1} the bottom {@code h} rows of the full bar (v 1) at {@code 65 - h}.</li>
 *   <li>{@code blast_furnace_fluid}: 32 frames of the molten fill, tinted as the crucible's.</li>
 * </ul>
 */
public final class BlastFurnaceScreenArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/blast_furnace.png";
    public static final String FLUID_TEXTURE = "src/main/resources/assets/tfc/textures/block/molten_still.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/BlastFurnaceScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/BlastFurnaceContainer.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/blast_furnace_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    public static final int TFC_HEIGHT = 186;
    public static final int TFC_INVENTORY_OFFSET = 20;
    /** The player inventory's move onto the chest's. */
    public static final int DY_PLAYER = CHEST.playerRowY(0) - (84 + TFC_INVENTORY_OFFSET);
    /** The plain panel row duplicated under the top border. */
    static final int INSERT_ROW = 8;
    /** Output row where the upper band ends and the player band begins. */
    static final int SPLIT = 95;

    /** The tint of the fill (as the crucible's: one molten orange). */
    static final int TINT_R = 0xFF;
    static final int TINT_G = 0x8C;
    static final int TINT_B = 0x2A;

    private BlastFurnaceScreenArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(SCREEN) && tfc.exists(CONTAINER) && tfc.exists(FLUID_TEXTURE);
    }

    /** Writes the images and their YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE), TEXTURE);
        BufferedImage molten = read(tfc.read(FLUID_TEXTURE), FLUID_TEXTURE);
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, BACKGROUND, background(src));
        put(out, images, THERMOMETER, thermometer(src));
        put(out, images, ORE_BAR, bar(src, ORE_BAR));
        put(out, images, FUEL_BAR, bar(src, FUEL_BAR));
        put(out, images, ORE_FILL, fill(src, ORE_FILL, ORE_FILL_UNLIT_U, ORE_FILL_LIT_U));
        put(out, images, FUEL_FILL, fill(src, FUEL_FILL, FUEL_FILL_U));
        put(out, images, FLUID, fluid(molten));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The source row of output row {@code y} of the 176 x 186 window. */
    static int sourceRow(int y) {
        if (y <= INSERT_ROW) {
            return y;
        }
        if (y <= INSERT_ROW + DY) {
            return INSERT_ROW; // the inserted plain row
        }
        if (y < SPLIT) {
            return y - DY;
        }
        return Math.min(y - DY_PLAYER, TFC_HEIGHT - 1);
    }

    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = CHEST.height();
        if (src.getWidth() < w || src.getHeight() < TFC_HEIGHT || h != TFC_HEIGHT || DY_PLAYER != -1) {
            throw new DatagenException(TEXTURE + ": not a 176 x 186 screen under a 4-row chest");
        }
        checkPlain(src, INSERT_ROW);
        for (int y = SPLIT - DY; y <= SPLIT - DY_PLAYER - 1; y++) {
            checkPlain(src, y); // the rows cut between the two bands
        }
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < h; y++) {
            copy(src, out, 0, sourceRow(y), w, 1, 0, y);
        }
        return out;
    }

    /** The thermometer strip: frame 0 empty, frame k the indicator {@code 51 - k} pixels below the frame top. */
    static BufferedImage thermometer(BufferedImage src) {
        GuiImage t = THERMOMETER;
        BufferedImage out = new BufferedImage(t.pngWidth(), t.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 1; k < ProgressFrames.THERMOMETER_FRAMES; k++) {
            int fx = t.frameCol(k) * t.width();
            int fy = t.frameRow(k) * t.height() + ProgressFrames.thermometerOffset(k);
            copy(src, out, THERMOMETER_U, THERMOMETER_V, ProgressFrames.THERMOMETER_WIDTH, ProgressFrames.THERMOMETER_HEIGHT,
                fx, fy);
        }
        keepAdvance(out, t.width(), t.height());
        return out;
    }

    /** The bar strip: frame 0 the dotted region, frame {@code 1 + e} the top {@code 1 + e} rows of the empty bar at {@code 64 - e}. */
    static BufferedImage bar(BufferedImage src, GuiImage g) {
        BufferedImage out = new BufferedImage(g.pngWidth(), g.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        copy(src, out, DOTTED_U, 0, METER_WIDTH, METER_HEIGHT, 0, 0);
        for (int e = 0; e <= METER_SPAN; e++) {
            int f = 1 + e;
            copy(src, out, EMPTY_U, 0, METER_WIDTH, 1 + e, g.frameCol(f) * g.width(), g.frameRow(f) * g.height() + METER_SPAN - e);
        }
        keepAdvance(out, g.width(), g.height());
        return out;
    }

    /** The fill strip: for each source column {@code us}, frames of {@code h} rows (v 1) at {@code 65 - h}, h = 1 to 64. */
    static BufferedImage fill(BufferedImage src, GuiImage g, int... us) {
        BufferedImage out = new BufferedImage(g.pngWidth(), g.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int s = 0; s < us.length; s++) {
            for (int h = 1; h <= METER_SPAN; h++) {
                int f = s * FILL_FRAMES + h - 1;
                copy(src, out, us[s], FILL_V, METER_WIDTH, h, g.frameCol(f) * g.width(), g.frameRow(f) * g.height() + 65 - h);
            }
        }
        keepAdvance(out, g.width(), g.height());
        return out;
    }

    /** The fill strip: frame k is {@code k} rows of the tinted sprite at the bottom, TFC's tiling of a 16 x 16 sprite. */
    static BufferedImage fluid(BufferedImage molten) {
        GuiImage f = FLUID;
        BufferedImage out = new BufferedImage(f.pngWidth(), f.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 1; k < FLUID_FRAMES; k++) {
            int fx = f.frameCol(k) * f.width();
            int fy = f.frameRow(k) * f.height();
            for (int j = 0; j < k; j++) {
                int y = FLUID_HEIGHT - 1 - j;
                for (int i = 0; i < FLUID_WIDTH; i++) {
                    out.setRGB(fx + i, fy + y, tint(molten.getRGB(i % 16, j % 16)));
                }
            }
        }
        keepAdvance(out, f.width(), f.height());
        return out;
    }

    private static int tint(int argb) {
        int a = argb >>> 24;
        int r = ((argb >> 16) & 0xFF) * TINT_R / 255;
        int g = ((argb >> 8) & 0xFF) * TINT_G / 255;
        int b = (argb & 0xFF) * TINT_B / 255;
        return a << 24 | r << 16 | g << 8 | b;
    }

    /** Alpha of the width marker: counted by the client's glyph width scan, discarded by the text shader (below 0.1). */
    static final int MARKER = 0x01000000;

    /** A frame with an empty right column gets a nearly transparent pixel in its corner (as the crucible art). */
    static void keepAdvance(BufferedImage png, int w, int h) {
        for (int fy = 0; fy < png.getHeight(); fy += h) {
            for (int fx = 0; fx < png.getWidth(); fx += w) {
                boolean any = false;
                for (int y = fy; y < fy + h && !any; y++) {
                    any = (png.getRGB(fx + w - 1, y) >>> 24) != 0;
                }
                if (!any) {
                    png.setRGB(fx + w - 1, fy + h - 1, MARKER);
                }
            }
        }
    }

    /** TFC's numbers this layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        String screen = tfc.readString(SCREEN).replaceAll("\\s+", " ");
        need(container, CONTAINER, ".init(playerInventory, " + TFC_INVENTORY_OFFSET + ")");
        need(container, CONTAINER, "addSlot(new CallbackSlot(blockEntity, 0, 152, 17));");
        need(screen, SCREEN, "imageHeight += " + TFC_INVENTORY_OFFSET + ";");
        need(screen, SCREEN, "renderCapacityLimitedFillMeter(graphics, " + ORE_X + ", " + METER_Y + ", lit ? "
            + ORE_FILL_LIT_U + " : " + ORE_FILL_UNLIT_U + ", maximumCapacity, capacity, inputCount);");
        need(screen, SCREEN, "renderCapacityLimitedFillMeter(graphics, " + FUEL_X + ", " + METER_Y + ", " + FUEL_FILL_U
            + ", maximumCapacity, capacity, fuelCount);");
        need(screen, SCREEN, "graphics.blit(texture, leftPos + " + TFC_THERMOMETER_X + ", topPos + " + TFC_THERMOMETER_BOTTOM
            + " - Math.min(" + ProgressFrames.THERMOMETER_TRAVEL + ", temperature), " + THERMOMETER_U + ", " + THERMOMETER_V
            + ", " + ProgressFrames.THERMOMETER_WIDTH + ", " + ProgressFrames.THERMOMETER_HEIGHT + ");");
        need(screen, SCREEN, "graphics.blit(texture, leftPos + x, topPos + y, " + DOTTED_U + ", 0, " + METER_WIDTH + ", "
            + METER_HEIGHT + ");");
        need(screen, SCREEN, "final int emptyHeight = (" + METER_SPAN + " * capacity) / maximum;");
        need(screen, SCREEN, "graphics.blit(texture, leftPos + x, topPos + y + " + METER_SPAN + " - emptyHeight, " + EMPTY_U
            + ", 0, " + METER_WIDTH + ", 1 + emptyHeight);");
        need(screen, SCREEN, "graphics.blit(texture, leftPos + x, topPos + y + 65 - fillHeight, fillU, " + FILL_V + ", "
            + METER_WIDTH + ", fillHeight);");
        need(screen, SCREEN, "final int fillHeight = (int) Math.ceil((float) " + FLUID_HEIGHT + " * fluid.getAmount()");
        need(screen, SCREEN, "leftPos + " + TFC_FLUID_X + ", topPos + " + TFC_FLUID_BOTTOM + " - fillHeight, " + FLUID_WIDTH
            + ", fillHeight, 16, 16");
        if (CHEST.slotY(TUYERE_SLOT) != 17 + DY || CHEST.slotX(TUYERE_SLOT) != 152) {
            throw new DatagenException("the tuyere slot does not land on chest slot " + TUYERE_SLOT);
        }
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the blast furnace screen art is stale");
        }
    }

    private static void checkPlain(BufferedImage src, int y) {
        int c = src.getRGB(4, y);
        for (int x = 4; x < ChestGeometry.WIDTH - 4; x++) {
            if (src.getRGB(x, y) != c) {
                throw new DatagenException(TEXTURE + ": row " + y + " is not plain panel; the re-layout would cut art");
            }
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        images.put(image.id(), e);
    }

    static BufferedImage read(byte[] bytes, String what) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(what + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
