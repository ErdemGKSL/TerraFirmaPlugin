    @Test
    void cooling() {
        List<String[]> rows = rows("A");
        assertThat(rows).hasSize(120);
        for (String[] r : rows) {
            float t = Float.parseFloat(r[1]);
            float c = Float.parseFloat(r[2]);
            long ticks = Long.parseLong(r[3]);
            float expected = Float.parseFloat(r[4]);
            assertThat(HeatState.adjust(t, c, ticks, CFG))
                .as("adjust(%s, %s, %s)", t, c, ticks)
                .isCloseTo(expected, within(TOL));
            assertThat(new HeatState(t, 0L).temperatureAt(ticks, c, CFG))
                .as("temperatureAt(%s, %s, %s)", t, c, ticks)
                .isCloseTo(expected, within(TOL));
        }
    }

    @Test
    void heating() {
        List<String[]> rows = rows("H");
        assertThat(rows).hasSize(48);
        for (String[] r : rows) {
            float initial = Float.parseFloat(r[1]);
            float target = Float.parseFloat(r[2]);
            float modifier = Float.parseFloat(r[3]);
            float c = Float.parseFloat(r[4]);
            float expected = Float.parseFloat(r[5]);
            float actual = new HeatState(initial, 0L).heat(target, modifier, 0L, c, CFG).temperature();
            assertThat(actual)
                .as("heat(%s -> %s, modifier %s, capacity %s)", initial, target, modifier, c)
                .isCloseTo(expected, within(TOL));
        }
    }

    @Test
    void levels() {
        List<String[]> rows = rows("L");
        assertThat(rows).hasSize(18);
        for (String[] r : rows) {
            float t = Float.parseFloat(r[1]);
            String expected = r[2];
            String actual = HeatLevel.of(t).map(Enum::name).orElse("none");
            assertThat(actual).as("level of %s", t).isEqualTo(expected);
        }
    }

    @Test
    void guiScale() {
        List<String[]> rows = rows("G");
        assertThat(rows).hasSize(7);
        for (String[] r : rows) {
            float t = Float.parseFloat(r[1]);
            assertThat(HeatLevel.scaleForGui(t)).as("gui pixels of %s", t).isEqualTo(Integer.parseInt(r[2]));
        }
    }

    /** The rows with the given tag, split on {@code |}; comment lines and other tags are skipped. */
    private static List<String[]> rows(String tag) {
        List<String[]> out = new ArrayList<>();
        for (String line : GOLDEN.split("\n")) {
            if (line.startsWith(tag + "|")) {
                out.add(line.split("\\|"));
            }
        }
        return out;
    }
