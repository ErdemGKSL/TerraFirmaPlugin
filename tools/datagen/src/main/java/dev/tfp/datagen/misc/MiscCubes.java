package dev.tfp.datagen.misc;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import dev.tfp.datagen.device.DeviceBlockSpec;
import dev.tfp.datagen.device.DeviceSound;
import dev.tfp.datagen.rendered.RenderedCubeSpec;
import dev.tfp.datagen.rendered.RenderedSound;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * PAR-DECO-12: the misc full cubes drawn by the renderer ({@code tfp:block/rendered_cube}, PAR-INFRA-17): the crate of each
 * of the 20 woods ({@code Wood.BlockType.CRATE}: strength 9, wood sounds, an axe, no tool needed for the drop) and the palm
 * mosaic ({@code Properties.ofFullCopy(Blocks.BAMBOO_MOSAIC)}: 2.0 / 3.0, {@code SoundType.BAMBOO_WOOD}, an axe). Both are
 * {@code cube_all} models in TFC. Written to {@code configuration/misc/cubes.yml}; the crate's inventory (a block entity) and
 * the mosaic's stairs and slabs are not in this file (see the PAR-DECO-12 item).
 */
public final class MiscCubes {
    public static final String OUTPUT = "craftengine/tfp/configuration/misc/cubes.yml";
    static final String RP = "craftengine/tfp/resourcepack/assets/tfp/";
    static final String LANG_RP = "craftengine/tfp/resourcepack/assets/tfp_misc/lang/";
    static final String BLOCKSTATES = TfcCheckout.ASSETS + "blockstates/";
    static final String MODELS = TfcCheckout.ASSETS + "models/";
    static final String TEXTURES = TfcCheckout.ASSETS + "textures/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String MINEABLE = TfcCheckout.GENERATED + "data/minecraft/tags/block/mineable/";
    static final String WOOD_JAVA = "src/main/java/net/dries007/tfc/common/blocks/wood/Wood.java";
    static final String PALM_MOSAIC = "wood/planks/palm_mosaic";
    private static final Pattern CRATE = Pattern.compile(
        "CRATE\\(\\(self, wood\\) -> new CrateBlock\\(properties\\(wood\\)\\.strength\\(([0-9.]+)f\\)\\.noOcclusion\\(\\)");
    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ " + TfcCheckout.PINNED_COMMIT.substring(0, 9)
        + ". Do not edit: fix the generator and regenerate.\nPAR-DECO-12: crates and the palm mosaic as renderer cubes.";

    private MiscCubes() {
    }

    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(BLOCKSTATES + PALM_MOSAIC + ".json") && tfc.exists(WOOD_JAVA)
            && !tfc.list(BLOCKSTATES + "wood/crate/").isEmpty();
    }

    /** The woods that have a crate blockstate. */
    public static List<String> crateWoods(TfcCheckout tfc) {
        String dir = BLOCKSTATES + "wood/crate/";
        TreeSet<String> woods = new TreeSet<>();
        for (String f : tfc.list(dir)) {
            if (f.endsWith(".json")) {
                woods.add(f.substring(dir.length(), f.length() - ".json".length()));
            }
        }
        return new ArrayList<>(woods);
    }

    /** The block paths written (below {@code tfp:}). */
    public static List<String> paths(TfcCheckout tfc) {
        List<String> paths = new ArrayList<>();
        for (String w : crateWoods(tfc)) {
            paths.add("wood/crate/" + w);
        }
        paths.add(PALM_MOSAIC);
        return paths;
    }

    /** Writes the blocks, models, textures and names; returns the number of cubes. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        String crateStrength = crateStrength(tfc);
        Map<String, Object> blocks = new LinkedHashMap<>();
        Map<String, Object> items = new LinkedHashMap<>();
        Map<String, Object> renderItems = new LinkedHashMap<>();
        for (String path : paths(tfc)) {
            boolean crate = path.startsWith("wood/crate/");
            DeviceBlockSpec.Settings settings = crate
                ? DeviceBlockSpec.Settings.of(crateStrength, crateStrength, DeviceSound.WOOD, tool(tfc, path))
                : DeviceBlockSpec.Settings.of("2.0", "3.0", RenderedSound.BAMBOO_WOOD, tool(tfc, path)); // Blocks.BAMBOO_MOSAIC
            String id = Json.TO_NS + ":" + path;
            String model = Json.TO_NS + ":block/" + path;
            copyModel(tfc, out, "block/" + path);
            copyModel(tfc, out, "item/" + path);
            RenderedCubeSpec spec = RenderedCubeSpec.of(id, model, settings, false, langKey(path));
            Map<String, Object> yaml = spec.yaml();
            @SuppressWarnings("unchecked")
            Map<String, Object> specBlocks = (Map<String, Object>) yaml.get("blocks");
            @SuppressWarnings("unchecked")
            Map<String, Object> specItems = (Map<String, Object>) yaml.get("items");
            blocks.putAll(specBlocks);
            specItems.forEach((k, v) -> (k.startsWith(Json.TO_NS + ":render/") ? renderItems : items).put(k, v));
        }
        Map<String, Object> all = new LinkedHashMap<>(items);
        all.putAll(renderItems);
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("blocks", blocks);
        root.put("items", all);
        out.put(OUTPUT, Yaml.write(HEADER, root));
        writeLang(tfc, out);
        return blocks.size();
    }

    static String langKey(String path) {
        return "block." + Json.TO_NS + "." + path.replace('/', '.');
    }

    static String crateStrength(TfcCheckout tfc) {
        Matcher m = CRATE.matcher(tfc.readString(WOOD_JAVA));
        if (!m.find()) {
            throw new DatagenException(WOOD_JAVA + ": the CRATE registration no longer matches " + CRATE.pattern());
        }
        return m.group(1);
    }

    /** The one {@code minecraft:mineable/<tool>} tag of TFC's generated data that holds the block. */
    static String tool(TfcCheckout tfc, String path) {
        String found = null;
        for (String t : List.of("axe", "hoe", "pickaxe", "shovel")) {
            String src = MINEABLE + t + ".json";
            for (JsonElement v : Json.parse(tfc.readString(src), src).getAsJsonObject().getAsJsonArray("values")) {
                if (v.isJsonPrimitive() && v.getAsString().equals(Json.FROM_NS + ":" + path)) {
                    if (found != null) {
                        throw new DatagenException("tfc:" + path + " is in two mineable tags: " + found + ", " + t);
                    }
                    found = t;
                }
            }
        }
        if (found == null) {
            throw new DatagenException("tfc:" + path + " is in no minecraft:mineable tag");
        }
        return found;
    }

    /** One block or item model (renamed) and the textures and parents it names that TFC owns. */
    static void copyModel(TfcCheckout tfc, OutputTree out, String path) {
        String src = MODELS + path + ".json";
        if (!tfc.exists(src)) {
            throw new DatagenException("TFC has no model " + path);
        }
        JsonObject m = Json.rename(Json.parse(tfc.readString(src), src)).getAsJsonObject();
        out.put(RP + "models/" + path + ".json", Json.write(m));
        if (m.has("parent") && m.get("parent").getAsString().startsWith(Json.TO_NS + ":")) {
            copyModel(tfc, out, m.get("parent").getAsString().substring(Json.TO_NS.length() + 1));
        }
        JsonObject textures = m.getAsJsonObject("textures");
        if (textures == null) {
            return;
        }
        for (Map.Entry<String, JsonElement> t : textures.entrySet()) {
            String v = t.getValue().getAsString();
            if (!v.startsWith(Json.TO_NS + ":")) {
                continue;
            }
            String rel = v.substring(Json.TO_NS.length() + 1);
            String png = TEXTURES + rel + ".png";
            if (!tfc.exists(png)) {
                throw new DatagenException(src + " names " + v + ", which TFC has no texture for");
            }
            out.put(RP + "textures/" + rel + ".png", tfc.read(png));
        }
    }

    static void writeLang(TfcCheckout tfc, OutputTree out) {
        List<String> paths = paths(tfc);
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            Map<String, String> keys = new TreeMap<>();
            for (String path : paths) {
                String tfcKey = "block." + Json.FROM_NS + "." + path.replace('/', '.');
                if (src.has(tfcKey)) {
                    keys.put(langKey(path), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }
}
