    private static Map<String, Object> settings(BigDecimal strength, Map<String, List<String>> tags, String path, String item) {
        List<String> t = tags.getOrDefault(Json.FROM_NS + ":" + path, List.of());
        if (t.stream().noneMatch(x -> x.startsWith("minecraft:mineable/"))) {
            throw new DatagenException(Json.FROM_NS + ":" + path + " is in no minecraft:mineable tag");
        }
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("template", "tfp:settings/sound");
        m.put("arguments", Map.of("sound_block_type", "wood"));
        m.put("hardness", strength);
        m.put("resistance", strength);
        m.put("tags", t);
        if (item != null) {
            m.put("item", item);
        }
        return m;
    }

    private static Map<String, Object> selfLoot(String item) {
        Map<String, Object> entry = new LinkedHashMap<>();
        entry.put("type", "item");
        entry.put("item", item);
        Map<String, Object> pool = new LinkedHashMap<>();
        pool.put("rolls", 1);
        pool.put("conditions", List.of(Map.of("type", "survives_explosion")));
        pool.put("entries", List.of(entry));
        return Map.of("pools", List.of(pool));
    }

    private static Map<String, Object> prop(String type, List<String> values, Object dflt) {
        Map<String, Object> p = new LinkedHashMap<>();
        p.put("type", type);
        if (values != null) {
            p.put("values", values);
        }
        p.put("default", dflt);
        return p;
    }

    private static Map<String, Object> bool() {
        return prop("boolean", null, false);
    }

    private static Map<String, Object> rotationProperty() {
        Map<String, Object> p = new LinkedHashMap<>();
        p.put("type", "int");
        p.put("range", "0~15");
        p.put("default", 0);
        return p;
    }

    private static Map<String, Object> facingProperty() {
        return prop("horizontal_direction", FACINGS, "north");
    }

    private static Map<String, Object> appearance(String carrier, String renderItem, String rotation) {
        Map<String, Object> renderer = new LinkedHashMap<>();
        renderer.put("item", renderItem);
        renderer.put("rotation", rotation);
        Map<String, Object> app = new LinkedHashMap<>();
        app.put("state", carrier);
        app.put("transparent", true);
        app.put("entity_renderer", List.of(renderer));
        return app;
    }

    private static Map<String, Object> variant(String appearance, boolean wet) {
        Map<String, Object> v = new LinkedHashMap<>();
        v.put("appearance", appearance);
        if (wet) {
            v.put("settings", Map.of("fluid_state", "water"));
        }
        return v;
    }

    /** The item display turn of a sign yaw in degrees (a block model's {@code y}): the half turn of block-model displays minus it. */
    static String rotation(double yaw) {
        double d = Math.floorMod(Math.round((180 - yaw) * 2), 720L) / 2.0;
        return "0," + BigDecimal.valueOf(d).stripTrailingZeros().toPlainString() + ",0";
    }

    static double standingYaw(int rotation) {
        return rotation * 22.5;
    }

    static double facingYaw(String facing) {
        return switch (facing) {
            case "south" -> 0;
            case "west" -> 90;
            case "north" -> 180;
            case "east" -> 270;
            default -> throw new IllegalArgumentException(facing);
        };
    }

    private static Map<String, Object> block(Map<String, Object> settings, List<Object> behavior, Map<String, Object> loot,
            Map<String, Object> properties, Map<String, Object> appearances, Map<String, Object> variants) {
        Map<String, Object> states = new LinkedHashMap<>();
        states.put("properties", properties);
        states.put("appearances", appearances);
        states.put("variants", variants);
        Map<String, Object> b = new LinkedHashMap<>();
        b.put("settings", settings);
        b.put("behavior", behavior);
        b.put("loot", loot);
        b.put("states", states);
        return b;
    }

    private static Map<String, Object> sturdy(String direction) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("type", "sturdy_base_block");
        m.put("direction", direction);
        m.put("support_types", List.of("full"));
        return m;
    }

    /** TFC's {@code SIGN}: {@code StandingSignBlock}, 16 rotations, waterloggable, a solid block (or a sign) below. */
    static Map<String, Object> standing(BigDecimal strength, Map<String, List<String>> tags, String path, String wood) {
        Map<String, Object> props = new LinkedHashMap<>();
        props.put("rotation", rotationProperty());
        props.put("waterlogged", bool());
        Map<String, Object> apps = new LinkedHashMap<>();
        Map<String, Object> vars = new LinkedHashMap<>();
        for (int r = 0; r < 16; r++) {
            apps.put("r" + r, appearance(CARRIER_FLOOR, renderId("sign/standing/" + wood), rotation(standingYaw(r))));
            for (boolean wet : new boolean[] {false, true}) {
                vars.put("rotation=" + r + ",waterlogged=" + wet, variant("r" + r, wet));
            }
        }
        return block(settings(strength, tags, path, null), List.of(sturdy("down")), selfLoot(id(path)), props, apps, vars);
    }

    /** TFC's {@code WALL_SIGN}: four facings, waterloggable, drops the standing sign. */
    static Map<String, Object> wall(BigDecimal strength, Map<String, List<String>> tags, String path, String wood, String dropItem) {
        Map<String, Object> props = new LinkedHashMap<>();
        props.put("facing", facingProperty());
        props.put("waterlogged", bool());
        Map<String, Object> apps = new LinkedHashMap<>();
        Map<String, Object> vars = new LinkedHashMap<>();
        for (String f : FACINGS) {
            apps.put(f, appearance(CARRIER_WALL.formatted(f), renderId("sign/wall/" + wood), rotation(facingYaw(f))));
            for (boolean wet : new boolean[] {false, true}) {
                vars.put("facing=" + f + ",waterlogged=" + wet, variant(f, wet));
            }
        }
        return block(settings(strength, tags, path, dropItem), List.of(Map.of("type", "directional_attached_block")),
            selfLoot(dropItem), props, apps, vars);
    }

    /** TFC's ceiling hanging sign: 16 rotations, {@code attached} (V chains), waterloggable. */
    static Map<String, Object> ceilingHanging(BigDecimal strength, Map<String, List<String>> tags, String path, String metal,
            String wood, String self) {
        Map<String, Object> props = new LinkedHashMap<>();
        props.put("rotation", rotationProperty());
        props.put("attached", bool());
        props.put("waterlogged", bool());
        Map<String, Object> apps = new LinkedHashMap<>();
        Map<String, Object> vars = new LinkedHashMap<>();
        for (int r = 0; r < 16; r++) {
            for (boolean attached : new boolean[] {false, true}) {
                String name = "r" + r + (attached ? "_attached" : "");
                String shape = attached ? "hanging_v" : "hanging";
                apps.put(name, appearance(CARRIER_CEILING.formatted("north"), renderId("sign/" + shape + "/" + metal + "/" + wood),
                    rotation(standingYaw(r))));
                for (boolean wet : new boolean[] {false, true}) {
                    vars.put("rotation=" + r + ",attached=" + attached + ",waterlogged=" + wet, variant(name, wet));
                }
            }
        }
        return block(settings(strength, tags, path, null), List.of(sturdy("up")), selfLoot(self), props, apps, vars);
    }

    /** TFC's wall hanging sign: four facings, waterloggable, drops the hanging sign item. */
    static Map<String, Object> wallHanging(BigDecimal strength, Map<String, List<String>> tags, String path, String metal,
            String wood, String dropItem) {
        Map<String, Object> props = new LinkedHashMap<>();
        props.put("facing", facingProperty());
        props.put("waterlogged", bool());
        Map<String, Object> apps = new LinkedHashMap<>();
        Map<String, Object> vars = new LinkedHashMap<>();
        for (String f : FACINGS) {
            apps.put(f, appearance(CARRIER_CEILING.formatted(f), renderId("sign/wall_hanging/" + metal + "/" + wood),
                rotation(facingYaw(f))));
            for (boolean wet : new boolean[] {false, true}) {
                vars.put("facing=" + f + ",waterlogged=" + wet, variant(f, wet));
            }
        }
        return block(settings(strength, tags, path, dropItem), List.of(), selfLoot(dropItem), props, apps, vars);
    }

    // ---- items ----------------------------------------------------------------------------------------------------------

    private static Map<String, Object> item(String path, List<Object> behavior) {
        Map<String, Object> item = new LinkedHashMap<>();
        item.put("material", "paper");
        item.put("data", Map.of("item_name", "<!i><lang:" + langKey(path) + ">"));
        item.put("model", Json.TO_NS + ":item/" + path);
        item.put("behavior", behavior);
        return item;
    }

    private static Map<String, Object> behaviorOf(String type, String block) {
        Map<String, Object> b = new LinkedHashMap<>();
        b.put("type", type);
        b.put("block", block);
        return b;
    }

    /** TFC {@code SignItem}: the wall sign on a side face, the standing sign otherwise. */
    static Map<String, Object> signItem(String path, String wallBlock, String standingBlock) {
        return item(path, List.of(behaviorOf("wall_block_item", wallBlock), behaviorOf("block_item", standingBlock)));
    }

    /** TFC {@code HangingSignItem}: the wall hanging sign on a side face, the ceiling one under a block. */
    static Map<String, Object> hangingItem(String path, String wallBlock, String ceilingBlock) {
        return item(path, List.of(behaviorOf("wall_block_item", wallBlock), behaviorOf("ceiling_block_item", ceilingBlock)));
    }

    // ---- names ----------------------------------------------------------------------------------------------------------

    static void writeLang(TfcCheckout tfc, OutputTree out, List<String> woods, List<String> metals) {
        List<String> paths = new ArrayList<>();
        for (String w : woods) {
            paths.add(path("sign", null, w));
            paths.add(path("wall_sign", null, w));
            for (String m : metals) {
                paths.add(path("hanging_sign", m, w));
                paths.add(path("wall_hanging_sign", m, w));
            }
        }
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            Map<String, String> keys = new TreeMap<>();
            for (String path : paths) {
                String tfcKey = "block." + Json.FROM_NS + "." + path.replace('/', '.');
                if (src.has(tfcKey)) {
                    keys.put(langKey(path), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }
