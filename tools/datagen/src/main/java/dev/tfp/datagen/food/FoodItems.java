package dev.tfp.datagen.food;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * PAR-SURV-01: every TFC food item as a CraftEngine item ({@code configuration/food.yml}) with its model and textures.
 *
 * <p>The items are the ones {@code TFCItems} registers from {@code Food} and {@code Nutrient}: {@code food/<food>} for every
 * food, {@code jar/<food>} and {@code jar/<food>_unsealed} (fruit preserves) and {@code <food>_jam} for every food with jam,
 * {@code food/<nutrient>_soup} and {@code food/<nutrient>_salad} for every nutrient. Ids are TFC's in our namespace.
 *
 * <p>Each item gets what TFC's {@code onModifyDefaultComponentsAfterResourceReload} gives it: a food component when its food
 * definition is edible (TFC's default {@code FoodProperties}: vanilla's 1.6 s eat time, never always-edible) and the stack
 * size of the weight of its {@code item_size} definition (the plain item's 64 without one). Both definitions are the first
 * match in TFC's load order ({@link TfcItemData}). Every item carries the {@code tfp:food_stamp} processor, so it is dated on
 * creation. The vanilla nutrition is the TFC hunger (the eat listener sets TFC's values one tick later); non-edible foods
 * (preserves, sealed jars) use the plain item template.
 *
 * <p>A missing source line, model, definition or name is an error, so a TFC change shows up here.
 */
public final class FoodItems {
    static final String FOOD_SOURCE = "src/main/java/net/dries007/tfc/common/items/Food.java";
    static final String NUTRIENT_SOURCE = "src/main/java/net/dries007/tfc/common/component/food/Nutrient.java";
    static final String ITEMS_SOURCE = "src/main/java/net/dries007/tfc/common/items/TFCItems.java";
    static final String LANG = TfcCheckout.ASSETS + "lang/en_us.json";
    static final String PACK = "craftengine/tfp/";
    static final String OUTPUT = PACK + "configuration/food.yml";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";

    /** TFC's default {@code FoodProperties} eat time (vanilla {@code FoodProperties.DEFAULT_EAT_SECONDS}). */
    static final BigDecimal EAT_SECONDS = new BigDecimal("1.6");
    /** The stack size of an item without an {@code item_size} definition (TFC {@code DEFAULT_SIZE}, very light). */
    static final int DEFAULT_STACK = 64;
    /** TFC {@code Weight} stack sizes. */
    static final Map<String, Integer> WEIGHT_STACK = Map.of(
        "very_light", 64, "light", 32, "medium", 16, "heavy", 4, "very_heavy", 1);

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";
    private static final Pattern ENUM_BODY = Pattern.compile("public enum Food implements StringRepresentable\\s*\\{(.*?);",
        Pattern.DOTALL);
    private static final Pattern FOOD_CONSTANT = Pattern.compile("^\\s*([A-Z_]+)(\\(true\\))?,?\\s*$");
    private static final Pattern NUTRIENT_CONSTANT = Pattern.compile("^ {4}([A-Z_]+)\\(ChatFormatting\\.[A-Z_]+\\)[,;]",
        Pattern.MULTILINE);
    /** The registrations this generator mirrors, exactly as TFC writes them (a change fails the run). */
    static final List<String> REGISTRATIONS = List.of(
        "FOOD = Helpers.mapOf(Food.class, food ->\n        register(\"food/\" + food.name(), () -> new Item(new Properties()))",
        "FRUIT_PRESERVES = Helpers.mapOf(Food.class, Food::hasJam, food ->\n        register(\"jar/\" + food.name(), () -> new Item(new Properties().component(Lore.TYPE, Lore.SEALED)))",
        "UNSEALED_FRUIT_PRESERVES = Helpers.mapOf(Food.class, Food::hasJam, food ->\n        register(\"jar/\" + food.name() + \"_unsealed\", () -> new Item(new Properties().component(Lore.TYPE, Lore.UNSEALED).craftRemainder(TFCItems.EMPTY_JAR.asItem())))",
        "JAM = Helpers.mapOf(Food.class, Food::hasJam, food ->\n        register(food.name() + \"_jam\", () -> new Item(new Properties()))",
        "SOUPS = Helpers.mapOf(Nutrient.class, nutrient ->\n        register(\"food/\" + nutrient.name() + \"_soup\", () -> new Item(new Properties()))",
        "SALADS = Helpers.mapOf(Nutrient.class, nutrient ->\n        register(\"food/\" + nutrient.name() + \"_salad\", () -> new Item(new Properties()))");

    /** One food constant of TFC's {@code Food} enum (lower case) and whether it has jam. */
    record Food(String name, boolean hasJam) {
    }

    /**
     * One generated food item.
     *
     * @param id         the path ({@code food/wheat_bread}), TFC's and ours
     * @param langKey    our item name key ({@code item.tfp.food.wheat_bread})
     * @param hunger     the TFC hunger of its food definition (0 when the definition has none)
     * @param edible     whether TFC gives it a food component
     * @param stackSize  the max stack size from its item size
     * @param definition the food definition's id, e.g. {@code tfc:wheat_bread}
     */
    public record FoodItem(String id, String langKey, int hunger, boolean edible, int stackSize, String definition) {
    }

    private FoodItems() {
    }

    /** Whether the checkout has TFC's food sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(FOOD_SOURCE) && tfc.exists(NUTRIENT_SOURCE) && tfc.exists(ITEMS_SOURCE);
    }

    /** Writes the CE items, their models and textures. Returns the number of items. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        List<FoodItem> items = items(tfc);
        Map<String, Object> entries = new TreeMap<>();
        for (FoodItem item : items) {
            copyModel(tfc, out, item.id());
            entries.put(Json.TO_NS + ":" + item.id(), entry(item));
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", entries);
        out.put(OUTPUT, Yaml.write(HEADER, root));
        return items.size();
    }

    /** The CE entry of one item: the shared template plus its stack size, eat time and the food stamp. */
    static Map<String, Object> entry(FoodItem item) {
        Map<String, Object> entry = new LinkedHashMap<>();
        Map<String, Object> args = new LinkedHashMap<>();
        args.put("item_lang_key", item.langKey());
        if (item.edible()) {
            entry.put("template", "tfp:item/food");
            args.put("nutrition", item.hunger());
        } else {
            entry.put("template", "tfp:item/simple");
        }
        entry.put("arguments", args);
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("max_stack_size", item.stackSize());
        if (item.edible()) {
            data.put("consumable", Map.of("consume_seconds", EAT_SECONDS));
        }
        data.put(Json.TO_NS + ":food_stamp", Map.of());
        entry.put("data", data);
        return entry;
    }

    /** Every food item of the checkout in TFC's registration order. */
    public static List<FoodItem> items(TfcCheckout tfc) {
        String registrations = tfc.readString(ITEMS_SOURCE).replace("\r\n", "\n");
        for (String r : REGISTRATIONS) {
            if (!registrations.contains(r)) {
                throw new DatagenException(ITEMS_SOURCE + " no longer registers: " + r.lines().findFirst().orElse(r)
                    + " (update the food generator)");
            }
        }
        List<Food> foods = foods(tfc.readString(FOOD_SOURCE));
        List<String> nutrients = nutrients(tfc.readString(NUTRIENT_SOURCE));
        List<String> ids = new ArrayList<>();
        foods.forEach(f -> ids.add("food/" + f.name()));
        foods.stream().filter(Food::hasJam).forEach(f -> ids.add("jar/" + f.name()));
        foods.stream().filter(Food::hasJam).forEach(f -> ids.add("jar/" + f.name() + "_unsealed"));
        foods.stream().filter(Food::hasJam).forEach(f -> ids.add(f.name() + "_jam"));
        nutrients.forEach(n -> ids.add("food/" + n + "_soup"));
        nutrients.forEach(n -> ids.add("food/" + n + "_salad"));

        TfcItemData data = new TfcItemData(tfc);
        List<TfcItemData.Definition> foodDefs = data.definitions("food");
        List<TfcItemData.Definition> sizeDefs = data.definitions("item_size");
        JsonObject lang = Json.parse(tfc.readString(LANG), LANG).getAsJsonObject();
        List<FoodItem> out = new ArrayList<>();
        for (String id : ids) {
            String tfcId = Json.FROM_NS + ":" + id;
            TfcItemData.Definition def = data.first(foodDefs, tfcId)
                .orElseThrow(() -> new DatagenException("TFC food item " + tfcId + " has no food definition"));
            JsonObject json = def.json();
            int hunger = json.has("hunger") ? json.get("hunger").getAsInt() : 0;
            boolean edible = !json.has("edible") || json.get("edible").getAsBoolean();
            int stack = data.first(sizeDefs, tfcId).map(FoodItems::stackSize).orElse(DEFAULT_STACK);
            String tfcKey = "item." + Json.FROM_NS + "." + id.replace('/', '.');
            if (!lang.has(tfcKey)) {
                throw new DatagenException("TFC food item " + tfcId + " has no English name " + tfcKey);
            }
            String key = "item." + Json.TO_NS + "." + id.replace('/', '.');
            out.add(new FoodItem(id, key, hunger, edible, stack, def.id()));
        }
        return out;
    }

    private static int stackSize(TfcItemData.Definition size) {
        String weight = size.json().get("weight").getAsString();
        Integer stack = WEIGHT_STACK.get(weight);
        if (stack == null) {
            throw new DatagenException("item size " + size.id() + " has unknown weight " + weight);
        }
        return stack;
    }

    /** The constants of TFC's {@code Food} enum in declaration order. */
    static List<Food> foods(String source) {
        Matcher body = ENUM_BODY.matcher(source.replace("\r\n", "\n"));
        if (!body.find()) {
            throw new DatagenException(FOOD_SOURCE + ": enum Food not found (the format changed?)");
        }
        List<Food> out = new ArrayList<>();
        for (String line : body.group(1).split("\n")) {
            String t = line.strip();
            if (t.isEmpty() || t.startsWith("//")) {
                continue;
            }
            Matcher m = FOOD_CONSTANT.matcher(t);
            if (!m.matches()) {
                throw new DatagenException(FOOD_SOURCE + ": unexpected line in enum Food: " + t);
            }
            out.add(new Food(m.group(1).toLowerCase(Locale.ROOT), m.group(2) != null));
        }
        if (out.isEmpty()) {
            throw new DatagenException(FOOD_SOURCE + " has no food constants");
        }
        return out;
    }

    /** The constants of TFC's {@code Nutrient} enum in declaration order (lower case). */
    static List<String> nutrients(String source) {
        List<String> out = new ArrayList<>();
        Matcher m = NUTRIENT_CONSTANT.matcher(source);
        while (m.find()) {
            out.add(m.group(1).toLowerCase(Locale.ROOT));
        }
        if (out.isEmpty()) {
            throw new DatagenException(NUTRIENT_SOURCE + " has no nutrient constants");
        }
        return out;
    }

    /** Copies the item model {@code models/item/<id>.json} (a generated item model) and its textures into the pack. */
    private static void copyModel(TfcCheckout tfc, OutputTree out, String id) {
        String src = TfcCheckout.ASSETS + "models/item/" + id + ".json";
        if (!tfc.exists(src)) {
            throw new DatagenException("TFC food item tfc:" + id + " has no item model " + src);
        }
        JsonObject model = Json.parse(tfc.readString(src), src).getAsJsonObject();
        String parent = model.has("parent") ? model.get("parent").getAsString() : "";
        if (model.has("loader") || !(parent.equals("item/generated") || parent.equals("minecraft:item/generated"))) {
            throw new DatagenException(src + ": the food generator copies plain generated item models only, got parent "
                + parent + (model.has("loader") ? " and a loader" : ""));
        }
        if (model.has("textures")) {
            for (Map.Entry<String, JsonElement> t : model.getAsJsonObject("textures").entrySet()) {
                String ref = t.getValue().getAsString();
                if (!ref.startsWith(Json.FROM_NS + ":")) {
                    continue; // a vanilla texture: the client has it
                }
                String path = ref.substring(Json.FROM_NS.length() + 1);
                String png = TfcCheckout.ASSETS + "textures/" + path + ".png";
                if (!tfc.exists(png)) {
                    throw new DatagenException(src + " uses missing texture " + ref);
                }
                out.put(RP + "textures/" + path + ".png", tfc.read(png));
                if (tfc.exists(png + ".mcmeta")) {
                    out.put(RP + "textures/" + path + ".png.mcmeta", tfc.read(png + ".mcmeta"));
                }
            }
        }
        out.put(RP + "models/item/" + id + ".json", Json.write(Json.rename(model)));
    }

    /** The food item ids of {@link #items}, for tests and reports. */
    static Optional<FoodItem> find(List<FoodItem> items, String id) {
        return items.stream().filter(i -> i.id().equals(id)).findFirst();
    }
}
