package dev.tfp.datagen.rendered;

import dev.tfp.datagen.TfcCheckout;

/**
 * The spike S2 block (PAR-INFRA-17, not shipped): TFC's copper block drawn as a renderer cube in the spike namespace
 * {@code tfps2}. Its CraftEngine config is {@link #FILE}; {@code RenderedCubeSpecTest} fails when that file is not this
 * generator's output and writes the expected text to {@code tools/datagen/build/s2/s2.yml}. The spike's
 * {@code build-pack.sh} copies the file and TFC's copper texture (from the checkout, never vendored) into a test
 * server's CraftEngine resources.
 */
public final class S2Spike {
    /** Repository-relative path of the spike config. */
    public static final String FILE = "spikes/s2-destroy-stages/pack/configuration/s2.yml";
    public static final String COPPER = "tfps2:metal/block/copper";
    static final String HEADER = "Generated by tools/datagen (dev.tfp.datagen.rendered.S2Spike) from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.\n"
        + "Spike S2 (PAR-INFRA-17), not shipped: TFC's copper block as a renderer cube (tfp:block/rendered_cube).";

    private S2Spike() {
    }

    /** The copper block spec with TFC's metal block settings. */
    public static RenderedCubeSpec copper(TfcCheckout tfc) {
        return RenderedCubeSpec.of(COPPER, "tfps2:block/metal/block/copper", RenderedCubeSpec.tfcMetalBlock(tfc, "copper"), true,
            "block.tfp.metal.block.copper");
    }

    /** The text of {@link #FILE}. */
    public static String text(TfcCheckout tfc) {
        return copper(tfc).write(HEADER);
    }
}
