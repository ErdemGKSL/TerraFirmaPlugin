"""Model generator coverage report (plan item X-MOD-01). Standard library only, no network.

python3 -I tools/models/coverage.py <tfc-checkout> [--out docs/art/model-coverage.md]

Reads, from the repo: tools/models/species/*.json (parameter files), tools/models/out/*.bbmodel
(scratch output, git-ignored), and `git ls-files` to tell which outputs are committed.
Reads, from the TFC checkout: client/model/entity/*.java (entity models), client/animation/*.java and
AnimationDefinition constants, and every *.bbmodel. Writes a Markdown report (stdout by default).
"""
from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
TFC_ENTITY_DIR = pathlib.PurePosixPath("src/main/java/net/dries007/tfc/client/model/entity")
TFC_ANIM_DIR = pathlib.PurePosixPath("src/main/java/net/dries007/tfc/client/animation")
ANIM_CONST = re.compile(r"public\s+static\s+final\s+AnimationDefinition\s+(\w+)\s*=")

# Classes in client/model/entity that are not living-entity models a plugin species needs.
EXCLUDED = {
    "HierarchicalAnimatedModel": "abstract base class of every entity model",
    "AquaticCritterModel": "base class of IsopodModel and HorseshoeCrabModel",
    "FelinePredatorModel": "base class of LionModel, TigerModel, CougarModel, SabertoothModel",
    "AnemometerModel": "block-entity model (weather station)",
    "CalendarClockModel": "block-entity model (mechanical clock)",
    "VaneModel": "block-entity model (weather vane)",
    "WaterWheelModel": "block-entity model (water wheel)",
    "WindmillBladeModel": "block-entity model (windmill)",
    "WindmillBladeLatticeModel": "block-entity model (windmill)",
    "WindmillBladeRusticModel": "block-entity model (windmill)",
    "JavelinModel": "projectile model, drawn as an item display",
}


def species_key(cls: str) -> str:
    """TFCWolfModel -> wolf, BactrianCamelModel -> bactrian_camel, MuskOxModel -> musk_ox."""
    name = cls[: -len("Model")]
    if name.startswith("TFC"):
        name = name[3:]
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()


def git_ls_files(prefix: str) -> set[str] | None:
    try:
        out = subprocess.run(["git", "-C", str(REPO), "ls-files", prefix], capture_output=True, text=True, check=True)
        return set(out.stdout.split())
    except (OSError, subprocess.CalledProcessError):
        return None


def tfc_head(tfc: pathlib.Path) -> str:
    try:
        out = subprocess.run(["git", "-C", str(tfc), "rev-parse", "HEAD"], capture_output=True, text=True, check=True)
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown (not a git checkout)"


def anim_constants(path: pathlib.Path) -> list[str]:
    return ANIM_CONST.findall(path.read_text(encoding="utf-8", errors="replace"))


def build(tfc: pathlib.Path) -> str:
    entity_dir = tfc / TFC_ENTITY_DIR
    anim_dir = tfc / TFC_ANIM_DIR
    if not entity_dir.is_dir():
        raise SystemExit(f"not a TFC checkout (missing {TFC_ENTITY_DIR}): {tfc}")

    pin_file = REPO / "docs/porting/tfc-pin.txt"
    pin = pin_file.read_text().strip() if pin_file.exists() else "unknown"

    # TFC entity models in scope, plus the animation constants each one owns.
    classes = sorted(p.stem for p in entity_dir.glob("*.java") if p.stem != "package-info")
    in_scope, excluded = [], []
    for cls in classes:
        if cls.endswith("Layer"):
            excluded.append((cls, "render layer, not a species"))
        elif cls in EXCLUDED:
            excluded.append((cls, EXCLUDED[cls]))
        else:
            in_scope.append(cls)

    rows = []
    attributed = 0
    for cls in in_scope:
        consts = anim_constants(entity_dir / f"{cls}.java")
        stem = cls[: -len("Model")]
        anim_file = anim_dir / f"{stem}Animation.java"
        if anim_file.exists():
            consts += anim_constants(anim_file)
        attributed += len(consts)
        rows.append((cls, species_key(cls), len(consts)))
    all_files = list(entity_dir.glob("*.java")) + list(anim_dir.glob("*.java"))
    total_anims = sum(len(anim_constants(p)) for p in all_files)

    species_dir = REPO / "tools/models/species"
    out_dir = REPO / "tools/models/out"
    param_ids = {p.stem for p in species_dir.glob("*.json")}
    local_out = {p.name for p in out_dir.glob("*.bbmodel")} if out_dir.is_dir() else set()
    committed = git_ls_files("tools/models/out/")
    committed_out = {pathlib.PurePosixPath(p).name for p in (committed or set())}
    tfc_bbmodels = sum(1 for f in tfc.rglob("*.bbmodel") if ".git" not in f.parts)

    lines = []
    lines.append("# Model generator coverage")
    lines.append("")
    lines.append("Generated by `tools/models/coverage.py` (plan item X-MOD-01). Refresh with:")
    lines.append("")
    lines.append("```bash")
    lines.append("python3 -I tools/models/coverage.py <tfc-checkout> --out docs/art/model-coverage.md")
    lines.append("```")
    lines.append("")
    lines.append(f"TFC checkout HEAD: `{tfc_head(tfc)}`. Pin in `docs/porting/tfc-pin.txt`: `{pin}`.")
    lines.append("")
    lines.append("## How to read the table")
    lines.append("")
    lines.append("- **TFC entity model**: a concrete class in `client/model/entity/`, minus layers, block-entity models, a projectile model and base classes (listed under Excluded).")
    lines.append("- **Species key**: the id our generator would use, `tools/models/species/tfp_<key>.json`.")
    lines.append("- **Parameter file**: `yes` if `tools/models/species/tfp_<key>.json` exists.")
    lines.append("- **Generated .bbmodel**: `yes` if `tools/models/out/tfp_<key>.bbmodel` is committed. `local only` if the file exists in the git-ignored `out/` folder (not reproducible from the repo without its inputs). `no` otherwise.")
    lines.append("- **TFC animations**: AnimationDefinition constants in the entity model class and its `client/animation/<Name>Animation.java` file.")
    lines.append("- **Our animations**: `0 of N` when no committed model exists. `unknown` for a local-only draft, because its source conversion cannot be verified from the repo.")
    lines.append("- **Status**: `not started` (no parameter file, no output), `param only` (inputs, no committed output), `local draft` (output without committed inputs or output), `generated` (committed output).")
    lines.append("")
    lines.append("## Coverage table")
    lines.append("")
    lines.append("| TFC entity model | Species key | TFC animations | Parameter file | Generated .bbmodel | Our animations | Status |")
    lines.append("|---|---|---:|---|---|---|---|")
    cov_species = local_drafts = unknown_anim_rows = 0
    for cls, key, n in rows:
        pf = "yes" if key in param_ids or f"tfp_{key}" in param_ids else "no"
        name = f"tfp_{key}"
        if name + ".bbmodel" in committed_out:
            gen, status, ours = "yes", "generated", "not parsed"  # committed output: animation mapping is not parsed here
            cov_species += 1
        elif name + ".bbmodel" in local_out:
            gen, status, ours = "local only", "local draft", "unknown"
            local_drafts += 1
            unknown_anim_rows += 1
        else:
            gen = "no"
            status = "param only" if pf == "yes" else "not started"
            ours = f"0 of {n}"
        if pf == "yes" and gen == "no":
            status = "param only"
        lines.append(f"| `{cls}` | `{key}` | {n} | {pf} | {gen} | {ours} | {status} |")
    lines.append("")
    lines.append("## Excluded from the table")
    lines.append("")
    lines.append("| Class | Reason |")
    lines.append("|---|---|")
    for cls, why in excluded:
        lines.append(f"| `{cls}` | {why} |")
    lines.append("")
    lines.append("## Totals")
    lines.append("")
    lines.append(f"- TFC entity models in scope: **{len(rows)}** (excluded: {len(excluded)})")
    lines.append(f"- Entity models with a parameter file: **{sum(1 for _, k, _ in rows if k in param_ids or f'tfp_{k}' in param_ids)}** of {len(rows)}")
    lines.append(f"- Entity models with a committed generated .bbmodel: **{cov_species}** of {len(rows)}")
    lines.append(f"- Local-only drafts (git-ignored `out/`, inputs not in repo): **{local_drafts}**")
    lines.append(f"- TFC AnimationDefinition constants: **{total_anims}** in {len(all_files)} Java files scanned; attributed to the table: {attributed}")
    lines.append(f"- Animations covered by committed generated models: **0** of {total_anims} (none committed); unknown for local-only drafts: {unknown_anim_rows} row(s)")
    lines.append(f"- Our parameter files: {len(param_ids)} ({', '.join(sorted(param_ids))}); TFC species among them: {sum(1 for _, k, _ in rows if k in param_ids or f'tfp_{k}' in param_ids)}")
    lines.append(f"- TFC `.bbmodel` files in the checkout (reference only, not all are entity models): {tfc_bbmodels}")
    lines.append("")
    lines.append("## Open")
    lines.append("")
    lines.append("- Generating the remaining entity models (parameter files, rigs for birds, fish and serpentine bodies).")
    lines.append("- Validation runs (`validate.py`) on each generated model and Blockbench render checks.")
    lines.append("- Animation mapping for committed models: the table reports counts, not which TFC constant each animation came from.")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("tfc", type=pathlib.Path, help="TFC checkout root (e.g. the scratch clone)")
    ap.add_argument("--out", type=pathlib.Path, help="write the report here instead of stdout")
    args = ap.parse_args(argv)
    text = build(args.tfc.resolve())
    if args.out:
        (REPO / args.out if not args.out.is_absolute() else args.out).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
