/**
 * PAR-POT-02: every {@code ceramic/*} item {@code TFCItems} registers (unfired and fired pottery, the 16 glazed and unfired
 * glazed vessels, the unfired large vessels, every metal mold, the bell and fire ingot molds, the jug, pot, spindle head, fire
 * brick, channel and mold table) as a CraftEngine item in {@code configuration/pottery/ceramic.yml}.
 *
 * <p>The items carry TFC's model, textures and names (in every TFC locale, as {@code assets/tfp_pottery/lang}) and the stack size
 * of TFC's {@code item_size} weight (64 without a definition, 1 for {@code stacksTo(1)}). Item heat is read at runtime from TFC's
 * {@code item_heat} data (pit kiln firing is the heating recipes'). The behaviours (vessel and mold contents, jug fluids, the
 * large vessel block) belong to the later pottery items; here every item is a plain stack. TFC's {@code fluid_container}
 * models (molds, jug) are a plain item of their empty texture: the fluid overlay is drawn by the item that gives the mold or jug
 * its contents.
 */
public final class PotteryItems {
    static final String PACK = "craftengine/tfp/";
    static final String DIR = PACK + "configuration/pottery/";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    static final String LANG_NS = "tfp_pottery";
    static final String LANG_RP = PACK + "resourcepack/assets/" + LANG_NS + "/lang/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String MODELS = TfcCheckout.ASSETS + "models/";
    static final String PREFIX = "ceramic/";
    static final String ITEMS_SOURCE = "src/main/java/net/dries007/tfc/common/items/TFCItems.java";
    static final String ITEM_MODELS = TfcCheckout.ASSETS + "models/item/";
    static final Map<String, Integer> WEIGHT_STACK = Map.of(
        "very_light", 64, "light", 32, "medium", 16, "heavy", 4, "very_heavy", 1);
    static final int DEFAULT_STACK = 64;
    private static final Pattern STACKS_TO = Pattern.compile("\\.stacksTo\\((\\d+)\\)");
    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    /** One generated item: path ({@code ceramic/vessel}), {@code TFCItems} field, name key and stack size. */
    public record PotteryItem(String id, String field, String langKey, int stackSize) {
    }

    private PotteryItems() {
    }

    /** Whether the checkout has {@code TFCItems} and the item sizes (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(ITEMS_SOURCE) && tfc.isDirectory(sizeDir());
    }

    private static String sizeDir() {
        return TfcCheckout.GENERATED + "data/tfc/tfc/item_size/";
    }

    /** Writes the CE items, models, textures and names. Returns the items. */
    public static List<PotteryItem> run(TfcCheckout tfc, OutputTree out) {
        List<PotteryItem> items = items(tfc);
        Map<String, Object> entries = new TreeMap<>();
        Set<String> textures = new TreeSet<>();
        Set<String> models = new TreeSet<>();
        for (PotteryItem item : items) {
            writeItemModel(tfc, out, item.id(), models, textures);
            entries.put(Json.TO_NS + ":" + item.id(), entry(item));
        }
        for (String t : textures) {
            String png = TfcCheckout.ASSETS + "textures/" + t + ".png";
            if (!tfc.exists(png)) {
                throw new DatagenException("a pottery model uses tfc:" + t + ", which TFC has no texture for");
            }
            out.put(RP + "textures/" + t + ".png", tfc.read(png));
            if (tfc.exists(png + ".mcmeta")) {
                out.put(RP + "textures/" + t + ".png.mcmeta", tfc.read(png + ".mcmeta"));
            }
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", entries);
        out.put(DIR + "ceramic.yml", Yaml.write(HEADER, root));
        writeLang(tfc, out, items);
        return items;
    }

    /** The items of the checkout in registration order. */
    public static List<PotteryItem> items(TfcCheckout tfc) {
        List<PotteryItem> out = new ArrayList<>();
        List<JsonObject> sizes = sizes(tfc);
        Map<String, Set<String>> tagCache = new java.util.HashMap<>();
        for (TfcItemRegistry.Registration r : TfcItemRegistry.registrations(tfc)) {
            for (String id : r.ids()) {
                if (!id.startsWith(PREFIX)) {
                    continue;
                }
                Matcher st = STACKS_TO.matcher(r.factory());
                int stack = st.find() ? Integer.parseInt(st.group(1)) : sizeStack(tfc, sizes, tagCache, id);
                out.add(new PotteryItem(id, r.field(), "item." + Json.TO_NS + "." + id.replace('/', '.'), stack));
            }
        }
        if (out.isEmpty()) {
            throw new DatagenException("TFCItems registers no ceramic/ items (update PotteryItems)");
        }
        return out;
    }

    static Map<String, Object> entry(PotteryItem item) {
        Map<String, Object> entry = new LinkedHashMap<>();
        entry.put("template", "tfp:item/simple");
        entry.put("arguments", Map.of("item_lang_key", item.langKey()));
        entry.put("data", Map.of("max_stack_size", item.stackSize()));
        return entry;
    }

    // ---- item size -------------------------------------------------------------------------------------------------------

    private static List<JsonObject> sizes(TfcCheckout tfc) {
        TreeMap<String, String> sorted = new TreeMap<>();
        for (String f : tfc.list(sizeDir())) {
            if (f.endsWith(".json")) {
                sorted.put(f, f);
            }
        }
        List<JsonObject> out = new ArrayList<>();
        for (String f : sorted.values()) {
            out.add(Json.parse(tfc.readString(f), f).getAsJsonObject());
        }
        return out;
    }

    private static int sizeStack(TfcCheckout tfc, List<JsonObject> sizes, Map<String, Set<String>> tags, String id) {
        Set<String> weights = new TreeSet<>();
        for (JsonObject d : sizes) {
            if (matches(tfc, tags, d.get("ingredient"), Json.FROM_NS + ":" + id)) {
                weights.add(d.has("weight") ? d.get("weight").getAsString() : "very_light");
            }
        }
        if (weights.size() > 1) {
            throw new DatagenException("tfc:" + id + " has conflicting item_size weights " + weights);
        }
        if (weights.isEmpty()) {
            return DEFAULT_STACK;
        }
        Integer stack = WEIGHT_STACK.get(weights.iterator().next());
        if (stack == null) {
            throw new DatagenException("tfc:" + id + " has unknown item_size weight " + weights);
        }
        return stack;
    }

    private static boolean matches(TfcCheckout tfc, Map<String, Set<String>> tags, JsonElement ing, String item) {
        if (ing.isJsonArray()) {
            for (JsonElement e : ing.getAsJsonArray()) {
                if (matches(tfc, tags, e, item)) {
                    return true;
                }
            }
            return false;
        }
        JsonObject o = ing.getAsJsonObject();
        if (o.has("type")) {
            if (o.get("type").getAsString().equals("neoforge:difference")) {
                return matches(tfc, tags, o.get("base"), item) && !matches(tfc, tags, o.get("subtracted"), item);
            }
            throw new DatagenException("item_size ingredient type " + o.get("type") + " is not read by the pottery generator");
        }
        if (o.has("item")) {
            return o.get("item").getAsString().equals(item);
        }
        if (o.has("tag")) {
            return tag(tfc, tags, o.get("tag").getAsString()).contains(item);
        }
        throw new DatagenException("unknown item_size ingredient " + o);
    }

    private static Set<String> tag(TfcCheckout tfc, Map<String, Set<String>> cache, String id) {
        Set<String> cached = cache.get(id);
        if (cached != null) {
            return cached;
        }
        cache.put(id, Set.of());
        int colon = id.indexOf(':');
        String rel = "data/" + id.substring(0, colon) + "/tags/item/" + id.substring(colon + 1) + ".json";
        Set<String> members = new LinkedHashSet<>();
        List<String> removed = new ArrayList<>();
        for (String root : List.of(TfcCheckout.GENERATED, TfcCheckout.MAIN)) {
            if (!tfc.exists(root + rel)) {
                continue;
            }
            JsonObject json = Json.parse(tfc.readString(root + rel), root + rel).getAsJsonObject();
            for (JsonElement v : json.has("values") ? json.getAsJsonArray("values") : new JsonArray()) {
                String value = v.isJsonObject() ? v.getAsJsonObject().get("id").getAsString() : v.getAsString();
                if (value.startsWith("#")) {
                    members.addAll(tag(tfc, cache, value.substring(1)));
                } else {
                    members.add(value);
                }
            }
            for (JsonElement v : json.has("remove") ? json.getAsJsonArray("remove") : new JsonArray()) {
                removed.add(v.isJsonObject() ? v.getAsJsonObject().get("id").getAsString() : v.getAsString());
            }
        }
        for (String r : removed) {
            if (r.startsWith("#")) {
                members.removeAll(tag(tfc, cache, r.substring(1)));
            } else {
                members.remove(r);
            }
        }
        Set<String> out = Set.copyOf(members);
        cache.put(id, out);
        return out;
    }

    // ---- models ----------------------------------------------------------------------------------------------------------

    /**
     * Writes {@code models/item/<id>.json}. A plain generated model is copied; a {@code tfc:fluid_container} model (molds, jug) is
     * its base texture as a generated model; a model with {@code overrides} (the large vessels' sealed predicate) is its main
     * model; a block-parented model (large vessel, channel, mold table) is copied with its whole {@code tfc:} parent chain.
     */
    static void writeItemModel(TfcCheckout tfc, OutputTree out, String id, Set<String> models, Set<String> textures) {
        String src = ITEM_MODELS + id + ".json";
        JsonObject model = Json.parse(tfc.readString(src), src).getAsJsonObject();
        if (model.has("loader")) {
            if (!model.get("loader").getAsString().equals("tfc:fluid_container") || !model.has("textures")
                || !model.getAsJsonObject("textures").has("base")) {
                throw new DatagenException(src + ": unknown model loader " + model.get("loader"));
            }
            String base = model.getAsJsonObject("textures").get("base").getAsString();
            JsonObject plain = new JsonObject();
            plain.addProperty("parent", "minecraft:item/generated");
            JsonObject t = new JsonObject();
            t.addProperty("layer0", base);
            plain.add("textures", t);
            collectTextures(plain, textures);
            out.put(RP + "models/item/" + id + ".json", Json.write(Json.rename(plain)));
            return;
        }
        model.remove("overrides");
        model.remove("__comment__");
        collectTextures(model, textures);
        copyParents(tfc, out, model, models, textures);
        out.put(RP + "models/item/" + id + ".json", Json.write(Json.rename(model)));
    }

    private static void copyParents(TfcCheckout tfc, OutputTree out, JsonObject model, Set<String> done, Set<String> textures) {
        if (!model.has("parent")) {
            return;
        }
        String parent = model.get("parent").getAsString();
        if (!parent.startsWith(Json.FROM_NS + ":") || !done.add(parent)) {
            return;
        }
        String path = parent.substring(Json.FROM_NS.length() + 1);
        String src = TfcCheckout.ASSETS + "models/" + path + ".json";
        if (!tfc.exists(src)) {
            throw new DatagenException("a pottery model has parent " + parent + ", which TFC has no model for");
        }
        JsonObject p = Json.parse(tfc.readString(src), src).getAsJsonObject();
        p.remove("__comment__");
        collectTextures(p, textures);
        out.put(RP + "models/" + path + ".json", Json.write(Json.rename(p)));
        copyParents(tfc, out, p, done, textures);
    }

    private static void collectTextures(JsonObject model, Set<String> textures) {
        if (!model.has("textures")) {
            return;
        }
        for (Map.Entry<String, JsonElement> e : model.getAsJsonObject("textures").entrySet()) {
            String v = e.getValue().getAsString();
            if (v.startsWith(Json.FROM_NS + ":")) {
                textures.add(v.substring(Json.FROM_NS.length() + 1));
            }
        }
    }

    // ---- names -----------------------------------------------------------------------------------------------------------

    private static void writeLang(TfcCheckout tfc, OutputTree out, List<PotteryItem> items) {
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            TreeMap<String, String> keys = new TreeMap<>();
            for (PotteryItem item : items) {
                String tfcKey = "item." + Json.FROM_NS + "." + item.id().replace('/', '.');
                if (src.has(tfcKey)) {
                    keys.put(item.langKey(), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC item tfc:" + item.id() + " has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }

    /** Ids helper for tests: the set of item paths. */
    static Set<String> ids(List<PotteryItem> items) {
        Set<String> s = new HashSet<>();
        items.forEach(i -> s.add(i.id()));
        return s;
    }
}
