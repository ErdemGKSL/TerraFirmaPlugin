/**
 * PAR-POT-08: drying bricks. Registers the device kind {@value DryingDevice#ID} ({@link DryingDevice}), the click listener
 * ({@link DryingListener}), the {@link DryingClock} task and a chunk-load hook (a pile that dried while its chunk was unloaded
 * is settled when the chunk loads). The CraftEngine blocks {@code tfp:drying_bricks/<soil>} and {@code tfp:thatch} and the
 * {@code tfp:mud_brick/<soil>} items are generated by datagen ({@code drying/DryingBlocks}); thatch needs nothing here (its
 * slowdown is PAR-GATHER-10's {@code PlantSlowProvider}). Needs the device, catch-up and weather modules before it.
 *
 * <p>Config, read from the plugin's {@code config.yml} when present: {@value #TICKS_KEY} (TFC {@code mudBricksTicks}, default
 * 28800, {@code -1} never dries).
 *
 * <p>Debug: {@code /tfp debug drying fill <x> <y> <z> <soil> <count>} places a wet pile in the first world.
 */
public final class DryingModule implements FeatureModule {
    public static final String ID = "drying";
    static final String TICKS_KEY = "drying.mud-bricks-ticks";

    private volatile Scheduler.TaskHandle task;
    private volatile DryingBricks bricks;
    private volatile Scheduler scheduler;
    private volatile Logger log;

    @Override
    public String id() {
        return ID;
    }

    @Override
    public void enable(ModuleContext context) {
        DeviceService devices = context.services().require(DeviceService.class);
        CustomBlocks blocks = context.integrations().customBlocks();
        Scheduler sched = context.scheduler();
        int threshold = threshold(config(context.config().file()), context.logger());
        DryingClock clock = new DryingClock();
        DryingBricks b = new DryingBricks(new DryingBricks.Services(blocks, context.integrations().customItems(), devices,
            (block, state) -> context.integrations().blockVisuals().blockData(state).ifPresent(d -> block.setBlockData(d, false)),
            DryingModule::baseSturdy, rain(context.services()), () -> context.clock().get().playerTicks(),
            () -> threshold, clock, sched));
        b.kind(devices.register(DryingDevice.kind(b)));
        context.listen(new DryingListener(b, blocks, sched));
        Optional<CatchUpService> catchUp = context.services().get(CatchUpService.class);
        blocks.onChunkLoad(chunk -> catchUp.ifPresent(c -> chunkLoaded(chunk, c, blocks, b, sched)));
        blocks.onChunkUnload(chunk -> clock.untrackChunk(chunk.getWorld(), chunk.getX(), chunk.getZ()));
        task = sched.globalRepeating(DryingClock.PERIOD_TICKS, DryingClock.PERIOD_TICKS,
            () -> period(clock, b, sched, context.clock().get().playerTicks()));
        bricks = b;
        scheduler = sched;
        log = context.logger();
    }

    @Override
    public void disable() {
        Scheduler.TaskHandle t = task;
        task = null;
        bricks = null;
        if (t != null) {
            t.cancel();
        }
    }

    /** TFC {@code BottomSupportedDeviceBlock}: the block below has a sturdy top face. */
    static boolean baseSturdy(Block pile) {
        return pile.getRelative(org.bukkit.block.BlockFace.DOWN).getBlockData()
            .isFaceSturdy(org.bukkit.block.BlockFace.UP, org.bukkit.block.BlockSupport.FULL);
    }

    /** TFC {@code level.isRainingAt(pos.above())}: vanilla's gates on the region thread, then the climate decision. */
    static DryingBricks.Rain rain(ModuleServices services) {
        return pile -> {
            int x = pile.getX();
            int y = pile.getY() + 1;
            int z = pile.getZ();
            if (!PrecipitationService.rainReaches(pile.getWorld(), x, y, z)) {
                return false;
            }
            Optional<PrecipitationService> p = services.get(PrecipitationService.class);
            return p.isPresent() && p.get().isRainingAt(pile.getWorld(), new BlockPos(x, y, z), true);
        };
    }

    /** The due piles go to their region threads. Global thread. */
    static void period(DryingClock clock, DryingBricks bricks, Scheduler scheduler, long now) {
        for (Block block : clock.due(now)) {
            scheduler.region(block.getWorld(), block.getX() >> 4, block.getZ() >> 4, () -> bricks.evaluate(block));
        }
    }

    /** The piles of a loaded chunk are settled: one that dried meanwhile is written, the wet ones are listed on the clock. */
    static void chunkLoaded(Chunk chunk, CatchUpService catchUp, CustomBlocks blocks, DryingBricks bricks, Scheduler scheduler) {
        Optional<LazyBlockIndex> index = catchUp.index(chunk);
        if (index.isEmpty()) {
            return;
        }
        World world = chunk.getWorld();
        for (Map.Entry<BlockPos, String> e : index.get().entries().entrySet()) {
            if (!CatchUpModule.DEVICE_KIND.equals(e.getValue())) {
                continue;
            }
            BlockPos p = e.getKey();
            Block block = world.getBlockAt(p.x(), p.y(), p.z());
            if (blocks.stateAt(block).filter(DryingBricks::isDrying).isPresent()) {
                scheduler.region(world, chunk.getX(), chunk.getZ(), () -> bricks.evaluate(block));
            }
        }
    }

    static YamlConfiguration config(Path file) {
        if (file == null || !Files.isRegularFile(file)) {
            return new YamlConfiguration();
        }
        return YamlConfiguration.loadConfiguration(file.toFile());
    }

    /** TFC's config ({@code -1} or more); a lower value falls back to the default with a warning. */
    static int threshold(YamlConfiguration yaml, Logger logger) {
        long ticks = yaml.getLong(TICKS_KEY, DryingRules.DEFAULT_THRESHOLD_TICKS);
        if (ticks < DryingRules.DISABLED || ticks > Integer.MAX_VALUE) {
            logger.warning(TICKS_KEY + ": " + ticks + " is outside -1.." + Integer.MAX_VALUE + "; using "
                + DryingRules.DEFAULT_THRESHOLD_TICKS);
            return DryingRules.DEFAULT_THRESHOLD_TICKS;
        }
        return (int) ticks;
    }

    @Override
    public void debugCommands(DebugTree tree) {
        var fill = Commands.literal("fill")
            .then(Commands.argument("x", IntegerArgumentType.integer())
                .then(Commands.argument("y", IntegerArgumentType.integer())
                    .then(Commands.argument("z", IntegerArgumentType.integer())
                        .then(Commands.argument("soil", StringArgumentType.word())
                            .then(Commands.argument("count", IntegerArgumentType.integer(1, DryingRules.MAX_COUNT))
                                .executes(tree.run(ctx -> fill(IntegerArgumentType.getInteger(ctx, "x"),
                                    IntegerArgumentType.getInteger(ctx, "y"), IntegerArgumentType.getInteger(ctx, "z"),
                                    StringArgumentType.getString(ctx, "soil"), IntegerArgumentType.getInteger(ctx, "count")))))))));
        tree.add("drying", c -> c.then(fill));
    }

    private CompletableFuture<Reply> fill(int x, int y, int z, String soil, int count) {
        CompletableFuture<Reply> reply = new CompletableFuture<>();
        DryingBricks b = bricks;
        Scheduler sch = scheduler;
        if (b == null || sch == null) {
            reply.complete(Reply.error("debug.drying.disabled"));
            return reply;
        }
        World world = org.bukkit.Bukkit.getWorlds().getFirst();
        sch.region(world, x >> 4, z >> 4, () -> {
            try {
                boolean placed = b.place(world.getBlockAt(x, y, z), soil, count, false);
                reply.complete(placed ? Reply.ok("debug.drying.filled", count, soil) : Reply.error("debug.drying.refused", soil));
            } catch (RuntimeException e) {
                log.log(Level.WARNING, "drying debug failed", e);
                reply.complete(Reply.error("debug.drying.refused", e.getMessage()));
            }
        });
        return reply;
    }
}
