/**
 * PAR-PROC-19: the plain TFC material items as CraftEngine items ({@code configuration/material/<group>.yml}): ore items,
 * gems, powders and ore powders, fibres, cloths, the papyrus/paper chain, glue, soot, mortar, sandpaper, straw, stick
 * bunches and bundles, blubber, wool and yarn, daub, handstone, spindle, brass mechanisms, jars and lids, every spawn egg and
 * the gem saw.
 *
 * <p>The items are the {@code TFCItems} registrations of {@link #GROUPS} ({@link TfcItemRegistry}) and every
 * {@code registerSpawnEgg}. An id another generator already defines as a CE item (the ore pieces of {@code drops.yml}) is
 * left to it. Each item gets its TFC model and textures, its TFC name in every TFC locale (written into the pack as
 * {@code assets/tfp_material/lang/<locale>.json}: the {@code tfp} lang files belong to the asset pipeline), and the stack
 * size of TFC's {@code item_size} weight (64 without one). Items with durability ({@code handstone} 250, {@code spindle} and
 * {@code sandpaper} 40, {@code bone_needle} 64) carry {@code max_damage} and {@code minecraft:damage} 0
 * (as TFC's {@code durability(n)}, so vanilla treats them as damageable) and stack to one, as vanilla requires. Item heat is
 * not written here: the runtime reads TFC's {@code item_heat} data. The gem saw is a mining tool of TFC's bronze tier
 * (TFC's {@code GemSawItem}: {@code tfc:mineable_with_glass_saw}); its glassworking use is PAR-PROC-16's.
 *
 * <p>A missing model, texture, name or source line is an error, so a TFC change shows up here.
 */
public final class MaterialItems {
    static final String PACK = "craftengine/tfp/";
    static final String DIR = PACK + "configuration/material/";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    /** The pack namespace of the material items' names (any namespace's lang file is merged by the client). */
    static final String LANG_NS = "tfp_material";
    static final String LANG_RP = PACK + "resourcepack/assets/" + LANG_NS + "/lang/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String TIERS_SOURCE = "src/main/java/net/dries007/tfc/common/TFCTiers.java";
    static final String GEM_SAW_TAG = "tfp:mineable/glass_saw";
    static final String SPAWN_EGG_GROUP = "spawn_egg";

    /** The {@code TFCItems} fields this generator owns, with the config file (group) each goes to. */
    static final Map<String, String> GROUPS = groups();

    /** TFC {@code Weight} stack sizes; an item without an {@code item_size} definition stacks to 64 (TFC's default size). */
    static final Map<String, Integer> WEIGHT_STACK = Map.of(
        "very_light", 64, "light", 32, "medium", 16, "heavy", 4, "very_heavy", 1);
    static final int DEFAULT_STACK = 64;

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";
    private static final Pattern DURABILITY = Pattern.compile("\\.durability\\((\\d+)\\)");

    private static Map<String, String> groups() {
        Map<String, String> g = new LinkedHashMap<>();
        for (String f : List.of("ORES", "GRADED_ORES")) {
            g.put(f, "ore");
        }
        g.put("GEMS", "gem");
        for (String f : List.of("POWDERS", "ORE_POWDERS")) {
            g.put(f, "powder");
        }
        g.put("GEM_SAW", "tool");
        for (String f : List.of("EMPTY_JAR", "EMPTY_JAR_WITH_LID", "JAR_LID", "ALABASTER_BRICK", "BONE_NEEDLE",
            "BLANK_DISC", "BLUBBER", "BRASS_MECHANISMS", "BURLAP_CLOTH", "COMPOST", "CACTUS_WOOD", "DAUB", "DIRTY_JUTE_NET",
            "DRIED_CACTUS_WOOD", "FIRE_CLAY", "GOAT_HORN", "GLUE", "ALFALFA", "CANOLA", "JUTE", "JUTE_FIBER", "JUTE_NET",
            "KAOLIN_CLAY", "HANDSTONE", "MORTAR", "OLIVE_PASTE", "CANOLA_PASTE", "PAPYRUS", "PAPYRUS_STRIP", "PURE_NITROGEN",
            "PURE_PHOSPHORUS", "PURE_POTASSIUM", "SILK_CLOTH", "SANDPAPER", "SOAKED_PAPYRUS_STRIP", "SOOT", "SPINDLE",
            "STICK_BUNCH", "STICK_BUNDLE", "STRAW", "TREATED_HIDE", "UNREFINED_PAPER", "WOOL", "WOOL_CLOTH", "WOOL_YARN",
            "WROUGHT_IRON_GRILL")) {
            g.put(f, "misc");
        }
        return java.util.Collections.unmodifiableMap(g);
    }

    /**
     * One generated item.
     *
     * @param id         the path ({@code gem/ruby}), TFC's and ours
     * @param field      the {@code TFCItems} field that registers it
     * @param group      the config file it is written to ({@code material/<group>.yml})
     * @param langKey    our name key ({@code item.tfp.gem.ruby})
     * @param stackSize  the max stack size
     * @param durability the max damage, 0 for none
     * @param sizeDef    the {@code item_size} definition id, or {@code ""} for none
     */
    public record MaterialItem(String id, String field, String group, String langKey, int stackSize, int durability,
        String sizeDef) {
    }

    private MaterialItems() {
    }

    /** Whether the checkout has {@code TFCItems} (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TfcItemRegistry.ITEMS_SOURCE) && tfc.exists(TIERS_SOURCE);
    }

    /** Writes the CE items, models, textures and names. Returns the items. */
    public static List<MaterialItem> run(TfcCheckout tfc, OutputTree out) {
        List<MaterialItem> items = items(tfc, CeItemIds.of(out, DIR).keySet());
        Map<String, Map<String, Object>> files = new TreeMap<>();
        for (MaterialItem item : items) {
            copyModel(tfc, out, item.id());
            files.computeIfAbsent(item.group(), k -> new TreeMap<>()).put(Json.TO_NS + ":" + item.id(), entry(tfc, item));
        }
        files.forEach((group, entries) -> {
            Map<String, Object> root = new LinkedHashMap<>();
            root.put("items", entries);
            out.put(DIR + group + ".yml", Yaml.write(HEADER, root));
        });
        writeLang(tfc, out, items);
        return items;
    }

    /** The items of the checkout in registration order, without the ids in {@code existing} (CE ids defined elsewhere). */
    public static List<MaterialItem> items(TfcCheckout tfc, Set<String> existing) {
        List<TfcItemRegistry.Registration> regs = TfcItemRegistry.registrations(tfc);
        Set<String> fields = new java.util.HashSet<>();
        regs.forEach(r -> fields.add(r.field()));
        for (String f : GROUPS.keySet()) {
            if (!fields.contains(f)) {
                throw new DatagenException(TfcItemRegistry.ITEMS_SOURCE + " no longer has " + f + " (update MaterialItems)");
            }
        }
        TfcItemData data = new TfcItemData(tfc);
        List<TfcItemData.Definition> sizes = data.definitions("item_size");
        List<MaterialItem> out = new ArrayList<>();
        for (TfcItemRegistry.Registration r : regs) {
            String group = r.factory().equals("spawn_egg") ? SPAWN_EGG_GROUP : GROUPS.get(r.field());
            if (group == null) {
                continue;
            }
            // The non-plain TFC items handled here on purpose: spawn eggs (ledger divergence "spawn eggs spawn nothing"), the
            // gem saw (divergence "gem saw") and wool cloth (TFC's glassworking-tagged cloth; divergence "wool cloth and lumber").
            if (!r.plain() && !group.equals(SPAWN_EGG_GROUP) && !r.field().equals("GEM_SAW") && !r.field().equals("WOOL_CLOTH")) {
                throw new DatagenException("TFCItems." + r.field() + " is no longer a plain item: " + r.factory());
            }
            Matcher dm = DURABILITY.matcher(r.factory());
            int durability = dm.find() ? Integer.parseInt(dm.group(1)) : 0;
            for (String id : r.ids()) {
                if (existing.contains(Json.TO_NS + ":" + id)) {
                    continue;
                }
                var size = data.first(sizes, Json.FROM_NS + ":" + id);
                int stack = r.field().equals("GEM_SAW") || durability > 0 ? 1 : size.map(MaterialItems::stackSize).orElse(DEFAULT_STACK);
                out.add(new MaterialItem(id, r.field(), group, "item." + Json.TO_NS + "." + id.replace('/', '.'), stack, durability,
                    size.map(TfcItemData.Definition::id).orElse("")));
            }
        }
        return out;
    }

    /** The CE entry of one item. */
    static Map<String, Object> entry(TfcCheckout tfc, MaterialItem item) {
        Map<String, Object> entry = new LinkedHashMap<>();
        Map<String, Object> args = new LinkedHashMap<>();
        args.put("item_lang_key", item.langKey());
        if (item.field().equals("GEM_SAW")) {
            Tier bronze = bronze(tfc);
            entry.put("template", "tfp:item/tool");
            args.put("material", "iron_pickaxe"); // bronze is INCORRECT_FOR_IRON_TOOL: the iron hand pose, no vanilla right-click action
            args.put("durability", bronze.uses());
            args.put("speed", bronze.speed());
            args.put("break_power", bronze.level());
            args.put("mineable_tag", GEM_SAW_TAG);
            args.put("tool_tag", "tfp:tools/gem_saw");
            entry.put("arguments", args);
            // TFC's productAttributes(tier, damageFactor, attackSpeed). These attribute_modifiers deep-merge into the template's
            // data and replace the iron pickaxe's vanilla modifiers: damage 1 + factor x tier damage, attack speed 4 + speed.
            BigDecimal[] attack = gemSawAttributes(tfc);
            Map<String, Object> damage = new LinkedHashMap<>();
            damage.put("type", "attack_damage");
            damage.put("amount", attack[0].multiply(bronze.damage()).stripTrailingZeros());
            damage.put("operation", "add_value");
            damage.put("slot", "mainhand");
            Map<String, Object> speed = new LinkedHashMap<>();
            speed.put("type", "attack_speed");
            speed.put("amount", attack[1]);
            speed.put("operation", "add_value");
            speed.put("slot", "mainhand");
            entry.put("data", Map.of("attribute_modifiers", List.of(damage, speed)));
            return entry;
        }
        entry.put("template", "tfp:item/simple");
        entry.put("arguments", args);
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("max_stack_size", item.stackSize());
        if (item.durability() > 0) {
            // TFC's Properties.durability(n) sets MAX_DAMAGE n and DAMAGE 0. Vanilla's isDamageableItem() needs both, and the
            // paper base has no damage component: without it set_damage, hurtAndBreak and ItemStack#damage do nothing.
            data.put("max_damage", item.durability());
            data.put("components", Map.of("minecraft:damage", 0));
        }
        entry.put("data", data);
        return entry;
    }

    /** One TFC tier ({@code TFCTiers.create(name, tag, level, uses, speed, damage, enchantment)}). */
    record Tier(int level, int uses, BigDecimal speed, BigDecimal damage) {
    }

    static final String GEM_SAW_SOURCE = "src/main/java/net/dries007/tfc/common/items/GemSawItem.java";

    /** The gem saw's {@code ToolItem.productAttributes(tier, attackDamageFactor, attackSpeed)} arguments. */
    static BigDecimal[] gemSawAttributes(TfcCheckout tfc) {
        Matcher m = Pattern.compile("productAttributes\\(tier, (-?[\\d.]+)f, (-?[\\d.]+)f\\)").matcher(tfc.readString(GEM_SAW_SOURCE));
        if (!m.find()) {
            throw new DatagenException(GEM_SAW_SOURCE + ": productAttributes(tier, damage, speed) not found (the format changed?)");
        }
        return new BigDecimal[] {new BigDecimal(m.group(1)), new BigDecimal(m.group(2))};
    }

    /** TFC's bronze tier, the gem saw's ({@code new GemSawItem(TFCTiers.BRONZE, ...)}). */
    static Tier bronze(TfcCheckout tfc) {
        String items = tfc.readString(TfcItemRegistry.ITEMS_SOURCE);
        if (!items.contains("new GemSawItem(TFCTiers.BRONZE, new Properties())")) {
            throw new DatagenException(TfcItemRegistry.ITEMS_SOURCE + ": the gem saw is no longer TFCTiers.BRONZE");
        }
        Matcher m = Pattern.compile(
                "BRONZE = create\\(\"bronze\", BlockTags\\.INCORRECT_FOR_IRON_TOOL, (\\d+), (\\d+), ([\\d.]+)f, ([\\d.]+)f,")
            .matcher(tfc.readString(TIERS_SOURCE));
        if (!m.find()) {
            throw new DatagenException(TIERS_SOURCE + ": BRONZE not found (the format changed?)");
        }
        return new Tier(Integer.parseInt(m.group(1)), Integer.parseInt(m.group(2)), new BigDecimal(m.group(3)),
            new BigDecimal(m.group(4)));
    }

    private static int stackSize(TfcItemData.Definition size) {
        String weight = size.json().has("weight") ? size.json().get("weight").getAsString() : "very_light";
        Integer stack = WEIGHT_STACK.get(weight);
        if (stack == null) {
            throw new DatagenException("item size " + size.id() + " has unknown weight " + weight);
        }
        return stack;
    }

    /**
     * The TFC names of the items in every TFC locale that has them (English must have all), except the names the asset
     * pipeline's {@code tfp} lang file already carries.
     */
    private static void writeLang(TfcCheckout tfc, OutputTree out, List<MaterialItem> items) {
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            byte[] pipeline = out.get(RP + "lang/" + locale + ".json");
            JsonObject named = pipeline == null ? new JsonObject()
                : Json.parse(new String(pipeline, java.nio.charset.StandardCharsets.UTF_8), RP + "lang").getAsJsonObject();
            TreeMap<String, String> keys = new TreeMap<>();
            for (MaterialItem item : items) {
                String tfcKey = "item." + Json.FROM_NS + "." + item.id().replace('/', '.');
                if (named.has(item.langKey())) {
                    continue; // the asset pipeline's lang names it already (its ore.* family)
                }
                if (src.has(tfcKey)) {
                    keys.put(item.langKey(), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC item tfc:" + item.id() + " has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }

    /**
     * Copies {@code models/item/<id>.json} and its textures into the pack. TFC's handstone model is its healthy model plus a
     * {@code tfc:damaged} predicate override (a NeoForge item property vanilla clients lack): the item takes the healthy model.
     */
    private static void copyModel(TfcCheckout tfc, OutputTree out, String id) {
        String src = TfcItemRegistry.MODELS + id + ".json";
        JsonObject model = Json.parse(tfc.readString(src), src).getAsJsonObject();
        if (model.has("overrides")) {
            String parent = model.has("parent") ? model.get("parent").getAsString() : "";
            if (!parent.startsWith(Json.FROM_NS + ":item/") || model.size() > 3) {
                throw new DatagenException(src + ": overrides on a model that is not parent + overrides");
            }
            src = TfcItemRegistry.MODELS + parent.substring((Json.FROM_NS + ":item/").length()) + ".json";
            model = Json.parse(tfc.readString(src), src).getAsJsonObject();
        }
        String parent = model.has("parent") ? model.get("parent").getAsString() : "";
        boolean generated = parent.equals("item/generated") || parent.equals("minecraft:item/generated");
        boolean standalone = parent.isEmpty() && model.has("elements"); // a Blockbench model (the handstone)
        if (model.has("loader") || model.has("overrides") || !(generated || standalone)) {
            throw new DatagenException(src + ": the material generator copies generated or standalone item models only, got parent "
                + parent);
        }
        for (Map.Entry<String, JsonElement> t : model.getAsJsonObject("textures").entrySet()) {
            String ref = t.getValue().getAsString();
            if (!ref.startsWith(Json.FROM_NS + ":")) {
                continue; // a vanilla texture: the client has it
            }
            String path = ref.substring(Json.FROM_NS.length() + 1);
            String png = TfcCheckout.ASSETS + "textures/" + path + ".png";
            if (!tfc.exists(png)) {
                throw new DatagenException(src + " uses missing texture " + ref);
            }
            out.put(RP + "textures/" + path + ".png", tfc.read(png));
            if (tfc.exists(png + ".mcmeta")) {
                out.put(RP + "textures/" + path + ".png.mcmeta", tfc.read(png + ".mcmeta"));
            }
        }
        out.put(RP + "models/item/" + id + ".json", Json.write(Json.rename(model)));
    }
}
