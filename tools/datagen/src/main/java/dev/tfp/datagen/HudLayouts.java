/**
 * The BetterHud layouts of the HUD catalogue ({@code docs/hud/catalogue.md}, section 1), written under
 * {@code betterhud/tfp/} by the {@code betterhud} skill's layout rules (see {@link BetterHudPack} for the font and the
 * other files of the pack).
 *
 * <p>The catalogue is the source of the element ids, kinds and placeholder names. It is parsed strictly: a row with the
 * wrong number of cells, an unknown kind, a duplicate id, a placeholder name without the {@code tfp_} prefix, a counts
 * section that disagrees with the table, or a missing file is an error, never a skipped row. Only the rows whose data
 * is specified get output. A row whose data says {@code unspecified in plan} is listed in {@link Summary#leftOut()} and
 * gets no output, because it names no placeholder to read; the same holds for the {@code indicator} kind, which the
 * task does not name.
 *
 * <p>Output: {@code images/tfp-bars.yml} (the bar art), {@code layouts/tfp-{bars,popups}.yml} and
 * {@code layouts/tfp-readouts.yml} (one layout per element; the readouts file is written only when a readout is not
 * already in {@link BetterHudPack}, see {@link #READOUTS_IN_PACK}), {@code popups/tfp-popups.yml} (the held-temperature popup), and {@code glue/placeholders.yml} and
 * {@code glue/hidden-vanilla.yml}, two lists that the Java placeholder glue and the installer read. BetterHud does not
 * read {@code glue/}, so the installer must not copy it into the pack folder (dependency-bootstrap).
 *
 * <p>Placements (GUI pixel offsets) are not in the catalogue. They are the skeleton coordinates of the betterhud skill
 * (section 11, placeholders to tune in game), keyed by catalogue id. An element without a placement is an error.
 */
final class HudLayouts {
    static final String CATALOGUE = "docs/hud/catalogue.md";
    static final String PREFIX = "tfp_";
    /** The font of {@link BetterHudPack}, the only text the layouts use. */
    static final String FONT = "tfp_font";
    static final String HEADER = "Generated by tools/datagen from docs/hud/catalogue.md. Do not edit: fix the generator"
        + " or the catalogue, then regenerate.";
    /** The vanilla sprite folder that the hidden-vanilla rows name without a folder (e.g. {@code air.png}). */
    static final String VANILLA_HUD = "gui/sprites/hud/";
    static final String IMAGES = BetterHudPack.DIR + "images/tfp-bars.yml";
    /** The approved bar sprites (docs/art/hud, copied here as resources), by file name. */
    private static final String BAR_ART = "/dev/tfp/datagen/hud/";
    /** The vanilla HUD sprite folder in CraftEngine's pack (the content is installed under plugins/CraftEngine/resources/tfp/). */
    private static final String CE_PACK_SPRITES = "craftengine/tfp/resourcepack/assets/minecraft/textures/gui/sprites/hud/";
    static final String BAR_LAYOUTS = BetterHudPack.DIR + "layouts/tfp-bars.yml";
    static final String READOUT_LAYOUTS = BetterHudPack.DIR + "layouts/tfp-readouts.yml";
    static final String POPUP_LAYOUTS = BetterHudPack.DIR + "layouts/tfp-popups.yml";
    static final String POPUPS = BetterHudPack.DIR + "popups/tfp-popups.yml";
    /** The HUD that shows the bars, anchored bottom-centre; the bars' own placements are relative to that anchor. */
    static final String BARS_HUDS = BetterHudPack.DIR + "huds/tfp-bars-hud.yml";
    static final String BARS_HUD = "tfp_bars_hud";
    static final String PLACEHOLDERS = BetterHudPack.DIR + "glue/placeholders.yml";
    static final String HIDDEN = BetterHudPack.DIR + "glue/hidden-vanilla.yml";

    static final List<String> KINDS = List.of("placeholder", "bar", "readout", "popup", "indicator", "hidden-vanilla");
    static final String UNSPECIFIED = "unspecified in plan";
    static final String ELEMENTS_HEADING = "## 1. Elements";
    static final String COUNTS_HEADING = "## 3. Counts";

    /** The popup condition: the held item temperature shows while it is above 0 (catalogue row shows this). */
    static final String POPUP_SHOWN_WHILE = "shown while above 0";
    static final String POPUP_OPERATION = ">";
    static final int POPUP_THRESHOLD = 0;

    /** The bars' HUD anchor: bottom-centre of the screen (the GUI anchors are 0/50/100 only). */
    static final int BARS_GUI_X = 50;
    static final int BARS_GUI_Y = 100;
    /** Anchor of the popup on the GUI (the betterhud skill, section 11: anchor at 0/50/100 only). */
    static final int POPUP_GUI_X = 50;
    static final int POPUP_GUI_Y = 100;
    /** Bar fill steps (the skill keeps split at 25 to 50). */
    static final int SPLIT = 50;

    /** A placement in GUI pixels from the layout anchor. */
    record Place(int x, int y) {
    }

    /** The background, fill and optional text of a bar. The text is set only for a value with a max. */
    record BarPlace(Place bg, Place fill, Place text) {
    }

    /**
     * Health on the left, thirst and hunger on the right, centred on the screen. The group sat about 125 screen px left
     * of centre, so the earlier offsets (health -91, food +10) move right by 43 units (about 125 px at 2.9 px per unit).
     */
    static final Map<String, BarPlace> BARS = Map.of(
        "m3-surv-06-health-bar", new BarPlace(new Place(-48, -40), new Place(-47, -39), new Place(-7, -40)),
        "m3-surv-06-thirst-bar", new BarPlace(new Place(53, -33), new Place(53, -33), null),
        "m3-surv-06-hunger-bar", new BarPlace(new Place(53, -39), new Place(53, -39), null),
        "m3-surv-06-air-bar", new BarPlace(new Place(53, -27), new Place(53, -27), null));

    static final Map<String, Place> READOUTS = Map.of(
        "m2-cal-02-date-readout", new Place(2, 2),
        "m2-clim-03-ambient-temp-readout", new Place(2, 12));

    /**
     * Catalogue readouts that duplicate a layout {@link BetterHudPack} already writes (same font, pattern, placement and
     * tick): catalogue id to that layout's id. They are not emitted, so the readout file has one copy of each layout.
     */
    static final Map<String, String> READOUTS_IN_PACK = Map.of(
        "m2-cal-02-date-readout", "tfp_date",
        "m2-clim-03-ambient-temp-readout", "tfp_ambient_temp");

    static final Map<String, Place> POPUPS_AT = Map.of(
        "m3-surv-06-held-temp-popup", new Place(0, -60));

    private static final Pattern COUNT_ROW = Pattern.compile(
        "^\\| (" + String.join("|", KINDS) + ") \\| (\\d+) \\| (\\d+) \\|$");
    private static final Pattern ID_CELL = Pattern.compile("^`([a-z0-9-]+)`$");
    private static final Pattern TOKEN = Pattern.compile("`([^`]+)`");
    private static final Pattern TICK = Pattern.compile("tick: (\\d+)");
    private static final Pattern FILE_COUNT = Pattern.compile("\\((\\d+) files?\\)");
    private static final Pattern SEPARATOR = Pattern.compile("^\\|[-| ]+\\|$");

    /** One row of section 1. {@code tokens} are the backticked names in the data cell, in order. */
    record Element(String id, String shows, String source, String kind, String data, String milestone, String notes,
                   List<String> tokens) {
        boolean unspecified() {
            return data.startsWith(UNSPECIFIED);
        }
    }

    /** The parsed catalogue: its rows, and the counts section per kind (total and unspecified). */
    record Catalogue(List<Element> elements, Map<String, Integer> total, Map<String, Integer> unspecified) {
    }

    /** What was emitted per kind, what the catalogue counts, and the rows left out with the reason. */
    record Summary(Map<String, Integer> catalogue, Map<String, Integer> emitted, List<String> leftOut) {
    }

    private HudLayouts() {
    }

    /** The catalogue in this checkout: {@code tfp.repoRoot} (set by the Gradle test task), else the nearest ancestor. */
    static Path catalogue() {
        String root = System.getProperty("tfp.repoRoot");
        Path start = root != null ? Path.of(root).toAbsolutePath().normalize() : Path.of("").toAbsolutePath();
        for (Path p = start; p != null; p = p.getParent()) {
            Path c = p.resolve(CATALOGUE);
            if (Files.isRegularFile(c)) {
                return c;
            }
        }
        throw new DatagenException("no " + CATALOGUE + " found at or above " + start);
    }

    /** Writes the HUD layouts into {@code out}. Fails on a missing, malformed or inconsistent catalogue. */
    static Summary run(OutputTree out, Path file) {
        Catalogue cat = parse(file);
        List<String> leftOut = new ArrayList<>();
        Map<String, Integer> emitted = new LinkedHashMap<>();
        for (String k : KINDS) {
            emitted.put(k, 0);
        }

        List<Map<String, Object>> placeholders = new ArrayList<>();
        Set<String> names = new HashSet<>();
        for (Element e : of(cat, "placeholder")) {
            if (e.unspecified() || e.tokens().size() != 1) {
                throw new DatagenException(row(e) + ": a placeholder row names exactly one placeholder");
            }
            String name = e.tokens().get(0);
            requirePrefix(e, name);
            if (!names.add(name)) {
                throw new DatagenException(row(e) + ": placeholder " + name + " is named twice");
            }
            placeholders.add(m("name", name, "catalogue-id", e.id(), "source", e.source(), "milestone", e.milestone()));
            emitted.merge("placeholder", 1, Integer::sum);
        }

        Map<String, Object> barImages = new LinkedHashMap<>();
        Map<String, Object> barLayouts = new LinkedHashMap<>();
        Map<String, Object> barHudLayouts = new LinkedHashMap<>();
        for (Element e : of(cat, "bar")) {
            if (e.unspecified()) {
                leftOut.add(leftOut(e, UNSPECIFIED));
                continue;
            }
            BarPlace p = BARS.get(e.id());
            if (p == null) {
                throw new DatagenException(row(e) + ": no bar placement in HudLayouts.BARS");
            }
            for (String t : e.tokens()) {
                requireKnown(e, t, names);
            }
            String name = name(e.id());
            String bg = name + "_bg";
            String fill = name + "_fill";
            Map<String, Object> listener;
            if (e.tokens().size() == 2 && !e.data().contains("listener")) {
                listener = m("class", "placeholder", "value", e.tokens().get(0), "max", e.tokens().get(1));
                if (p.text() == null) {
                    throw new DatagenException(row(e) + ": a value and a max need a text placement in HudLayouts.BARS");
                }
            } else if (e.tokens().size() == 1 && e.data().contains("listener")) {
                listener = m("class", e.tokens().get(0));
            } else {
                throw new DatagenException(row(e) + ": a bar names a value and a max, or one listener");
            }
            barImages.put(bg, m("type", "single", "file", imageFile(e.id(), "bg")));
            barImages.put(fill, m("type", "listener", "file", imageFile(e.id(), "fill"), "split", SPLIT,
                "split-type", "left", "setting", m("listener", listener)));
            putBarArt(out, imageFile(e.id(), "bg"));
            putBarArt(out, imageFile(e.id(), "fill"));
            Map<String, Object> layout = m("images", m(
                "1", m("name", bg, "x", p.bg().x(), "y", p.bg().y()),
                "2", m("name", fill, "x", p.fill().x(), "y", p.fill().y())));
            if (e.tokens().size() == 2) {
                layout.put("texts", m("1", m("name", FONT,
                    "pattern", "[" + e.tokens().get(0) + "]//[" + e.tokens().get(1) + "]",
                    "placeholder-string-format", m("number", "#"),
                    "align", "center", "x", p.text().x(), "y", p.text().y(), "scale", scale())));
            }
            barLayouts.put(name, layout);
            barHudLayouts.put(String.valueOf(barHudLayouts.size() + 1),
                m("name", name, "gui", m("x", BARS_GUI_X, "y", BARS_GUI_Y)));
            emitted.merge("bar", 1, Integer::sum);
        }

        Map<String, Object> readoutLayouts = new LinkedHashMap<>();
        for (Element e : of(cat, "readout")) {
            if (e.unspecified()) {
                leftOut.add(leftOut(e, UNSPECIFIED));
                continue;
            }
            Place at = READOUTS.get(e.id());
            if (at == null) {
                throw new DatagenException(row(e) + ": no readout placement in HudLayouts.READOUTS");
            }
            for (String t : e.tokens()) {
                requireKnown(e, t, names);
            }
            Matcher tick = TICK.matcher(e.data());
            if (!tick.find()) {
                throw new DatagenException(row(e) + ": a readout names its tick (text `tick: N`)");
            }
            String pattern = switch (e.tokens().size()) {
                case 1 -> "[" + e.tokens().get(0) + "]";
                case 2 -> "[" + e.tokens().get(0) + "]  ([" + e.tokens().get(1) + "])";
                default -> throw new DatagenException(row(e) + ": a readout names one or two placeholders");
            };
            String inPack = READOUTS_IN_PACK.get(e.id());
            if (inPack != null) {
                if (!BetterHudPack.LAYOUT_IDS.contains(inPack)) {
                    throw new DatagenException(row(e) + ": " + inPack + " is not a layout of BetterHudPack");
                }
                continue;
            }
            readoutLayouts.put(name(e.id()), m("texts", m("1", m("name", FONT, "pattern", pattern, "align", "left",
                "x", at.x(), "y", at.y(), "scale", scale(), "tick", Integer.parseInt(tick.group(1))))));
            emitted.merge("readout", 1, Integer::sum);
        }

        Map<String, Object> popupLayouts = new LinkedHashMap<>();
        Map<String, Object> popups = new LinkedHashMap<>();
        for (Element e : of(cat, "popup")) {
            if (e.unspecified()) {
                leftOut.add(leftOut(e, UNSPECIFIED));
                continue;
            }
            Place at = POPUPS_AT.get(e.id());
            if (at == null) {
                throw new DatagenException(row(e) + ": no popup placement in HudLayouts.POPUPS_AT");
            }
            if (e.tokens().size() != 1 || !e.shows().contains(POPUP_SHOWN_WHILE)) {
                throw new DatagenException(row(e) + ": a popup names one placeholder and is \"" + POPUP_SHOWN_WHILE + "\"");
            }
            String value = e.tokens().get(0);
            requireKnown(e, value, names);
            String name = name(e.id());
            popupLayouts.put(name, m("texts", m("1", m("name", FONT, "pattern", "[" + value + "]", "align", "center",
                "x", 0, "y", 0, "scale", scale()))));
            popups.put(name, m("default", true,
                "conditions", m("1", m("first", value, "second", POPUP_THRESHOLD, "operation", POPUP_OPERATION)),
                "layouts", m("1", m("name", name, "gui", m("x", POPUP_GUI_X, "y", POPUP_GUI_Y),
                    "pixel", m("x", at.x(), "y", at.y())))));
            emitted.merge("popup", 1, Integer::sum);
        }

        List<Map<String, Object>> hidden = new ArrayList<>();
        for (Element e : of(cat, "hidden-vanilla")) {
            if (e.unspecified() || e.tokens().isEmpty()) {
                throw new DatagenException(row(e) + ": a hidden-vanilla row names its sprites");
            }
            List<String> sprites = new ArrayList<>();
            for (String t : e.tokens()) {
                sprites.add(t.contains("/") ? t : VANILLA_HUD + t);
            }
            Matcher count = FILE_COUNT.matcher(e.data());
            int files = count.find() ? Integer.parseInt(count.group(1)) : e.tokens().size();
            hidden.add(m("id", name(e.id()), "catalogue-id", e.id(), "source", e.source(), "sprites", sprites,
                "files", files));
            emitted.merge("hidden-vanilla", 1, Integer::sum);
        }

        for (Element e : cat.elements()) {
            if (e.kind().equals("indicator")) {
                leftOut.add(leftOut(e, "kind indicator is not one of the kinds this generator emits"));
            }
        }

        out.put(IMAGES, Yaml.write(HEADER, barImages));
        out.put(BAR_LAYOUTS, Yaml.write(HEADER, barLayouts));
        out.put(BARS_HUDS, Yaml.write(HEADER, m(BARS_HUD, m("layouts", barHudLayouts))));
        putHiddenVanillaSprites(out);
        if (!readoutLayouts.isEmpty()) {
            out.put(READOUT_LAYOUTS, Yaml.write(HEADER, readoutLayouts));
        }
        out.put(POPUP_LAYOUTS, Yaml.write(HEADER, popupLayouts));
        out.put(POPUPS, Yaml.write(HEADER, popups));
        out.put(PLACEHOLDERS, Yaml.write(HEADER, m("placeholders", placeholders)));
        out.put(HIDDEN, Yaml.write(HEADER, m("hidden-vanilla", hidden)));
        return new Summary(cat.total(), emitted, leftOut);
    }

    /** Parses the catalogue. Fails on any row or count that does not match the format. */
    static Catalogue parse(Path file) {
        if (!Files.isRegularFile(file)) {
            throw new DatagenException("HUD catalogue not found: " + file);
        }
        List<String> lines;
        try {
            lines = Files.readAllLines(file, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        List<Element> elements = new ArrayList<>();
        Map<String, Integer> total = new LinkedHashMap<>();
        Map<String, Integer> unspecified = new LinkedHashMap<>();
        boolean sawElements = false;
        boolean sawCounts = false;
        String section = "";
        Set<String> ids = new HashSet<>();
        for (int i = 0; i < lines.size(); i++) {
            String line = lines.get(i);
            if (line.startsWith("## ")) {
                section = line;
                sawElements |= line.equals(ELEMENTS_HEADING);
                sawCounts |= line.equals(COUNTS_HEADING);
                continue;
            }
            if (section.equals(ELEMENTS_HEADING)) {
                if (!line.startsWith("|") || line.startsWith("| id |") || SEPARATOR.matcher(line).matches()) {
                    continue;
                }
                Element e = element(line, i + 1);
                if (!ids.add(e.id())) {
                    throw new DatagenException(CATALOGUE + " line " + (i + 1) + ": id " + e.id() + " is listed twice");
                }
                elements.add(e);
            } else if (section.equals(COUNTS_HEADING)) {
                Matcher m = COUNT_ROW.matcher(line);
                if (m.matches()) {
                    if (total.containsKey(m.group(1))) {
                        throw new DatagenException(CATALOGUE + " line " + (i + 1) + ": kind " + m.group(1) + " is counted twice");
                    }
                    total.put(m.group(1), Integer.parseInt(m.group(2)));
                    unspecified.put(m.group(1), Integer.parseInt(m.group(3)));
                }
            }
        }
        if (!sawElements) {
            throw new DatagenException(CATALOGUE + ": no \"" + ELEMENTS_HEADING + "\" section");
        }
        if (!sawCounts) {
            throw new DatagenException(CATALOGUE + ": no \"" + COUNTS_HEADING + "\" counts section");
        }
        if (!total.keySet().equals(new HashSet<>(KINDS))) {
            throw new DatagenException(CATALOGUE + ": the counts section lists " + total.keySet() + ", expected " + KINDS);
        }
        for (String k : KINDS) {
            long rows = elements.stream().filter(e -> e.kind().equals(k)).count();
            long open = elements.stream().filter(e -> e.kind().equals(k) && e.unspecified()).count();
            if (rows != total.get(k)) {
                throw new DatagenException(CATALOGUE + ": kind " + k + " has " + rows + " rows, the counts section says "
                    + total.get(k));
            }
            if (open != unspecified.get(k)) {
                throw new DatagenException(CATALOGUE + ": kind " + k + " has " + open + " unspecified rows, the counts section says "
                    + unspecified.get(k));
            }
        }
        return new Catalogue(elements, total, unspecified);
    }

    private static Element element(String line, int lineNo) {
        String[] raw = line.split("\\|", -1);
        if (raw.length != 10) {
            throw new DatagenException(CATALOGUE + " line " + lineNo + ": expected 8 cells, found " + (raw.length - 2)
                + ": " + line);
        }
        List<String> c = new ArrayList<>();
        for (int i = 1; i <= 8; i++) {
            c.add(raw[i].trim());
        }
        Matcher id = ID_CELL.matcher(c.get(0));
        if (!id.matches()) {
            throw new DatagenException(CATALOGUE + " line " + lineNo + ": the id cell is not a backticked id: " + line);
        }
        String kind = c.get(3);
        if (!KINDS.contains(kind)) {
            throw new DatagenException(CATALOGUE + " line " + lineNo + ": unknown kind \"" + kind + "\": " + line);
        }
        List<String> tokens = new ArrayList<>();
        Matcher t = TOKEN.matcher(c.get(4));
        while (t.find()) {
            if (!t.group(1).startsWith("tick: ")) {
                tokens.add(t.group(1));
            }
        }
        if (!c.get(4).startsWith(UNSPECIFIED) && tokens.isEmpty()) {
            throw new DatagenException(CATALOGUE + " line " + lineNo + ": the data cell names nothing: " + line);
        }
        return new Element(id.group(1), c.get(1), c.get(2), kind, c.get(4), c.get(5), c.get(7), List.copyOf(tokens));
    }

    private static List<Element> of(Catalogue cat, String kind) {
        return cat.elements().stream().filter(e -> e.kind().equals(kind)).toList();
    }

    private static void requirePrefix(Element e, String name) {
        if (!name.startsWith(PREFIX)) {
            throw new DatagenException(row(e) + ": placeholder " + name + " must start with " + PREFIX);
        }
    }

    private static void requireKnown(Element e, String name, Set<String> placeholders) {
        if (!placeholders.contains(name)) {
            throw new DatagenException(row(e) + ": " + name + " is not a placeholder row of the catalogue");
        }
    }

    private static String row(Element e) {
        return CATALOGUE + " row " + e.id();
    }

    private static String leftOut(Element e, String reason) {
        return e.id() + " (" + e.kind() + "): " + reason;
    }

    /** The BetterHud name of a catalogue id: the tfp_ prefix and the id with underscores. */
    static String name(String id) {
        return PREFIX + id.replace('-', '_');
    }

    /** Copies a bar sprite into the pack's assets folder, where its image file path points (relative to assets/). */
    private static void putBarArt(OutputTree out, String file) {
        String resource = BAR_ART + file.substring(file.lastIndexOf('/') + 1);
        try (InputStream in = HudLayouts.class.getResourceAsStream(resource)) {
            if (in == null) {
                throw new DatagenException("missing bar sprite " + resource);
            }
            out.put(BetterHudPack.DIR + "assets/" + file, in.readAllBytes());
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /**
     * Replaces the vanilla hearts, food and air sprites (the hide rows) with a transparent image, so the bars are the only
     * health and food display. The sprites go into CraftEngine's pack: BetterHud's merged zip does not carry {@code
     * assets/minecraft} sprites from its pack folder. The list is the 1.21.11 client's sprite names ({@code hidden-vanilla-sprites.txt}).
     */
    private static void putHiddenVanillaSprites(OutputTree out) {
        byte[] transparent = resourceBytes(BAR_ART + "transparent-9x9.png");
        for (String sprite : resourceLines(BAR_ART + "hidden-vanilla-sprites.txt")) {
            out.put(CE_PACK_SPRITES + sprite, transparent);
        }
    }

    private static byte[] resourceBytes(String resource) {
        try (InputStream in = HudLayouts.class.getResourceAsStream(resource)) {
            if (in == null) {
                throw new DatagenException("missing datagen resource " + resource);
            }
            return in.readAllBytes();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** The non-blank lines of a text resource that do not start with {@code #}. */
    private static List<String> resourceLines(String resource) {
        List<String> lines = new ArrayList<>();
        for (String line : new String(resourceBytes(resource), StandardCharsets.UTF_8).split("\\R")) {
            if (!line.isBlank() && !line.startsWith("#")) {
                lines.add(line.strip());
            }
        }
        return lines;
    }

    private static String imageFile(String id, String part) {
        return "tfp/hud/" + id.replace('-', '_') + "_" + part + ".png";
    }

    private static BigDecimal scale() {
        return new BigDecimal("0.5");
    }

    /** An ordered map from alternating keys and values. */
    static Map<String, Object> m(Object... kv) {
        Map<String, Object> out = new LinkedHashMap<>();
        for (int i = 0; i < kv.length; i += 2) {
            out.put((String) kv[i], kv[i + 1]);
        }
        return out;
    }
}
