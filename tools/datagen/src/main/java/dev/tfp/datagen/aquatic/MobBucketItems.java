package dev.tfp.datagen.aquatic;

import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import dev.tfp.datagen.material.TfcItemRegistry;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * PAR-FAUNA-25: TFC's mob buckets as CraftEngine items ({@code configuration/mob_bucket.yml}): the four sea ones and the 16
 * freshwater fish buckets ({@code TFCItems} {@code MobBucketItem}s, stack 1). TFC draws each with a plain
 * {@code item/generated} model of {@code tfc:item/bucket/<species>}; so do we. The base material is {@code paper}, like the
 * other bucket items ({@code BucketItems}), so the vanilla server never scoops or places water with them: the aquatic
 * module (PAR-FAUNA-11) handles pickup and release itself. Names come from TFC's lang files.
 */
public final class MobBucketItems {
    static final String PACK = "craftengine/tfp/";
    static final String CONFIG = PACK + "configuration/mob_bucket.yml";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    static final String LANG_NS = "tfp_mob_bucket";
    static final String LANG_RP = PACK + "resourcepack/assets/" + LANG_NS + "/lang/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String TEXTURES = TfcCheckout.ASSETS + "textures/";
    static final String MODELS = TfcCheckout.ASSETS + "models/item/";
    static final String ITEMS_SOURCE = "src/main/java/net/dries007/tfc/common/items/TFCItems.java";
    static final int EXPECTED = 20;

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (PAR-FAUNA-25, dev.tfp.datagen.aquatic). Do not edit: fix the "
        + "generator and regenerate.";

    private MobBucketItems() {
    }

    /** Whether the checkout has {@code TFCItems} (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(ITEMS_SOURCE) && tfc.exists(TEXTURES + "item/bucket/cod.png");
    }

    /** The {@code bucket/<species>} paths of every {@code MobBucketItem} in TFC registration order. */
    static List<String> paths(TfcCheckout tfc) {
        List<String> ids = new ArrayList<>();
        for (TfcItemRegistry.Registration r : TfcItemRegistry.registrations(tfc)) {
            if (r.factory().contains("new MobBucketItem(")) {
                ids.addAll(r.ids());
            }
        }
        if (ids.size() != EXPECTED) {
            throw new DatagenException("TFCItems has " + ids.size() + " MobBucketItems, expected " + EXPECTED + ": " + ids);
        }
        return ids;
    }

    /** Writes the items, models, textures and names. Returns the item paths. */
    public static List<String> run(TfcCheckout tfc, OutputTree out) {
        List<String> ids = paths(tfc);
        Map<String, Object> items = new LinkedHashMap<>();
        for (String path : ids) {
            String texture = texture(tfc, path);
            String png = TEXTURES + texture + ".png";
            if (!tfc.exists(png)) {
                throw new DatagenException("missing mob bucket texture " + png);
            }
            out.put(RP + "textures/" + texture + ".png", tfc.read(png));
            JsonObject model = new JsonObject();
            model.addProperty("parent", "minecraft:item/generated");
            JsonObject tex = new JsonObject();
            tex.addProperty("layer0", Json.TO_NS + ":" + texture);
            model.add("textures", tex);
            out.put(RP + "models/item/" + path + ".json", Json.write(model));
            items.put(Json.TO_NS + ":" + path, entry(path));
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", items);
        out.put(CONFIG, Yaml.write(HEADER, root));
        writeLang(tfc, out, ids);
        return ids;
    }

    /** The layer0 texture of TFC's {@code models/item/<path>.json}. */
    static String texture(TfcCheckout tfc, String path) {
        String model = MODELS + path + ".json";
        if (!tfc.exists(model)) {
            throw new DatagenException("missing TFC item model " + model);
        }
        JsonObject m = Json.parse(tfc.readString(model), model).getAsJsonObject();
        String layer0 = m.getAsJsonObject("textures").get("layer0").getAsString();
        if (!layer0.startsWith(Json.FROM_NS + ":")) {
            throw new DatagenException(model + ": unexpected texture " + layer0);
        }
        return layer0.substring(Json.FROM_NS.length() + 1);
    }

    static String langKey(String path) {
        return "item." + Json.TO_NS + "." + path.replace('/', '.');
    }

    static Map<String, Object> entry(String path) {
        Map<String, Object> model = new LinkedHashMap<>();
        model.put("type", "minecraft:model");
        model.put("path", Json.TO_NS + ":item/" + path);
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("item_name", "<!i><lang:" + langKey(path) + ">");
        data.put("max_stack_size", 1);
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("material", "paper");
        e.put("data", data);
        e.put("model", model);
        return e;
    }

    /** TFC's names of the items in every locale that has them (English must have all). */
    private static void writeLang(TfcCheckout tfc, OutputTree out, List<String> ids) {
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            byte[] pipeline = out.get(RP + "lang/" + locale + ".json");
            JsonObject named = pipeline == null ? new JsonObject()
                : Json.parse(new String(pipeline, StandardCharsets.UTF_8), RP + "lang").getAsJsonObject();
            TreeMap<String, String> keys = new TreeMap<>();
            for (String id : ids) {
                String tfcKey = "item." + Json.FROM_NS + "." + id.replace('/', '.');
                if (named.has(langKey(id))) {
                    continue;
                }
                if (src.has(tfcKey)) {
                    keys.put(langKey(id), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC item tfc:" + id + " has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }
}
