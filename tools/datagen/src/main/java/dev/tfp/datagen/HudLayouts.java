    /** The catalogue in this checkout: {@code tfp.repoRoot} (set by the Gradle test task), else the nearest ancestor. */
    static Path catalogue() {
        String root = System.getProperty("tfp.repoRoot");
        Path start = root != null ? Path.of(root).toAbsolutePath().normalize() : Path.of("").toAbsolutePath();
        for (Path p = start; p != null; p = p.getParent()) {
            Path c = p.resolve(CATALOGUE);
            if (Files.isRegularFile(c)) {
                return c;
            }
        }
        throw new DatagenException("no " + CATALOGUE + " found at or above " + start);
    }

    /** Writes the HUD layouts into {@code out}. Fails on a missing, malformed or inconsistent catalogue. */
    static Summary run(OutputTree out, Path file) {
        Catalogue cat = parse(file);
        List<String> leftOut = new ArrayList<>();
        Map<String, Integer> emitted = new LinkedHashMap<>();
        for (String k : KINDS) {
            emitted.put(k, 0);
        }

        List<Map<String, Object>> placeholders = new ArrayList<>();
        Set<String> names = new HashSet<>();
        for (Element e : of(cat, "placeholder")) {
            if (e.unspecified() || e.tokens().size() != 1) {
                throw new DatagenException(row(e) + ": a placeholder row names exactly one placeholder");
            }
            String name = e.tokens().get(0);
            requirePrefix(e, name);
            if (!names.add(name)) {
                throw new DatagenException(row(e) + ": placeholder " + name + " is named twice");
            }
            placeholders.add(m("name", name, "catalogue-id", e.id(), "source", e.source(), "milestone", e.milestone()));
            emitted.merge("placeholder", 1, Integer::sum);
        }

        Map<String, Object> barImages = new LinkedHashMap<>();
        Map<String, Object> barLayouts = new LinkedHashMap<>();
        Map<String, Object> barHudLayouts = new LinkedHashMap<>();
        Map<String, Object> infoLayouts = new LinkedHashMap<>();
        for (Element e : of(cat, "bar")) {
            if (e.unspecified()) {
                leftOut.add(leftOut(e, UNSPECIFIED));
                continue;
            }
            BarSpec spec = BAR_SPECS.get(e.id());
            if (spec == null) {
                throw new DatagenException(row(e) + ": no bar spec in HudLayouts.BAR_SPECS");
            }
            for (String t : e.tokens()) {
                requireKnown(e, t, names);
            }
            Map<String, Object> listener;
            if (e.tokens().size() == 2 && !e.data().contains("listener")) {
                listener = m("class", "placeholder", "value", e.tokens().get(0), "max", e.tokens().get(1));
            } else if (e.tokens().size() == 1 && e.data().contains("listener")) {
                listener = m("class", e.tokens().get(0));
            } else {
                throw new DatagenException(row(e) + ": a bar names a value and a max, or one listener");
            }
            HudArt.Bar art = HudArt.bar(spec.art());
            if (!art.variants().equals(spec.variants().stream().map(Variant::name).sorted().toList())) {
                throw new DatagenException(row(e) + ": fill variants " + art.variants() + " in " + spec.art()
                    + ".layers.json do not match HudLayouts.BAR_SPECS");
            }
            String name = name(e.id());
            int split = spec.split() > 0 ? spec.split() : art.interiorWidth();
            barImages.put(name + "_bg", m("type", "single", "file", artPath(packFile(name, spec, art.bgFile()))));
            putArt(out, art.bgFile(), packFile(name, spec, art.bgFile()));
            List<String> fills = new ArrayList<>();
            fills.add(art.fillFile());
            spec.variants().forEach(v -> fills.add(art.variantFile(v.name())));
            for (String f : fills) {
                String packed = packFile(name, spec, f);
                barImages.put(imageName(packed), m("type", "listener", "file", artPath(packed), "split", split,
                    "split-type", "left", "setting", m("listener", listener)));
                putArt(out, f, packed);
            }
            List<StateLayer> states = STATES.getOrDefault(e.id(), List.of());
            for (StateLayer st : states) {
                String packed = packFile(name, spec, st.file());
                Map<String, Object> image = st.listener() == null
                    ? m("type", "single", "file", artPath(packed))
                    : m("type", "listener", "file", artPath(packed), "split", split, "split-type", "left",
                        "setting", m("listener", m("class", st.listener())));
                if (st.listener() != null) {
                    requireKnown(e, st.listener(), names);
                }
                barImages.put(imageName(packed), image);
                out.put(BetterHudPack.DIR + "assets/" + artPath(packed), HudArt.indexedPng(st.image(art)));
            }

            boolean info = spec.hud().equals(INFO_HUD);
            Lowered low = LOWERED.get(e.id());
            List<Cond> own = new ArrayList<>(spec.shownWhile());
            if (low != null) {
                own.add(new Cond(low.when().value(), negate(low.when().operation()), low.when().threshold()));
            }
            Map<String, Object> layout = barLayout(spec, art, name, spec.y(), info ? own : gated(own), states, e, names);
            (info ? infoLayouts : barLayouts).put(name, layout);
            if (!info) {
                barHudLayouts.put(String.valueOf(barHudLayouts.size() + 1),
                    m("name", name, "gui", m("x", BARS_GUI_X, "y", BARS_GUI_Y)));
            }
            if (low != null) {
                if (info) {
                    throw new DatagenException(row(e) + ": only a bar of the bars HUD can have a lowered placement");
                }
                List<Cond> lowOwn = new ArrayList<>(spec.shownWhile());
                lowOwn.add(low.when());
                String lowName = name + LOWERED_SUFFIX;
                barLayouts.put(lowName, barLayout(spec, art, name, low.y(), gated(lowOwn), states, e, names));
                barHudLayouts.put(String.valueOf(barHudLayouts.size() + 1),
                    m("name", lowName, "gui", m("x", BARS_GUI_X, "y", BARS_GUI_Y)));
            }
            emitted.merge("bar", 1, Integer::sum);
        }

        for (Element e : of(cat, "overlay")) {
            List<OverlaySpec> specs = OVERLAYS.get(e.id());
            if (specs == null) {
                throw new DatagenException(row(e) + ": no overlay spec in HudLayouts.OVERLAYS");
            }
            for (String t : e.tokens()) {
                requireKnown(e, t, names);
            }
            String name = name(e.id());
            for (int i = 0; i < specs.size(); i++) {
                OverlaySpec o = specs.get(i);
                // A mirrored copy is its own file: BetterHud names generated textures by file path (first wins), so a
                // second image with flip: [x] on the same file could silently reuse the unflipped texture.
                String art = o.flipX() ? HudArt.mirroredFile(o.file()) : o.file();
                String image = imageName(art);
                barImages.put(image, m("type", "single", "file", artPath(art)));
                out.put(BetterHudPack.DIR + "assets/" + artPath(art), o.flipX() ? HudArt.mirrored(o.file()) : HudArt.bytes(art));
                String layoutName = specs.size() == 1 ? name : name + "_" + (i + 1);
                Map<String, Object> entry = m("name", image, "x", o.x(), "y", o.y() + HudArt.firstOpaqueRow(o.file()),
                    "layer", LAYER_OVERLAY);
                if (o.opacity() < 1.0) {
                    entry.put("opacity", BigDecimal.valueOf(o.opacity()));
                }
                Map<String, Object> layout = m("offset", "left", "images", m("1", entry));
                List<Cond> shown = o.hud().equals(INFO_HUD) ? o.shownWhile() : gated(o.shownWhile());
                if (!shown.isEmpty()) {
                    layout.put("conditions", conditions(shown, e, names));
                }
                if (o.hud().equals(INFO_HUD)) {
                    infoLayouts.put(layoutName, layout);
                } else {
                    barLayouts.put(layoutName, layout);
                    barHudLayouts.put(String.valueOf(barHudLayouts.size() + 1),
                        m("name", layoutName, "gui", m("x", o.guiX(), "y", o.guiY())));
                }
            }
            emitted.merge("overlay", 1, Integer::sum);
        }
        for (String id : infoLayouts.keySet()) {
            if (!BetterHudPack.INFO_LAYOUTS.contains(id)) {
                throw new DatagenException(id + " is not listed in BetterHudPack.INFO_LAYOUTS, so no HUD would show it");
            }
        }

        Map<String, Object> readoutLayouts = new LinkedHashMap<>();
        for (Element e : of(cat, "readout")) {
            if (e.unspecified()) {
                leftOut.add(leftOut(e, UNSPECIFIED));
                continue;
            }
            Place at = READOUTS.get(e.id());
            if (at == null) {
                throw new DatagenException(row(e) + ": no readout placement in HudLayouts.READOUTS");
            }
            for (String t : e.tokens()) {
                requireKnown(e, t, names);
            }
            Matcher tick = TICK.matcher(e.data());
            if (!tick.find()) {
                throw new DatagenException(row(e) + ": a readout names its tick (text `tick: N`)");
            }
            String pattern = switch (e.tokens().size()) {
                case 1 -> "[" + e.tokens().get(0) + "]";
                case 2 -> "[" + e.tokens().get(0) + "]  ([" + e.tokens().get(1) + "])";
                default -> throw new DatagenException(row(e) + ": a readout names one or two placeholders");
            };
            String inPack = READOUTS_IN_PACK.get(e.id());
            if (inPack != null) {
                if (!BetterHudPack.LAYOUT_IDS.contains(inPack)) {
                    throw new DatagenException(row(e) + ": " + inPack + " is not a layout of BetterHudPack");
                }
                continue;
            }
            readoutLayouts.put(name(e.id()), m("texts", m("1", m("name", FONT, "pattern", pattern, "align", "left",
                "x", at.x(), "y", at.y(), "scale", scale(), "outline", true, "tick", Integer.parseInt(tick.group(1))))));
            emitted.merge("readout", 1, Integer::sum);
        }

        Map<String, Object> popupLayouts = new LinkedHashMap<>();
        Map<String, Object> popups = new LinkedHashMap<>();
        for (Element e : of(cat, "popup")) {
            if (e.unspecified()) {
                leftOut.add(leftOut(e, UNSPECIFIED));
                continue;
            }
            PopupSpec spec = POPUPS_AT.get(e.id());
            if (spec == null) {
                throw new DatagenException(row(e) + ": no popup spec in HudLayouts.POPUPS_AT");
            }
            if (!e.tokens().equals(spec.tokens()) || !e.shows().contains(POPUP_SHOWN_WHILE)) {
                throw new DatagenException(row(e) + ": a popup names " + spec.tokens()
                    + " (condition, text, colour) and is \"" + POPUP_SHOWN_WHILE + "\"");
            }
            for (String t : e.tokens()) {
                requireKnown(e, t, names);
            }
            String name = name(e.id());
            Map<String, Object> texts = new LinkedHashMap<>();
            for (String colour : HEAT_COLORS) {
                // BetterHud string conditions compare with a quoted literal ('#ff5555'); only == and != apply.
                texts.put(String.valueOf(texts.size() + 1), m("name", FONT, "pattern", "[" + spec.text() + "]",
                    "align", "center", "x", 0, "y", 0, "scale", scale(), "outline", POPUP_TEXT_SHADOW, "color", colour,
                    "conditions", m("1", m("first", spec.colour(), "second", "'" + colour + "'", "operation", "=="))));
            }
            popupLayouts.put(name, m("texts", texts));
            Map<String, Object> popupConditions = conditions(
                gated(List.of(new Cond(spec.condition(), POPUP_OPERATION, POPUP_THRESHOLD))), e, names);
            popups.put(name, m("default", true,
                "conditions", popupConditions,
                "layouts", m("1", m("name", name, "gui", m("x", POPUP_GUI_X, "y", POPUP_GUI_Y),
                    "pixel", m("x", spec.at().x(), "y", spec.at().y())))));
            emitted.merge("popup", 1, Integer::sum);
        }

        List<Map<String, Object>> hidden = new ArrayList<>();
        for (Element e : of(cat, "hidden-vanilla")) {
            if (e.unspecified() || e.tokens().isEmpty()) {
                throw new DatagenException(row(e) + ": a hidden-vanilla row names its sprites");
            }
            List<String> sprites = new ArrayList<>();
            for (String t : e.tokens()) {
                sprites.add(t.contains("/") ? t : VANILLA_HUD + t);
            }
            Matcher count = FILE_COUNT.matcher(e.data());
            int files = count.find() ? Integer.parseInt(count.group(1)) : e.tokens().size();
            hidden.add(m("id", name(e.id()), "catalogue-id", e.id(), "source", e.source(), "sprites", sprites,
                "files", files));
            emitted.merge("hidden-vanilla", 1, Integer::sum);
        }

        for (Element e : cat.elements()) {
            if (e.kind().equals("indicator")) {
                leftOut.add(leftOut(e, "kind indicator is not one of the kinds this generator emits"));
            }
        }

        out.put(IMAGES, Yaml.write(HEADER, barImages));
        out.put(BAR_LAYOUTS, Yaml.write(HEADER, barLayouts));
        out.put(INFO_LAYOUTS, Yaml.write(HEADER, infoLayouts));
        out.put(BARS_HUDS, Yaml.write(HEADER, m(BARS_HUD, m("layouts", barHudLayouts))));
        putHiddenVanillaSprites(out);
        if (!readoutLayouts.isEmpty()) {
            out.put(READOUT_LAYOUTS, Yaml.write(HEADER, readoutLayouts));
        }
        out.put(POPUP_LAYOUTS, Yaml.write(HEADER, popupLayouts));
        out.put(POPUPS, Yaml.write(HEADER, popups));
        out.put(PLACEHOLDERS, Yaml.write(HEADER, m("placeholders", placeholders)));
        out.put(HIDDEN, Yaml.write(HEADER, m("hidden-vanilla", hidden)));
        return new Summary(cat.total(), emitted, leftOut);
    }

    /**
     * One bar layout at canvas row {@code y}: the bg and fill layers (each y plus its first opaque row), the fill
     * variants, the state layers (PAR-HUD-19), the texts and the layout's {@code shown} conditions (already gated when
     * the bar is on the bars HUD).
     */
    private static Map<String, Object> barLayout(BarSpec spec, HudArt.Bar art, String name, int y, List<Cond> shown,
                                                 List<StateLayer> states, Element e, Set<String> names) {
        Map<String, Object> images = new LinkedHashMap<>();
        images.put("1", layer(name + "_bg", spec.x(), y + HudArt.firstOpaqueRow(art.bgFile()), LAYER_BG, List.of(), e, names));
        List<Cond> plain = new ArrayList<>();
        for (Variant v : spec.variants()) {
            plain.add(new Cond(v.when().get(0).value(), negate(v.when().get(0).operation()), v.when().get(0).threshold()));
        }
        images.put("2", layer(imageName(packFile(name, spec, art.fillFile())), spec.x(),
            y + HudArt.firstOpaqueRow(art.fillFile()), LAYER_FILL, plain.isEmpty() ? List.of() : List.of(plain.get(0)), e,
            names));
        Map<String, Object> layout = m("offset", "left", "images", images);
        for (Variant v : spec.variants()) {
            String vf = art.variantFile(v.name());
            Map<String, Object> img = layer(imageName(packFile(name, spec, vf)), spec.x(), y + HudArt.firstOpaqueRow(vf),
                LAYER_FILL, v.when(), e, names);
            images.put(String.valueOf(images.size() + 1), img);
        }
        for (StateLayer st : states) {
            int row = HudArt.firstOpaqueRow(st.image(art), st.file());
            images.put(String.valueOf(images.size() + 1), layer(imageName(packFile(name, spec, st.file())), spec.x(),
                y + row, st.layer(), st.when(), e, names));
        }
        if (!spec.texts().isEmpty()) {
            Map<String, Object> texts = new LinkedHashMap<>();
            for (Text t : spec.texts()) {
                for (Matcher ph = PLACEHOLDER.matcher(t.pattern()); ph.find(); ) {
                    requireKnown(e, ph.group(1), names);
                }
                texts.put(String.valueOf(texts.size() + 1), m("name", FONT, "pattern", t.pattern(),
                    "placeholder-string-format", m("number", "#"), "align", t.align(),
                    "x", spec.x() + t.x(), "y", y + t.y(), "scale", scale(), "outline", t.outline(),
                    "layer", LAYER_TEXT));
            }
            layout.put("texts", texts);
        }
        if (!shown.isEmpty()) {
            layout.put("conditions", conditions(shown, e, names));
        }
        return layout;
    }

    /**
     * The pack file name of an art file of {@code spec} for the bar {@code name}: the art's own name when the bar owns
     * the art (its BetterHud name is {@code tfp_} + the art name), else a copy named after the bar (the mount bar reuses
     * the health art). BetterHud keys textures by file name (first wins, silently) and a listener belongs to its image,
     * so a bar that borrows art gets its own files and image ids.
     */
    static String packFile(String name, BarSpec spec, String file) {
        String base = name.substring(PREFIX.length());
        if (base.equals(spec.art())) {
            return file;
        }
        if (!file.startsWith(spec.art())) {
            throw new DatagenException(file + " is not an art file of " + spec.art());
        }
        return base + file.substring(spec.art().length());
    }

    /** Parses the catalogue. Fails on any row or count that does not match the format. */
    static Catalogue parse(Path file) {
        if (!Files.isRegularFile(file)) {
            throw new DatagenException("HUD catalogue not found: " + file);
        }
        List<String> lines;
        try {
            lines = Files.readAllLines(file, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        List<Element> elements = new ArrayList<>();
        Map<String, Integer> total = new LinkedHashMap<>();
        Map<String, Integer> unspecified = new LinkedHashMap<>();
        boolean sawElements = false;
        boolean sawCounts = false;
        String section = "";
        Set<String> ids = new HashSet<>();
        for (int i = 0; i < lines.size(); i++) {
            String line = lines.get(i);
            if (line.startsWith("## ")) {
                section = line;
                sawElements |= line.equals(ELEMENTS_HEADING);
                sawCounts |= line.equals(COUNTS_HEADING);
                continue;
            }
            if (section.equals(ELEMENTS_HEADING)) {
                if (!line.startsWith("|") || line.startsWith("| id |") || SEPARATOR.matcher(line).matches()) {
                    continue;
                }
                Element e = element(line, i + 1);
                if (!ids.add(e.id())) {
                    throw new DatagenException(CATALOGUE + " line " + (i + 1) + ": id " + e.id() + " is listed twice");
                }
                elements.add(e);
            } else if (section.equals(COUNTS_HEADING)) {
                Matcher m = COUNT_ROW.matcher(line);
                if (m.matches()) {
                    if (total.containsKey(m.group(1))) {
                        throw new DatagenException(CATALOGUE + " line " + (i + 1) + ": kind " + m.group(1) + " is counted twice");
                    }
                    total.put(m.group(1), Integer.parseInt(m.group(2)));
                    unspecified.put(m.group(1), Integer.parseInt(m.group(3)));
                }
            }
        }
        if (!sawElements) {
            throw new DatagenException(CATALOGUE + ": no \"" + ELEMENTS_HEADING + "\" section");
        }
        if (!sawCounts) {
            throw new DatagenException(CATALOGUE + ": no \"" + COUNTS_HEADING + "\" counts section");
        }
        if (!total.keySet().equals(new HashSet<>(KINDS))) {
            throw new DatagenException(CATALOGUE + ": the counts section lists " + total.keySet() + ", expected " + KINDS);
        }
        for (String k : KINDS) {
            long rows = elements.stream().filter(e -> e.kind().equals(k)).count();
            long open = elements.stream().filter(e -> e.kind().equals(k) && e.unspecified()).count();
            if (rows != total.get(k)) {
                throw new DatagenException(CATALOGUE + ": kind " + k + " has " + rows + " rows, the counts section says "
                    + total.get(k));
            }
            if (open != unspecified.get(k)) {
                throw new DatagenException(CATALOGUE + ": kind " + k + " has " + open + " unspecified rows, the counts section says "
                    + unspecified.get(k));
            }
        }
        return new Catalogue(elements, total, unspecified);
    }

    private static Element element(String line, int lineNo) {
        String[] raw = line.split("\\|", -1);
        if (raw.length != 10) {
            throw new DatagenException(CATALOGUE + " line " + lineNo + ": expected 8 cells, found " + (raw.length - 2)
                + ": " + line);
        }
        List<String> c = new ArrayList<>();
        for (int i = 1; i <= 8; i++) {
            c.add(raw[i].trim());
        }
        Matcher id = ID_CELL.matcher(c.get(0));
        if (!id.matches()) {
            throw new DatagenException(CATALOGUE + " line " + lineNo + ": the id cell is not a backticked id: " + line);
        }
        String kind = c.get(3);
        if (!KINDS.contains(kind)) {
            throw new DatagenException(CATALOGUE + " line " + lineNo + ": unknown kind \"" + kind + "\": " + line);
        }
        List<String> tokens = new ArrayList<>();
        Matcher t = TOKEN.matcher(c.get(4));
        while (t.find()) {
            if (!t.group(1).startsWith("tick: ")) {
                tokens.add(t.group(1));
            }
        }
        if (!c.get(4).startsWith(UNSPECIFIED) && tokens.isEmpty()) {
            throw new DatagenException(CATALOGUE + " line " + lineNo + ": the data cell names nothing: " + line);
        }
        return new Element(id.group(1), c.get(1), c.get(2), kind, c.get(4), c.get(5), c.get(7), List.copyOf(tokens));
    }

    private static List<Element> of(Catalogue cat, String kind) {
        return cat.elements().stream().filter(e -> e.kind().equals(kind)).toList();
    }

    private static void requirePrefix(Element e, String name) {
        if (!name.startsWith(PREFIX)) {
            throw new DatagenException(row(e) + ": placeholder " + name + " must start with " + PREFIX);
        }
    }

    private static void requireKnown(Element e, String name, Set<String> placeholders) {
        if (!placeholders.contains(name)) {
            throw new DatagenException(row(e) + ": " + name + " is not a placeholder row of the catalogue");
        }
    }

    private static String row(Element e) {
        return CATALOGUE + " row " + e.id();
    }

    private static String leftOut(Element e, String reason) {
        return e.id() + " (" + e.kind() + "): " + reason;
    }

    /** The BetterHud name of a catalogue id: the tfp_ prefix and the id with underscores. */
    static String name(String id) {
        return PREFIX + id.replace('-', '_');
    }

    /** Copies a HUD art resource ({@link HudArt}) into the pack's assets folder, where its image path points. */
    private static void putArt(OutputTree out, String file) {
        putArt(out, file, file);
    }

    /** Copies the art resource {@code file} into the pack's assets folder under the name {@code as}. */
    private static void putArt(OutputTree out, String file, String as) {
        out.put(BetterHudPack.DIR + "assets/" + artPath(as), HudArt.bytes(file));
    }

    /** The image's path relative to the pack's {@code assets/} folder. */
    static String artPath(String file) {
        return "tfp/hud/" + file;
    }

    /** The BetterHud image id of an art file: {@code tfp_} + the file name without {@code .png}. */
    static String imageName(String file) {
        return PREFIX + file.substring(0, file.length() - ".png".length());
    }

    private static Map<String, Object> layer(String image, int x, int y, int layer, List<Cond> when, Element e,
                                             Set<String> names) {
        Map<String, Object> img = m("name", image, "x", x, "y", y, "layer", layer);
        if (!when.isEmpty()) {
            img.put("conditions", conditions(when, e, names));
        }
        return img;
    }

    private static Map<String, Object> conditions(List<Cond> when, Element e, Set<String> names) {
        Map<String, Object> c = new LinkedHashMap<>();
        for (Cond w : when) {
            requireKnown(e, w.value(), names);
            c.put(String.valueOf(c.size() + 1), m("first", w.value(), "second", w.threshold(), "operation", w.operation()));
        }
        return c;
    }

    /** {@code when} with the game-mode gate {@link #NEEDS_ACTIVE} after it (PAR-HUD-12). */
    static List<Cond> gated(List<Cond> when) {
        List<Cond> all = new ArrayList<>(when);
        all.add(NEEDS_ACTIVE);
        return List.copyOf(all);
    }

    private static String negate(String op) {
        return switch (op) {
            case "<" -> ">=";
            case "<=" -> ">";
            case ">" -> "<=";
            case ">=" -> "<";
            default -> throw new DatagenException("cannot negate " + op);
        };
    }

    /**
     * Replaces the vanilla hearts, food and air sprites (the hide rows) with a transparent image, so the bars are the only
     * health and food display. The sprites go into CraftEngine's pack: BetterHud's merged zip does not carry {@code
     * assets/minecraft} sprites from its pack folder. The list is the 1.21.11 client's sprite names ({@code hidden-vanilla-sprites.txt}).
     */
    private static void putHiddenVanillaSprites(OutputTree out) {
        byte[] transparent = resourceBytes(BAR_ART + "transparent-9x9.png");
        for (String sprite : resourceLines(BAR_ART + "hidden-vanilla-sprites.txt")) {
            out.put(CE_PACK_SPRITES + sprite, transparent);
        }
    }

    private static byte[] resourceBytes(String resource) {
        try (InputStream in = HudLayouts.class.getResourceAsStream(resource)) {
            if (in == null) {
                throw new DatagenException("missing datagen resource " + resource);
            }
            return in.readAllBytes();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** The non-blank lines of a text resource that do not start with {@code #}. */
    private static List<String> resourceLines(String resource) {
        List<String> lines = new ArrayList<>();
        for (String line : new String(resourceBytes(resource), StandardCharsets.UTF_8).split("\\R")) {
            if (!line.isBlank() && !line.startsWith("#")) {
                lines.add(line.strip());
            }
        }
        return lines;
    }

    private static BigDecimal scale() {
        return new BigDecimal("0.5");
    }

    /** An ordered map from alternating keys and values. */
    static Map<String, Object> m(Object... kv) {
        Map<String, Object> out = new LinkedHashMap<>();
        for (int i = 0; i < kv.length; i += 2) {
            out.put((String) kv[i], kv[i + 1]);
        }
        return out;
    }
