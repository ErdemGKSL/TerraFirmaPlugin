/**
 * PAR-HEAT-24: the grill screen's art (TFC {@code GrillScreen}) for the 4-row chest of the plugin's
 * {@code dev.tfp.paper.grill.gui.GrillScreenLayout}: {@code tfp:gui/grill} in {@code configuration/grill_gui.yml}. The
 * numbers here must equal that layout's.
 *
 * <p>TFC's {@code fire_pit_grill.png} is 176 x 186, exactly a 4-row chest, and differs from {@code fire_pit.png} only in
 * the middle (five grill frames, a connector and the grill icon instead of the input, arrows and outputs). As the firepit
 * art ({@code FirepitScreenArt}) the content band moves down {@link #DY} = 2, so the fuel column sits on chest column 0,
 * and the player inventory up {@link #DY_PLAYER} = -1 onto the chest's (y 103). TFC's grill frames (items at
 * (62 + 18k, 20)) would then sit 4 pixels under chest row 0, so the frame band goes up onto chest slots 3 to 7 (frame top
 * y 17: TFC's 19 minus 2) and the connector's five stems are drawn {@link #GRID_LIFT} pixels longer, from one plain row
 * under the frames down to TFC's own stems. The thermometer column is the firepit's in the same place, so the screen uses
 * the firepit's thermometer strip ({@code tfp:gui/firepit_thermometer}, PAR-HEAT-20); {@link #checkSources} checks that
 * the grill art's indicator sprite is the firepit's.
 */
public final class GrillScreenArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/fire_pit_grill.png";
    /** The firepit's art, whose thermometer indicator the grill screen reuses. */
    public static final String FIREPIT_TEXTURE = "src/main/resources/assets/tfc/textures/gui/fire_pit.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/GrillScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/GrillContainer.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/grill_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    /** The chest: TFC's screen is 166 + 20 = 186 tall, a 4-row chest. */
    public static final ChestGeometry CHEST = new ChestGeometry(4);
    public static final int TFC_HEIGHT = 186;
    /** TFC's player inventory offset ({@code init(playerInv, 20)}): its inventory at y 104. */
    public static final int TFC_INVENTORY_OFFSET = 20;
    /** The player inventory's move onto the 4-row chest's (y 103). */
    public static final int DY_PLAYER = CHEST.playerRowY(0) - (84 + TFC_INVENTORY_OFFSET);
    /** The content's move: fuel slot 3 (y 16) onto chest row 0 (y 18). */
    public static final int DY = 2;

    /** TFC's slot item positions, in block entity order (fuel 0..3, grill 4..8). */
    public static final List<int[]> TFC_SLOTS = List.of(new int[] {8, 70}, new int[] {8, 52}, new int[] {8, 34},
        new int[] {8, 16}, new int[] {62, 20}, new int[] {80, 20}, new int[] {98, 20}, new int[] {116, 20},
        new int[] {134, 20});
    /** The chest slot of each TFC slot ({@code GrillScreenLayout.CHEST_SLOTS}). */
    public static final List<Integer> CHEST_SLOTS = List.of(27, 18, 9, 0, 3, 4, 5, 6, 7);
    public static final int FIRST_GRILL_SLOT = 4;

    /** The grill frames' extra lift over the content move: TFC's frame top 19 + DY onto chest row 0's frame top 17. */
    public static final int GRID_LIFT = TFC_SLOTS.get(FIRST_GRILL_SLOT)[1] + DY - CHEST.slotY(0);

    /** TFC's thermometer indicator sprite (u 176, v 0, 15 x 5), shared with the firepit's art. */
    public static final int THERMOMETER_U = 176;
    public static final int THERMOMETER_V = 0;

    public static final GuiImage BACKGROUND = GuiImage.of("tfp:gui/grill", 0, 0, ChestGeometry.WIDTH, CHEST.height());

    /** A plain panel row of TFC's art (above the fuel column). */
    static final int PLAIN_ROW = 10;
    /** The top and bottom border rows, kept in place. */
    static final int BORDER = 4;
    /** TFC's content band [BORDER, CONTENT_END) moves by DY; the player band [CONTENT_END, height - BORDER) by DY_PLAYER. */
    static final int CONTENT_END = 94;
    /** TFC's grill frame band: the five frames, x [61, 151), rows 19 to 36. */
    static final int GRID_X0 = 61;
    static final int GRID_X1 = GRID_X0 + 5 * ChestGeometry.SLOT;
    static final int GRID_Y0 = 19;
    static final int GRID_Y1 = GRID_Y0 + ChestGeometry.SLOT;
    /** TFC's connector stems start two rows under the frames (one plain row between). */
    static final int STEM_Y = GRID_Y1 + 1;

    private GrillScreenArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(FIREPIT_TEXTURE) && tfc.exists(SCREEN) && tfc.exists(CONTAINER);
    }

    /** Writes the background and its YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE), TEXTURE);
        checkThermometer(src, read(tfc.read(FIREPIT_TEXTURE), FIREPIT_TEXTURE));
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, BACKGROUND, background(src));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The 176 x 186 window. */
    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = CHEST.height();
        if (src.getWidth() < w || src.getHeight() < TFC_HEIGHT || h != TFC_HEIGHT) {
            throw new DatagenException(TEXTURE + ": not a 176 x 186 screen over a 4-row chest");
        }
        checkPlain(src, PLAIN_ROW);
        if (CHEST.hotbarY() - (142 + TFC_INVENTORY_OFFSET) != DY_PLAYER) {
            throw new DatagenException(TEXTURE + ": the chest's hotbar does not move with its inventory");
        }
        for (int y = CONTENT_END - DY + DY_PLAYER; y < CONTENT_END + DY - DY_PLAYER; y++) {
            checkPlain(src, y); // the rows the content band and the player band both cover
        }
        for (int y = GRID_Y0 - GRID_LIFT - DY; y < GRID_Y0; y++) {
            checkPlain(src, y, GRID_X0, GRID_X1); // the rows the lifted frames move into
        }
        checkPlain(src, GRID_Y1, GRID_X0, GRID_X1);
        List<Integer> stems = stems(src);
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < h; y++) {
            copy(src, out, 0, PLAIN_ROW, w, 1, 0, y);
        }
        copy(src, out, 0, BORDER, w, CONTENT_END - BORDER, 0, BORDER + DY); // the content, moved down
        copy(src, out, 0, CONTENT_END, w, TFC_HEIGHT - BORDER - CONTENT_END, 0, CONTENT_END + DY_PLAYER); // the inventory
        copy(src, out, 0, 0, w, BORDER, 0, 0); // top border
        copy(src, out, 0, TFC_HEIGHT - BORDER, w, BORDER, 0, h - BORDER); // bottom border

        // the grill frames, lifted onto chest row 0, and the stems drawn up to one plain row under them
        int top = GRID_Y0 + DY - GRID_LIFT;
        for (int y = top; y < STEM_Y + DY; y++) {
            copy(src, out, GRID_X0, PLAIN_ROW, GRID_X1 - GRID_X0, 1, GRID_X0, y);
        }
        copy(src, out, GRID_X0, GRID_Y0, GRID_X1 - GRID_X0, GRID_Y1 - GRID_Y0, GRID_X0, top);
        int ink = src.getRGB(stems.getFirst(), STEM_Y);
        for (int x : stems) {
            for (int y = top + (GRID_Y1 - GRID_Y0) + 1; y < STEM_Y + DY; y++) {
                out.setRGB(x, y, ink);
            }
        }
        return out;
    }

    /** The columns of TFC's connector stems under the frames: one under each frame. */
    static List<Integer> stems(BufferedImage src) {
        int plain = src.getRGB(PLAIN_ROW, PLAIN_ROW);
        List<Integer> stems = new ArrayList<>();
        for (int x = GRID_X0; x < GRID_X1; x++) {
            if (src.getRGB(x, STEM_Y) != plain) {
                stems.add(x);
            }
        }
        if (stems.size() != 5) {
            throw new DatagenException(TEXTURE + ": " + stems.size() + " connector stems under the grill frames, expected 5");
        }
        int ink = src.getRGB(stems.getFirst(), STEM_Y);
        for (int x : stems) {
            if (src.getRGB(x, STEM_Y) != ink) {
                throw new DatagenException(TEXTURE + ": the connector stems are not one colour");
            }
        }
        return stems;
    }

    /** The grill screen draws the firepit's thermometer strip, so TFC's two indicator sprites must be equal. */
    static void checkThermometer(BufferedImage grill, BufferedImage firepit) {
        for (int y = 0; y < ProgressFrames.THERMOMETER_HEIGHT; y++) {
            for (int x = 0; x < ProgressFrames.THERMOMETER_WIDTH; x++) {
                if (grill.getRGB(THERMOMETER_U + x, THERMOMETER_V + y) != firepit.getRGB(THERMOMETER_U + x, THERMOMETER_V + y)) {
                    throw new DatagenException(TEXTURE + ": the thermometer indicator differs from " + FIREPIT_TEXTURE
                        + "'s; the grill screen can no longer reuse the firepit strip");
                }
            }
        }
    }

    /** TFC's numbers this layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        String screen = tfc.readString(SCREEN).replaceAll("\\s+", " ");
        need(container, CONTAINER, "addSlot(new CallbackSlot(blockEntity, i, " + TFC_SLOTS.get(0)[0] + ", "
            + TFC_SLOTS.get(0)[1] + " - 18 * i));");
        need(container, CONTAINER, "addSlot(new CallbackSlot(blockEntity, i, " + TFC_SLOTS.get(FIRST_GRILL_SLOT)[0]
            + " + (i - SLOT_EXTRA_INPUT_START) * 18, " + TFC_SLOTS.get(FIRST_GRILL_SLOT)[1] + "));");
        need(container, CONTAINER, ".init(playerInv, " + TFC_INVENTORY_OFFSET + ")");
        need(screen, SCREEN, "textures/gui/fire_pit_grill.png");
        need(screen, SCREEN, "imageHeight += " + TFC_INVENTORY_OFFSET + ";");
        need(screen, SCREEN, "graphics.blit(texture, leftPos + 30, topPos + 76 - Math.min("
            + ProgressFrames.THERMOMETER_TRAVEL + ", temp), " + THERMOMETER_U + ", " + THERMOMETER_V + ", "
            + ProgressFrames.THERMOMETER_WIDTH + ", " + ProgressFrames.THERMOMETER_HEIGHT + ");");
        for (int i = 0; i < TFC_SLOTS.size(); i++) {
            int[] p = TFC_SLOTS.get(i);
            int slot = CHEST_SLOTS.get(i);
            int dy = i < FIRST_GRILL_SLOT ? DY : DY - GRID_LIFT;
            if (CHEST.slotX(slot) != p[0] || CHEST.slotY(slot) != p[1] + dy) {
                throw new DatagenException("TFC slot " + i + " does not land on chest slot " + slot + " moved by " + dy);
            }
        }
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the grill screen art is stale");
        }
    }

    private static void checkPlain(BufferedImage src, int y) {
        checkPlain(src, y, BORDER, ChestGeometry.WIDTH - BORDER);
    }

    private static void checkPlain(BufferedImage src, int y, int x0, int x1) {
        int c = src.getRGB(PLAIN_ROW, PLAIN_ROW);
        for (int x = x0; x < x1; x++) {
            if (src.getRGB(x, y) != c) {
                throw new DatagenException(TEXTURE + ": row " + y + " is not plain panel; the re-layout would cut art");
            }
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        images.put(image.id(), e);
    }

    static BufferedImage read(byte[] bytes, String what) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(what + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
