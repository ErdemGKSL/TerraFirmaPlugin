    @Test
    void driedTickAndResetMatchTfcReplay() {
        for (long[] r : ROWS) {
            long threshold = r[0];
            long add = r[1];
            long[] rain = rain((int) r[2], r[3], r[4], r[5]);
            Pile p = Pile.placed(0);
            if (add != NOT) {
                p = DryingRules.advance(p, add, (int) threshold, rain);
                p = DryingRules.reset(p, add);
            }
            p = DryingRules.advance(p, r[5], (int) threshold, rain);
            String what = java.util.Arrays.toString(r);
            assertThat(p.dried() ? p.driedTick() : NOT).as(what).isEqualTo(r[6]);
            assertThat(p.lastUpdateTick()).as(what).isEqualTo(r[7]);
        }
    }

    /** The rain ticks up to {@code limit} for a golden pattern. */
    static long[] rain(int kind, long a, long b, long limit) {
        if (kind == 0) {
            return new long[0];
        }
        java.util.List<Long> ticks = new java.util.ArrayList<>();
        if (kind == 1) {
            if (a <= limit) {
                ticks.add(a);
            }
        } else {
            for (long t = b; t <= limit; t += a) {
                ticks.add(t);
            }
        }
        return ticks.stream().mapToLong(Long::longValue).toArray();
    }
