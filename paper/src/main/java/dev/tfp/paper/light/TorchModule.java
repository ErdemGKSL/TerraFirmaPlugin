/**
 * PAR-HEAT-10: torches. Registers the {@link TorchDevice} kinds {@code tfp:torch} and {@code tfp:wall_torch}, provides
 * {@link TorchService} (lazy burnout to the dead torches, relight, douse), registers its {@code FireLightable} with the
 * fire starting service, catches the lit torches of a loaded chunk up and listens for the held torch's weak fire start.
 * Needs the tags, device, catch-up and fire modules before it in the service file.
 *
 * <p>The CraftEngine blocks and items ({@code tfp:torch}, {@code tfp:wall_torch}, {@code tfp:dead_torch},
 * {@code tfp:dead_wall_torch}) are generated by {@code tools/datagen} {@code light/TorchBlocks} and loaded with
 * PAR-HEAT-21; until then no torch block exists and nothing here runs.
 */
public final class TorchModule implements FeatureModule {
    public static final String ID = "torch";
    /** TFC {@code TFCTags.Items.CAN_BE_LIT_ON_TORCH} ({@code #c:rods/wooden}). */
    public static final String CAN_BE_LIT_ON_TORCH = "tfc:can_be_lit_on_torch";
    /** TFC {@code torchTicks} default (not configurable yet: ledger). */
    public static final int TORCH_TICKS = LightSourceRules.DEFAULT_TORCH_TICKS;

    @Override
    public String id() {
        return ID;
    }

    @Override
    public void enable(ModuleContext context) {
        DeviceService devices = context.services().require(DeviceService.class);
        Tags tags = context.services().require(Tags.class);
        CustomBlocks blocks = context.integrations().customBlocks();
        AtomicReference<TorchService> ref = new AtomicReference<>();
        PaperTorchEffects effects = new PaperTorchEffects(context.scheduler(), ref::get);
        TorchDevice device = new TorchDevice(new TorchDevice.Services(() -> TORCH_TICKS,
            stack -> tags.is(stack, CAN_BE_LIT_ON_TORCH),
            () -> context.integrations().customItems().create(TorchListener.TORCH_ITEM, 1).orElse(ItemStack.empty()),
            effects));
        device.kinds().forEach(devices::register);
        TorchService service = new TorchService(blocks, devices, device, () -> context.clock().get().playerTicks(),
            () -> TORCH_TICKS, context::regions, context.scheduler().cpuExecutor(),
            new CommitBudget(TorchService.BUDGET_NANOS, System::nanoTime));
        ref.set(service);
        context.services().provide(TorchService.class, service);
        Optional<FireStarting> fire = context.services().get(FireStarting.class);
        fire.ifPresent(f -> f.register(service.lightable()));
        blocks.onChunkLoad(chunk -> {
            for (TorchService.Waiting w : service.chunkLoaded(chunk, lazyBlocks(context, chunk))) {
                effects.burnoutIn(w.block(), w.ticks());
            }
        });
        context.listen(new TorchListener(stack -> context.integrations().customItems().idOf(stack), blocks,
            (block, face, player, stack) -> {
                if (fire.isPresent()) {
                    fire.get().start(block, face, player, stack,
                        FireStarting.Starter.fixed(FireStart.Strength.WEAK, FireStart.NO_FIREPIT), r -> { });
                } else {
                    service.light(block);
                }
            }));
    }

    /** The devices of the chunk's lazy block index (PAR-INFRA-25 lists every device there). Region thread. */
    static Collection<BlockPos> lazyBlocks(ModuleContext context, Chunk chunk) {
        return context.services().get(CatchUpService.class).flatMap(c -> c.index(chunk))
            .map(index -> index.entries().entrySet().stream()
                .filter(e -> CatchUpModule.DEVICE_KIND.equals(e.getValue()))
                .map(Map.Entry::getKey).toList())
            .orElse(List.of());
    }
}
