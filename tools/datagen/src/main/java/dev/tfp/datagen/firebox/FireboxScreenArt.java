/**
 * PAR-HEAT-12: the firebox screen's art (TFC {@code FireboxScreen}) for a 5-row chest, in the layout of
 * {@link FireboxScreenLayout} ({@code configuration/firebox/firebox_gui.yml}).
 *
 * <ul>
 *   <li>{@code tfp:gui/firebox}: TFC's {@code firebox.png} re-laid out: the panel, the 4 x 4 slot block and TFC's
 *       thermometer sprite moved up one pixel onto the chest grid, the player inventory moved down one pixel onto the
 *       chest's rows.</li>
 *   <li>{@code tfp:gui/firebox_thermometer}: the 52-frame indicator strip (frame k: TFC's indicator k pixels up).</li>
 * </ul>
 */
public final class FireboxScreenArt {
    public static final String TEXTURE = "src/main/resources/assets/tfc/textures/gui/firebox.png";
    public static final String THERMOMETER_SPRITE = "src/main/resources/assets/tfc/textures/gui/sprites/container/thermometer.png";
    public static final String INDICATOR_SPRITE =
        "src/main/resources/assets/tfc/textures/gui/sprites/container/thermometer_indicator.png";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/FireboxScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/FireboxContainer.java";
    public static final String ENTITY = "src/main/java/net/dries007/tfc/common/blockentities/FireboxBlockEntity.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/firebox/firebox_gui.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";

    /** TFC's slot block frame: one pixel up and left of the first item position, 18 per slot. */
    static final int GRID_X = FireboxScreenLayout.TFC_SLOT_X - 1;
    static final int GRID_Y = FireboxScreenLayout.TFC_SLOT_Y - 1;
    static final int GRID_W = FireboxScreenLayout.COLUMNS * ChestGeometry.SLOT;
    static final int GRID_H = FireboxScreenLayout.ROWS * ChestGeometry.SLOT;
    /** A plain panel row of TFC's art. */
    static final int PLAIN_ROW = 10;
    static final int BORDER = 4;
    /** TFC's player inventory part, from the first slot frame row to above the bottom border. */
    static final int INVENTORY_TOP = 84 + FireboxScreenLayout.TFC_INVENTORY_OFFSET - 1;
    static final int INVENTORY_BOTTOM = FireboxScreenLayout.TFC_HEIGHT - BORDER;

    private FireboxScreenArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(TEXTURE) && tfc.exists(THERMOMETER_SPRITE) && tfc.exists(INDICATOR_SPRITE) && tfc.exists(SCREEN)
            && tfc.exists(CONTAINER);
    }

    /** Writes the images and their YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkSources(tfc);
        BufferedImage src = read(tfc.read(TEXTURE), TEXTURE);
        BufferedImage thermometer = read(tfc.read(THERMOMETER_SPRITE), THERMOMETER_SPRITE);
        BufferedImage indicator = read(tfc.read(INDICATOR_SPRITE), INDICATOR_SPRITE);
        Map<String, Object> images = new LinkedHashMap<>();
        put(out, images, FireboxScreenLayout.BACKGROUND, background(src, thermometer));
        put(out, images, FireboxScreenLayout.THERMOMETER, indicatorStrip(indicator));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    /** The 176 x 204 window. */
    static BufferedImage background(BufferedImage src, BufferedImage thermometer) {
        int w = ChestGeometry.WIDTH;
        int h = FireboxScreenLayout.CHEST.height();
        if (src.getWidth() < w || src.getHeight() < FireboxScreenLayout.TFC_HEIGHT) {
            throw new DatagenException(TEXTURE + ": smaller than TFC's 176 x 202 screen");
        }
        if (thermometer.getWidth() != FireboxScreenLayout.THERMOMETER_WIDTH
                || thermometer.getHeight() != FireboxScreenLayout.THERMOMETER_HEIGHT) {
            throw new DatagenException(THERMOMETER_SPRITE + " is no longer 17 x 74");
        }
        checkPlain(src, PLAIN_ROW);
        for (int y = GRID_Y + GRID_H; y < INVENTORY_TOP; y++) {
            checkPlain(src, y); // between the slot block and the inventory: nothing is cut
        }
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < h; y++) {
            copy(src, out, 0, PLAIN_ROW, w, 1, 0, y);
        }
        copy(src, out, 0, 0, w, BORDER, 0, 0); // top border
        copy(src, out, 0, INVENTORY_TOP, w, INVENTORY_BOTTOM - INVENTORY_TOP, 0,
            INVENTORY_TOP + FireboxScreenLayout.DY_PLAYER); // the player inventory
        copy(src, out, 0, FireboxScreenLayout.TFC_HEIGHT - BORDER, w, BORDER, 0, h - BORDER); // bottom border
        copy(src, out, GRID_X, GRID_Y, GRID_W, GRID_H, GRID_X, GRID_Y + FireboxScreenLayout.DY); // the slot block
        over(thermometer, out, FireboxScreenLayout.TFC_THERMOMETER_X,
            FireboxScreenLayout.TFC_THERMOMETER_Y + FireboxScreenLayout.DY); // TFC's blitSprite(THERMOMETER)
        return out;
    }

    /** The indicator strip: frame 0 empty, frame k the 15 x 5 indicator {@code 51 - k} pixels below the frame top. */
    static BufferedImage indicatorStrip(BufferedImage indicator) {
        if (indicator.getWidth() != ProgressFrames.THERMOMETER_WIDTH || indicator.getHeight() != ProgressFrames.THERMOMETER_HEIGHT) {
            throw new DatagenException(INDICATOR_SPRITE + " is no longer 15 x 5");
        }
        GuiImage t = FireboxScreenLayout.THERMOMETER;
        BufferedImage out = new BufferedImage(t.pngWidth(), t.pngHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int k = 1; k < ProgressFrames.THERMOMETER_FRAMES; k++) {
            int fx = t.frameCol(k) * t.width();
            int fy = t.frameRow(k) * t.height() + ProgressFrames.thermometerOffset(k);
            copy(indicator, out, 0, 0, ProgressFrames.THERMOMETER_WIDTH, ProgressFrames.THERMOMETER_HEIGHT, fx, fy);
        }
        keepAdvance(out, t.width(), t.height());
        return out;
    }

    /** Alpha of the width marker: counted by the client's glyph width scan, discarded by the text shader (below 0.1). */
    static final int MARKER = 0x01000000;

    /**
     * A frame with an empty right column gets a nearly transparent pixel (alpha 1) in its bottom-right corner, so the
     * client measures the glyph's full advance (as {@code FirepitScreenArt.keepAdvance}).
     */
    static void keepAdvance(BufferedImage png, int w, int h) {
        for (int fy = 0; fy < png.getHeight(); fy += h) {
            for (int fx = 0; fx < png.getWidth(); fx += w) {
                boolean any = false;
                for (int y = fy; y < fy + h && !any; y++) {
                    any = (png.getRGB(fx + w - 1, y) >>> 24) != 0;
                }
                if (!any) {
                    png.setRGB(fx + w - 1, fy + h - 1, MARKER);
                }
            }
        }
    }

    /** TFC's numbers the layout assumes; a TFC change fails here instead of misaligning. */
    static void checkSources(TfcCheckout tfc) {
        String container = tfc.readString(CONTAINER).replaceAll("\\s+", " ");
        String screen = tfc.readString(SCREEN).replaceAll("\\s+", " ");
        String entity = tfc.readString(ENTITY);
        need(container, CONTAINER, "new CallbackSlot(blockEntity, i, 18 * (i % " + FireboxScreenLayout.COLUMNS + ") + "
            + FireboxScreenLayout.TFC_SLOT_X + ", 18 * (i / " + FireboxScreenLayout.COLUMNS + ") + "
            + FireboxScreenLayout.TFC_SLOT_Y + ")");
        need(container, CONTAINER, ".init(playerInventory, " + FireboxScreenLayout.TFC_INVENTORY_OFFSET + ")");
        need(screen, SCREEN, "imageHeight += " + FireboxScreenLayout.TFC_INVENTORY_OFFSET + ";");
        need(screen, SCREEN, "graphics.blitSprite(THERMOMETER, leftPos + " + FireboxScreenLayout.TFC_THERMOMETER_X
            + ", topPos + " + FireboxScreenLayout.TFC_THERMOMETER_Y + ", " + FireboxScreenLayout.THERMOMETER_WIDTH + ", "
            + FireboxScreenLayout.THERMOMETER_HEIGHT + ");");
        need(screen, SCREEN, "graphics.blitSprite(THERMOMETER_INDICATOR, leftPos + " + FireboxScreenLayout.TFC_INDICATOR_X
            + ", topPos + " + FireboxScreenLayout.TFC_INDICATOR_BOTTOM + " - temperature, "
            + ProgressFrames.THERMOMETER_WIDTH + ", " + ProgressFrames.THERMOMETER_HEIGHT + ");");
        need(screen, SCREEN, "leftPos + " + FireboxScreenLayout.TFC_STATUS_X + ", topPos + " + FireboxScreenLayout.TFC_STATUS_Y);
        need(entity, ENTITY, "public static final int SLOTS = " + FireboxSim.SLOTS + ";");
    }

    private static void need(String text, String file, String snippet) {
        if (!text.contains(snippet)) {
            throw new DatagenException(file + " no longer contains \"" + snippet + "\": the firebox screen art is stale");
        }
    }

    private static void checkPlain(BufferedImage src, int y) {
        int c = src.getRGB(BORDER, y);
        for (int x = BORDER; x < ChestGeometry.WIDTH - BORDER; x++) {
            if (src.getRGB(x, y) != c) {
                throw new DatagenException(TEXTURE + ": row " + y + " is not plain panel; the re-layout would cut art");
            }
        }
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        images.put(image.id(), e);
    }

    static BufferedImage read(byte[] bytes, String what) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(bytes));
            if (img == null) {
                throw new DatagenException(what + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            copy(img, argb, 0, 0, img.getWidth(), img.getHeight(), 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void copy(BufferedImage src, BufferedImage dst, int sx, int sy, int w, int h, int dx, int dy) {
        for (int j = 0; j < h; j++) {
            for (int i = 0; i < w; i++) {
                int x = dx + i;
                int y = dy + j;
                if (x >= 0 && y >= 0 && x < dst.getWidth() && y < dst.getHeight()) {
                    dst.setRGB(x, y, src.getRGB(sx + i, sy + j));
                }
            }
        }
    }

    /** Draws {@code sprite} over {@code dst} at (dx, dy) with alpha blending (TFC blits sprites over the panel). */
    private static void over(BufferedImage sprite, BufferedImage dst, int dx, int dy) {
        for (int j = 0; j < sprite.getHeight(); j++) {
            for (int i = 0; i < sprite.getWidth(); i++) {
                int s = sprite.getRGB(i, j);
                int a = s >>> 24;
                if (a == 0) {
                    continue;
                }
                int d = dst.getRGB(dx + i, dy + j);
                if (a == 255) {
                    dst.setRGB(dx + i, dy + j, s);
                    continue;
                }
                int r = blend((s >> 16) & 255, (d >> 16) & 255, a);
                int g = blend((s >> 8) & 255, (d >> 8) & 255, a);
                int b = blend(s & 255, d & 255, a);
                dst.setRGB(dx + i, dy + j, 0xFF000000 | (r << 16) | (g << 8) | b);
            }
        }
    }

    private static int blend(int s, int d, int a) {
        return (s * a + d * (255 - a) + 127) / 255;
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
