package dev.tfp.core.animal;

import dev.tfp.core.livestock.LivestockAge;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;
import java.util.Optional;

/**
 * The BetterModel model of a TFC animal for its gender and stage (PAR-FAUNA-03): the texture of its age (TFC
 * {@code getTextureForAge}), the male's own texture, the baby texture, and the parts shown by gender are each a model of
 * their own, listed in {@code model_variants.tsv} (generated by {@code tools/models/publish_models.py}).
 */
public final class ModelVariants {
    public static final String RESOURCE = "/dev/tfp/core/animal/model_variants.tsv";
    private static final ModelVariants INSTANCE = load();

    private final Map<String, String> byKey;

    ModelVariants(Map<String, String> byKey) {
        this.byKey = Map.copyOf(byKey);
    }

    public static ModelVariants get() {
        return INSTANCE;
    }

    /**
     * The model id for {@code species} ({@code tfc:cow}) of the given gender and stage, empty if the species has no
     * model (it is drawn as its carrier).
     */
    public Optional<String> pick(String species, boolean male, LivestockAge age) {
        String key = key(species, male, age);
        return Optional.ofNullable(byKey.get(key));
    }

    static String key(String species, boolean male, LivestockAge age) {
        String name = species.startsWith("tfc:") ? species.substring(4) : species;
        return name + "\t" + (male ? "male" : "female") + "\t" + age.name().toLowerCase(java.util.Locale.ROOT);
    }

    public int size() {
        return byKey.size();
    }

    /** Every distinct model id of the table. */
    public java.util.Set<String> modelIds() {
        return new java.util.TreeSet<>(byKey.values());
    }

    static ModelVariants parse(String text) {
        Map<String, String> map = new HashMap<>();
        for (String line : text.split("\n")) {
            if (line.isBlank() || line.startsWith("#")) {
                continue;
            }
            String[] c = line.split("\t");
            if (c.length != 4) {
                throw new IllegalStateException("bad model variant row: " + line);
            }
            map.put(c[0] + "\t" + c[1] + "\t" + c[2], c[3]);
        }
        return new ModelVariants(map);
    }

    private static ModelVariants load() {
        try (InputStream in = ModelVariants.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                return new ModelVariants(Map.of());
            }
            return parse(new String(in.readAllBytes(), StandardCharsets.UTF_8));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
