package dev.tfp.datagen;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.regex.Pattern;

/**
 * X-I18N-01 (data slice): TFC's language files as plugin data, one file per locale: {@code lang/<locale>.json}, plus
 * {@code lang/index.json} with the coverage of each locale.
 *
 * <p>Every TFC locale file is read as it is: its translation keys are kept verbatim (TFC's {@code tfc.} and
 * {@code block.tfc.} keys are not renamed, so the keys match TFC's own files and its English text). The
 * {@code __comment__} entries that mcresources writes into the files are dropped; they are not translations. Keys are
 * written in sorted order, and each file is a flat object of key to string.
 *
 * <p>Coverage is counted against {@code en_us}: {@code keys} is the number of translation keys in the locale,
 * {@code missing} the {@code en_us} keys the locale lacks, and {@code extra} the locale keys that {@code en_us} does not
 * have. A missing key is a gap to review, not an error: TFC's translations are not all complete. An extra key is reported,
 * not dropped. The English file is the source; it must exist.
 *
 * <p>These files are not vanilla resources. They are under {@code lang/}, which is {@link OutputTree#OWNED} with its own
 * root, so the server does not read them as a resource pack or a datapack. The client lang that CraftEngine ships is
 * {@link AssetPipeline}'s job and is unchanged.
 *
 * <p>Missing or unexpected data is an error: no lang folder, no {@code en_us.json}, a file that is not {@code <locale>.json}
 * with a locale id like {@code en_us}, a nested file, a file that is not a JSON object, a translation that is not a
 * string, or an empty English file.
 */
final class Locales {
    static final String SOURCE = TfcCheckout.ASSETS + "lang/";
    static final String OUTPUT_DIR = "lang/";
    static final String INDEX = OUTPUT_DIR + "index.json";
    static final String SOURCE_LOCALE = "en_us";

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (" + SOURCE + "). Do not edit: fix the generator and regenerate. "
        + "Translation keys are TFC's own, verbatim. Coverage is counted against en_us.";
    private static final Pattern LOCALE_FILE = Pattern.compile("[a-z]{2}_[a-z]{2}\\.json");
    /** mcresources writes {@code __comment__}, {@code __comment1__}, ... into the files; they are not translations. */
    private static final Pattern COMMENT_KEY = Pattern.compile("__comment\\d*__");

    /**
     * One locale: its id (e.g. {@code de_de}), its translations in key order, and its coverage against en_us.
     *
     * @param missing the en_us keys this locale does not have
     * @param extra   the keys this locale has that en_us does not
     */
    record Locale(String id, TreeMap<String, String> entries, int missing, int extra) {
        int keys() {
            return entries.size();
        }
    }

    private Locales() {
    }

    /** Writes every locale file and the index. Returns the number of locales. Fails when TFC's lang data is missing or unexpected. */
    static int run(TfcCheckout tfc, OutputTree out) {
        List<Locale> locales = read(tfc);
        JsonObject index = new JsonObject();
        index.addProperty("comment", HEADER);
        index.addProperty("source", SOURCE_LOCALE);
        int enKeys = locales.get(0).keys(); // en_us sorts first
        index.addProperty("en_us_keys", enKeys);
        JsonArray list = new JsonArray();
        for (Locale l : locales) {
            JsonObject entries = new JsonObject();
            l.entries().forEach(entries::addProperty);
            out.put(OUTPUT_DIR + l.id() + ".json", Json.write(entries));

            JsonObject row = new JsonObject();
            row.addProperty("locale", l.id());
            row.addProperty("file", OUTPUT_DIR + l.id() + ".json");
            row.addProperty("keys", l.keys());
            row.addProperty("missing", l.missing());
            row.addProperty("extra", l.extra());
            list.add(row);
        }
        index.add("locales", list);
        out.put(INDEX, Json.write(index));
        return locales.size();
    }

    /**
     * Every locale of the checkout, English first and the rest by id. Fails on any missing or unexpected data
     * (see the class comment).
     */
    static List<Locale> read(TfcCheckout tfc) {
        List<String> files = tfc.list(SOURCE);
        if (files.isEmpty()) {
            throw new DatagenException("TFC has no language files at " + SOURCE + " (the pinned checkout is incomplete)");
        }
        Map<String, TreeMap<String, String>> byId = new TreeMap<>();
        for (String file : files) {
            String rest = file.substring(SOURCE.length());
            if (rest.indexOf('/') >= 0 || !LOCALE_FILE.matcher(rest).matches()) {
                throw new DatagenException("unexpected language file " + file + " (expected " + SOURCE + "<locale>.json)");
            }
            String id = rest.substring(0, rest.length() - ".json".length());
            byId.put(id, entries(tfc.readString(file), file));
        }
        TreeMap<String, String> en = byId.get(SOURCE_LOCALE);
        if (en == null) {
            throw new DatagenException("TFC has no " + SOURCE_LOCALE + ".json at " + SOURCE + " (the pinned checkout is incomplete)");
        }
        if (en.isEmpty()) {
            throw new DatagenException(SOURCE + SOURCE_LOCALE + ".json has no translation keys");
        }
        Set<String> enKeys = en.keySet();
        List<Locale> out = new ArrayList<>();
        for (Map.Entry<String, TreeMap<String, String>> e : byId.entrySet()) {
            Set<String> keys = e.getValue().keySet();
            int missing = 0;
            for (String k : enKeys) {
                if (!keys.contains(k)) {
                    missing++;
                }
            }
            int extra = 0;
            for (String k : keys) {
                if (!enKeys.contains(k)) {
                    extra++;
                }
            }
            out.add(new Locale(e.getKey(), e.getValue(), missing, extra));
        }
        // English first, then the rest by id (the TreeMap order already puts them in id order).
        out.sort((a, b) -> a.id().equals(SOURCE_LOCALE) ? -1 : b.id().equals(SOURCE_LOCALE) ? 1 : a.id().compareTo(b.id()));
        return out;
    }

    /** One locale file: a flat object of string values, comments dropped, keys sorted. */
    static TreeMap<String, String> entries(String text, String source) {
        JsonElement root = Json.parse(text, source);
        if (!root.isJsonObject()) {
            throw new DatagenException(source + ": language file is not a JSON object");
        }
        TreeMap<String, String> out = new TreeMap<>();
        for (Map.Entry<String, JsonElement> e : root.getAsJsonObject().entrySet()) {
            if (COMMENT_KEY.matcher(e.getKey()).matches()) {
                continue;
            }
            JsonElement v = e.getValue();
            if (!v.isJsonPrimitive() || !v.getAsJsonPrimitive().isString()) {
                throw new DatagenException(source + ": translation " + e.getKey() + " is not a string");
            }
            out.put(e.getKey(), v.getAsString());
        }
        return out;
    }
}
