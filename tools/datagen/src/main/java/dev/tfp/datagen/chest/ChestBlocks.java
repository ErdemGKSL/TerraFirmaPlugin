package dev.tfp.datagen.chest;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import dev.tfp.datagen.device.DeviceAppearance;
import dev.tfp.datagen.device.DeviceBlockSpec;
import dev.tfp.datagen.device.DeviceLoot;
import dev.tfp.datagen.device.DeviceProperty;
import dev.tfp.datagen.device.DeviceSound;
import dev.tfp.datagen.device.DeviceYaml;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * PAR-DECO-04: the chest and the trapped chest of the 20 woods ({@code wood/chest/<wood>}, {@code wood/trapped_chest/<wood>})
 * as CraftEngine device blocks, one {@code configuration/chest/<wood>.yml} per wood.
 *
 * <ul>
 *   <li>TFC draws a chest with vanilla's chest block entity renderer, which a vanilla client cannot do for a custom block
 *       (and the carrier selector bans the chest states for that reason). Each block is a full-collision barrier carrier
 *       (the one the renderer cubes of PAR-INFRA-17 use) and shows its chest as one item display of the models of
 *       {@link ChestModels} (single, left, right), turned by the facing.</li>
 *   <li>States: {@code facing} (4), {@code type} (single, left, right) as TFC's {@code ChestBlock}, and {@code open}
 *       (PAR-DECO-26: set while a player has the chest open; its model has the lid turned up as vanilla's openness 1);
 *       not waterlogged (ledger). The block has the {@code tfp:device} behaviour: 18 slots per chest, the double chest and the placement
 *       are the plugin's {@code chest} module.</li>
 *   <li>TFC's strength (2.5), wood sounds, the axe tag, the plain self drop and names; the item is the block item.</li>
 * </ul>
 */
public final class ChestBlocks {
    public static final List<String> KINDS = List.of("chest", "trapped_chest");
    public static final List<String> TYPES = List.of("single", "left", "right");
    public static final List<String> FACINGS = List.of("north", "east", "south", "west");
    /** The invisible full-collision carrier (PAR-INFRA-17's renderer cubes use it too). */
    public static final String CARRIER = "minecraft:barrier";

    static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/chest/";
    static final String RP = PACK + "resourcepack/assets/tfp/";
    static final String LANG_RP = PACK + "resourcepack/assets/tfp_chest/lang/";
    static final String BLOCKSTATES = TfcCheckout.ASSETS + "blockstates/wood/";
    static final String TEXTURES = TfcCheckout.ASSETS + "textures/entity/chest/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String WOOD_JAVA = "src/main/java/net/dries007/tfc/common/blocks/wood/Wood.java";
    static final String MINEABLE = TfcCheckout.GENERATED + "data/minecraft/tags/block/mineable/";
    private static final Pattern STRENGTH = Pattern.compile(
        "^ {8}(CHEST|TRAPPED_CHEST)\\(\\(self, wood\\) -> new TFC(?:Trapped)?ChestBlock\\(properties\\(wood\\)\\.strength\\(([0-9.]+)[fF]\\)",
        Pattern.MULTILINE);
    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ " + TfcCheckout.PINNED_COMMIT.substring(0, 9)
        + ". Do not edit: fix the generator and regenerate.\nPAR-DECO-04: chests and trapped chests.";

    private ChestBlocks() {
    }

    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(WOOD_JAVA) && !tfc.list(BLOCKSTATES + "chest/").isEmpty()
            && !tfc.list(BLOCKSTATES + "trapped_chest/").isEmpty() && tfc.exists(TEXTURES + "normal/oak.png")
            && tfc.exists(TEXTURES + "trapped_right/oak.png");
    }

    /** The woods that have a chest blockstate. */
    public static List<String> woods(TfcCheckout tfc) {
        String dir = BLOCKSTATES + "chest/";
        TreeSet<String> woods = new TreeSet<>();
        for (String f : tfc.list(dir)) {
            if (f.endsWith(".json")) {
                woods.add(f.substring(dir.length(), f.length() - ".json".length()));
            }
        }
        return new ArrayList<>(woods);
    }

    /** {@code wood/chest/oak}. */
    public static String path(String kind, String wood) {
        return "wood/" + kind + "/" + wood;
    }

    /** The number of blocks written: two per wood. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        List<String> woods = woods(tfc);
        BigDecimal strength = strength(tfc);
        int count = 0;
        for (String wood : woods) {
            Map<String, Object> blocks = new LinkedHashMap<>();
            Map<String, Object> items = new LinkedHashMap<>();
            for (String kind : KINDS) {
                String path = path(kind, wood);
                DeviceBlockSpec spec = spec(tfc, kind, wood, strength);
                Map<String, Object> entry = DeviceYaml.templated(spec);
                copyModels(tfc, out, kind, wood);
                merge(entry, blocks, items);
                count++;
            }
            Map<String, Object> root = new LinkedHashMap<>();
            root.put("blocks", blocks);
            root.put("items", items);
            out.put(CONFIG + wood + ".yml", Yaml.write(HEADER, root));
        }
        writeLang(tfc, out, woods);
        return count;
    }

    @SuppressWarnings("unchecked")
    private static void merge(Map<String, Object> entry, Map<String, Object> blocks, Map<String, Object> items) {
        blocks.putAll((Map<String, Object>) entry.get("blocks"));
        items.putAll((Map<String, Object>) entry.get("items"));
    }

    static String id(String path) {
        return Json.TO_NS + ":" + path;
    }

    /** {@code tfp:render/wood/chest/left/oak}; the lid-open model of a shape is {@code .../left_open/...} ({@code single_open}). */
    static String renderId(String kind, String type, String wood) {
        return Json.TO_NS + ":render/wood/" + kind + "/" + type + "/" + wood;
    }

    /** The block model path of a shape: {@code block/wood/chest/oak} (single) or {@code block/wood/chest/left/oak}. */
    static String modelPath(String kind, String type, String wood) {
        return "block/wood/" + kind + "/" + (type.equals("single") ? "" : type + "/") + wood;
    }

    /** The shape name of the lid-open model of {@code type}: {@code single_open}, {@code left_open}, {@code right_open}. */
    static String openType(String type) {
        return type + "_open";
    }

    /** The block model path of the lid-open shape: {@code block/wood/chest/single_open/oak}, {@code .../left_open/oak}. */
    static String openModelPath(String kind, String type, String wood) {
        return "block/wood/" + kind + "/" + openType(type) + "/" + wood;
    }

    static String langKey(String path) {
        return "block." + Json.TO_NS + "." + path.replace('/', '.');
    }

    /** The turn of the item display of a chest facing {@code facing}: the half turn of block-model displays minus its yaw. */
    static String rotation(String facing) {
        int yaw = switch (facing) {
            case "south" -> 0;
            case "west" -> 90;
            case "north" -> 180;
            case "east" -> 270;
            default -> throw new IllegalArgumentException(facing);
        };
        return "0," + Math.floorMod(180 - yaw, 360) + ",0";
    }

    static DeviceBlockSpec spec(TfcCheckout tfc, String kind, String wood, BigDecimal strength) {
        String path = path(kind, wood);
        DeviceBlockSpec.Builder b = DeviceBlockSpec.builder(id(path))
            .property(DeviceProperty.names("facing", FACINGS, "north"))
            .property(DeviceProperty.names("type", TYPES, "single"))
            .property(DeviceProperty.bool("open", false));
        DeviceAppearance.Carrier carrier = DeviceAppearance.Carrier.state(CARRIER);
        for (String type : TYPES) {
            b.renderItem(renderId(kind, type, wood), id(modelPath(kind, type, wood)));
            b.renderItem(renderId(kind, openType(type), wood), id(openModelPath(kind, type, wood)));
            for (String facing : FACINGS) {
                b.appearance(DeviceAppearance.rendered(facing + "_" + type, carrier,
                    List.of(DeviceAppearance.Renderer.item(renderId(kind, type, wood)).rotated(rotation(facing)))));
                b.appearance(DeviceAppearance.rendered(facing + "_" + type + "_open", carrier,
                    List.of(DeviceAppearance.Renderer.item(renderId(kind, openType(type), wood)).rotated(rotation(facing)))));
            }
        }
        return b.everyState(s -> s.get("facing") + "_" + s.get("type") + (s.get("open").equals("true") ? "_open" : ""), null)
            .settings(DeviceBlockSpec.Settings.of(strength.toPlainString(), strength.toPlainString(), DeviceSound.WOOD, tool(tfc, path)))
            .loot(DeviceLoot.fromTfc(tfc, path))
            .deviceBehaviour()
            .blockItem(langKey(path))
            .build();
    }

    /** TFC's {@code strength(2.5F)} of the chest and the trapped chest (hardness and resistance), read from Wood.java. */
    static BigDecimal strength(TfcCheckout tfc) {
        Matcher m = STRENGTH.matcher(tfc.readString(WOOD_JAVA));
        BigDecimal found = null;
        int n = 0;
        while (m.find()) {
            BigDecimal s = new BigDecimal(m.group(2));
            if (found != null && found.compareTo(s) != 0) {
                throw new DatagenException(WOOD_JAVA + ": the chest and the trapped chest differ in strength");
            }
            found = s;
            n++;
        }
        if (n != 2) {
            throw new DatagenException(WOOD_JAVA + ": CHEST and TRAPPED_CHEST no longer match " + STRENGTH.pattern());
        }
        return found;
    }

    /** The one {@code minecraft:mineable/<tool>} tag of TFC's generated data that holds the block. */
    static String tool(TfcCheckout tfc, String path) {
        String found = null;
        for (String t : List.of("axe", "hoe", "pickaxe", "shovel")) {
            String src = MINEABLE + t + ".json";
            for (JsonElement v : Json.parse(tfc.readString(src), src).getAsJsonObject().getAsJsonArray("values")) {
                if (v.isJsonPrimitive() && v.getAsString().equals(Json.FROM_NS + ":" + path)) {
                    if (found != null) {
                        throw new DatagenException("tfc:" + path + " is in two mineable tags: " + found + ", " + t);
                    }
                    found = t;
                }
            }
        }
        if (found == null) {
            throw new DatagenException("tfc:" + path + " is in no minecraft:mineable tag");
        }
        return found;
    }

    /** The three models of a chest kind and wood, the item model, and the textures (TFC's entity textures). */
    static void copyModels(TfcCheckout tfc, OutputTree out, String kind, String wood) {
        String tex = kind.equals("chest") ? "normal" : "trapped";
        String particle = "block/wood/planks/" + wood;
        for (String type : TYPES) {
            String from = TEXTURES + tex + (type.equals("single") ? "" : "_" + type) + "/" + wood + ".png";
            if (!tfc.exists(from)) {
                throw new DatagenException("TFC has no chest texture " + from);
            }
            String model = modelPath(kind, type, wood);
            out.put(RP + "textures/" + model + ".png", tfc.read(from));
            out.put(RP + "models/" + model + ".json", ChestModels.model(model, particle, type, false));
            // the lid-open shape draws the same texture
            String open = openModelPath(kind, type, wood);
            out.put(RP + "textures/" + open + ".png", tfc.read(from));
            out.put(RP + "models/" + open + ".json", ChestModels.model(open, particle, type, true));
        }
        out.put(RP + "models/item/" + path(kind, wood) + ".json", ChestModels.itemModel(modelPath(kind, "single", wood)));
    }

    static void writeLang(TfcCheckout tfc, OutputTree out, List<String> woods) {
        List<String> paths = new ArrayList<>();
        for (String w : woods) {
            for (String kind : KINDS) {
                paths.add(path(kind, w));
            }
        }
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            Map<String, String> keys = new TreeMap<>();
            for (String path : paths) {
                String tfcKey = "block." + Json.FROM_NS + "." + path.replace('/', '.');
                if (src.has(tfcKey)) {
                    keys.put(langKey(path), src.get(tfcKey).getAsString());
                } else if (locale.equals("en_us")) {
                    throw new DatagenException("TFC has no English name " + tfcKey);
                }
            }
            if (!keys.isEmpty()) {
                JsonObject o = new JsonObject();
                keys.forEach(o::addProperty);
                out.put(LANG_RP + locale + ".json", Json.write(o));
            }
        }
    }
}
