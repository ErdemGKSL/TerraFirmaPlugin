    private static final String RP = "craftengine/tfp/resourcepack/assets/tfp/";
    private static final String SOIL_RP = "craftengine/tfp/resourcepack/assets/tfp_soil/";
    private static final VisualDemand EARLIER = new VisualDemand("rock/raw/granite", "", List.of());
    private static TfcCheckout tfc;
