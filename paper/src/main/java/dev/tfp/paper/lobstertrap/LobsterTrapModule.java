/**
 * PAR-FAUNA-19: lobster traps. Registers the {@link LobsterTrapDevice} kind {@code tfp:lobster_trap}, TFC's
 * {@code EnterLobsterTrapGoal} for the four animals of {@code tfc:caught_in_lobster_traps} (isopod, lobster, crayfish, horseshoe crab:
 * {@link EnterTrapGoal}) and a chunk-load callback that registers the baited traps of a loaded chunk for them. The CraftEngine block
 * {@code tfp:lobster_trap} (properties {@code facing}, {@code trap}, {@code fluid}) is generated by PAR-FAUNA-36 (it needs a hitbox
 * demand row); until it exists the kind is registered and idle.
 */
public final class LobsterTrapModule implements FeatureModule {
    public static final String ID = "lobstertrap";
    static final String BAIT_TAG = "tfc:lobster_bait";
    static final String JUNK_TAG = "tfc:lobster_trap_junk";

    private ModuleContext ctx;
    private Tags tags;
    private DeviceService devices;
    private Scheduler scheduler;
    private final TrapFinder finder = new TrapFinder();
    private final AtomicReference<DeviceKind<LobsterTrapState>> kind = new AtomicReference<>();
    private LobsterTrapDevice.Services services;

    @Override
    public String id() {
        return ID;
    }

    @Override
    public void enable(ModuleContext context) {
        this.ctx = context;
        this.devices = context.services().require(DeviceService.class);
        this.tags = context.services().require(Tags.class);
        this.scheduler = context.scheduler();
        CustomBlocks blocks = context.integrations().customBlocks();
        AnimalService animals = ((TfpPlugin) context.plugin()).animals();
        PaperTrapEffects effects = new PaperTrapEffects(scheduler, blocks, () -> context.integrations().blockVisuals(), finder);
        services = new LobsterTrapDevice.Services(stack -> tags.is(stack, BAIT_TAG), effects);
        kind.set(devices.register(LobsterTrapDevice.kind(services)));
        animals.behaviours().register(new Seeker(animals));
        Optional<CatchUpService> catchUp = context.services().get(CatchUpService.class);
        blocks.onChunkLoad(chunk -> catchUp.ifPresent(c -> chunkLoaded(chunk, c, blocks)));
    }

    /** The traps of a loaded chunk: each is read once and, when baited with a free slot, registered for the animals. */
    private void chunkLoaded(Chunk chunk, CatchUpService catchUp, CustomBlocks blocks) {
        Optional<LazyBlockIndex> index = catchUp.index(chunk);
        if (index.isEmpty()) {
            return;
        }
        World world = chunk.getWorld();
        for (Map.Entry<BlockPos, String> e : index.get().entries().entrySet()) {
            if (!CatchUpModule.DEVICE_KIND.equals(e.getValue())) {
                continue;
            }
            BlockPos p = e.getKey();
            Block block = world.getBlockAt(p.x(), p.y(), p.z());
            scheduler.region(world, chunk.getX(), chunk.getZ(), () -> {
                if (blocks.stateAt(block).map(s -> s.id().equals(LobsterTrapDevice.ID)).orElse(false)) {
                    devices.edit(block, kind.get(), (record, now) -> {
                        services.effects().baited(block, LobsterTrapDevice.canCatch(record));
                        return record;
                    });
                }
            });
        }
    }

    /** The animals that walk into a trap. */
    private final class Seeker implements SpeciesBehaviour, EnterTrapGoal.Site {
        private final AnimalService animals;

        Seeker(AnimalService animals) {
            this.animals = animals;
        }

        @Override
        public Set<String> species() {
            return LobsterTrap.CAUGHT_SPECIES.stream().map(s -> "tfc:" + s).collect(Collectors.toUnmodifiableSet());
        }

        @Override
        public boolean keepVanillaGoals() {
            return true;
        }

        @Override
        public List<GoalSpec> goals(Mob mob, dev.tfp.core.animal.AnimalRecord record) {
            return List.of(new GoalSpec(1, new EnterTrapGoal(mob, this)));
        }

        @Override
        public Optional<BlockPos> nearest(Mob mob) {
            Location at = mob.getLocation();
            return finder.nearest(mob.getWorld().getUID(), at.getX(), at.getY(), at.getZ(), EnterTrapGoal.SEARCH_RANGE);
        }

        @Override
        public void reached(Mob mob, BlockPos at) {
            World world = mob.getWorld();
            Optional<String> species = animals.record(mob).map(r -> r.species().substring(r.species().indexOf(':') + 1));
            if (species.isEmpty()) {
                return;
            }
            scheduler.region(world, at.x() >> 4, at.z() >> 4, () -> catchAt(mob, world.getBlockAt(at.x(), at.y(), at.z()), species.get()));
        }
    }

    /** On the trap's region: the catch, then the mob is discarded on its own thread. */
    void catchAt(Mob mob, Block block, String species) {
        LobsterTrapDevice.Caught[] caught = {null};
        UUID world = block.getWorld().getUID();
        Optional<?> stored = devices.edit(block, kind.get(), (record, now) -> {
            LobsterTrapDevice.Caught c = LobsterTrapDevice.catchMob(kind.get(), record, devices.stacks(), species, junk(),
                () -> ThreadLocalRandom.current().nextDouble(), this::stacks);
            if (c == null) {
                return record;
            }
            caught[0] = c;
            return c.record();
        });
        if (stored.isEmpty()) {
            finder.remove(world, new BlockPos(block.getX(), block.getY(), block.getZ())); // not a trap any more
        }
        if (caught[0] == null) {
            return;
        }
        services.effects().sound(block, TrapEffects.Sound.CAUGHT);
        services.effects().bubbles(block, 12);
        services.effects().show(block, LobsterTrapDevice.trapState(caught[0].record()));
        services.effects().baited(block, LobsterTrapDevice.canCatch(caught[0].record()));
        scheduler.entity(mob, mob::remove, () -> { });
    }

    private List<String> junk() {
        return tags.snapshot().registry().members(TagType.ITEM, TagSnapshot.normalise(JUNK_TAG)).stream().sorted().toList();
    }

    /** The yields as stacks: TFC's {@code tfc:} items are our {@code tfp:} items (the hunt module's mapping). */
    private List<ItemStack> stacks(List<HuntYield> yields) {
        List<LootDrop> drops = new ArrayList<>(yields.size());
        for (HuntYield y : yields) {
            String id = y.item().startsWith("tfc:") ? "tfp:" + y.item().substring("tfc:".length()) : y.item();
            drops.add(LootDrop.of(id, y.count()));
        }
        return ctx.services().get(LootService.class).map(l -> l.stacks(drops, null)).orElse(List.of());
    }
}
