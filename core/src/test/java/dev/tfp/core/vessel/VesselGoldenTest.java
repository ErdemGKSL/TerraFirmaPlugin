    private static List<String[]> rows(String block) {
        List<String[]> rows = new ArrayList<>();
        for (String line : block.strip().split("\n")) {
            String trimmed = line.strip();
            if (!trimmed.isEmpty()) {
                rows.add(trimmed.split("\\|", -1));
            }
        }
        return rows;
    }

    private static List<VesselSlot> slotsOf(List<float[]> items) {
        List<VesselSlot> slots = new ArrayList<>();
        for (float[] item : items) {
            slots.add(new VesselSlot("item", (int) item[0], item[1], null));
        }
        while (slots.size() < VesselRules.SLOTS) {
            slots.add(VesselSlot.EMPTY);
        }
        return slots;
    }

