    @Test
    void sealMatchesTfcRows() {
        int rows = 0;
        for (String line : SEAL.strip().split("\n")) {
            String[] f = line.trim().split("\\|");
            long ci = Long.parseLong(f[0]);
            long now = Long.parseLong(f[1]);
            FoodState food = new FoodState(ci, List.of());
            FoodState sealed = LargeVesselRules.sealFood(food, true, 1f, now, CFG);
            if (f[2].equals("-")) {
                assertThat(sealed.hasTrait(FoodTrait.PRESERVED)).as("row %s", line).isFalse();
                assertThat(sealed.isRotten(1f, now, CFG)).as("row %s", line).isTrue();
            } else {
                assertThat(sealed.creationDate()).as("row %s", line).isEqualTo(Long.parseLong(f[2]));
                assertThat(sealed.hasTrait(FoodTrait.PRESERVED)).as("row %s", line).isTrue();
            }
            rows++;
        }
        assertThat(rows).isEqualTo(80);
    }

    @Test
    void unsealMatchesTfcRows() {
        int rows = 0;
        for (String line : UNSEAL.strip().split("\n")) {
            String[] f = line.trim().split("\\|");
            long ci = Long.parseLong(f[0]);
            long now = Long.parseLong(f[1]);
            FoodState food = new FoodState(ci, List.of(FoodTrait.PRESERVED));
            FoodState unsealed = LargeVesselRules.sealFood(food, false, 1f, now, CFG);
            assertThat(unsealed.creationDate()).as("row %s", line).isEqualTo(Long.parseLong(f[2]));
            assertThat(unsealed.hasTrait(FoodTrait.PRESERVED)).as("row %s", line).isFalse();
            rows++;
        }
        assertThat(rows).isEqualTo(49);
    }

    @Test
    void neverDecayFlagsRoundFromTheSealTick() {
        // TFC: the flag is replaced by getRoundedCreationDate(now) before the formula. At tick 0 the window rounds to 7200,
        // then (1 - 2) * 0 + 2 * 7200 = 14400 for the seal.
        assertThat(FoodDecay.roundedCreationDate(0L, CFG.stackTicks())).isEqualTo(7200L);
        assertThat(LargeVesselRules.sealFood(new FoodState(FoodDecay.NEVER_DECAY_FLAG, List.of()), true, 1f, 0L, CFG)
            .creationDate()).isEqualTo(14400L);
    }
