    @Test
    void matchesTfcDecisions() {
        assertThat(ROWS.length).isEqualTo(12);
        for (Object[] row : ROWS) {
            long seed = (long) row[0];
            int cx = (int) row[1];
            int cz = (int) row[2];
            assertThat(decisions(seed, cx, cz)).as("seed %d chunk %d,%d", seed, cx, cz).isEqualTo((String) row[3]);
        }
    }

    /** The decisions of one chunk on the grid, as the letters of the golden rows. */
    static String decisions(long seed, int cx, int cz) {
        PositionalRandom fork = PositionalRandom.fork(new XoroshiroRandomSource(seed));
        int[] heights = new int[16];
        for (int i = 0; i < 16; i++) {
            heights[i] = 40 + Math.floorMod(i * 7 + cx * 3 - cz * 5, 32);
        }
        Aquifer aquifer = new Aquifer(cx, cz, MIN_Y, SEA_LEVEL, fork, (x, y, z) -> StrictMath.sin(0.7 * x + 1.3 * y + 2.1 * z) * 0.8, heights);
        StringBuilder sb = new StringBuilder();
        for (int x : XS) {
            for (int z : ZS) {
                for (int y : YS) {
                    int wx = cx * 16 + x;
                    int wz = cz * 16 + z;
                    Carve carve = CaveCarver.carve(aquifer, wx, y, wz, true);
                    sb.append(switch (carve) {
                        case AIR -> 'A';
                        case WATER -> 'W';
                        case LAVA -> 'L';
                        case KEEP -> '.';
                    });
                }
            }
        }
        return sb.toString();
    }
