package dev.tfp.datagen.basket;

import com.google.gson.JsonObject;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.Json;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import dev.tfp.datagen.material.TfcItemRegistry;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * PAR-PROC-22: TFC's basket ({@code TFCItems.BASKET}, a {@code TFCBundleItem} with an empty {@code BUNDLE_CONTENTS}) as
 * the CraftEngine item {@code tfp:basket} ({@code configuration/basket.yml}).
 *
 * <p>It is built on {@code minecraft:bundle}, so the vanilla client draws the bundle tooltip and fullness bar and runs
 * the bundle clicks itself, and carries an explicit empty {@code minecraft:bundle_contents} like TFC's registration. The
 * look is TFC's {@code models/item/basket.json} ({@code item/generated}, {@code tfc:item/basket}) in every display
 * context: no open-bundle variant with the selected item, which TFC's 1.21.1 basket does not have. The stack size is TFC's {@code item_size/basket} weight (very heavy: 1). TFC's size
 * rule ({@code overrideOtherStackedOnMe}: lighter than medium and smaller than large) is enforced at runtime by
 * PAR-SURV-06's {@code ContainerSizeListener} for every bundle item. The name comes from TFC's lang files
 * ({@code assets/tfp_basket/lang}).
 */
public final class BasketItem {
    static final String PACK = "craftengine/tfp/";
    static final String CONFIG = PACK + "configuration/basket.yml";
    static final String RP = PACK + "resourcepack/assets/" + Json.TO_NS + "/";
    static final String LANG_NS = "tfp_basket";
    static final String LANG_RP = PACK + "resourcepack/assets/" + LANG_NS + "/lang/";
    static final String LANG = TfcCheckout.ASSETS + "lang/";
    static final String ITEMS_SOURCE = "src/main/java/net/dries007/tfc/common/items/TFCItems.java";
    static final String ID = "basket";
    static final String MODEL = TfcCheckout.ASSETS + "models/item/" + ID + ".json";
    static final String ITEM_SIZE = "src/generated/resources/data/tfc/tfc/item_size/" + ID + ".json";
    static final String TEXTURES = TfcCheckout.ASSETS + "textures/";
    /** TFC {@code Weight} stack sizes. */
    static final Map<String, Integer> WEIGHT_STACK = Map.of(
        "very_light", 64, "light", 32, "medium", 16, "heavy", 4, "very_heavy", 1);

    private static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + " (PAR-PROC-22, dev.tfp.datagen.basket). Do not edit: fix the "
        + "generator and regenerate.";

    private BasketItem() {
    }

    /** Whether the checkout has {@code TFCItems} and the basket model (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(ITEMS_SOURCE) && tfc.exists(MODEL);
    }

    /** Checks that TFC still registers the basket as a {@code TFCBundleItem} with empty bundle contents. */
    static void checkRegistration(TfcCheckout tfc) {
        for (TfcItemRegistry.Registration r : TfcItemRegistry.registrations(tfc)) {
            if (r.field().equals("BASKET")) {
                if (!r.factory().contains("new TFCBundleItem(") || !r.factory().contains("BundleContents.EMPTY")) {
                    throw new DatagenException("TFCItems.BASKET is no longer an empty TFCBundleItem: " + r.factory());
                }
                return;
            }
        }
        throw new DatagenException(ITEMS_SOURCE + " no longer has BASKET (update BasketItem)");
    }

    /** The {@code layer0} texture of TFC's basket model, as a texture path ({@code item/basket}). */
    static String texture(TfcCheckout tfc) {
        JsonObject model = Json.parse(tfc.readString(MODEL), MODEL).getAsJsonObject();
        if (!model.has("parent") || !model.get("parent").getAsString().endsWith("item/generated")
                || !model.has("textures")) {
            throw new DatagenException(MODEL + " is no longer an item/generated model");
        }
        JsonObject tex = model.getAsJsonObject("textures");
        if (tex.size() != 1 || !tex.has("layer0")) {
            throw new DatagenException(MODEL + ": expected exactly layer0, got " + tex.keySet());
        }
        String layer0 = tex.get("layer0").getAsString();
        String prefix = Json.FROM_NS + ":";
        if (!layer0.startsWith(prefix)) {
            throw new DatagenException(MODEL + ": layer0 outside the tfc namespace: " + layer0);
        }
        return layer0.substring(prefix.length());
    }

    /** TFC's stack size of the basket: its {@code item_size} weight. */
    static int stackSize(TfcCheckout tfc) {
        if (!tfc.exists(ITEM_SIZE)) {
            throw new DatagenException("missing " + ITEM_SIZE);
        }
        JsonObject def = Json.parse(tfc.readString(ITEM_SIZE), ITEM_SIZE).getAsJsonObject();
        String weight = def.get("weight").getAsString();
        Integer stack = WEIGHT_STACK.get(weight);
        if (stack == null) {
            throw new DatagenException(ITEM_SIZE + ": unknown weight " + weight);
        }
        return stack;
    }

    /** Writes the item, its model, texture and names. */
    public static void run(TfcCheckout tfc, OutputTree out) {
        checkRegistration(tfc);
        String texture = texture(tfc);
        String png = TEXTURES + texture + ".png";
        if (!tfc.exists(png)) {
            throw new DatagenException("missing basket texture " + png);
        }
        out.put(RP + "textures/" + texture + ".png", tfc.read(png));
        JsonObject model = new JsonObject();
        model.addProperty("parent", "minecraft:item/generated");
        JsonObject tex = new JsonObject();
        tex.addProperty("layer0", Json.TO_NS + ":" + texture);
        model.add("textures", tex);
        out.put(RP + "models/item/" + ID + ".json", Json.write(model));

        Map<String, Object> items = new LinkedHashMap<>();
        items.put(Json.TO_NS + ":" + ID, entry(stackSize(tfc)));
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("items", items);
        out.put(CONFIG, Yaml.write(HEADER, root));
        writeLang(tfc, out);
    }

    static String langKey() {
        return "item." + Json.TO_NS + "." + ID;
    }

    static Map<String, Object> entry(int stack) {
        Map<String, Object> model = new LinkedHashMap<>();
        model.put("type", "minecraft:model");
        model.put("path", Json.TO_NS + ":item/" + ID);

        Map<String, Object> components = new LinkedHashMap<>();
        components.put("minecraft:bundle_contents", List.of());
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("item_name", "<!i><lang:" + langKey() + ">");
        data.put("max_stack_size", stack);
        data.put("components", components);
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("material", "bundle");
        e.put("data", data);
        e.put("model", model);
        return e;
    }

    /** TFC's name of the basket in every locale that has it (English must). */
    private static void writeLang(TfcCheckout tfc, OutputTree out) {
        String tfcKey = "item." + Json.FROM_NS + "." + ID;
        for (String f : tfc.list(LANG)) {
            if (!f.endsWith(".json")) {
                continue;
            }
            String locale = f.substring(LANG.length(), f.length() - ".json".length());
            JsonObject src = Json.parse(tfc.readString(f), f).getAsJsonObject();
            if (src.has(tfcKey)) {
                JsonObject o = new JsonObject();
                o.addProperty(langKey(), src.get(tfcKey).getAsString());
                out.put(LANG_RP + locale + ".json", Json.write(o));
            } else if (locale.equals("en_us")) {
                throw new DatagenException("TFC item tfc:" + ID + " has no English name " + tfcKey);
            }
        }
    }
}
