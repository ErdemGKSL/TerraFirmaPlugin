/**
 * The BetterHud layouts of the HUD catalogue ({@code docs/hud/catalogue.md}, section 1), written under
 * {@code betterhud/tfp/} by the {@code betterhud} skill's layout rules (see {@link BetterHudPack} for the font and the
 * other files of the pack).
 *
 * <p>The catalogue is the source of the element ids, kinds and placeholder names. It is parsed strictly: a row with the
 * wrong number of cells, an unknown kind, a duplicate id, a placeholder name without the {@code tfp_} prefix, a counts
 * section that disagrees with the table, or a missing file is an error, never a skipped row. Only the rows whose data
 * is specified get output. A row whose data says {@code unspecified in plan} is listed in {@link Summary#leftOut()} and
 * gets no output, because it names no placeholder to read; the same holds for the {@code indicator} kind, which the
 * task does not name.
 *
 * <p>Output: {@code images/tfp-bars.yml} (the bar art), {@code layouts/tfp-{bars,popups}.yml} and
 * {@code layouts/tfp-readouts.yml} (one layout per element; the readouts file is written only when a readout is not
 * already in {@link BetterHudPack}, see {@link #READOUTS_IN_PACK}), {@code popups/tfp-popups.yml} (the held-temperature popup), and {@code glue/placeholders.yml} and
 * {@code glue/hidden-vanilla.yml}, two lists that the Java placeholder glue and the installer read. BetterHud does not
 * read {@code glue/}, so the installer must not copy it into the pack folder (dependency-bootstrap).
 *
 * <p>Placements (GUI pixel offsets) are not in the catalogue. They follow TFC's {@code IngameOverlays} geometry (see
 * {@link #BAR_SPECS}, {@link #OVERLAYS}), keyed by catalogue id. An element without a placement is an error. The art
 * comes from {@link HudArt} (two pixel-aligned layers per bar, {@code plans/hud-layered-redesign.md}).
 */
