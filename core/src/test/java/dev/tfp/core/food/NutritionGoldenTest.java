    static String fmt(PlayerNutrition s) {
        NutritionLevels l = s.levels(CFG);
        StringBuilder sb = new StringBuilder();
        sb.append(s.hunger().hunger()).append('|').append(s.hunger().saturation()).append('|');
        for (float v : l.values()) {
            sb.append(v).append(',');
        }
        return sb.append(l.average()).append('|').append(l.healthModifier(CFG)).append('|')
                .append(s.nutrition().records().size()).toString();
    }

    static List<String> rows(char kind) {
        return GOLDEN.lines().map(String::strip).filter(l -> l.startsWith(kind + "|")).toList();
    }

    @TestFactory
    Stream<DynamicTest> healthModifier() {
        return rows('H').stream().map(row -> DynamicTest.dynamicTest(row, () -> {
            String[] p = row.split("\\|");
            assertThat(NutritionLevels.healthModifier(Float.parseFloat(p[1]), CFG)).isEqualTo(Float.parseFloat(p[2]));
        }));
    }

    @TestFactory
    Stream<DynamicTest> eatingSequences() {
        List<DynamicTest> tests = new ArrayList<>();
        List<String> expected = rows('N');
        int row = 0;
        for (int s = 0; s < SCENARIOS.length; s++) {
            List<String> actual = new ArrayList<>();
            PlayerNutrition state = PlayerNutrition.fresh(0);
            actual.add("N|" + s + "|start|" + fmt(state));
            for (String op : SCENARIOS[s].split(" ")) {
                String[] kv = op.split(":");
                state = kv[0].equals("e") ? state.eat(FOODS.get(kv[1]), 0, CFG)
                        : state.withHunger(Integer.parseInt(kv[1]), 0, CFG);
                actual.add("N|" + s + "|" + op + "|" + fmt(state));
            }
            for (String a : actual) {
                String e = expected.get(row++);
                tests.add(DynamicTest.dynamicTest(e, () -> assertThat(a).isEqualTo(e)));
            }
        }
        assertThat(row).isEqualTo(expected.size());
        return tests.stream();
    }

    @TestFactory
    Stream<DynamicTest> timelines() {
        List<DynamicTest> tests = new ArrayList<>();
        List<String> expected = rows('T');
        int row = 0;
        for (int s = 0; s < TIMELINES.length; s++) {
            TreeMap<Long, String> meals = new TreeMap<>();
            for (String m : TIMELINES[s]) {
                String[] kv = m.split(":");
                meals.put(Long.parseLong(kv[0]), kv[1]);
            }
            PlayerNutrition state = PlayerNutrition.fresh(0);
            for (long t = 1500; t <= 200_000; t += 9000) {
                // the meals up to t, each at its own tick, then one lazy jump to t
                Map<Long, String> due = meals.headMap(t, true);
                for (Map.Entry<Long, String> m : due.entrySet()) {
                    state = state.eat(FOODS.get(m.getValue()), m.getKey(), CFG);
                }
                due.clear();
                state = state.at(t, CFG);
                String e = expected.get(row++);
                String a = "T|" + s + "|" + t + "|" + fmt(state);
                tests.add(DynamicTest.dynamicTest(e, () -> assertThat(a).isEqualTo(e)));
            }
        }
        assertThat(row).isEqualTo(expected.size());
        return tests.stream();
    }
