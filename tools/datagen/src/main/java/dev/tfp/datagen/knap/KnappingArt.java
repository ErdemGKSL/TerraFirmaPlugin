package dev.tfp.datagen.knap;

import dev.tfp.core.gui.ChestGeometry;
import dev.tfp.core.gui.GuiImage;
import dev.tfp.core.knap.KnappingRules;
import dev.tfp.core.knap.KnappingScreen;
import dev.tfp.datagen.DatagenException;
import dev.tfp.datagen.OutputTree;
import dev.tfp.datagen.TfcCheckout;
import dev.tfp.datagen.Yaml;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import javax.imageio.ImageIO;

/**
 * PAR-PROC-01: the knapping screen's art ({@link KnappingScreen}) as CraftEngine font images in {@code
 * configuration/knapping.yml}: TFC's {@code knapping.png} re-laid out into a 6-row chest (the arrow and output frame moved
 * to the output slot, the player inventory to the chest's), and every knapping button texture as one 2-frame (on, disabled)
 * or 1-frame image per grid row. TFC's numbers the layout uses are read from its sources and must equal the core's, and
 * the set of textures must equal {@link KnappingScreen#TEXTURES}, so a TFC change fails here instead of misaligning.
 */
public final class KnappingArt {
    public static final String GUI = "src/main/resources/assets/tfc/textures/gui/";
    public static final String BACKGROUND = GUI + "knapping.png";
    public static final String BUTTONS = GUI + "knapping/";
    public static final String SCREEN = "src/main/java/net/dries007/tfc/client/screen/KnappingScreen.java";
    public static final String CONTAINER = "src/main/java/net/dries007/tfc/common/container/KnappingContainer.java";

    public static final String PACK = "craftengine/tfp/";
    public static final String CONFIG = PACK + "configuration/knapping.yml";
    public static final String RP = PACK + "resourcepack/assets/tfp/";

    static final String HEADER = "Generated by tools/datagen from TerraFirmaCraft @ "
        + TfcCheckout.PINNED_COMMIT.substring(0, 9) + ". Do not edit: fix the generator and regenerate.";
    /** Rows of the top and bottom border kept in place. */
    static final int BORDER = 4;

    private static final Pattern HEIGHT = Pattern.compile("imageHeight = (\\d+);");
    private static final Pattern BX = Pattern.compile("int bx = \\(width - getXSize\\(\\)\\) / 2 \\+ (\\d+) \\+ (\\d+) \\* x;");
    private static final Pattern BY = Pattern.compile("int by = \\(height - getYSize\\(\\)\\) / 2 \\+ (\\d+) \\+ (\\d+) \\* y;");
    private static final Pattern ID = Pattern.compile("new KnappingButton\\(x \\+ (\\d+) \\* y,");
    private static final Pattern OUTPUT = Pattern.compile("new ItemStackHandler\\(1\\), 0, (\\d+), (\\d+)\\)\\);");
    private static final Pattern OFFSET = Pattern.compile("init\\(playerInventory, (\\d+)\\)");

    private KnappingArt() {
    }

    /** True when the checkout has the art and sources (the small test fixtures do not). */
    public static boolean available(TfcCheckout tfc) {
        return tfc.exists(BACKGROUND) && tfc.exists(SCREEN) && tfc.exists(CONTAINER) && tfc.exists(BUTTONS + "leather.png");
    }

    /** Writes the images and their YAML. Returns the number of images. */
    public static int run(TfcCheckout tfc, OutputTree out) {
        checkLayout(tfc);
        checkTextures(tfc);
        Map<String, Object> images = new LinkedHashMap<>();
        BufferedImage bg = background(read(tfc, BACKGROUND));
        put(out, images, KnappingScreen.BACKGROUND, bg);
        for (GuiImage image : KnappingScreen.rowImages()) {
            String texture = image.name().substring("knapping/".length(), image.name().lastIndexOf("_r"));
            BufferedImage png = new BufferedImage(image.pngWidth(), image.pngHeight(), BufferedImage.TYPE_INT_ARGB);
            blit(cell(tfc, BUTTONS + texture + ".png"), png, 0, 0);
            if (image.frames() > 1) {
                blit(cell(tfc, BUTTONS + texture + "_disabled.png"), png, KnappingScreen.CELL, 0);
            }
            put(out, images, image, png);
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("images", images);
        out.put(CONFIG, Yaml.write(HEADER, root));
        return images.size();
    }

    private static void put(OutputTree out, Map<String, Object> images, GuiImage image, BufferedImage png) {
        if (png.getWidth() != image.pngWidth() || png.getHeight() != image.pngHeight()) {
            throw new DatagenException(image.id() + ": art is " + png.getWidth() + "x" + png.getHeight());
        }
        out.put(RP + image.packPath(), png(png));
        Map<String, Object> e = new LinkedHashMap<>();
        e.put("file", image.file());
        e.put("font", GuiImage.FONT);
        e.put("height", image.height());
        e.put("ascent", image.ascent());
        if (image.frames() > 1) {
            e.put("grid_size", image.rows() + "," + image.cols());
        }
        if (images.put(image.id(), e) != null) {
            throw new DatagenException("duplicate knapping image " + image.id());
        }
    }

    /**
     * The 176 x 222 window: TFC's top border, a plain panel, TFC's arrow and output frame moved by ({@code ART_DX},
     * {@code ART_DY}), TFC's player inventory part (from the plain row above it) moved by {@code PLAYER_DY}, and TFC's bottom
     * border at the bottom. The grid area stays plain panel: TFC draws only the buttons there.
     */
    static BufferedImage background(BufferedImage src) {
        int w = ChestGeometry.WIDTH;
        int h = KnappingScreen.CHEST.height();
        int srcH = KnappingScreen.TFC_HEIGHT;
        int playerTop = 84 + KnappingScreen.TFC_INVENTORY_OFFSET - 1; // the first row of the player slot frames
        int plainRow = playerTop - 2;
        if (!plain(src, plainRow) || !plain(src, srcH - BORDER - 1)) {
            throw new DatagenException(BACKGROUND + ": rows " + plainRow + " and " + (srcH - BORDER - 1) + " must be plain panel");
        }
        for (int y = BORDER; y < playerTop - 1; y++) {
            boolean art = y >= KnappingScreen.TFC_ART_Y && y < KnappingScreen.TFC_ART_Y + KnappingScreen.TFC_ART_HEIGHT;
            if (!art && !plain(src, y)) {
                throw new DatagenException(BACKGROUND + ": unexpected art on row " + y);
            }
        }
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        for (int t = 0; t < h; t++) {
            int s;
            if (t < BORDER) {
                s = t;
            } else if (t >= h - BORDER) {
                s = srcH - (h - t);
            } else if (t - KnappingScreen.PLAYER_DY >= plainRow && t - KnappingScreen.PLAYER_DY < srcH - BORDER) {
                s = t - KnappingScreen.PLAYER_DY;
            } else if (t - KnappingScreen.PLAYER_DY >= srcH - BORDER) {
                s = srcH - BORDER - 1;
            } else {
                s = plainRow;
            }
            for (int x = 0; x < w; x++) {
                out.setRGB(x, t, src.getRGB(x, s));
            }
        }
        for (int j = 0; j < KnappingScreen.TFC_ART_HEIGHT; j++) {
            for (int i = 0; i < KnappingScreen.TFC_ART_WIDTH; i++) {
                out.setRGB(KnappingScreen.TFC_ART_X + KnappingScreen.ART_DX + i, KnappingScreen.TFC_ART_Y + KnappingScreen.ART_DY + j,
                    src.getRGB(KnappingScreen.TFC_ART_X + i, KnappingScreen.TFC_ART_Y + j));
            }
        }
        return out;
    }

    /** A row whose pixels between the side borders all have one opaque colour. */
    static boolean plain(BufferedImage src, int y) {
        int c = src.getRGB(BORDER, y);
        if ((c >>> 24) == 0) {
            return false;
        }
        for (int x = BORDER; x < ChestGeometry.WIDTH - BORDER; x++) {
            if (src.getRGB(x, y) != c) {
                return false;
            }
        }
        return true;
    }

    /** TFC's layout numbers must be the ones {@link KnappingScreen} holds. */
    static void checkLayout(TfcCheckout tfc) {
        String screen = tfc.readString(SCREEN);
        String container = tfc.readString(CONTAINER);
        int[] bx = ints(BX, screen, SCREEN, 2);
        int[] by = ints(BY, screen, SCREEN, 2);
        expect(ints(HEIGHT, screen, SCREEN, 1)[0], KnappingScreen.TFC_HEIGHT, "screen height");
        expect(bx[0], KnappingScreen.TFC_BUTTON_X0, "button x0");
        expect(by[0], KnappingScreen.TFC_BUTTON_Y0, "button y0");
        expect(bx[1], KnappingScreen.CELL, "button pitch x");
        expect(by[1], KnappingScreen.CELL, "button pitch y");
        expect(ints(ID, screen, SCREEN, 1)[0], KnappingRules.GRID, "button id stride");
        int[] output = ints(OUTPUT, container, CONTAINER, 2);
        expect(output[0], KnappingScreen.TFC_OUTPUT_X, "output x");
        expect(output[1], KnappingScreen.TFC_OUTPUT_Y, "output y");
        expect(ints(OFFSET, container, CONTAINER, 1)[0], KnappingScreen.TFC_INVENTORY_OFFSET, "inventory offset");
    }

    /** TFC's button textures must be exactly {@link KnappingScreen#TEXTURES} plus the disabled variants. */
    static void checkTextures(TfcCheckout tfc) {
        TreeSet<String> expected = new TreeSet<>();
        for (String t : KnappingScreen.TEXTURES) {
            expected.add(t);
            if (KnappingScreen.WITH_DISABLED.contains(t)) {
                expected.add(t + "_disabled");
            }
        }
        TreeSet<String> found = new TreeSet<>();
        for (String f : tfc.list(BUTTONS)) {
            String rel = f.replace('\\', '/').substring(BUTTONS.length());
            if (rel.endsWith(".png")) {
                found.add(rel.substring(0, rel.length() - 4));
            }
        }
        if (!found.equals(expected)) {
            TreeSet<String> extra = new TreeSet<>(found);
            extra.removeAll(expected);
            TreeSet<String> missing = new TreeSet<>(expected);
            missing.removeAll(found);
            throw new DatagenException(BUTTONS + ": textures differ from KnappingScreen.TEXTURES; extra " + extra + ", missing " + missing);
        }
    }

    private static BufferedImage cell(TfcCheckout tfc, String path) {
        BufferedImage img = read(tfc, path);
        if (img.getWidth() != KnappingScreen.CELL || img.getHeight() != KnappingScreen.CELL) {
            throw new DatagenException(path + " is " + img.getWidth() + "x" + img.getHeight() + ", not 16x16");
        }
        return img;
    }

    private static int[] ints(Pattern p, String text, String file, int n) {
        Matcher m = p.matcher(text);
        if (!m.find()) {
            throw new DatagenException(file + ": no match for " + p.pattern());
        }
        int[] out = new int[n];
        for (int i = 0; i < n; i++) {
            out[i] = Integer.parseInt(m.group(i + 1));
        }
        return out;
    }

    private static void expect(int tfc, int ours, String what) {
        if (tfc != ours) {
            throw new DatagenException("TFC's knapping " + what + " is " + tfc + ", KnappingScreen says " + ours);
        }
    }

    static BufferedImage read(TfcCheckout tfc, String path) {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(tfc.read(path)));
            if (img == null) {
                throw new DatagenException(path + " is not an image");
            }
            BufferedImage argb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
            blit(img, argb, 0, 0);
            return argb;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void blit(BufferedImage src, BufferedImage dst, int x, int y) {
        for (int j = 0; j < src.getHeight(); j++) {
            for (int i = 0; i < src.getWidth(); i++) {
                dst.setRGB(x + i, y + j, src.getRGB(i, j));
            }
        }
    }

    static byte[] png(BufferedImage img) {
        try {
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            if (!ImageIO.write(img, "png", bytes)) {
                throw new DatagenException("no PNG writer");
            }
            return bytes.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
